create or replace view PA_LINE_GP_SPECIFIEDTOOLS(
	PUREPOLICYNUMBER,
	LEGACYPOLICYNUMBER,
	VALUE,
	DESCRIPTION
) as
SELECT
    ID AS PUREPOLICYNUMBER,
    PUREPOLICYNUMBER AS LEGACYPOLICYNUMBER,
    cast(COALESCE(VALUE ,0)as varchar) AS VALUE,
    CAST(DESCRIPTION AS VARCHAR) AS DESCRIPTION
    FROM 
    AGGNE.PRD.line_gp_coverage_policyattach_IDENTIFIER;