create or replace view PA_PER_HOME_CONTENTS_PAYLOAD(
	PUREPOLICYNUMBER,
	ACTUALID,
	COVERAGE,
	UW,
	SUBCOV,
	HC_SC,
	HC_EV,
	VOLUNTARYEXCESS,
	STANDARDEXCESS,
	IMPOSEDEXCESS,
	EARTHQUAKEEXCESS,
	FLOODEXCESS,
	ACCIDENTALLOSSORDAMAGE,
	FLOODDAMAGE,
	SPECIFIEDITEMSAWAY,
	UNSPECIFIEDITEMSAWAY,
	UNSPECIFIEDITEMSAWAYLIMIT,
	HCCLMCNT,
	HCCLMINCD,
	HBEXPPREM,
	LOAD_DATE
) as
with cte_SAMPLE_CBP_LOCATION as
(
select distinct trim(T1.PUREPOLICYNUMBER)AS PUREPOLICYNUMBER ,trim(t1.CMLNUMBER) AS CMLNUMBER,T1.EXPIRINGID_P,T1.INSURANCE_FILE_CNT,T1.ACTUALID,T2.ID
from AGGNE.PRD.Locationdetails_PER_Policyattach_IDENTIFIER T1 
INNER JOIN AGGNE.PRD.Policyattach_PER_IDENTIFIER
T2 ON TRIM(T1.ID)=TRIM(T2.ID) 
),cte_COVERAGES as 
(
select distinct PUREPOLICYNUMBER,cmlnumber,EXPIRINGID_P,INSURANCE_FILE_CNT,'BB' AS CLAUSE,'Building' AS  COVERAGE, "VOLUNTARYEXCESS" AS VOLUNTARYEXCESS,STANDARDEXCESS,IMPOSEDEXCESS,EARTHQUAKEEXCESS,FLOODEXCESS,ID,ACTUALID,
CASE WHEN ACCIDENTALLOSSORDAMAGE='Taken' then CAST(CAST(1 AS NUMBER(1,0)) AS VARCHAR)  ELSE CAST(CAST(0 AS NUMBER(1,0)) AS VARCHAR) END AS ACCIDENTALLOSSORDAMAGE,
CASE WHEN FLOODDAMAGE='Taken' then CAST(CAST(1 AS NUMBER(1,0)) AS VARCHAR)  ELSE CAST(CAST(0 AS NUMBER(1,0)) AS VARCHAR) END AS FLOODDAMAGE,
SPECIFIEDITEMSAWAY,UNSPECIFIEDITEMSAWAY,UNSPECIFIEDITEMSAWAYLIMIT
from AGGNE.PRD.HC_02_Policyattach_IDENTIFIER T1 
) 
 , CTE_EXCESS AS(
SELECT 
    T1.ID AS PUREPOLICYNUMBER,T1.ID,T2.ACTUALID,
t2.PUREPOLICYNUMBER AS LEGACYPOLICYNUMBER,T2.cmlnumber,T2.EXPIRINGID_P,COVERAGE,T2.VOLUNTARYEXCESS,T2.INSURANCE_FILE_CNT,
ACCIDENTALLOSSORDAMAGE,STANDARDEXCESS,IMPOSEDEXCESS,EARTHQUAKEEXCESS,FLOODEXCESS,FLOODDAMAGE,
SPECIFIEDITEMSAWAY,UNSPECIFIEDITEMSAWAY,UNSPECIFIEDITEMSAWAYLIMIT
FROM 
cte_SAMPLE_CBP_LOCATION T1 
INNER JOIN cte_COVERAGES T2 ON T1.ID=T2.ID AND T1.EXPIRINGID_P=T2.EXPIRINGID_P
)
,CTE_LISTAGG AS(
SELECT
  ID,
  LISTAGG(CASE WHEN ITR_TYPE = 'Building_SubCov' THEN payload END, '\n') AS SUBCOV,
  LISTAGG(CASE WHEN ITR_TYPE = 'BUILDING_UW' THEN payload END, '\n') AS UW,  
  LISTAGG(CASE WHEN ITR_TYPE = 'HC_Specified_Contents'     THEN payload END, '\n') AS HC_SC,
  LISTAGG(CASE WHEN ITR_TYPE = 'HC_exceed_values'     THEN payload END, '\n') AS HC_EV,
  CAST(LOAD_DATE AS DATE) AS LOAD_DATE
FROM AGGNE.PRD.PA_PER_HC_TARGET
WHERE ITR_TYPE IN ('Building_SubCov','HC_Specified_Contents','HC_exceed_values','BUILDING_UW')   
GROUP BY ID, CAST(LOAD_DATE AS DATE)
)
SELECT distinct 
T1.PUREPOLICYNUMBER,
T1.ACTUALID,
COVERAGE,
CAST(UW AS VARCHAR) AS UW,
CAST(SUBCOV AS VARCHAR) AS SUBCOV,
CAST(HC_SC AS VARCHAR) AS HC_SC,
CAST(HC_EV AS VARCHAR) AS HC_EV,
-- CASE WHEN LOC_BB_CLAUSE IS NOT NULL AND LOC_BB_CLAUSE<> '' THEN '<Clauses><Type>Building</Type>'||CAST(LOC_BB_CLAUSE AS VARCHAR)||'</Clauses>' ELSE '' END AS LOC_BB_CLAUSE,
-- CAST(UW AS VARCHAR) AS UW,
CAST(CAST(COALESCE(VOLUNTARYEXCESS,0)AS NUMBER(20,0)) AS VARCHAR) AS VOLUNTARYEXCESS,
CAST(CAST(COALESCE(STANDARDEXCESS,0)AS NUMBER(20,0)) AS VARCHAR) AS STANDARDEXCESS,
CAST(CAST(COALESCE(IMPOSEDEXCESS,0)AS NUMBER(20,0)) AS VARCHAR) AS IMPOSEDEXCESS,
CAST(CAST(COALESCE(EARTHQUAKEEXCESS,0)AS NUMBER(20,0)) AS VARCHAR) AS EARTHQUAKEEXCESS,
CASE WHEN FLOODDAMAGE='1' then CAST(CAST(COALESCE(FLOODEXCESS,0)AS NUMBER(20,0)) AS VARCHAR) ELSE CAST('0' AS VARCHAR) END AS FLOODEXCESS,
CAST(ACCIDENTALLOSSORDAMAGE AS VARCHAR) AS ACCIDENTALLOSSORDAMAGE,
CAST(FLOODDAMAGE AS VARCHAR) AS FLOODDAMAGE,
CASE WHEN SPECIFIEDITEMSAWAY='Taken' then CAST(CAST(1 AS NUMBER(1,0)) AS VARCHAR)  ELSE CAST(CAST(0 AS NUMBER(1,0)) AS VARCHAR) END AS SPECIFIEDITEMSAWAY,
CASE WHEN UNSPECIFIEDITEMSAWAY='Taken' then CAST(CAST(1 AS NUMBER(1,0)) AS VARCHAR)  ELSE CAST(CAST(0 AS NUMBER(1,0)) AS VARCHAR) END AS UNSPECIFIEDITEMSAWAY,
CASE WHEN UNSPECIFIEDITEMSAWAYLIMIT='$2,000 per item up to $10,000 per event' THEN '2000peritemupto20000perevent' 
WHEN UNSPECIFIEDITEMSAWAYLIMIT='$1,250 per item up to $5,000 per event' THEN '1250peritemupto5000perevent'
ELSE '' END AS UNSPECIFIEDITEMSAWAYLIMIT,
CAST(COALESCE(T4.HCCLMCNT,0) AS VARCHAR) AS HCCLMCNT,
CAST(COALESCE(T4.HCCLMINCD,0) AS VARCHAR) AS HCCLMINCD,
CAST(COALESCE(T4.HMEXPPREM,0) AS VARCHAR) AS HBEXPPREM,
CAST(GETDATE() AS DATE) as LOAD_DATE
FROM CTE_EXCESS T1
-- LEFT JOIN  AGGNE.PRD.PA_PER_HC_TARGET T2 ON T1.PUREPOLICYNUMBER=T2.ID
LEFT JOIN CTE_LISTAGG T3 ON T1.PUREPOLICYNUMBER = T3.ID 
LEFT JOIN AGGNE.PRD.Output_Coverage_PER_Policyattach T4 ON trim(T1.LEGACYPOLICYNUMBER)=trim(T4.policynumber) AND  T1.EXPIRINGID_P=T4.EXPIRINGID_P
WHERE   COVERAGE='Building'  ;