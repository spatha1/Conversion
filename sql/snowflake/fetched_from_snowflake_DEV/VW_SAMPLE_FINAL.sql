create or replace view VW_SAMPLE_FINAL(
	ID,
	LEGACYPOLICYNUMBER,
	CMLNUMBER,
	CSLNUMBER,
	EXPIRINGID_P,
	INSURANCE_FILE_CNT,
	COUNTRY,
	PRIMARYRATINGSTATE,
	LINEOFBUSINESS,
	EFFECTIVEDATE,
	EXPIRATIONDATE,
	MEMBERSHIPSYSTEMDATE,
	LINEOFBUSINESS_STD,
	CHOOSEPROTECTION,
	INCEPTIONDATE,
	COMMENCEMENTDATE
) as 
SELECT DISTINCT
CAST(trim(T1.LEGACYPOLICYNUMBER) ||'|' || TRIM(T1.cmlnumber) ||'|' || TRIM(T1.EXPIRINGID_P) AS VARCHAR) AS ID,
T1.* 
FROM AGGNE.DEV.SAMPLE_FINAL  T1
 WHERE EXPIRATIONDATE >= '2026-01-01' and LINEOFBUSINESS = 'Business Protections';