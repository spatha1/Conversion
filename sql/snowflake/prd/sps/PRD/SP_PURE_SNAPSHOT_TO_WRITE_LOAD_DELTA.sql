CREATE OR REPLACE TRANSIENT TABLE AGGNE.PRD.CML_MEMBERDATA AS
SELECT
  TRIM(d.CMLNUMBER) AS CMLNUMBER,
  d.COUNTRY,
  d.CMLLEGALENTITY,
  d.CMLTRADINGNAME,
  d.MAINCONTACT,
  d.CORRESPONDENCELINE1,
  d.CORRESPONDENCELINE2,
  d.CORRESPONDENCELINE3,
  d.CORRESPONDENCELINE4,
  d.CORRESPONDENCEPOSTCODE,
  d.SITE_STREET,
  d.SITE_SUBURB,
  d.SITE_STATE,
  d.SITE_POSTCODE,
  d.CSLNUMBER,
  TRIM(p.NUMBER) AS PRIMARY_PHONE,
  p.PHONETYPE         AS PRIMARY_PHONE_TYPE,
  TRIM(e.EMAIL)     AS PRIMARY_EMAIL,
  e.EMAILTYPE         AS PRIMARY_EMAIL_TYPE,
  '' AS SCONDARYCONTACTKEY,

  -- OTHERPHONE: exclude blanks and PRIMARY_PHONE
  ARRAY_TO_STRING(
    ARRAY_SORT(
      ARRAY_AGG(
        DISTINCT CASE
          WHEN TRIM(o.NUMBER) IS NOT NULL
           AND TRIM(o.NUMBER) <> ''
           AND (p.NUMBER IS NULL OR TRIM(o.NUMBER) <> TRIM(p.NUMBER))
          THEN TRIM(o.NUMBER)
        END
      )
    ),
    '|'
  ) AS OTHERPHONE,

  -- SCONDARYCONTACT: exclude blanks and MAINCONTACT (case-insensitive)
  ARRAY_TO_STRING(
    ARRAY_SORT(
      ARRAY_AGG(
        DISTINCT CASE
          WHEN TRIM(s.SECONDARYCONTACT) IS NOT NULL
           AND TRIM(s.SECONDARYCONTACT) <> ''
           AND (d.MAINCONTACT IS NULL
                OR LOWER(TRIM(s.SECONDARYCONTACT)) <> LOWER(TRIM(d.MAINCONTACT)))
          THEN TRIM(s.SECONDARYCONTACT)
        END
      )
    ),
    '|'
  ) AS SCONDARYCONTACT,

  -- OTHEREMAIL: exclude blanks and PRIMARY_EMAIL (case-insensitive)
  ARRAY_TO_STRING(
    ARRAY_SORT(
      ARRAY_AGG(
        DISTINCT CASE
          WHEN TRIM(oe.EMAIL) IS NOT NULL
           AND TRIM(oe.EMAIL) <> ''
           AND (e.EMAIL IS NULL
                OR LOWER(TRIM(oe.EMAIL)) <> LOWER(TRIM(e.EMAIL)))
          THEN LOWER(TRIM(oe.EMAIL))
        END
      )
    ),
    '|'
  ) AS OTHEREMAIL,

  (SELECT COUNT(DISTINCT NUMBER)
     FROM AGGNE.PRD.T_CML_OTHERPHONE_OUT cp
    WHERE TRIM(cp.CMLNUMBER) = TRIM(d.CMLNUMBER)) AS PHONE_COUNT,

  (SELECT COUNT(DISTINCT EMAIL)
     FROM AGGNE.PRD.T_CML_OTHEREMAIL_OUT ce
    WHERE TRIM(ce.CMLNUMBER) = TRIM(d.CMLNUMBER)) AS EMAIL_COUNT,

  (SELECT COUNT(DISTINCT SECONDARYCONTACT)
     FROM AGGNE.PRD.T_CML_OTHERCONTACTS_OUT cs
    WHERE TRIM(cs.CMLNUMBER) = TRIM(d.CMLNUMBER)) AS SECONDARYCONTACT_COUNT

FROM AGGNE.PRD.T_CMLMAINDETAILS d
LEFT JOIN AGGNE.PRD.T_CML_MAINPHONE p   ON TRIM(p.CMLNUMBER) = TRIM(d.CMLNUMBER)
LEFT JOIN AGGNE.PRD.T_CML_MAINEMAIL e   ON TRIM(e.CMLNUMBER) = TRIM(d.CMLNUMBER)
LEFT JOIN AGGNE.PRD.T_CML_OTHERCONTACTS_OUT s
