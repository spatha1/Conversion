    END AS EXP_PREM
FROM AGGNE.PRD.PM_03_Policyattach_IDENTIFIER T1 LEFT JOIN  AGGNE.PRD.Output_SubCover_PER_Policyattach T2 
ON TRIM(T1.PUREPOLICYNUMBER)=TRIM(T2.PolicyNumber) AND T1.EXPIRINGID_P=T2.EXPIRINGID_P  
