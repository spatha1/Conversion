create or replace view CV_MOTOR_UW_POLICYATTACH(
	PUREPOLICYNUMBER,
	PUREPOLICYNUMBER_ACTUAL,
	POLICYNUMBER,
	EXPIRINGID_P,
	CMLNUMBER,
	VEHICLE_ID,
	RECURRINGIND,
	ADJUSTMENTTYPE,
	COVERAGE,
	UWADJUSTNOTE,
	UWADJUSTAMOUNT
) as
SELECT
CAST(TRIM(ID) || '|' || TRIM(vehicleid) AS VARCHAR ) AS PUREPOLICYNUMBER,
	ID AS PUREPOLICYNUMBER_ACTUAL,
    POLICYNUMBER,
    A.EXPIRINGID_P,
    A.CMLNUMBER,
    B.VEHICLE_ID,
    '1' AS RECURRINGIND,
    '1' AS ADJUSTMENTTYPE,
       COVERAGE,
    UWADJUSTNOTE,
    CAST(UWADJUSTAMOUNT AS VARCHAR) AS UWADJUSTAMOUNT
FROM 
AGGNE.PRD.CM_03_POLICYATTACH_IDENTIFIER A INNER JOIN
AGGNE.PRD.OUTPUT_UWADJUST_BSP_POLICYATTACH B ON TRIM(A.PUREPOLICYNUMBER) = TRIM(B.POLICYNUMBER)
AND TRIM(A.EXPIRINGID_P) = TRIM(B.EXPIRINGID_P)
AND TRIM(A.CMLNUMBER) = TRIM(B.CMLNUMBER)
AND TRIM(A.VEHICLEID) = TRIM(B.VEHICLE_ID)
WHERE B.COVERAGE = 'CM';