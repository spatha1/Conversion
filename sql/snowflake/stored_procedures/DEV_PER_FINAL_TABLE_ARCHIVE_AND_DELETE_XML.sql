CREATE OR REPLACE PROCEDURE "PER_FINAL_TABLE_ARCHIVE_AND_DELETE_XML"()
RETURNS VARCHAR
LANGUAGE SQL
EXECUTE AS OWNER
AS '
DECLARE
  v_rows_archived NUMBER := 0;
  v_rows_deleted  NUMBER := 0;
BEGIN
  BEGIN TRANSACTION;

  INSERT INTO AGGNE.DEV.PER_POLICYATTACH_MIGRATION_DCT_PREVDATA
  SELECT T2.*
  FROM AGGNE.DEV.PER_POLICYATTACH_MIGRATION_DCT AS T2
  JOIN AGGNE.DEV.PER_SAMPLE_POLICYATTACH_FINAL_IDENTIFIER AS T1
    ON TRIM(T1.LEGACYPOLICYNUMBER) = TRIM(T2.LEGACYPOLICYNUMBER);

  v_rows_archived := SQLROWCOUNT;

  DELETE FROM AGGNE.DEV.PER_POLICYATTACH_MIGRATION_DCT AS T2
  USING AGGNE.DEV.PER_SAMPLE_POLICYATTACH_FINAL_IDENTIFIER AS T1
  WHERE TRIM(T1.LEGACYPOLICYNUMBER) = TRIM(T2.LEGACYPOLICYNUMBER);

  v_rows_deleted := SQLROWCOUNT;

  COMMIT;

  RETURN ''Final table Archived and Deleted. Archived='' || v_rows_archived || '', Deleted='' || v_rows_deleted;

EXCEPTION
  WHEN OTHER THEN
    ROLLBACK;
    RETURN ''Error during archive/delete: '' || SQLERRM;
END;
';