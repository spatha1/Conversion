BEGIN

CREATE OR REPLACE TABLE AGGNE.PRD.PER_POLICYATTACH_BP_MAX_NEW AS
SELECT 
    TRIM(PUREPOLICYNUMBER) AS PUREPOLICYNUMBER,
    MAX(EXPIRINGID_P) AS EXPIRINGID_P,
    MAX(INSURANCE_FILE_CNT) AS INSURANCE_FILE_CNT
FROM AGGNE.PRD.PER_STEP1
GROUP BY PUREPOLICYNUMBER;
 
 
DELETE FROM AGGNE.PRD.PER_POLICYATTACH_TO_PROCESS;
INSERT INTO AGGNE.PRD.PER_POLICYATTACH_TO_PROCESS
SELECT TRIM(T1.PUREPOLICYNUMBER) FROM AGGNE.PRD.PER_POLICYATTACH_BP_MAX_OLD T1 INNER JOIN AGGNE.PRD.PER_POLICYATTACH_BP_MAX_NEW T2 ON  TRIM(T1.PUREPOLICYNUMBER)=TRIM(T2.PUREPOLICYNUMBER)
AND (T1.EXPIRINGID_P<>T2.EXPIRINGID_P OR T1.INSURANCE_FILE_CNT<>T2.INSURANCE_FILE_CNT)
UNION ALL
SELECT TRIM(T2.PUREPOLICYNUMBER) FROM AGGNE.PRD.PER_POLICYATTACH_BP_MAX_OLD T1 RIGHT JOIN AGGNE.PRD.PER_POLICYATTACH_BP_MAX_NEW T2 ON  TRIM(T1.PUREPOLICYNUMBER)=TRIM(T2.PUREPOLICYNUMBER)
WHERE T1.PUREPOLICYNUMBER IS NULL;

RETURN 'DELTA PROCESS COMPLETED';

END;
