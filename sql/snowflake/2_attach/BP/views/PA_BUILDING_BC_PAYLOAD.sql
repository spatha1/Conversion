create or replace view PA_BUILDING_BC_PAYLOAD(
	LEGACYPOLICYNUMBER,
	PUREPOLICYNUMBER,
	COVERAGE,
	SUBCOV,
	UW,
	LOC_BC_CLAUSE,
	VOLUNTARYEXCESS,
	CONTENTSLIMIT,
	EARTHQUAKEEXCESS,
	FLOODEXCESS,
	HAILDAMAGEEXCESS,
	STANDARDEXCESS,
	IMPOSEDEXCESS,
	BUSINESSCONTENTS_IND,
	PROPORTIONOFHAILNETTING,
	BCCLMCNT,
	BCCLMINCD,
	BCEXPPREM,
	HAILDAMAGE,
	EXP_PREM_BCHAL_SD,
	EXP_PREM_BCLND_SD,
	EXP_PREM_BCSTD_BF,
	EXP_PREM_BCSTD_CY,
	EXP_PREM_BCSTD_EQ,
	EXP_PREM_BCSTD_ST,
	LOAD_DATE
) as
 with cte_SAMPLE_CBP_LOCATION as
(
select distinct T1.PUREPOLICYNUMBER,T1.cmlnumber,T1.EXPIRINGID,T1.INSURANCE_FILE_CNT ,T2.ID from AGGNE.PRD.Location_01_Policyattach_IDENTIFIER T1 INNER JOIN AGGNE.PRD.location_bc_coverage_policyattach_IDENTIFIER T2 ON TRIM(T1.PUREPOLICYNUMBER)=TRIM(T2.PUREPOLICYNUMBER) and 
T1.EXPIRINGID=T2.EXPIRINGID_P   
),cte_COVERAGES as 
(
select distinct PUREPOLICYNUMBER,cmlnumber,EXPIRINGID_P,ID,'BC' AS CLAUSE,'ContentsAndStocks' AS  COVERAGE, CAST(VOLUNTARYEXCESS AS VARCHAR) AS VOLUNTARYEXCESS,
CASE WHEN FLOODDAMAGE ='Taken' THEN FLOODEXCESS ELSE CAST(NULL AS VARCHAR) END AS FLOODEXCESS,
HAILDAMAGEEXCESS,EARTHQUAKEEXCESS,
STANDARDEXCESS,IMPOSEDEXCESS,
 CAST(CAST(COALESCE(CONTENTSLIMIT,0) AS NUMBER(20,0))AS VARCHAR) AS CONTENTSLIMIT,
cast(cast(COALESCE(HAILDAMAGE,0) AS NUMBER(20,0)) as varchar) AS HAILDAMAGE,
CAST(BUSINESSCONTENTS_IND AS VARCHAR) AS BUSINESSCONTENTS_IND ,
CAST(PROPORTIONOFHAILNETTING AS VARCHAR) AS PROPORTIONOFHAILNETTING
FROM AGGNE.PRD.location_bc_coverage_policyattach_IDENTIFIER T1 
) 
, CTE_EXCESS AS(
SELECT 
T1.ID AS PUREPOLICYNUMBER,
T1.ID,
t2.PUREPOLICYNUMBER AS LEGACYPOLICYNUMBER,T2.cmlnumber,T2.EXPIRINGID_P,COVERAGE,CAST(VOLUNTARYEXCESS AS VARCHAR) AS VOLUNTARYEXCESS,
FLOODEXCESS,HAILDAMAGEEXCESS,
EARTHQUAKEEXCESS
,STANDARDEXCESS,IMPOSEDEXCESS,
CAST(BUSINESSCONTENTS_IND AS VARCHAR) AS BUSINESSCONTENTS_IND ,
 CAST(CAST(COALESCE(CONTENTSLIMIT,0) AS NUMBER(20,0))AS VARCHAR) AS CONTENTSLIMIT,
cast(cast(COALESCE(HAILDAMAGE,0) AS NUMBER(20,0)) as varchar) AS HAILDAMAGE,
CAST(PROPORTIONOFHAILNETTING AS VARCHAR) AS PROPORTIONOFHAILNETTING
FROM  
cte_SAMPLE_CBP_LOCATION T1 
INNER JOIN cte_COVERAGES T2 ON T1.ID=T2.ID
-- TRIM(T1.EXPIRINGID) =TRIM(T2.EXPIRINGID_P)
-- AND TRIM(T1.PUREPOLICYNUMBER)=TRIM(T2.PUREPOLICYNUMBER) AND TRIM(T1.INSURANCE_FILE_CNT)=TRIM(T2.INSURANCE_FILE_CNT)
)
,CTE_LISTAGG AS(
SELECT
  ID,
  LISTAGG(CASE WHEN ITR_TYPE = 'BP_Risk_Building_BC_Subcov' THEN payload END, '\n') AS SUBCOV,
  LISTAGG(CASE WHEN ITR_TYPE = 'BP_RISK_BUILDING_BC_UW'     THEN payload END, '\n') AS UW,
  LISTAGG(CASE WHEN ITR_TYPE = 'BP_LOC_BC_CLAUSE'     THEN payload END, '\n') AS LOC_BC_CLAUSE,
  CAST(LOAD_DATE AS DATE) AS LOAD_DATE
FROM AGGNE.PRD.PA_RISK_Building_BC_TARGET
WHERE ITR_TYPE IN ('BP_Risk_Building_BC_Subcov', 'BP_RISK_BUILDING_BC_UW','BP_LOC_BC_CLAUSE') 
GROUP BY ID,CAST(LOAD_DATE AS DATE)
),
SUB_COV_PREM AS (
SELECT
  POLICYNUMBER,
BCHAL_ST,
BCLND_SD,
BCSTD_BF,
BCSTD_CY,
BCSTD_EQ,
BCSTD_ST
FROM (
  SELECT POLICYNUMBER, SUB_COVERAGE, EXPPREMIUM
  FROM AGGNE.PRD.Output_SubCover_BSP_Policyattach
) src
PIVOT (
  SUM(EXPPREMIUM) FOR SUB_COVERAGE IN (
    ('BCHAL_ST') AS BCHAL_ST,
    ('BCLND_SD') AS BCLND_SD,
    ('BCSTD_BF') AS BCSTD_BF,
    ('BCSTD_CY') AS BCSTD_CY,
    ('BCSTD_EQ') AS BCSTD_EQ,
    ('BCSTD_ST') AS BCSTD_ST
    )
) p
)
SELECT distinct 
T1.PUREPOLICYNUMBER AS LEGACYPOLICYNUMBER,
T1.ID AS PUREPOLICYNUMBER,
COVERAGE,CAST(SUBCOV AS VARCHAR) AS SUBCOV,
CAST(UW AS VARCHAR) AS UW,
CASE WHEN LOC_BC_CLAUSE IS NOT NULL AND LOC_BC_CLAUSE<> '' THEN '<Clauses><Type>ContentsAndStocks</Type>'||CAST(LOC_BC_CLAUSE AS VARCHAR)||'</Clauses>' ELSE '' END AS LOC_BC_CLAUSE,
-- CAST(LOC_BC_CLAUSE AS VARCHAR) AS LOC_BC_CLAUSE,
 CAST(CAST(COALESCE(VOLUNTARYEXCESS,0) AS NUMBER(20,0)) AS VARCHAR) AS VOLUNTARYEXCESS,
 CAST(CAST(COALESCE(CONTENTSLIMIT,0) AS NUMBER(20,0))AS VARCHAR) AS CONTENTSLIMIT,
 -- CAST(CAST(0 AS NUMBER(20,0))AS VARCHAR) AS EARTHQUAKEEXCESS,
 CAST(CAST(REPLACE(REPLACE(EARTHQUAKEEXCESS, '$', ''), ',', '') AS NUMBER)AS VARCHAR) AS EARTHQUAKEEXCESS,
 CAST(CAST(COALESCE(FLOODEXCESS,0) AS NUMBER(20,0)) AS VARCHAR)  AS FLOODEXCESS,
  CAST(CAST(COALESCE(HAILDAMAGEEXCESS,0) AS NUMBER(20,0)) AS VARCHAR)  AS HAILDAMAGEEXCESS,
 CAST(CAST(COALESCE(STANDARDEXCESS,0) AS NUMBER(20,0)) AS VARCHAR) AS STANDARDEXCESS,
 CAST(CAST(COALESCE(IMPOSEDEXCESS,0) AS NUMBER(20,0)) AS VARCHAR) AS IMPOSEDEXCESS,
CAST(CAST(COALESCE(BUSINESSCONTENTS_IND,0) AS NUMBER(20,0)) AS VARCHAR) AS BUSINESSCONTENTS_IND ,
CAST(CAST(PROPORTIONOFHAILNETTING AS NUMBER(20,0)) AS VARCHAR) AS PROPORTIONOFHAILNETTING,
 CAST(CAST(COALESCE(T4.BCCLMCNT,0) AS NUMBER(20,0)) AS VARCHAR) AS BCCLMCNT,
 CAST(CAST(COALESCE(T4.BCCLMINCD,0) AS NUMBER(20,0)) AS VARCHAR) AS  BCCLMINCD,
 CAST(COALESCE(T4.BCEXPPREM,0) AS VARCHAR) AS  BCEXPPREM,
cast(cast(COALESCE(HAILDAMAGE,0) AS NUMBER(20,0)) as varchar) AS HAILDAMAGE,
 CAST(COALESCE(CAST(BCHAL_ST AS NUMBER(36,3)),0)AS VARCHAR) AS EXP_PREM_BCHAL_ST,
 CAST(COALESCE(CAST(BCLND_SD AS NUMBER(36,3)),0)AS VARCHAR) AS EXP_PREM_BCLND_SD,
 CAST(COALESCE(CAST(BCSTD_BF AS NUMBER(36,3)),0)AS VARCHAR) AS EXP_PREM_BCSTD_BF,
 CAST(COALESCE(CAST(BCSTD_CY AS NUMBER(36,3)),0)AS VARCHAR) AS EXP_PREM_BCSTD_CY,
 CAST(COALESCE(CAST(BCSTD_EQ AS NUMBER(36,3)),0)AS VARCHAR) AS EXP_PREM_BCSTD_EQ,
 CAST(COALESCE(CAST(BCSTD_ST AS NUMBER(36,3)),0)AS VARCHAR) AS EXP_PREM_BCSTD_ST,
 CAST(GETDATE() AS DATE) AS LOAD_DATE
 FROM CTE_EXCESS T1
--  INNER JOIN  AGGNE.PRD.RISK_BUILDING_BC_TARGET T2
-- ON T1.PUREPOLICYNUMBER=T2.ID
LEFT JOIN CTE_LISTAGG T3 ON T1.ID = T3.ID 
LEFT JOIN AGGNE.PRD.Output_Coverage_BSP_Policyattach T4 
ON  TRIM(T1.PUREPOLICYNUMBER)=TRIM(T4.POLICYNUMBER) AND TRIM(T1.EXPIRINGID_P)=TRIM(T4.EXPIRINGID_P)
LEFT JOIN SUB_COV_PREM T5 ON TRIM(T1.PUREPOLICYNUMBER)=TRIM(T5.POLICYNUMBER) 
WHERE   COVERAGE='ContentsAndStocks';