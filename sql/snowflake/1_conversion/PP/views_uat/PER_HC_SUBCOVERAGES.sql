-- Template (seq 10 ConversionScript):
--   <coverage>
--       <Type>{TYPE}</Type>
--       <limit><Type>{TYPE}</Type><iValue>{IVALUE}</iValue></limit>
--       <Indicator>1</Indicator>          ← hardcoded in template, INDICATOR col unused
--       {SVALUE}                          ← column MUST include the XML tags
--       <Code>{CODE}</Code>
--       <Description>{DESCRIPTION}</Description>
--       <Premium>{EXP_PREM}</Premium>
--   </coverage>
--
-- Each UNION ALL block = one sub-coverage type per policy.
-- All rows are aggregated by CTE_LISTAGG in PER_HOME_BUILDING_PAYLOAD
-- into {SUBCOV} which is substituted into the seq 7 and seq 13 payloads.
--
-- NOTE (PL101 cross-check, 2026-06-25):
--   SpecifiedItemsPremises and UnspecifiedItemsAwayPremises are DIRECT FIELDS
--   on the seq 13 template (tokens {SPECIFIEDITEMSAWAY} and {UNSPECIFIEDITEMSAWAY}),
--   NOT sub-coverage blocks.  They are sourced from PER_HOME_BUILDING_PAYLOAD,
--   not from this view.  Adding HCSPE_AW / HCUNS_AW UNION ALL blocks here
--   would produce spurious <coverage> nodes in the payload.
-- ============================================================

