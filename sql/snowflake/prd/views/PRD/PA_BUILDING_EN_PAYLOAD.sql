create or replace view PA_BUILDING_EN_PAYLOAD(
	PUREPOLICYNUMBER,
	COVERAGE,
	SUBCOV,
	UW,
	LOC_EN_CLAUSE,
	EQUIPMENTREGULAR,
	ENGINEERING_IND,
	AVERAGEAGEOFEQUIPMENT,
	AGEOFTHEOLDEST,
	ENCLMCNT,
	ENCLMINCD,
	ENEXPPREM,
	STANDARDEXCESS,
	IMPOSEDEXCESS,
	VOLUNTARYEXCESS,
	LOAD_DATE
) as
 with cte_SAMPLE_CBP_LOCATION as
(
select distinct T1.PUREPOLICYNUMBER,T1.cmlnumber,T1.EXPIRINGID,T1.INSURANCE_FILE_CNT ,T1.ID from AGGNE.PRD.LOCATION_01_POLICYATTACH_IDENTIFIER T1 INNER JOIN AGGNE.PRD.SAMPLE_POLICYATTACH_FINAL_IDENTIFIER T2 ON T1.ID=T2.ID
),cte_COVERAGES as 
(
select distinct ID,PUREPOLICYNUMBER,cmlnumber,EXPIRINGID_P,INSURANCE_FILE_CNT,'EN' AS CLAUSE,'Engineering' AS  COVERAGE, CAST("ENCWEQUIPMENTMAINTENANCE" AS VARCHAR) AS EQUIPMENTREGULAR,
CAST(ENGINEERING_IND AS VARCHAR) AS ENGINEERING_IND ,
CAST(AVERAGEAGEOFEQUIPMENT AS VARCHAR) AS AVERAGEAGEOFEQUIPMENT,
CAST(cast(COALESCE(STANDARDEXCESS, 0) AS NUMBER(10,0)) AS VARCHAR) AS  STANDARDEXCESS,
 CAST(cast(COALESCE(IMPOSEDEXCESS, 0) AS NUMBER(10,0)) AS VARCHAR) AS  IMPOSEDEXCESS,
  CAST(cast(COALESCE(VOLUNTARYEXCESS, 0) AS NUMBER(10,0)) AS VARCHAR) AS  VOLUNTARYEXCESS,
CAST(AGEOFTHEOLDEST AS VARCHAR) AS AGEOFTHEOLDEST
FROM AGGNE.PRD.LOCATION_EN_COVERAGE_POLICYATTACH_IDENTIFIER T1 
) 
, CTE_EXCESS AS(
SELECT 
T2.ID AS PUREPOLICYNUMBER,
t2.PUREPOLICYNUMBER AS LEGACYPOLICYNUMBER,T2.cmlnumber,T2.EXPIRINGID_P,COVERAGE,CAST(EQUIPMENTREGULAR AS VARCHAR) AS EQUIPMENTREGULAR,
CAST(ENGINEERING_IND AS VARCHAR) AS ENGINEERING_IND ,
CAST(AVERAGEAGEOFEQUIPMENT AS VARCHAR) AS AVERAGEAGEOFEQUIPMENT,
CAST(cast(COALESCE(STANDARDEXCESS, 0) AS NUMBER(10,0)) AS VARCHAR) AS  STANDARDEXCESS,
 CAST(cast(COALESCE(IMPOSEDEXCESS, 0) AS NUMBER(10,0)) AS VARCHAR) AS  IMPOSEDEXCESS,
  CAST(cast(COALESCE(VOLUNTARYEXCESS, 0) AS NUMBER(10,0)) AS VARCHAR) AS  VOLUNTARYEXCESS,
CAST(AGEOFTHEOLDEST AS VARCHAR) AS AGEOFTHEOLDEST
FROM  
cte_SAMPLE_CBP_LOCATION T1 
INNER JOIN cte_COVERAGES T2 ON T1.ID=T2.ID
)
,CTE_LISTAGG AS(
SELECT
  ID,
  LISTAGG(CASE WHEN ITR_TYPE = 'BP_Risk_Building_EN_Subcov' THEN payload END, '\n') AS SUBCOV,
  LISTAGG(CASE WHEN ITR_TYPE = 'BP_RISK_BUILDING_EN_UW'     THEN payload END, '\n') AS UW,
  LISTAGG(CASE WHEN ITR_TYPE = 'BP_LOC_EN_CLAUSE'     THEN payload END, '\n') AS LOC_EN_CLAUSE,
  CAST(LOAD_DATE AS DATE) AS LOAD_DATE
FROM AGGNE.PRD.PA_RISK_BUILDING_EN_TARGET
WHERE ITR_TYPE IN ('BP_Risk_Building_EN_Subcov', 'BP_RISK_BUILDING_EN_UW','BP_LOC_EN_CLAUSE') 
GROUP BY ID,CAST(LOAD_DATE AS DATE)
)
SELECT distinct 
T1.PUREPOLICYNUMBER,
COVERAGE,CAST(SUBCOV AS VARCHAR) AS SUBCOV,
CAST(UW AS VARCHAR) AS UW,
CASE WHEN LOC_EN_CLAUSE IS NOT NULL AND LOC_EN_CLAUSE<> '' THEN '<Clauses><Type>Engineering</Type>'||CAST(LOC_EN_CLAUSE AS VARCHAR)||'</Clauses>' ELSE '' END AS LOC_EN_CLAUSE,
-- CAST(LOC_EN_CLAUSE AS VARCHAR) AS LOC_EN_CLAUSE,
 CAST(EQUIPMENTREGULAR AS VARCHAR) AS EQUIPMENTREGULAR,
CAST(cast(COALESCE(ENGINEERING_IND,0)as NUMBER(10,0) )AS VARCHAR) AS ENGINEERING_IND ,
CAST(AVERAGEAGEOFEQUIPMENT AS VARCHAR) AS AVERAGEAGEOFEQUIPMENT,
CAST(AGEOFTHEOLDEST AS VARCHAR) AS AGEOFTHEOLDEST,
CAST(COALESCE(T4.ENCLMCNT,0 )AS VARCHAR) AS ENCLMCNT,
CAST(COALESCE(T4.ENCLMINCD,0) AS VARCHAR) AS ENCLMINCD,
CAST(COALESCE(T4.ENEXPPREM,0) AS VARCHAR) AS ENEXPPREM,
CAST(cast(COALESCE(STANDARDEXCESS, 0) AS NUMBER(10,0)) AS VARCHAR) AS  STANDARDEXCESS,
 CAST(cast(COALESCE(IMPOSEDEXCESS, 0) AS NUMBER(10,0)) AS VARCHAR) AS  IMPOSEDEXCESS,
  CAST(cast(COALESCE(VOLUNTARYEXCESS, 0) AS NUMBER(10,0)) AS VARCHAR) AS  VOLUNTARYEXCESS,
CAST(GETDATE() AS DATE) AS LOAD_DATE
 FROM CTE_EXCESS T1
 -- INNER JOIN  AGGNE.PRD.RISK_BUILDING_EN_TARGET T2 ON T1.PUREPOLICYNUMBER=T2.ID
LEFT JOIN CTE_LISTAGG T3 ON T1.PUREPOLICYNUMBER = T3.ID 
LEFT JOIN AGGNE.PRD.VW_OUTPUT_COVERAGE_BSP_policyattach T4 
ON CAST(trim(T1.LEGACYPOLICYNUMBER) ||'|' || TRIM(T1.cmlnumber) ||'|' || TRIM(T1.EXPIRINGID_P) AS VARCHAR)=CAST(trim(T4.POLICYNUMBER) ||'|' || TRIM(T4.cmlnumber) ||'|' || TRIM(T4.EXPIRINGID_P) AS VARCHAR)
WHERE   COVERAGE='Engineering';