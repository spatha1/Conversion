create or replace view PA_BUILDING_FINAL_AGG(
	ACTUALID,
	PAYLOAD,
	LOAD_DATE
) as 
SELECT distinct
  TRIM(ACTUALID) AS ACTUALID,
  LISTAGG(distinct CASE WHEN ITR_TYPE = 'BP_RISK_Building' THEN payload END, '\n') AS PAYLOAD,
  CAST(T1.LOAD_DATE AS DATE) AS LOAD_DATE
FROM AGGNE.PRD.PA_RISK_BUILDING_FINAL_TARGET T1 INNER JOIN AGGNE.PRD.PA_RISK_BUILDING_FINAL T2 ON T1.ID=T2.PUREPOLICYNUMBER
WHERE ITR_TYPE IN ('BP_RISK_Building')
GROUP BY TRIM(ACTUALID),CAST(T1.LOAD_DATE AS DATE);