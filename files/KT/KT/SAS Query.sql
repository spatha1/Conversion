CREATE OR REPLACE temp TABLE AGGNE.DEV.POLICYATTACH_SAS_COVERENDDATE_SCENARIO1 AS
   SELECT DISTINCT
        
        PUREPOLICYNUMBER,
        INSURANCE_FILE_CNT,
        CoverStartDate,
		RN3,
		PUREExpiryDate,
		CoverEndDate_pre,
    Pol_type_adj  ,RISK_FOLDER_CNT,RISK_ADDRESS,POLICY_BINDER_ID,
        CASE
            WHEN rn3 = 1
                 AND COALESCE(LagPolType, '__NOT_MTA__') <> 'MTA Cancelled'
                THEN PUREExpiryDate
            WHEN LagPolType = 'MTA Cancelled'
                THEN CoverEndDate_pre
            ELSE DATEADD(DAY, -1, CoverEndDate_pre)
        END AS CoverEndDate      
    FROM AGGNE.DEV.POLICYATTACH_SAS_FINAL_SCENARIO1;


