create or replace view LINE_GP_SPECIFIEDTOOLS(
	PUREPOLICYNUMBER,
	LEGACYPOLICYNUMBER,
	VALUE,
	DESCRIPTION
) as
SELECT
    CAST(trim(PUREPOLICYNUMBER) ||'|' || TRIM(cmlnumber) ||'|' || TRIM(EXPIRINGID_P) AS VARCHAR) AS PUREPOLICYNUMBER,
    PUREPOLICYNUMBER AS LEGACYPOLICYNUMBER,
    cast(COALESCE(VALUE ,0)as varchar) AS VALUE,
    CAST(DESCRIPTION AS VARCHAR) AS DESCRIPTION
    FROM 
    AGGNE.DEV.LINE_GP_COVERAGE WHERE  EXPIRYDATE>='2026-01-01';