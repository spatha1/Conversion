  CASE
    WHEN CMLNUMBER = 'CML00021661' THEN '152/156 Parramatta Rd'
    WHEN CMLNUMBER = 'CML00000835' THEN '18 Petunia Street'
    WHEN CMLNUMBER = 'CML00028873' THEN '19 London Street'
