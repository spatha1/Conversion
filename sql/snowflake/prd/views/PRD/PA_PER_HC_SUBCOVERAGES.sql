SELECT DISTINCT
ID AS PUREPOLICYNUMBER,
T1.PUREPOLICYNUMBER AS LEGACYPOLICYNUMBER,
    T1.cmlnumber,
    T1.EXPIRINGID_P AS Coverage,
    'Building' AS CoverageType,
    'Standard' AS Description,
    'CNT_SD' AS Type,
    'HCCNT_SD' AS CODE,
    CAST(CAST(COALESCE(HOMECONTENTSLIMIT_NEW,0) AS NUMBER(10,0)) AS VARCHAR)   AS IVALUE,
     '' AS SVALUE,
    CAST(CAST(1 AS NUMBER(1,0)) AS VARCHAR) AS INDICATOR,
    CASE WHEN SUB_COVERAGE='HCCNT_SD' THEN CAST(CAST(COALESCE(EXPPREMIUM ,0) AS NUMBER(36,3)) AS VARCHAR) ELSE cast(0 as varchar)
    END AS EXP_PREM
FROM AGGNE.PRD.HC_02_Policyattach_IDENTIFIER
 T1 LEFT JOIN  AGGNE.PRD.Output_SubCover_PER_Policyattach T2 
ON trim(T1.PUREPOLICYNUMBER)=trim(T2.policynumber) 
and t1.EXPIRINGID_P=T2.EXPIRINGID_P
 AND SUB_COVERAGE='HCCNT_SD' WHERE  COALESCE(HOMECONTENTSLIMIT_NEW,0)<>0

UNION ALL

