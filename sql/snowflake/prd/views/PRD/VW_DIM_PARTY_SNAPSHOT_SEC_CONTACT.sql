create or replace view VW_DIM_PARTY_SNAPSHOT_SEC_CONTACT(
	CATEGORY,
	USERNAME,
	PARTY_DIM_ID,
	BK_CMLNUMBER,
	MEMBER_TA_NUMBER,
	CSL_LEGAL_ENTITY,
	CML_RISK_ACCOUNT_MANAGER,
	CSL_AREA_MANAGER,
	CSL_ZONE,
	CSL_REGION,
	CSL_NUMBER,
	CML_LEGAL_ENTITY,
	CSL_MEMBER_STATUS,
	ABN_NZBN,
	STOP_CREDIT,
	STOP_CREDIT_REASON,
	CSL_TENURE,
	CSL_MONTHLY_SPEND,
	STANDARD_INDUSTRY_CODE,
	STANDARD_INDUSTRY_CODE_DESCRIPTION,
	CSL_CREDIT_LIMIT,
	CSL_CREDIT_RISK,
	CSL_CREDIT_USAGE,
	PROBABILITY_OF_DEFAULT,
	TA_PAYMENT_METHOD,
	STREET,
	SUBURB,
	STATE,
	POSTCODE,
	CONTACT_NAME,
	PHONE,
	EMAIL,
	SITE_COUNTRY,
	MESSAGE,
	CMLNUMBER,
	COUNTRY,
	CMLLEGALENTITY,
	CMLTRADINGNAME,
	MAINCONTACT,
	CORRESPONDENCELINE1,
	CORRESPONDENCELINE2,
	CORRESPONDENCELINE3,
	CORRESPONDENCELINE4,
	LOCATIONSTATECODE,
	CORRESPONDENCEPOSTCODE,
	SITE_STREET,
	SITE_SUBURB,
	SITE_STATE,
	SITE_POSTCODE,
	CSLNUMBER,
	PHONE_DETAILS,
	PRIMARY_PHONE,
	PRIMARY_PHONE_TYPE,
	PRIMARY_EMAIL,
	PRIMARY_EMAIL_TYPE,
	PHONE_COUNT,
	EMAIL_COUNT,
	PAID2DATE,
	MEM_REF,
	EFFECTIVE_DATE,
	AMOUNT,
	SECONDARYCONTACT_XMLDATA,
	EMAIL_XMLDATA,
	PHONE_XMLDATA,
	HASH_DIFF,
	EFFECTIVE_FROM,
	EFFECTIVE_TO,
	IS_CURRENT,
	ACTIVE_FLAG,
	LOAD_DATE
) as
SELECT
CASE WHEN otheremail != '' and otherphone != '' THEN 'MULTICONTACT(ACTIVE/INACTIVE)' ELSE 'SINGLE(ACTIVE/INACTIVE)' END AS CATEGORY,
concat('ConversionUser'::varchar,(ROW_NUMBER()Over(order by PARTY_DIM_ID)%5)+1 )as USERNAME,
    PARTY_DIM_ID ,
	BK_CMLNUMBER ,
	MEMBER_TA_NUMBER ,
	REPLACE(CSL_LEGAL_ENTITY,'&','&amp;') AS CSL_LEGAL_ENTITY  ,
	REPLACE(CML_RISK_ACCOUNT_MANAGER,'&','&amp;')  AS CML_RISK_ACCOUNT_MANAGER,
	REPLACE(CSL_AREA_MANAGER,'&','&amp;')as  CSL_AREA_MANAGER,
	-- trim(upper(REPLACE(CSL_ZONE,'&','&amp;'))) as CSL_ZONE,
	trim(REPLACE(CSL_ZONE,'&','&amp;')) as CSL_ZONE,    
	trim(upper(REPLACE(CSL_REGION,'&','&amp;')))as CSL_REGION,
	CSL_NUMBER ,
	REPLACE(CML_LEGAL_ENTITY,'&','&amp;')as CML_LEGAL_ENTITY ,
	CSL_MEMBER_STATUS ,
	ABN_NZBN ,
	STOP_CREDIT ,
	REPLACE(STOP_CREDIT_REASON,'&','&amp;')as STOP_CREDIT_REASON , 
	CSL_TENURE ,
	CSL_MONTHLY_SPEND ,
	STANDARD_INDUSTRY_CODE ,
	REPLACE(STANDARD_INDUSTRY_CODE_DESCRIPTION,'&','&amp;') as STANDARD_INDUSTRY_CODE_DESCRIPTION,
	CSL_CREDIT_LIMIT ,
	CSL_CREDIT_RISK ,
	CSL_CREDIT_USAGE ,
	PROBABILITY_OF_DEFAULT ,
	TA_PAYMENT_METHOD ,
	REPLACE(STREET,'&','&amp;') as STREET,
	trim(upper(REPLACE(SUBURB,'&','&amp;')))as SUBURB,
	trim(upper(STATE)) AS STATE ,
	trim(upper(POSTCODE)) AS POSTCODE ,
	REPLACE(CONTACT_NAME,'&','&amp;') CONTACT_NAME,
	PHONE ,
	REPLACE(EMAIL,'&','&amp;') as EMAIL,
    CASE
    WHEN TRIM(SITE_COUNTRY) = 'New Zealand' THEN 'NZ'
    WHEN TRIM(SITE_COUNTRY) = 'Australia' THEN 'AU'
    ELSE TRIM(SITE_COUNTRY)
  END AS SITE_COUNTRY,
	REPLACE(MESSAGE,'&','&amp;') as MESSAGE,
	CMLNUMBER ,
	CASE
    WHEN TRIM(COUNTRY) = 'New Zealand' THEN 'NZ'
    WHEN TRIM(COUNTRY) = 'Australia' THEN 'AU'
    ELSE TRIM(COUNTRY)
  END AS COUNTRY,
	REPLACE(CMLLEGALENTITY,'&','&amp;')as CMLLEGALENTITY,
	REPLACE(CMLTRADINGNAME,'&','&amp;')as CMLTRADINGNAME ,
	REPLACE(MAINCONTACT,'&','&amp;')as MAINCONTACT,
	REPLACE(CORRESPONDENCELINE1,'&','&amp;')as  CORRESPONDENCELINE1,
	REPLACE(CORRESPONDENCELINE2,'&','&amp;') as CORRESPONDENCELINE2,
	trim(upper(REPLACE(CORRESPONDENCELINE3,'&','&amp;'))) as CORRESPONDENCELINE3,
    CASE
    WHEN TRIM(COUNTRY) = 'New Zealand' THEN UPPER(CORRESPONDENCELINE4)
    WHEN TRIM(COUNTRY) = 'Australia' THEN trim(upper(CONCAT(CORRESPONDENCELINE4, 'AU')))
    ELSE CORRESPONDENCELINE4
  END AS CORRESPONDENCELINE4,
   CASE
    WHEN TRIM(COUNTRY) = 'New Zealand' THEN '100'
    WHEN TRIM(COUNTRY) = 'Australia' THEN trim(upper(CONCAT(CORRESPONDENCELINE4, 'AU')))
    ELSE CORRESPONDENCELINE4
  END AS LOCATIONSTATECODE,
	CORRESPONDENCEPOSTCODE ,
	REPLACE(SITE_STREET,'&','&amp;')SITE_STREET , 
	trim(upper(SITE_SUBURB )) AS SITE_SUBURB,
	CASE
    WHEN TRIM(COUNTRY) = 'New Zealand' THEN trim(upper(SITE_STATE))
    WHEN TRIM(COUNTRY) = 'Australia' THEN trim(upper(CONCAT(SITE_STATE, 'AU')))
    ELSE trim(upper(SITE_STATE)) 
  END AS SITE_STATE,
	trim(upper(SITE_POSTCODE)) AS SITE_POSTCODE,
	CSLNUMBER ,
    LEFT(PRIMARY_PHONE, 2)  AS PHONE_DETAILS,
	PRIMARY_PHONE ,
	PRIMARY_PHONE_TYPE ,
	PRIMARY_EMAIL ,
	PRIMARY_EMAIL_TYPE ,
	PHONE_COUNT ,
	EMAIL_COUNT ,
	-- SECONDARYCONTACT_COUNT ,
	-- SECONDARYCONTACT ARRAY,
	-- SECONDARYCONTACTKEY ,
	TO_CHAR(PAID2DATE::DATE, 'YYYY-MM-DD')as PAID2DATE ,
	MEM_REF ,
	TO_CHAR(EFFECTIVE_DATE::DATE, 'YYYY-MM-DD')as EFFECTIVE_DATE ,
	AMOUNT ,
   REPLACE(REPLACE(SECONDARYCONTACT_XMLDATA,'&','&amp;'),'{LOAD_DATE}',TO_CHAR(CURRENT_DATE::DATE, 'YYYY-MM-DD'))  AS SECONDARYCONTACT_XMLDATA,
   REPLACE(EMAIL_XMLDATA,'{LOAD_DATE}',TO_CHAR(CURRENT_DATE::DATE, 'YYYY-MM-DD')) AS EMAIL_XMLDATA ,
   PHONE_XMLDATA,
	HASH_DIFF ,
	EFFECTIVE_FROM ,
	EFFECTIVE_TO ,
	IS_CURRENT ,
	ACTIVE_FLAG ,
    TO_VARCHAR(CURRENT_TIMESTAMP(), 'YYYY-MM-DD') AS LOAD_DATE
FROM AGGNE.PRD.DIM_PARTY_SNAPSHOT_ACTIVE_INACTIVE_MEMBERS_SCD2 WHERE IS_CURRENT=FALSE ;