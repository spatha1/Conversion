-- ...paste updated seq 18 ConversionScript here...
-- </risk>$$,
--     'AGGNE.DEV.PER_COM_COVERAGES_TARGET',
--     'RISK_Building_PM'
-- );


-- ── Step 6: Verify new payload — no stale tokens ─────────────────────────
SELECT ID, LEFT(PAYLOAD, 500) AS PAYLOAD_PREVIEW
FROM   AGGNE.DEV.PER_COM_COVERAGES_TARGET
WHERE  ITR_TYPE = 'RISK_Building_PM'
  AND  ID LIKE '%P00012922%';
-- Payload should NOT contain {IMPOSEDEXCESS}, {STANDARDEXCESS} etc.
-- {COM_CLAUSE} and {UW} should be replaced with actual content.


-- ── Step 7: Check for any remaining tokens in new payload ────────────────
SELECT COUNT(*) AS POLICIES_WITH_TOKENS
FROM   AGGNE.DEV.PER_COM_COVERAGES_TARGET
WHERE  ITR_TYPE = 'RISK_Building_PM'
  AND  PAYLOAD  LIKE '%{%}%';
-- Expected: 0


-- ── Step 8: Regenerate final XML ─────────────────────────────────────────
CALL AGGNE.DEV.PER_CONVERSION_FINAL_LOAD();
CALL AGGNE.DEV.PER_CONVERSION_FINAL_XML();


-- ── Step 9: Final token check across all policies ────────────────────────
SELECT LEGACYPOLICYNUMBER,
       CASE WHEN REQUEST_XML LIKE '%{%}%' THEN 'TOKENS REMAIN' ELSE 'CLEAN' END AS STATUS,
       REGEXP_COUNT(REQUEST_XML, '\\{[^}]+\\}') AS TOKEN_COUNT
FROM   AGGNE.DEV.PER_POLICY_MIGRATION_DCT
WHERE  STATUS = 'TOKENS REMAIN'
   OR  REQUEST_XML LIKE '%{%}%'
ORDER  BY LEGACYPOLICYNUMBER;
-- Expected: 0 rows (all CLEAN after motor fix)
