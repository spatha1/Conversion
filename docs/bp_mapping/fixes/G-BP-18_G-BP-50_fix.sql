SELECT SequenceID, ScriptName,
       LEN(ConversionScript) - LEN(REPLACE(ConversionScript, '<Indicator>1</Indicator>', '')) AS HARDCODED_IND1_CHARS,
       CASE WHEN CHARINDEX('<sValue>Taken</sValue>', ConversionScript) > 0 THEN 'PRESENT' ELSE 'MISSING' END AS DFW_SVALUE_HARDCODE
FROM dbo.ConversionConfig
WHERE SequenceID = 11 AND ScriptName = 'BP_LINE_PPL';
-- Expect HARDCODED_IND1_CHARS = 100 (4 * LEN('<Indicator>1</Indicator>') = 4*25), DFW_SVALUE_HARDCODE = 'PRESENT'

-- UPDATE
UPDATE dbo.ConversionConfig
SET ConversionScript = REPLACE(
        REPLACE(ConversionScript,
            '<Indicator>1</Indicator>', '<Indicator>{PROTECTIONTYPESTANDARD}</Indicator>'),
        '<sValue>Taken</sValue>', '<sValue>{PROTECTIONTYPESTANDARD_IND}</sValue>')
WHERE SequenceID = 11 AND ScriptName = 'BP_LINE_PPL'
  AND CHARINDEX('<Indicator>1</Indicator>', ConversionScript) > 0
  AND CHARINDEX('<sValue>Taken</sValue>', ConversionScript) > 0;

