create or replace view PA_PER_ACCOUNT_LOC_AGG(
	ID,
	AOI,
	LOAD_DATE
) as 
WITH cte1 AS (
  SELECT DISTINCT
         *
  FROM AGGNE.PRD.PA_PER_ACCOUNT_LOC_TARGET
  WHERE  ITR_TYPE = 'ACC_LOC'
),
acc AS (
  SELECT DISTINCT
         *
  FROM AGGNE.PRD.PA_PER_ACCOUNT_LOC
)
SELECT
  A.ACTUALID AS ID,
  LISTAGG(t1.payload, '\n') WITHIN GROUP (ORDER BY a.RISKNUMBER) AS AOI,
  t1.LOAD_DATE
FROM cte1 t1
JOIN acc a
  ON a.PUREPOLICYNUMBER = t1.ID 
GROUP BY t1.LOAD_DATE,A.ACTUALID
ORDER BY A.ACTUALID, t1.LOAD_DATE;