ON  TRIM(T1.LEGACYPOLICYNUMBER) = SPLIT_PART(TRIM(T17.ID), '|', 1) AND T17.ITR_TYPE='Line_LE' AND   T17.load_date in (select max(load_date) as load_date  from AGGNE.DEV.LINE_LE_Target)
