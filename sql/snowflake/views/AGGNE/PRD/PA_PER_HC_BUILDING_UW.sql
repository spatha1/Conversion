create or replace view PA_PER_HC_BUILDING_UW(
	PUREPOLICYNUMBER,
	LEGACYPOLICYNUMBER,
	EXPIRINGID_P,
	INSURANCE_FILE_CNT,
	RECURRINGINDICATOR,
	UNDERWRITINGDESCRIPTION,
	ADJUSTMENTDOLLARANDPERCENT,
	ADJUSTMENTSELECTION,
	COVERAGE
) as
SELECT DISTINCT
    ID  AS PUREPOLICYNUMBER,
    CAST(T1.PolicyNumber AS VARCHAR) AS LEGACYPOLICYNUMBER,
    CAST(T1.EXPIRINGID_P AS VARCHAR) AS EXPIRINGID_P,
    CAST(T2.INSURANCE_FILE_CNT AS VARCHAR) AS INSURANCE_FILE_CNT,
    CAST('1'  AS VARCHAR)AS RECURRINGINDICATOR,
    CAST(REPLACE(REPLACE(T1.UWADJUSTNOTE,  '&', '&amp;'),'''', '''''') AS VARCHAR) AS UnderwritingDescription,
    CAST(T1.UWADJUSTAMOUNT AS VARCHAR) AS AdjustmentDollarAndPercent,
    CAST('1'  AS VARCHAR)AS AdjustmentSelection,
    CAST(T1.COVERAGE AS VARCHAR) AS COVERAGE
FROM AGGNE.PRD.Output_UWAdjust_PER_Policyattach T1
INNER JOIN AGGNE.PRD.HC_02_Policyattach_IDENTIFIER T2
    ON trim(T2.PUREPOLICYNUMBER) = trim(T1.PolicyNumber)
    AND T1.EXPIRINGID_P = T2.EXPIRINGID_P
    WHERE COVERAGE='HC' AND UWADJUSTAMOUNT IS NOT NULL;