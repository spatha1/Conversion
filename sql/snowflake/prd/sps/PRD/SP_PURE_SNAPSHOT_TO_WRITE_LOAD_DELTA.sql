update AGGNE.PRD.DIM_PARTY_SNAPSHOT_ACTIVE_INACTIVE_MEMBERS_SCD2_DELTA t1 set CORRESPONDENCELINE3=trim(upper(t2."DCValue")) from AGGNE.UAT.SUBURB_LOOKUP t2 where trim(upper(t1.CORRESPONDENCELINE3))=trim(upper(t2.site_suburb));

