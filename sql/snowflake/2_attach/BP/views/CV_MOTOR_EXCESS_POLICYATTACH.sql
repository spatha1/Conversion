create or replace view CV_MOTOR_EXCESS_POLICYATTACH(
	PUREPOLICYNUMBER,
	PUREPOLICYNUMBER_ACTUAL,
	CMLNUMBER,
	LEGACYPOLICYNUMBER,
	EXPIRINGID_P,
	VEHICLEID,
	TYPE,
	FLEETTYPE,
	VOLUNTARYEXCESS,
	STANDARDEXCESS,
	IMPOSEDEXCESS,
	ONHOOKTOWINGPROTECTION,
	CMCVAGE17,
	CMCVAGE19,
	CMCVAGE21,
	CMCVAGE25
) as 
select
   CAST(TRIM(ID) || '|' || TRIM(vehicleid) AS VARCHAR ) AS PUREPOLICYNUMBER,
    ID AS PUREPOLICYNUMBER_actual,
    cmlnumber,
    purepolicynumber AS legacypolicynumber,
    expiringid_p,
    CAST(vehicleid AS VARCHAR) AS vehicleid,
    'CommercialVehicle' as Type,
    'Default' as FleetType,
    CAST(CAST(T1.CMCVVOLUNTARY AS INT) AS VARCHAR) AS VOLUNTARYEXCESS,
    CAST(CAST(standardexcess AS INT) AS VARCHAR) AS standardexcess,
    CAST(CAST(imposedexcess AS INT) AS VARCHAR) AS imposedexcess,
    CAST(CAST(CMCVHOOKLIABEXCESS AS INT) AS VARCHAR) AS onhooktowingprotection,
    CAST(CAST(T1.CMCVAGE17 AS INT) AS VARCHAR) AS CMCVAGE17,
    CAST(CAST(T1.CMCVAGE19 AS INT) AS VARCHAR) AS CMCVAGE19,
    CAST(CAST(T1.CMCVAGE21 AS INT) AS VARCHAR) AS CMCVAGE21,
    CAST(CAST(T1.CMCVAGE25 AS INT) AS VARCHAR) AS CMCVAGE25
from
    AGGNE.PRD.CM_03_POLICYATTACH_IDENTIFIER T1;