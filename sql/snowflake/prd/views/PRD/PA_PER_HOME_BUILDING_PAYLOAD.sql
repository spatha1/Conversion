create or replace view PA_PER_HOME_BUILDING_PAYLOAD(
	ACTUALID,
	PUREPOLICYNUMBER,
	COVERAGE,
	SUBCOV,
	UW,
	VOLUNTARYEXCESS,
	STANDARDEXCESS,
	IMPOSEDEXCESS,
	EARTHQUAKEEXCESS,
	FLOODEXCESS,
	ACCIDENTALLOSSORDAMAGE,
	HOMEBUILDINGSLIMIT,
	LANDLORDPROTECTIONS,
	MINIMUMRENTALPERIOD,
	WEEKLYRENT,
	HBCLMCNT,
	HBCLMINCD,
	HBEXPPREM,
	LOAD_DATE
) as
with cte_SAMPLE_CBP_LOCATION as
(
select distinct
trim(T1.PUREPOLICYNUMBER)AS PUREPOLICYNUMBER ,
trim(t1.CMLNUMBER) AS CMLNUMBER,T1.EXPIRINGID_P,
T1.INSURANCE_FILE_CNT,
T1.ID,
T1.ACTUALID,
from AGGNE.PRD.Locationdetails_PER_Policyattach_IDENTIFIER T1 
INNER JOIN AGGNE.PRD.Policyattach_PER_IDENTIFIER
T2 ON TRIM(T1.ID)=TRIM(T2.ID) 

),cte_COVERAGES as 
(
select distinct ID,ACTUALID,PUREPOLICYNUMBER,cmlnumber,EXPIRINGID_P,INSURANCE_FILE_CNT,'BB' AS CLAUSE,'Building' AS  COVERAGE, "VOLUNTARYEXCESS" AS VOLUNTARYEXCESS,STANDARDEXCESS,IMPOSEDEXCESS,EARTHQUAKEEXCESS,FLOODEXCESS,ACCIDENTALLOSSORDAMAGE,FLOODDAMAGE,
 CAST(CAST(COALESCE(HOMEBUILDINGSLIMIT,0) AS NUMBER(20,0))AS VARCHAR) as HOMEBUILDINGSLIMIT,
LANDLORDPROTECTIONS,
MINIMUMRENTALPERIOD,
CAST(CAST(WEEKLYRENT AS NUMBER(10,0))AS VARCHAR) AS WEEKLYRENT
from AGGNE.PRD.HB_02_Policyattach_IDENTIFIER T1 
) 
 , CTE_EXCESS AS(
SELECT 
 T1.ID AS PUREPOLICYNUMBER,
 T1.ID,T1.ACTUALID,
 T2.INSURANCE_FILE_CNT,
t2.PUREPOLICYNUMBER AS LEGACYPOLICYNUMBER,T2.cmlnumber,T2.EXPIRINGID_P,COVERAGE,T2.VOLUNTARYEXCESS,STANDARDEXCESS,IMPOSEDEXCESS,EARTHQUAKEEXCESS,FLOODEXCESS,
ACCIDENTALLOSSORDAMAGE,FLOODDAMAGE,
 CAST(CAST(COALESCE(HOMEBUILDINGSLIMIT,0) AS NUMBER(20,0))AS VARCHAR) as HOMEBUILDINGSLIMIT,
LANDLORDPROTECTIONS,
MINIMUMRENTALPERIOD,
CAST(CAST(WEEKLYRENT AS NUMBER(10,0))AS VARCHAR) AS WEEKLYRENT
FROM 
cte_SAMPLE_CBP_LOCATION T1 
INNER JOIN cte_COVERAGES T2 ON T1.ID=T2.ID AND T1.EXPIRINGID_P=T2.EXPIRINGID_P
)
,CTE_LISTAGG AS(
SELECT
  ID,
  LISTAGG(CASE WHEN ITR_TYPE = 'Building_SubCov' THEN payload END, '\n') AS SUBCOV,
  LISTAGG(CASE WHEN ITR_TYPE = 'BUILDING_UW' THEN payload END, '\n') AS UW,
  CAST(LOAD_DATE AS DATE) AS LOAD_DATE
FROM AGGNE.PRD.PA_PER_BUILDING_TARGET
WHERE ITR_TYPE IN ('Building_SubCov','BUILDING_UW')   
GROUP BY ID, CAST(LOAD_DATE AS DATE)
)
SELECT distinct 
T1.ACTUALID,
T1.PUREPOLICYNUMBER,
COVERAGE,
CAST(SUBCOV AS VARCHAR) AS SUBCOV,
CAST(UW AS VARCHAR) AS UW,
CAST(CAST(COALESCE(VOLUNTARYEXCESS,0)AS NUMBER(20,0)) AS VARCHAR) AS VOLUNTARYEXCESS,
CAST(CAST(COALESCE(STANDARDEXCESS,0)AS NUMBER(20,0)) AS VARCHAR) AS STANDARDEXCESS,
CAST(CAST(COALESCE(IMPOSEDEXCESS,0)AS NUMBER(20,0)) AS VARCHAR) AS IMPOSEDEXCESS,
CAST(CAST(COALESCE(EARTHQUAKEEXCESS,0)AS NUMBER(20,0)) AS VARCHAR) AS EARTHQUAKEEXCESS,
CASE WHEN FLOODDAMAGE='Taken' THEN CAST(CAST(COALESCE(FLOODEXCESS,0)AS NUMBER(20,0)) AS VARCHAR) ELSE CAST('0' AS VARCHAR) END AS FLOODEXCESS,
CASE WHEN ACCIDENTALLOSSORDAMAGE='Taken' then CAST(CAST(1 AS NUMBER(1,0)) AS VARCHAR)  ELSE CAST(CAST(0 AS NUMBER(1,0)) AS VARCHAR) END AS ACCIDENTALLOSSORDAMAGE,
 CAST(CAST(COALESCE(HOMEBUILDINGSLIMIT,0) AS NUMBER(20,0))AS VARCHAR) as HOMEBUILDINGSLIMIT,
CASE WHEN LANDLORDPROTECTIONS='Taken' then CAST(CAST(1 AS NUMBER(1,0)) AS VARCHAR)  ELSE CAST(CAST(0 AS NUMBER(1,0)) AS VARCHAR) END AS LANDLORDPROTECTIONS,
CASE WHEN MINIMUMRENTALPERIOD='More than 90 Days' THEN 'Morethan90Days' WHEN  MINIMUMRENTALPERIOD='Less than 90 Days' THEN 'Lessthan90Days'  ELSE MINIMUMRENTALPERIOD END AS MINIMUMRENTALPERIOD,
CAST(CAST(WEEKLYRENT AS NUMBER(10,0))AS VARCHAR) AS WEEKLYRENT,
CAST(COALESCE(T4.HBCLMCNT,0) AS VARCHAR) AS HBCLMCNT,
CAST(COALESCE(T4.HBCLMINCD,0) AS VARCHAR) AS HBCLMINCD,
CAST(COALESCE(T4.HMEXPPREM,0) AS VARCHAR) AS HBEXPPREM,
CAST(GETDATE() AS DATE) as LOAD_DATE
FROM CTE_EXCESS T1
-- LEFT JOIN  AGGNE.PRD.PER_BUILDING_TARGET T2 ON T1.PUREPOLICYNUMBER=T2.ID
LEFT JOIN CTE_LISTAGG T3 ON T1.PUREPOLICYNUMBER = T3.ID 
LEFT JOIN AGGNE.PRD.Output_Coverage_PER_Policyattach T4 ON trim(T1.LEGACYPOLICYNUMBER)=trim(T4.policynumber) AND T1.EXPIRINGID_P=T4.EXPIRINGID_P 
WHERE   COVERAGE='Building'  ;