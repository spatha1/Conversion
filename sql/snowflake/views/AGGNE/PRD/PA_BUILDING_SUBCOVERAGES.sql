create or replace view PA_BUILDING_SUBCOVERAGES(
	PUREPOLICYNUMBER,
	LEGACYPOLICYNUMBER,
	CMLNUMBER,
	COVERAGE,
	COVERAGETYPE,
	DESCRIPTION,
	TYPE,
	CODE,
	IVALUE,
	SVALUE,
	EXP_PREM
) as
SELECT  DISTINCT
ID AS PUREPOLICYNUMBER,
T1.PUREPOLICYNUMBER AS LEGACYPOLICYNUMBER,
    T1.cmlnumber,
    T1.EXPIRINGID_P AS Coverage,
    'Building' AS CoverageType,
    'Glass' AS Description,
    'GLS_SD' AS Type,
    'BBGLS_SD' AS Code,
   CASE  WHEN FIXEDGLASS='0' THEN CAST(0 AS VARCHAR)
WHEN FIXEDGLASS='0-10' THEN  CAST(5 AS VARCHAR)
WHEN FIXEDGLASS='11-20' THEN  CAST(15 AS VARCHAR)
WHEN FIXEDGLASS='21-30' THEN  CAST(25 AS VARCHAR)
WHEN FIXEDGLASS='31-40' THEN  CAST(35 AS VARCHAR)
WHEN FIXEDGLASS='41+' THEN  CAST(45 AS VARCHAR) ELSE  CAST(0 AS VARCHAR) END AS iValue,
    CONCAT('<sValue>',case when COALESCE(glass, '')='Not Taken' then 'NotTaken' ELSE COALESCE(glass, '') end , '</sValue>') AS sValue,
    CASE WHEN SUB_COVERAGE='BBGLS_SD' THEN CAST(CAST(COALESCE(EXPPREMIUM ,0) AS NUMBER(36,3)) AS VARCHAR) ELSE cast(0 as varchar) END AS EXP_PREM
FROM AGGNE.PRD.location_bb_coverage_policyattach_IDENTIFIER T1 LEFT JOIN  AGGNE.PRD.VW_OUTPUT_SUBCOVERAGE_BSP_POLICYATTACH T2 ON CAST(trim(T1.PUREPOLICYNUMBER) ||'|' || TRIM(T1.cmlnumber) ||'|' || TRIM(T1.EXPIRINGID_P) AS VARCHAR)=T2.PUREPOLICYNUMBER --AND T1.EXPIRINGID_P=T2.EXPIRINGID_P
AND SUB_COVERAGE='BBGLS_SD' WHERE COALESCE(glass, '')<>'Not Taken'

UNION ALL

SELECT DISTINCT
    ID AS PUREPOLICYNUMBER,
T1.PUREPOLICYNUMBER AS LEGACYPOLICYNUMBER,
    T1.cmlnumber,
    T1.EXPIRINGID_P AS Coverage,
    'Building' AS CoverageType,
    'Flood' AS Description,
    'FLD_SD' AS Type,
    'BBFLD_SD' AS Code,
    CAST(CAST(COALESCE("BBFLOODPROTECTION",0) AS NUMBER(20,0)) AS VARCHAR) AS iValue,
    CONCAT('<sValue>', case when COALESCE(flooddamage, '')='Not Taken' then 'NotTaken' ELSE COALESCE(flooddamage, '') end, '</sValue>') AS sValue,
    CASE WHEN SUB_COVERAGE='BBFLD_SD' THEN CAST(CAST(COALESCE(EXPPREMIUM ,0) AS NUMBER(36,3)) AS VARCHAR) ELSE cast(0 as varchar) END AS EXP_PREM
FROM AGGNE.PRD.location_bb_coverage_policyattach_IDENTIFIER T1 LEFT JOIN  AGGNE.PRD.VW_OUTPUT_SUBCOVERAGE_BSP_POLICYATTACH T2 ON CAST(trim(T1.PUREPOLICYNUMBER) ||'|' || TRIM(T1.cmlnumber) ||'|' || TRIM(T1.EXPIRINGID_P) AS VARCHAR)=T2.PUREPOLICYNUMBER --AND T1.EXPIRINGID_P=T2.EXPIRINGID_P
AND SUB_COVERAGE='BBFLD_SD' where COALESCE(flooddamage, '')<>'Not Taken'

UNION ALL

