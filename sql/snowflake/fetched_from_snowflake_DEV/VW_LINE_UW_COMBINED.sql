create or replace view VW_LINE_UW_COMBINED(
	LEGACYPOLICYNUMBER,
	UW,
	LOAD_DATE
) as 
SELECT
  T2.LEGACYPOLICYNUMBER AS LEGACYPOLICYNUMBER,
  LISTAGG(CASE WHEN ITR_TYPE = 'BP_Risk_Building_Combine_UW' THEN payload END, '\n') AS UW,
  CAST(LOAD_DATE AS DATE) AS LOAD_DATE
FROM AGGNE.DEV.RISK_BUILDING_FINAL_TARGET T1 LEFT JOIN AGGNE.DEV.VW_SAMPLE_FINAL T2 ON T1.ID=T2.ID
WHERE ITR_TYPE IN ('BP_Risk_Building_Combine_UW')
GROUP BY LEGACYPOLICYNUMBER,CAST(LOAD_DATE AS DATE);