create or replace view PER_HOME_BUILDING_PAYLOAD(
	PUREPOLICYNUMBER,
	COVERAGE,
	SUBCOV,
	HC_EXCEED_VALUES,
	HC_SPECIFIED_CONTENTS,
	VOLUNTARYEXCESS,
	ACCIDENTALLOSSORDAMAGE,
	SPECIFIEDITEMSAWAY,
	UNSPECIFIEDITEMSAWAY,
	UNSPECIFIEDITEMSAWAYLIMIT,
	HCCLMCNT,
	HCCLMINCD,
	HBEXPPREM,
	LOAD_DATE
) as
with cte_SAMPLE_CBP_LOCATION as
(
select distinct trim(T1.PUREPOLICYNUMBER)AS PUREPOLICYNUMBER ,trim(t1.CMLNUMBER) AS CMLNUMBER,T1.EXPIRINGID_P
from AGGNE.DEV.Locationdetails_PER T1 
INNER JOIN AGGNE.DEV.SAMPLE_PER
T2 ON TRIM(T1.PUREPOLICYNUMBER)=TRIM(T2.PUREPOLICYNUMBER) 
--and 
--T1.EXPIRINGID=T2.EXPIRINGID_P  
WHERE t1.EFFECTIVEDATE>='2026-01-01'
),cte_COVERAGES as 
(
select distinct PUREPOLICYNUMBER,cmlnumber,EXPIRINGID_P,'BB' AS CLAUSE,'Building' AS  COVERAGE, "VOLUNTARYEXCESS" AS VOLUNTARYEXCESS,
CASE WHEN ACCIDENTALLOSSORDAMAGE='Taken' then CAST(CAST(1 AS NUMBER(1,0)) AS VARCHAR)  ELSE CAST(CAST(0 AS NUMBER(1,0)) AS VARCHAR) END AS ACCIDENTALLOSSORDAMAGE,
SPECIFIEDITEMSAWAY,UNSPECIFIEDITEMSAWAY,UNSPECIFIEDITEMSAWAYLIMIT

from AGGNE.DEV.HC_02 T1 
) 
 , CTE_EXCESS AS(
SELECT 
    CAST(trim(T2.PUREPOLICYNUMBER) ||'|' || TRIM(T2.cmlnumber) ||'|' || TRIM(T2.EXPIRINGID_P) AS VARCHAR) AS PUREPOLICYNUMBER,
t2.PUREPOLICYNUMBER AS LEGACYPOLICYNUMBER,T2.cmlnumber,T2.EXPIRINGID_P,COVERAGE,T2.VOLUNTARYEXCESS,
CASE WHEN ACCIDENTALLOSSORDAMAGE='Taken' then CAST(CAST(1 AS NUMBER(1,0)) AS VARCHAR)  ELSE CAST(CAST(0 AS NUMBER(1,0)) AS VARCHAR) END AS ACCIDENTALLOSSORDAMAGE,
SPECIFIEDITEMSAWAY,UNSPECIFIEDITEMSAWAY,UNSPECIFIEDITEMSAWAYLIMIT
FROM 
cte_SAMPLE_CBP_LOCATION T1 
INNER JOIN cte_COVERAGES T2 ON T1.EXPIRINGID_P=T2.EXPIRINGID_P
AND TRIM(T1.PUREPOLICYNUMBER)=TRIM(T2.PUREPOLICYNUMBER)
)
,CTE_LISTAGG AS(
SELECT
  ID,
  LISTAGG(CASE WHEN ITR_TYPE = 'Building_SubCov' THEN payload END, '\n') AS SUBCOV,
  LISTAGG(CASE WHEN ITR_TYPE = 'HC_exceed_values'     THEN payload END, '\n') AS HC_exceed_values,
  LISTAGG(CASE WHEN ITR_TYPE = 'HC_Specified_Contents'     THEN payload END, '\n') AS HC_Specified_Contents,
  CAST(LOAD_DATE AS DATE) AS LOAD_DATE
FROM AGGNE.DEV.PER_HC_TARGET
WHERE ITR_TYPE IN ('Building_SubCov','HC_exceed_values','HC_Specified_Contents')   AND CAST(LOAD_DATE AS DATE)= CAST(GETDATE() AS DATE)
GROUP BY ID, CAST(LOAD_DATE AS DATE)
)
SELECT distinct 
T1.PUREPOLICYNUMBER,
COVERAGE,
CAST(SUBCOV AS VARCHAR) AS SUBCOV,
CAST(HC_exceed_values AS VARCHAR) AS HC_EXCEED_VALUES,
CAST(HC_Specified_Contents AS VARCHAR) AS HC_SPECIFIED_CONTENTS,
CAST(CAST(COALESCE(VOLUNTARYEXCESS,0)AS NUMBER(20,0)) AS VARCHAR) AS VOLUNTARYEXCESS,
CASE WHEN ACCIDENTALLOSSORDAMAGE='Taken' then CAST(CAST(1 AS NUMBER(1,0)) AS VARCHAR)  ELSE CAST(CAST(0 AS NUMBER(1,0)) AS VARCHAR) END AS ACCIDENTALLOSSORDAMAGE,
CASE WHEN SPECIFIEDITEMSAWAY='Taken' then CAST(CAST(1 AS NUMBER(1,0)) AS VARCHAR)  ELSE CAST(CAST(0 AS NUMBER(1,0)) AS VARCHAR) END AS SPECIFIEDITEMSAWAY,
CASE WHEN UNSPECIFIEDITEMSAWAY='Taken' then CAST(CAST(1 AS NUMBER(1,0)) AS VARCHAR)  ELSE CAST(CAST(0 AS NUMBER(1,0)) AS VARCHAR) END AS UNSPECIFIEDITEMSAWAY,
CASE WHEN UNSPECIFIEDITEMSAWAYLIMIT='$2,000 per item up to $10,000 per event' THEN '2000peritemupto20000perevent' 
WHEN UNSPECIFIEDITEMSAWAYLIMIT='$1,250 per item up to $5,000 per event' THEN '1250peritemupto5000perevent'
ELSE '' END AS UNSPECIFIEDITEMSAWAYLIMIT,
CAST(COALESCE(T4.HCCLMCNT,0) AS VARCHAR) AS HCCLMCNT,
CAST(COALESCE(T4.HCCLMINCD,0) AS VARCHAR) AS HCCLMINCD,
CAST(COALESCE(T4.HMEXPPREM,0) AS VARCHAR) AS HBEXPPREM,
CAST(GETDATE() AS DATE) as LOAD_DATE
FROM CTE_EXCESS T1
LEFT JOIN  AGGNE.DEV.PER_HC_TARGET T2 ON T1.PUREPOLICYNUMBER=T2.ID
LEFT JOIN CTE_LISTAGG T3 ON T1.PUREPOLICYNUMBER = T3.ID 
LEFT JOIN AGGNE.DEV.Output_Coverage_PER T4 ON T1.PUREPOLICYNUMBER=T4.POLICYNUMBER 
WHERE   COVERAGE='Building'  ;