create or replace view PA_LINE_GT_PAYLOAD(
	PUREPOLICYNUMBER,
	LINE_GT_UW,
	LINE_GT_CLAUSE,
	VOLUNTARYEXCESS,
	STANDARDEXCESS,
	IMPOSEDEXCESS,
	GOODSINTRANSIT_IND,
	GTINLANDSHIPLIMIT,
	BUSINESSCONTENTANDSTOCK,
	ESTIMATEDANNUALVALUE,
	HAZARDOUSGOODS,
	HAZARDOUSGOODSTRANSPORTED,
	CONTENTSANDSTOCKTRANSPORTED,
	GTCLMCNT,
	GTCLMINCD,
	GTEXPPREM,
	EXP_PREM_GTSTD_SD,
	LOAD_DATE
) as
 with cte_SAMPLE_CBP as
(
select distinct LEGACYPOLICYNUMBER,cmlnumber,EXPIRINGID_P,TRIM(INSURANCE_FILE_CNT) AS INSURANCE_FILE_CNT from AGGNE.PRD.sample_policyattach_final_identifier -- WHERE DATEDIFF(DAY,EXPIRYDATE,GETDATE())<=45 
),cte_COVERAGES as 
(
select distinct PUREPOLICYNUMBER,cmlnumber,EXPIRINGID_P,ID,INSURANCE_FILE_CNT,
CAST(COALESCE(VOLUNTARYEXCESS,0) AS VARCHAR) AS VOLUNTARYEXCESS,
CAST(COALESCE(STANDARDEXCESS,0) AS VARCHAR) AS STANDARDEXCESS,
CAST(COALESCE(IMPOSEDEXCESS,0) AS VARCHAR) AS IMPOSEDEXCESS,
CAST(COALESCE(GOODSINTRANSIT_IND,0) AS VARCHAR) AS GOODSINTRANSIT_IND,
CAST(COALESCE(GTINLANDSHIPLIMIT,0) AS VARCHAR) AS GTINLANDSHIPLIMIT,
CAST(COALESCE(BUSINESSCONTENTANDSTOCK,0) AS VARCHAR) AS BUSINESSCONTENTANDSTOCK,
CAST(COALESCE(ESTIMATEDANNUALVALUE,'0') AS VARCHAR) AS ESTIMATEDANNUALVALUE,
CAST(COALESCE(HAZARDOUSGOODS,'0') AS VARCHAR) AS HAZARDOUSGOODS,
CAST(COALESCE(HAZARDOUSGOODSTRANSPORTED,'0') AS VARCHAR) AS HAZARDOUSGOODSTRANSPORTED,
CAST(COALESCE(CONTENTSANDSTOCKTRANSPORTED,'0') AS VARCHAR) AS CONTENTSANDSTOCKTRANSPORTED
from AGGNE.PRD.Line_GT_Coverage_Policyattach_IDENTIFIER T1 
) 
, CTE_EXCESS AS(
SELECT DISTINCT
   ID AS PUREPOLICYNUMBER,
t2.PUREPOLICYNUMBER AS LEGACYPOLICYNUMBER,T2.cmlnumber,T2.EXPIRINGID_P,
CAST(COALESCE(VOLUNTARYEXCESS,0) AS VARCHAR) AS VOLUNTARYEXCESS,
CAST(COALESCE(STANDARDEXCESS,0) AS VARCHAR) AS STANDARDEXCESS,
CAST(COALESCE(IMPOSEDEXCESS,0) AS VARCHAR) AS IMPOSEDEXCESS,
CAST(COALESCE(GOODSINTRANSIT_IND,0) AS VARCHAR) AS GOODSINTRANSIT_IND,
CAST(COALESCE(GTINLANDSHIPLIMIT,0) AS VARCHAR) AS GTINLANDSHIPLIMIT,
CAST(COALESCE(BUSINESSCONTENTANDSTOCK,0) AS VARCHAR) AS BUSINESSCONTENTANDSTOCK,
CAST(COALESCE(ESTIMATEDANNUALVALUE,'0') AS VARCHAR) AS ESTIMATEDANNUALVALUE,
CAST(COALESCE(HAZARDOUSGOODS,'0') AS VARCHAR) AS HAZARDOUSGOODS,
CAST(COALESCE(HAZARDOUSGOODSTRANSPORTED,'0') AS VARCHAR) AS HAZARDOUSGOODSTRANSPORTED,
CAST(COALESCE(CONTENTSANDSTOCKTRANSPORTED,'0') AS VARCHAR) AS CONTENTSANDSTOCKTRANSPORTED
FROM 
cte_SAMPLE_CBP T1 
INNER JOIN cte_COVERAGES T2 ON TRIM(T1.EXPIRINGID_P)=TRIM(T2.EXPIRINGID_P) AND TRIM(T1.INSURANCE_FILE_CNT)=TRIM(T2.INSURANCE_FILE_CNT)
AND TRIM(T1.LEGACYPOLICYNUMBER)=TRIM(T2.PUREPOLICYNUMBER)
)
,CTE_LISTAGG AS(
SELECT
  ID,
  LISTAGG(CASE WHEN ITR_TYPE = 'BP_LINE_GT_UW' THEN payload END, '\n') AS PA_LINE_GT_UW,
  LISTAGG(CASE WHEN ITR_TYPE = 'BP_LINE_GT_CLAUSE' THEN payload END, '\n') AS PA_LINE_GT_CLAUSE,
  CAST(LOAD_DATE AS DATE) AS LOAD_DATE
FROM AGGNE.PRD.PA_LINE_GT_Target
WHERE ITR_TYPE IN ('BP_LINE_GT_UW','BP_LINE_GT_CLAUSE') 
GROUP BY ID,CAST(LOAD_DATE AS DATE)
)
,SUB_COV_PREM AS (
SELECT
  POLICYNUMBER,
GTSTD_SD
FROM (
  SELECT POLICYNUMBER, SUB_COVERAGE, EXPPREMIUM
  FROM AGGNE.PRD.Output_SubCover_BSP_Policyattach
) src
PIVOT (
  SUM(EXPPREMIUM) FOR SUB_COVERAGE IN (
    ('GTSTD_SD') AS GTSTD_SD
  )
) p
)
SELECT distinct 
T1.PUREPOLICYNUMBER,
CASE WHEN PA_LINE_GT_UW IS NOT NULL AND PA_LINE_GT_UW<> '' THEN CAST(PA_LINE_GT_UW AS VARCHAR) ELSE '' END AS LINE_GT_UW,
-- CAST(LINE_GT_UW AS VARCHAR) AS LINE_GT_UW,
CASE WHEN PA_LINE_GT_CLAUSE IS NOT NULL AND PA_LINE_GT_CLAUSE<> '' THEN '<Clauses><Type>GoodsInTransit</Type>'||CAST(PA_LINE_GT_CLAUSE AS VARCHAR)||'</Clauses>' ELSE '' END AS LINE_GT_CLAUSE,
-- CAST(LINE_GT_CLAUSE AS VARCHAR) AS LINE_GT_CLAUSE,
CAST(CAST(COALESCE(VOLUNTARYEXCESS,0)AS NUMBER(10,0)) AS VARCHAR) AS VOLUNTARYEXCESS,
CAST(CAST(COALESCE(STANDARDEXCESS,0)AS NUMBER(10,0)) AS VARCHAR)  AS STANDARDEXCESS,
CAST(CAST(COALESCE(IMPOSEDEXCESS,0)AS NUMBER(10,0)) AS VARCHAR) AS IMPOSEDEXCESS,
CAST(CAST(COALESCE(GOODSINTRANSIT_IND,0)AS NUMBER(10,0)) AS VARCHAR) AS GOODSINTRANSIT_IND,
CAST(CAST(COALESCE(GTINLANDSHIPLIMIT,0)AS NUMBER(10,0)) AS VARCHAR) AS GTINLANDSHIPLIMIT,
CAST(CAST(COALESCE(BUSINESSCONTENTANDSTOCK,0)AS NUMBER(10,0)) AS VARCHAR) AS BUSINESSCONTENTANDSTOCK,
CAST(CAST(COALESCE(ESTIMATEDANNUALVALUE,'')AS NUMBER(10,0)) AS VARCHAR) AS ESTIMATEDANNUALVALUE,
CAST(COALESCE(HAZARDOUSGOODS,'') AS VARCHAR) AS HAZARDOUSGOODS,
CAST(COALESCE(HAZARDOUSGOODSTRANSPORTED,'') AS VARCHAR) AS HAZARDOUSGOODSTRANSPORTED,
CAST(COALESCE(REPLACE(CONTENTSANDSTOCKTRANSPORTED, '&','&amp;'),'') AS VARCHAR) AS CONTENTSANDSTOCKTRANSPORTED,
CAST(CAST(COALESCE(T4.GTCLMCNT,0)AS NUMBER(10,0)) AS VARCHAR) AS GTCLMCNT,
CAST(CAST(COALESCE(T4.GTCLMINCD,0) AS NUMBER(10,0)) AS VARCHAR) AS GTCLMINCD,
CAST(COALESCE(T4.GTEXPPREM,0) AS VARCHAR) AS GTEXPPREM,
CAST(COALESCE(CAST(GTSTD_SD AS NUMBER(36,3)),0)AS VARCHAR) AS EXP_PREM_GTSTD_SD,
CAST(GETDATE() AS DATE) AS LOAD_DATE
FROM CTE_EXCESS T1 
-- INNER JOIN  AGGNE.PRD.PA_LINE_GT_Target T2 ON T1.PUREPOLICYNUMBER=T2.ID
LEFT JOIN CTE_LISTAGG T3 ON T1.PUREPOLICYNUMBER = T3.ID 
LEFT JOIN AGGNE.PRD.Output_Coverage_BSP_Policyattach  T4 
ON CAST(trim(T1.LEGACYPOLICYNUMBER) ||'|' || TRIM(T1.cmlnumber) ||'|' || TRIM(T1.EXPIRINGID_P) AS VARCHAR)=CAST(trim(T4.POLICYNUMBER) ||'|' || TRIM(T4.cmlnumber) ||'|' || TRIM(T4.EXPIRINGID_P) AS VARCHAR)
LEFT JOIN SUB_COV_PREM T5 ON CAST(trim(T1.LEGACYPOLICYNUMBER) ||'|' || TRIM(T1.cmlnumber) ||'|' || TRIM(T1.EXPIRINGID_P) AS VARCHAR)=T5.POLICYNUMBER;