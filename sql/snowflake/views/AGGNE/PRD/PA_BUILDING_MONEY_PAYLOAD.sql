create or replace view PA_BUILDING_MONEY_PAYLOAD(
	PUREPOLICYNUMBER,
	COVERAGE,
	SUBCOV,
	UW,
	LOC_MY_CLAUSE,
	ISMONEYSTOREDINALOCKEDSAFE,
	MONEY_IND,
	LOCATIONOUTSIDEBUSINESSHOURS,
	MYCLMCNT,
	MYCLMINCD,
	MYEXPPREM,
	STANDARDEXCESS,
	IMPOSEDEXCESS,
	VOLUNTARYEXCESS,
	LOAD_DATE
) as
 with cte_SAMPLE_CBP_LOCATION as
(
select distinct T1.PUREPOLICYNUMBER,T1.cmlnumber,T1.EXPIRINGID,T1.INSURANCE_FILE_CNT,T1.ID from AGGNE.PRD.LOCATION_01_POLICYATTACH_IDENTIFIER T1 INNER JOIN AGGNE.PRD.SAMPLE_POLICYATTACH_FINAL_IDENTIFIER T2 ON T1.ID=T2.ID
),cte_COVERAGES as 
(
select distinct ID,PUREPOLICYNUMBER,cmlnumber,EXPIRINGID_P,INSURANCE_FILE_CNT,'MY' AS CLAUSE,'Money' AS  COVERAGE, CAST(ISMONEYSTOREDINALOCKEDSAFE AS VARCHAR) AS ISMONEYSTOREDINALOCKEDSAFE,
CAST(MONEY_IND AS VARCHAR) AS MONEY_IND ,
CAST(LOCATIONOUTSIDEBUSINESSHOURS AS VARCHAR) AS LOCATIONOUTSIDEBUSINESSHOURS,STANDARDEXCESS,IMPOSEDEXCESS,VOLUNTARYEXCESS
FROM AGGNE.PRD.location_money_coverage_policyattach_identifier T1 
) 
, CTE_EXCESS AS(
SELECT 
T2.ID AS PUREPOLICYNUMBER,
t2.PUREPOLICYNUMBER AS LEGACYPOLICYNUMBER,T2.cmlnumber,T2.EXPIRINGID_P,COVERAGE,CAST(ISMONEYSTOREDINALOCKEDSAFE AS VARCHAR) AS ISMONEYSTOREDINALOCKEDSAFE,
CAST(MONEY_IND AS VARCHAR) AS MONEY_IND ,
CAST(LOCATIONOUTSIDEBUSINESSHOURS AS VARCHAR) AS LOCATIONOUTSIDEBUSINESSHOURS,STANDARDEXCESS,IMPOSEDEXCESS,VOLUNTARYEXCESS
FROM  
cte_SAMPLE_CBP_LOCATION T1 
INNER JOIN cte_COVERAGES T2 ON T1.ID=T2.ID
)
,CTE_LISTAGG AS(
SELECT DISTINCT 
  ID,
  LISTAGG(CASE WHEN ITR_TYPE = 'BP_Risk_Building_Money_Subcov' THEN payload END, '\n') AS SUBCOV,
  LISTAGG(CASE WHEN ITR_TYPE = 'BP_RISK_BUILDING_MY_UW'     THEN payload END, '\n') AS UW,
  LISTAGG(CASE WHEN ITR_TYPE = 'BP_LOC_MY_CLAUSE'     THEN payload END, '\n') AS LOC_MY_CLAUSE,
  CAST(LOAD_DATE AS DATE) AS LOAD_DATE
FROM AGGNE.PRD.PA_RISK_BUILDING_Money_TARGET
WHERE ITR_TYPE IN ('BP_Risk_Building_Money_Subcov', 'BP_RISK_BUILDING_MY_UW','BP_LOC_MY_CLAUSE') 
GROUP BY ID,CAST(LOAD_DATE AS DATE)
)
SELECT distinct 
t1.PUREPOLICYNUMBER,
COVERAGE,CAST(SUBCOV AS VARCHAR) AS SUBCOV,
CAST(UW AS VARCHAR) AS UW,
CASE WHEN LOC_MY_CLAUSE IS NOT NULL AND LOC_MY_CLAUSE<> '' THEN '<Clauses><Type>Money</Type>'||CAST(LOC_MY_CLAUSE AS VARCHAR)||'</Clauses>' ELSE '' END AS LOC_MY_CLAUSE,
-- CAST(LOC_MY_CLAUSE AS VARCHAR) AS LOC_MY_CLAUSE,
 CAST(ISMONEYSTOREDINALOCKEDSAFE AS VARCHAR) AS ISMONEYSTOREDINALOCKEDSAFE,
CAST(CAST(COALESCE(MONEY_IND,0)AS NUMBER(10,0)) AS VARCHAR) AS MONEY_IND ,
CAST(LOCATIONOUTSIDEBUSINESSHOURS AS VARCHAR) AS LOCATIONOUTSIDEBUSINESSHOURS,
CAST(CAST(COALESCE(T4.MYCLMCNT,0)AS NUMBER(10,0)) AS VARCHAR) AS MYCLMCNT,
CAST(CAST(COALESCE(T4.MYCLMINCD,0)AS NUMBER(10,0)) AS VARCHAR) AS MYCLMINCD,
CAST(COALESCE(T4.MYEXPPREM,0) AS VARCHAR) AS MYEXPPREM,
CAST(cast(COALESCE(STANDARDEXCESS, 0) AS NUMBER(10,0)) AS VARCHAR) AS  STANDARDEXCESS,
 CAST(cast(COALESCE(IMPOSEDEXCESS, 0) AS NUMBER(10,0)) AS VARCHAR) AS  IMPOSEDEXCESS,
  CAST(cast(COALESCE(VOLUNTARYEXCESS, 0) AS NUMBER(10,0)) AS VARCHAR) AS  VOLUNTARYEXCESS,
CAST(GETDATE() AS DATE) as LOAD_DATE
 FROM CTE_EXCESS T1 
 --INNER JOIN  AGGNE.PRD.RISK_BUILDING_Money_TARGET T2 ON T1.PUREPOLICYNUMBER=T2.ID
LEFT JOIN CTE_LISTAGG T3 ON T1.PUREPOLICYNUMBER = T3.ID 
LEFT JOIN AGGNE.PRD.VW_OUTPUT_COVERAGE_BSP_policyattach T4 
ON CAST(trim(T1.LEGACYPOLICYNUMBER) ||'|' || TRIM(T1.cmlnumber) ||'|' || TRIM(T1.EXPIRINGID_P) AS VARCHAR)=CAST(trim(T4.POLICYNUMBER) ||'|' || TRIM(T4.cmlnumber) ||'|' || TRIM(T4.EXPIRINGID_P) AS VARCHAR)
WHERE   COVERAGE='Money' ;