create or replace view PA_PER_VW_CBP_COMPETITOR_INFORMATION(
	PUREPOLICYNUMBER,
	ACTUALID,
	LEGACYPOLICYNUMBER,
	PRIORCARRIER,
	PRICE
) as 
SELECT DISTINCT
ID AS PUREPOLICYNUMBER,ACTUALID,
 TRIM(PUREPOLICYNUMBER) AS LEGACYPOLICYNUMBER,
case when PRIORCARRIER='Motor Trade Direct' then 'MotorTradeDirect' else PRIORCARRIER END AS PRIORCARRIER,
CAST(COALESCE(CAST (PRICE AS NUMBER(10,2)),0)AS VARCHAR) AS PRICE 
FROM AGGNE.PRD.PER_Competitor_Information_Policyattach_IDENTIFIER
  T1 ;