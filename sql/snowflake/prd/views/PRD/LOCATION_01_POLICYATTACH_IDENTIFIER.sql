create or replace view LOCATION_01_POLICYATTACH_IDENTIFIER(
	ID,
	ACTUALID,
	PUREPOLICYNUMBER,
	CMLNUMBER,
	INSURANCE_FILE_CNT,
	EXPIRINGID,
	EXPIRYDATE,
	PRODUCT,
	ADDRESS1,
	GNAFPID,
	COUNTRY,
	ADDRESSDESCRIPTION,
	SUBURB,
	POSTCODE,
	STATE,
	BUSINESSBUILDINGS,
	BUSINESSCONTENTS,
	BURGLARY,
	MONEY,
	ENGINEERING,
	BUSINESSINTERRUPTION,
	YEARBUILDINGCONSTRUCTED,
	YEARLASTREWIRED,
	ADDRESS2,
	OCCUPATIONOFHIGHESTRISKTENANT,
	BUSINESSTYPE,
	LOCATIONANZSICCODE,
	YEARLASTREROOFED,
	YEARLASTREPLUMBED,
	DESCRIPTION,
	MAINWALLCONSTRUCTION,
	ROOFCONSTRUCTION,
	FLOORCONSTRUCTION,
	ALARMSYSTEMINSTALLED,
	SECURITYCAMERAS,
	TWOMETERHIGHPERIMETERFENCE,
	SECURITYBOLLARDS,
	PATROLLEDBYASECURITYGUARD,
	DEADLOCKSINSTALLED,
	EXTERIORSECURITYLIGHTING,
	BARSORGRILLSINSTALLED,
	TWENTYFOURHOURSATTENDANCE,
	CONDITIONOFBUILDING,
	CONDITIONOFROOF,
	ADEQUATESECOVSTORAGE,
	HIGHRISKSPECIALISEDEQUIP,
	DETAILSHIGHRISKSPECEQUIP,
	INADEQUATEFUELSTORAGE,
	MORETHANFEWTYRESTACK,
	VOLTYRESTACK,
	VOLTYRESTACKIN,
	TYRESTOREDOUTORDERLY,
	EXCOILRESIDUEOUT,
	SATISFACTORYRISKMITIGATION,
	NOOFSPRAYBOOTHS,
	SMASHREPAIR_CONDITION,
	SURRAREAFREEOFHEATWORK,
	SURRAREAHOUSEKEEP,
	MIXINGRMHOUSEKEEP,
	AGEOFOLDESTBOOTH,
	REPLACECOST,
	REGULARSERVICELOG,
	INTERIORWALLPROTECTIONUSED,
	EXHAUSTFANREPLACED,
	FLOORCONDITION,
	DISMANTLEAREAHOUSEKEEP,
	DEFUELLOCATION,
	DISMANTLELOC,
	HOISTSUSED,
	FIREEQUIPNEAR,
	METALRECYCLEONSITE,
	METALRECYCLEINSIDE,
	STOCKHOUSEKEEPING,
	TYRESBATTERIESHOUSEKEEP,
	EVSTORAGE,
	VEHICLESSTACKED,
	FUELSTORE,
	AVGNOVEHSSTORED,
	YARDFLOORHOUSEKEEP,
	CLEARLANDSQM
) as WITH PB AS (
        SELECT
            ROW_NUMBER() OVER (
                PARTITION BY TRIM(PUREPOLICYNUMBER)
                ORDER BY
                    SD ASC,
                    ED DESC,
                    LENGTH(INSURANCE_FILE_CNT_LIST) DESC
            ) AS RNO,
            CONCAT(
                TRIM(PUREPOLICYNUMBER),
                '|',
                TRIM(CMLNUMBER),
                '|',
                TRIM(EXPIRINGID_P_LIST),
                '|',
                TRIM(INSURANCE_FILE_CNT_LIST)
            ) AS ID,
            *
        FROM
            AGGNE.PRD.POLICYATTACH_BP_V1
    ),
    BD AS (
        SELECT
            *
        FROM
            AGGNE.PRD.Location_01_Policyattach
    ),
    PB_FLAT AS (
        SELECT
            pb.*,
            TRIM(f_ifc.value::STRING) AS INSURANCE_FILE_CNT_TOKEN,
            TRIM(f_exp.value::STRING) AS EXPIRINGID_P_TOKEN
        FROM
            PB pb,
            LATERAL FLATTEN(
                INPUT => SPLIT(pb.INSURANCE_FILE_CNT_LIST, ',')
            ) f_ifc,
            LATERAL FLATTEN(
                INPUT => SPLIT(pb.EXPIRINGID_P_LIST, ',')
            ) f_exp
        WHERE
            f_ifc.index = f_exp.index
    )
SELECT
    DISTINCT concat(
        pb.ID,
        '/',
        BD.EXPIRINGID,
        '/',
        BD.INSURANCE_FILE_CNT
    ) as id,
    pb.id as ACTUALID,
    bd.*
FROM
    PB_FLAT pb
    INNER JOIN BD bd ON TRIM(pb.PUREPolicyNumber) = TRIM(bd.PUREPolicyNumber)
    AND TRIM(pb.CMLNumber) = TRIM(bd.CMLNumber)
    AND TRIM(pb.EXPIRINGID_P_TOKEN) = TRIM(bd.ExpiringID)
    AND TRIM(pb.INSURANCE_FILE_CNT_TOKEN) = TRIM(bd.INSURANCE_FILE_CNT)
WHERE
    (
        NOT EXISTS (
            SELECT
                1
            FROM
                AGGNE.PRD.POLICYATTACH_TO_PROCESS
        )
        OR EXISTS (
            SELECT
                1
            FROM
                AGGNE.PRD.POLICYATTACH_TO_PROCESS p
            WHERE
                TRIM(p.PUREPOLICYNUMBER) = TRIM(pb.PUREPOLICYNUMBER)
        )
    );