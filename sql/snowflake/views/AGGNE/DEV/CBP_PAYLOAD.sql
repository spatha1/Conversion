ON TRIM(T1.LEGACYPOLICYNUMBER) = SPLIT_PART(TRIM(T19.ID), '|', 1) AND T19.ITR_TYPE='LINE_CV' AND   T19.load_date in (select max(load_date) as load_date  from AGGNE.DEV.LINE_CV_Target)
