create or replace view VW_DIM_PARTY_SEC_CONTACT(
	CATEGORY,
	USERNAME,
	PARTY_DIM_ID,
	BK_CMLNUMBER,
	MEMBER_TA_NUMBER,
	CSL_LEGAL_ENTITY,
	CML_RISK_ACCOUNT_MANAGER,
	CSL_AREA_MANAGER,
	CSL_ZONE,
	CSL_REGION,
	CSL_NUMBER,
	CML_LEGAL_ENTITY,
	CSL_MEMBER_STATUS,
	ABN_NZBN,
	STOP_CREDIT,
	STOP_CREDIT_REASON,
	CSL_TENURE,
	CSL_MONTHLY_SPEND,
	STANDARD_INDUSTRY_CODE,
	STANDARD_INDUSTRY_CODE_DESCRIPTION,
	CSL_CREDIT_LIMIT,
	CSL_CREDIT_RISK,
	CSL_CREDIT_USAGE,
	PROBABILITY_OF_DEFAULT,
	TA_PAYMENT_METHOD,
	STREET,
	SUBURB,
	STATE,
	POSTCODE,
	CONTACT_NAME,
	PHONE,
	EMAIL,
	SITE_COUNTRY,
	MESSAGE,
	CMLNUMBER,
	COUNTRY,
	CMLLEGALENTITY,
	CMLTRADINGNAME,
	MAINCONTACT,
	CORRESPONDENCELINE1,
	CORRESPONDENCELINE2,
	CORRESPONDENCELINE3,
	CORRESPONDENCELINE4,
	LOCATIONSTATECODE,
	CORRESPONDENCEPOSTCODE,
	SITE_STREET,
	SITE_SUBURB,
	SITE_STATE,
	SITE_POSTCODE,
	CSLNUMBER,
	PHONE_DETAILS,
	PRIMARY_PHONE,
	PRIMARY_PHONE_TYPE,
	PRIMARY_EMAIL,
	PRIMARY_EMAIL_TYPE,
	PHONE_COUNT,
	EMAIL_COUNT,
	PAID2DATE,
	MEM_REF,
	EFFECTIVE_DATE,
	AMOUNT,
	SECONDARYCONTACT_XMLDATA,
	EMAIL_XMLDATA,
	PHONE_XMLDATA,
	HASH_DIFF,
	EFFECTIVE_FROM,
	EFFECTIVE_TO,
	IS_CURRENT,
	ACTIVE_FLAG,
	LOAD_DATE
) as
SELECT
CASE WHEN otheremail != '' and otherphone != '' THEN 'MULTICONTACT(ACTIVE/INACTIVE)' ELSE 'SINGLE(ACTIVE/INACTIVE)' END AS CATEGORY,
concat('ConversionUser'::varchar,(ROW_NUMBER()Over(order by PARTY_DIM_ID)%5)+1 )as ConversionCounter,
    PARTY_DIM_ID ,
	BK_CMLNUMBER ,
	MEMBER_TA_NUMBER ,
	REPLACE(CSL_LEGAL_ENTITY,'&','&amp;')  ,
	REPLACE(CML_RISK_ACCOUNT_MANAGER,'&','&amp;')  ,
	REPLACE(CSL_AREA_MANAGER,'&','&amp;') ,
	REPLACE(CSL_ZONE,'&','&amp;') ,
	REPLACE(CSL_REGION,'&','&amp;') ,
	CSL_NUMBER ,
	REPLACE(CML_LEGAL_ENTITY,'&','&amp;') ,
	CSL_MEMBER_STATUS ,
	ABN_NZBN ,
	STOP_CREDIT ,
	REPLACE(STOP_CREDIT_REASON,'&','&amp;') , 
	CSL_TENURE ,
	CSL_MONTHLY_SPEND ,
	STANDARD_INDUSTRY_CODE ,
	REPLACE(STANDARD_INDUSTRY_CODE_DESCRIPTION,'&','&amp;') ,
	CSL_CREDIT_LIMIT ,
	CSL_CREDIT_RISK ,
	CSL_CREDIT_USAGE ,
	PROBABILITY_OF_DEFAULT FLOAT,
	TA_PAYMENT_METHOD ,
	REPLACE(STREET,'&','&amp;') ,
	REPLACE(SUBURB,'&','&amp;') ,
	STATE ,
	POSTCODE ,
	REPLACE(CONTACT_NAME,'&','&amp;') ,
	PHONE ,
	REPLACE(EMAIL,'&','&amp;') ,
    CASE
    WHEN TRIM(SITE_COUNTRY) = 'New Zealand' THEN 'NZ'
    WHEN TRIM(SITE_COUNTRY) = 'Australia' THEN 'AU'
    ELSE TRIM(SITE_COUNTRY)
  END AS SITE_COUNTRY,
	REPLACE(MESSAGE,'&','&amp;') ,
	CMLNUMBER ,
	CASE
    WHEN TRIM(COUNTRY) = 'New Zealand' THEN 'NZ'
    WHEN TRIM(COUNTRY) = 'Australia' THEN 'AU'
    ELSE TRIM(COUNTRY)
  END AS COUNTRY,
	REPLACE(CMLLEGALENTITY,'&','&amp;') ,
	REPLACE(CMLTRADINGNAME,'&','&amp;') ,
	REPLACE(MAINCONTACT,'&','&amp;'),
	REPLACE(CORRESPONDENCELINE1,'&','&amp;') ,
	REPLACE(CORRESPONDENCELINE2,'&','&amp;') ,
	REPLACE(CORRESPONDENCELINE3,'&','&amp;') ,
    CASE
    WHEN TRIM(COUNTRY) = 'New Zealand' THEN UPPER(CORRESPONDENCELINE4)
    WHEN TRIM(COUNTRY) = 'Australia' THEN CONCAT(CORRESPONDENCELINE4, 'AU')
    ELSE CORRESPONDENCELINE4
  END AS CORRESPONDENCELINE4,
   CASE
    WHEN TRIM(COUNTRY) = 'New Zealand' THEN '100'
    WHEN TRIM(COUNTRY) = 'Australia' THEN CONCAT(CORRESPONDENCELINE4, 'AU')
    ELSE CORRESPONDENCELINE4
  END AS LOCATIONSTATECODE,
	CORRESPONDENCEPOSTCODE ,
	REPLACE(SITE_STREET,'&','&amp;') , 
	SITE_SUBURB ,
	CASE
    WHEN TRIM(COUNTRY) = 'New Zealand' THEN SITE_STATE
    WHEN TRIM(COUNTRY) = 'Australia' THEN CONCAT(SITE_STATE, 'AU')
    ELSE SITE_STATE
  END AS SITE_STATE,
	SITE_POSTCODE ,
	CSLNUMBER ,
    LEFT(PRIMARY_PHONE, 2)  AS PHONE_DETAILS,
	PRIMARY_PHONE ,
	PRIMARY_PHONE_TYPE ,
	PRIMARY_EMAIL ,
	PRIMARY_EMAIL_TYPE ,
	PHONE_COUNT ,
	EMAIL_COUNT ,
	-- SECONDARYCONTACT_COUNT ,
	-- SECONDARYCONTACT ARRAY,
	-- SECONDARYCONTACTKEY ,
	PAID2DATE ,
	MEM_REF ,
	EFFECTIVE_DATE ,
	AMOUNT ,
   REPLACE(REPLACE(SECONDARYCONTACT_XMLDATA,'&','&amp;'),'{LOAD_DATE}',CURRENT_DATE()) ,
   REPLACE(EMAIL_XMLDATA,'{LOAD_dATE}',CURRENT_DATE()) ,
   PHONE_XMLDATA,
	HASH_DIFF ,
	EFFECTIVE_FROM ,
	EFFECTIVE_TO ,
	IS_CURRENT ,
	ACTIVE_FLAG ,
    TO_VARCHAR(CURRENT_TIMESTAMP(), 'YYYY-MM-DD') AS CURRENTDATE
FROM AGGNE.DEV.DIM_PARTY_ACTIVE_INACTIVE_MEMBERS_SCD2  ;