create or replace view PA_LINE_CV_PAYLOAD(
	PUREPOLICYNUMBER,
	LINE_CV_UW,
	LINE_CV_CLAUSE,
	VOLUNTARYEXCESS,
	STANDARDEXCESS,
	IMPOSEDEXCESS,
	STOLENKEYSEXCESS,
	CUSTOMERVEHICLES_IND,
	LOSSDAMAGELIMIT,
	CVCLMCNT,
	CVCLMINCD,
	CVEXPPREM,
	EXP_PREM_CVSTD_SD,
	LOAD_DATE
) as
 with cte_SAMPLE_CBP_LOCATION as
(
select distinct TRIM(LEGACYPOLICYNUMBER) AS PUREPOLICYNUMBER ,cmlnumber,EXPIRINGID_P,INSURANCE_FILE_CNT,ID from AGGNE.PRD.SAMPLE_POLICYATTACH_FINAL_IDENTIFIER -- WHERE DATEDIFF(DAY,EXPIRYDATE,GETDATE())<=45 
),cte_COVERAGES as 
(
select distinct PUREPOLICYNUMBER,cmlnumber,EXPIRINGID_P,INSURANCE_FILE_CNT,ID,
CAST(COALESCE(VOLUNTARYEXCESS ,0) AS VARCHAR) AS VOLUNTARYEXCESS ,
CAST(CAST(COALESCE(STANDARDEXCESS,0)AS NUMBER(10,0)) AS VARCHAR) AS STANDARDEXCESS,
CAST(CAST(COALESCE(IMPOSEDEXCESS,0)AS NUMBER(10,0)) AS VARCHAR) AS IMPOSEDEXCESS,STOLENKEYSEXCESS,
CAST(COALESCE(CUSTOMERVEHICLES_IND ,0) AS VARCHAR) AS CUSTOMERVEHICLES_IND ,
CAST(COALESCE(CVSUMPROTECTED ,0) AS VARCHAR) AS LOSSDAMAGELIMIT 
from AGGNE.PRD.line_cv_coverage_policyattach_IDENTIFIER T1 
) 
, CTE_EXCESS AS(
SELECT DISTINCT
    T1.ID AS PUREPOLICYNUMBER,
t2.PUREPOLICYNUMBER AS LEGACYPOLICYNUMBER,T2.cmlnumber,T2.EXPIRINGID_P,
CAST(COALESCE(VOLUNTARYEXCESS ,0) AS VARCHAR) AS VOLUNTARYEXCESS ,
CAST(COALESCE(CUSTOMERVEHICLES_IND ,0) AS VARCHAR) AS CUSTOMERVEHICLES_IND ,
CAST(COALESCE(LOSSDAMAGELIMIT ,0) AS VARCHAR) AS LOSSDAMAGELIMIT,
CAST(CAST(COALESCE(STANDARDEXCESS,0)AS NUMBER(10,0)) AS VARCHAR) AS STANDARDEXCESS,
CAST(CAST(COALESCE(IMPOSEDEXCESS,0)AS NUMBER(10,0)) AS VARCHAR) AS IMPOSEDEXCESS,STOLENKEYSEXCESS
FROM 
cte_SAMPLE_CBP_LOCATION T1 
INNER JOIN cte_COVERAGES T2 ON T1.ID=T2.ID
)
,CTE_LISTAGG AS(
SELECT
  ID,
  LISTAGG(CASE WHEN ITR_TYPE = 'BP_LINE_CV_UW' THEN payload END, '\n') AS PA_LINE_CV_UW,
  LISTAGG(CASE WHEN ITR_TYPE = 'BP_LINE_CV_CLAUSE' THEN payload END, '\n') AS PA_LINE_CV_CLAUSE,
  CAST(LOAD_DATE AS DATE) AS LOAD_DATE
FROM AGGNE.PRD.PA_LINE_CV_Target
WHERE ITR_TYPE IN ('BP_LINE_CV_UW','BP_LINE_CV_CLAUSE') 
GROUP BY ID,CAST(LOAD_DATE AS DATE)
)
,SUB_COV_PREM AS (
SELECT
  PUREPOLICYNUMBER,
CVSTD_SD
FROM (
  SELECT PUREPOLICYNUMBER, SUB_COVERAGE, EXPPREMIUM
  FROM AGGNE.PRD.VW_OUTPUT_SUBCOVERAGE_BSP_POLICYATTACH
) src
PIVOT (
  SUM(EXPPREMIUM) FOR SUB_COVERAGE IN (
    ('CVSTD_SD') AS CVSTD_SD
  )
) p
)
SELECT  DISTINCT  T1.PUREPOLICYNUMBER,
CASE WHEN PA_LINE_CV_UW IS NOT NULL AND PA_LINE_CV_UW<> '' THEN CAST(PA_LINE_CV_UW AS VARCHAR) ELSE '' END AS LINE_CV_UW,
-- CAST(LINE_CV_UW AS VARCHAR) AS LINE_CV_UW,
CASE WHEN PA_LINE_CV_CLAUSE IS NOT NULL AND PA_LINE_CV_CLAUSE<> '' THEN '<Clauses><Type>CustomerVehicles</Type>'||CAST(PA_LINE_CV_CLAUSE AS VARCHAR)||'</Clauses>' ELSE '' END AS LINE_CV_CLAUSE,
-- CAST(LINE_CV_CLAUSE AS VARCHAR) AS LINE_CV_CLAUSE,
CAST(COALESCE(cast(VOLUNTARYEXCESS as number(30,0)) ,0) AS VARCHAR) AS VOLUNTARYEXCESS ,
CAST(CAST(COALESCE(STANDARDEXCESS,0)AS NUMBER(10,0)) AS VARCHAR) AS STANDARDEXCESS,
CAST(CAST(COALESCE(IMPOSEDEXCESS,0)AS NUMBER(10,0)) AS VARCHAR) AS IMPOSEDEXCESS,
CAST(CAST(COALESCE(STOLENKEYSEXCESS,0)AS NUMBER(10,0)) AS VARCHAR) AS STOLENKEYSEXCESS,
CAST(COALESCE(cast(CUSTOMERVEHICLES_IND as number(3,0)),0) AS VARCHAR) AS CUSTOMERVEHICLES_IND ,
CAST(COALESCE(cast(LOSSDAMAGELIMIT as number(38,0)) ,0) AS VARCHAR) AS LOSSDAMAGELIMIT ,
CAST(CAST(COALESCE(T4.CVCLMCNT ,0)as number(38,0)) AS VARCHAR) AS CVCLMCNT,
CAST(CAST(COALESCE(T4.CVCLMINCD ,0)as number(38,0)) AS VARCHAR) AS CVCLMINCD,
CAST(COALESCE(T4.CVEXPPREM ,0) AS VARCHAR) AS CVEXPPREM,
CAST(COALESCE(CAST(CVSTD_SD AS NUMBER(36,3)),0)AS VARCHAR) AS EXP_PREM_CVSTD_SD,
CAST(GETDATE() AS DATE) AS LOAD_DATE
FROM CTE_EXCESS T1 
-- INNER JOIN  AGGNE.PRD.LINE_CV_Target T2 ON T1.PUREPOLICYNUMBER=T2.ID
LEFT  JOIN CTE_LISTAGG T3 ON T1.PUREPOLICYNUMBER = T3.ID 
LEFT JOIN AGGNE.PRD.VW_OUTPUT_COVERAGE_BSP_policyattach T4 
ON CAST(trim(T1.LEGACYPOLICYNUMBER) ||'|' || TRIM(T1.cmlnumber) ||'|' || TRIM(T1.EXPIRINGID_P) AS VARCHAR)=CAST(trim(T4.POLICYNUMBER) ||'|' || TRIM(T4.cmlnumber) ||'|' || TRIM(T4.EXPIRINGID_P) AS VARCHAR)
LEFT JOIN SUB_COV_PREM T5 ON CAST(trim(T1.LEGACYPOLICYNUMBER) ||'|' || TRIM(T1.cmlnumber) ||'|' || TRIM(T1.EXPIRINGID_P) AS VARCHAR)=T5.PUREPOLICYNUMBER;