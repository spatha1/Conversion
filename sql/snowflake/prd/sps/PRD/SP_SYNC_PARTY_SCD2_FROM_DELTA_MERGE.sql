        SELECT C.*
        FROM CUR C
        LEFT JOIN DELTA D
          ON D.BK_CMLNUMBER = C.BK_CMLNUMBER
        WHERE D.BK_CMLNUMBER IS NULL
      ),

      /* 3) Source stream for MERGE = EXPIRE rows + INSERT rows */
      SRC AS (

        /* --- EXPIRE: current rows that will be superseded (changed OR missing) --- */
