create or replace view PA_AOI_FINAL(
	PUREPOLICYNUMBER,
	EXPIRINGID_P,
	CMLNUMBER,
	INSURANCE_FILE_CNT,
	ADDITIONALINTDETS,
	LOC_VALUE,
	ADDITIONALINTERESTLINE,
	LINE_VALUE,
	RISKNUMBER,
	LOC_ADDRESS,
	LOC_SUB,
	LOC_POSTCODE,
	LOC_STATE,
	LOC_COUNTRY
) as
with cte1 as(
SELECT DISTINCT * FROM AGGNE.PRD.Additional_Interest_Policyattach_IDENTIFIER --WHERE DATEDIFF(DAY,EXPIRYDATE,GETDATE())<=45
),
cte2 as (
SELECT DISTINCT trim(PUREPOLICYNUMBER) AS ID,* FROM AGGNE.PRD.ACCOUNT_LOC_PolicyAttach

)
SELECT  DISTINCT
T1.ID AS PUREPOLICYNUMBER, 
CAST(T1.EXPIRINGID_P AS VARCHAR) AS EXPIRINGID_P,
T1.CMLNUMBER,t1.INSURANCE_FILE_CNT,
REPLACE (ADDITIONALINTDETS,'&','&amp;') AS ADDITIONALINTDETS ,
CASE WHEN LOC_VALUE= 'Business Buildings' THEN 'Building'
 WHEN LOC_VALUE= 'Business Contents' THEN 'ContentsAndStocks'
 WHEN LOC_VALUE= 'Burglary' THEN 'Burglary'
 WHEN LOC_VALUE= 'Business Interruption' THEN 'BusinessInterruption'
 WHEN LOC_VALUE= 'Engineering' THEN 'Engineering'
 WHEN LOC_VALUE= 'Money' THEN 'Money' ELSE LOC_VALUE END AS LOC_VALUE,
CASE WHEN ADDITIONALINTERESTLINE='Yes' THEN  cast('1' as varchar) ELSE cast('0' as varchar) END AS ADDITIONALINTERESTLINE,
CASE WHEN LINE_VALUE= 'Products And Public Liability'  THEN 'PublicProductLiability'
 WHEN LINE_VALUE='General Property'   THEN 'GeneralProperty'
 WHEN LINE_VALUE= 'Stock Vehicles'  THEN 'StockVehicles'
 WHEN LINE_VALUE='Professional Protection'   THEN 'ProfessionalProtection'
 WHEN LINE_VALUE='Customer Vehicles'   THEN 'CustomerVehicles'
 WHEN LINE_VALUE= 'Tax Audit'  THEN 'TaxAudit'
 WHEN LINE_VALUE='Goods In Transit'   THEN 'GoodsInTransit'
 WHEN LINE_VALUE='Legal Expenses'   THEN 'LegalExpenses' ELSE LINE_VALUE END AS LINE_VALUE,
CAST(RISKNUMBER AS VARCHAR) AS RISKNUMBER,
T2.ADDRESS1 AS LOC_ADDRESS,
CAST(T2.SUBURB AS VARCHAR) AS LOC_SUB,
T2.POSTCODE AS LOC_POSTCODE,
T2.STATE  AS LOC_STATE,
LOC_COUNTRY
FROM 
CTE1 T1 INNER JOIN CTE2 T2 ON T1.ID=T2.ID;