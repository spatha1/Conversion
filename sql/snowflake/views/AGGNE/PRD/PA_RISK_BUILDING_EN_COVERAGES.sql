create or replace view PA_RISK_BUILDING_EN_COVERAGES(
	PUREPOLICYNUMBER,
	LEGACYPOLICYNUMBER,
	CMLNUMBER,
	COVERAGE,
	COVERAGETYPE,
	DESCRIPTION,
	TYPE,
	CODE,
	IVALUE,
	INDICATOR,
	EXCESSINFO,
	EXP_PREM
) as
SELECT DISTINCT
ID AS PUREPOLICYNUMBER,
    T1.PUREPOLICYNUMBER AS LEGACYPOLICYNUMBER,
    T1.cmlnumber,
    T1.EXPIRINGID_P AS Coverage,
    'Building_EN' AS CoverageType,
    'Car Wash' AS Description,
    'CWS_SD' AS Type,
    'ENCWS_SD' AS Code,
    CAST(COALESCE(ENCARWASHVALUE,0) AS VARCHAR) AS iValue,
    cast('1' as varchar) AS Indicator,
    '' AS EXCESSINFO,
    CASE WHEN SUB_COVERAGE='ENCWS_SD' THEN CAST(CAST(COALESCE(EXPPREMIUM ,0) AS NUMBER(36,3)) AS VARCHAR) ELSE cast(0 as varchar) END AS EXP_PREM
FROM AGGNE.PRD.location_en_coverage_policyattach_IDENTIFIER T1 LEFT JOIN  AGGNE.PRD.VW_OUTPUT_SUBCOVERAGE_BSP_POLICYATTACH T2 ON CAST(trim(T1.PUREPOLICYNUMBER) ||'|' || TRIM(T1.cmlnumber) ||'|' || TRIM(T1.EXPIRINGID_P) AS VARCHAR)=T2.PUREPOLICYNUMBER 
and SUB_COVERAGE='ENCWS_SD' where COALESCE(ENCARWASHVALUE,0)<>0
UNION ALL
SELECT DISTINCT
ID AS PUREPOLICYNUMBER,   T1.PUREPOLICYNUMBER AS LEGACYPOLICYNUMBER,
    T1.cmlnumber,
    T1.EXPIRINGID_P AS Coverage,
    'Building_EN' AS CoverageType,
    'Deterioration of Stock' AS Description,
    'DET_SD' AS Type,
    'ENDET_SD' AS Code,
    cast(COALESCE(ENSTOCKDETERIORATION ,0) as varchar) AS iValue,
   cast('1' as varchar) AS Indicator,
    '' AS EXCESSINFO,
    CASE WHEN SUB_COVERAGE='ENDET_SD' THEN CAST(CAST(COALESCE(EXPPREMIUM ,0) AS NUMBER(36,3)) AS VARCHAR) ELSE cast(0 as varchar) END AS EXP_PREM
FROM AGGNE.PRD.location_en_coverage_policyattach_IDENTIFIER T1 LEFT JOIN  AGGNE.PRD.VW_OUTPUT_SUBCOVERAGE_BSP_POLICYATTACH T2 ON CAST(trim(T1.PUREPOLICYNUMBER) ||'|' || TRIM(T1.cmlnumber) ||'|' || TRIM(T1.EXPIRINGID_P) AS VARCHAR)=T2.PUREPOLICYNUMBER 
and SUB_COVERAGE='ENDET_SD' where COALESCE(ENSTOCKDETERIORATION,0)<>0
UNION ALL
SELECT DISTINCT
ID AS PUREPOLICYNUMBER,    T1.PUREPOLICYNUMBER AS LEGACYPOLICYNUMBER,
    T1.cmlnumber,
    T1.EXPIRINGID_P AS Coverage,
    'Building_EN' AS CoverageType,
    'Increased Cost of Working' AS Description,
    'ICW_SD' AS Type,
    'ENICW_SD' AS Code,
    cast(COALESCE(ENINCREASECOST,0) as varchar) AS iValue,
    cast('1' as varchar) AS Indicator,
    '' AS EXCESSINFO,
    CASE WHEN SUB_COVERAGE='ENICW_SD' THEN CAST(CAST(COALESCE(EXPPREMIUM ,0) AS NUMBER(36,3)) AS VARCHAR) ELSE cast(0 as varchar) END AS EXP_PREM
FROM AGGNE.PRD.location_en_coverage_policyattach_IDENTIFIER T1 LEFT JOIN  AGGNE.PRD.VW_OUTPUT_SUBCOVERAGE_BSP_POLICYATTACH T2 ON CAST(trim(T1.PUREPOLICYNUMBER) ||'|' || TRIM(T1.cmlnumber) ||'|' || TRIM(T1.EXPIRINGID_P) AS VARCHAR)=T2.PUREPOLICYNUMBER 
and SUB_COVERAGE='ENICW_SD' where COALESCE(ENINCREASECOST,0)<>0

UNION ALL
SELECT DISTINCT
ID AS PUREPOLICYNUMBER,  T1.PUREPOLICYNUMBER AS LEGACYPOLICYNUMBER,
    T1.cmlnumber,
    T1.EXPIRINGID_P AS Coverage,
    'Building_EN' AS CoverageType,
    'Loss of Information' AS Description,
    'LOI_SD' AS Type,
    'ENLOI_SD' AS Code,
    cast(COALESCE(ENLOSSINFO ,0) as varchar) AS iValue,
    cast('1' as varchar) AS Indicator,
    '' AS EXCESSINFO,
    CASE WHEN SUB_COVERAGE='ENLOI_SD' THEN CAST(CAST(COALESCE(EXPPREMIUM ,0) AS NUMBER(36,3)) AS VARCHAR) ELSE cast(0 as varchar) END AS EXP_PREM
FROM AGGNE.PRD.location_en_coverage_policyattach_IDENTIFIER T1 LEFT JOIN  AGGNE.PRD.VW_OUTPUT_SUBCOVERAGE_BSP_POLICYATTACH T2 ON CAST(trim(T1.PUREPOLICYNUMBER) ||'|' || TRIM(T1.cmlnumber) ||'|' || TRIM(T1.EXPIRINGID_P) AS VARCHAR)=T2.PUREPOLICYNUMBER 
and SUB_COVERAGE='ENLOI_SD' where COALESCE(ENLOSSINFO,0)<>0


UNION ALL
SELECT DISTINCT
ID AS PUREPOLICYNUMBER,   T1.PUREPOLICYNUMBER AS LEGACYPOLICYNUMBER,
    T1.cmlnumber,
    T1.EXPIRINGID_P AS Coverage,
    'Building_EN' AS CoverageType,
    'Machinery' AS Description,
    'MAC_SD' AS Type,
    'ENMAC_SD' AS Code,
    cast(COALESCE(ENMACHINERYECEVALUE,0) as varchar) AS iValue,
    cast('1' as varchar) AS Indicator,
    '' AS EXCESSINFO,
    CASE WHEN SUB_COVERAGE='ENMAC_SD' THEN CAST(CAST(COALESCE(EXPPREMIUM ,0) AS NUMBER(36,3)) AS VARCHAR) ELSE cast(0 as varchar) END AS EXP_PREM
FROM AGGNE.PRD.location_en_coverage_policyattach_IDENTIFIER T1 LEFT JOIN  AGGNE.PRD.VW_OUTPUT_SUBCOVERAGE_BSP_POLICYATTACH T2 ON CAST(trim(T1.PUREPOLICYNUMBER) ||'|' || TRIM(T1.cmlnumber) ||'|' || TRIM(T1.EXPIRINGID_P) AS VARCHAR)=T2.PUREPOLICYNUMBER
and SUB_COVERAGE='ENMAC_SD' where COALESCE(ENMACHINERYECEVALUE,0)<>0
