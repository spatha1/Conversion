create or replace view PA_PER_COM_CLAUSE(
	PUREPOLICYNUMBER,
	PUREPOLICYNUMBER_ACTUAL,
	EXPIRINGID_P,
	CLAUSESSELECTION,
	SELECTCLAUSEDESCRIPTION
) as
SELECT DISTINCT 
CAST(
        trim(ID) || '|' || TRIM(VEHICLEID) AS VARCHAR
    ) AS PUREPOLICYNUMBER,
ID AS PUREPOLICYNUMBER_ACTUAL,
-- CAST(PUREPOLICYBINDERID AS VARCHAR) AS PUREPOLICYBINDERID,
CAST(EXPIRINGID_P AS VARCHAR) AS EXPIRINGID_P,
CAST(CLAUSESSELECTION AS VARCHAR) AS CLAUSESSELECTION,
CAST(SELECTCLAUSEDESCRIPTION  AS VARCHAR) AS SELECTCLAUSEDESCRIPTION  FROM AGGNE.PRD.PM_03_Policyattach_IDENTIFIER
  WHERE CLAUSESSELECTION IS NOT NULL;