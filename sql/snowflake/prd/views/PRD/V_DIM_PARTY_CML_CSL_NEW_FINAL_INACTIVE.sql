  /* Step 1: NULL or empty → default by country */
  WHEN PRIMARY_PHONE IS NULL OR TRIM(PRIMARY_PHONE) = '' THEN
    CASE
      WHEN TRIM(COUNTRY) IN ('AU', 'Australia') THEN '0400000000'
      WHEN TRIM(COUNTRY) IN ('NZ', 'New Zealand') THEN '0200000000'
      ELSE NULL
    END

  /* Step 2: Keep only valid digits-only phones with length 9/10/11 */
  WHEN LENGTH(REGEXP_REPLACE(PRIMARY_PHONE, '[^0-9]', '')) IN (9,10,11) THEN
    REGEXP_REPLACE(PRIMARY_PHONE, '[^0-9]', '')

  /* Step 3: Anything else → default by country */
  ELSE
    CASE
      WHEN TRIM(COUNTRY) IN ('AU', 'Australia') THEN '0400000000'
      WHEN TRIM(COUNTRY) IN ('NZ', 'New Zealand') THEN '0200000000'
      ELSE NULL
    END
END AS PRIMARY_PHONE,

  CASE
    WHEN TRIM(SITE_COUNTRY) = 'Australia'
         AND TRIM(PRIMARY_PHONE) LIKE '04%' THEN 'C'

    WHEN TRIM(SITE_COUNTRY) = 'New Zealand'
         AND TRIM(PRIMARY_PHONE) LIKE '02%' THEN 'C'

    ELSE 'T'
END AS PRIMARY_PHONE_TYPE,
