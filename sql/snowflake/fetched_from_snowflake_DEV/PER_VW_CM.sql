create or replace view PER_VW_CM(
	PUREPOLICYNUMBER,
	CM,
	LOAD_DATE
) as 
with CTE1 as(
SELECT SPLIT_PART(TRIM(ID), '|', 1)  AS PUREPOLICYNUMBER,SPLIT_PART(TRIM(ID), '|', 3)  AS EXPIRYID_P, * FROM AGGNE.DEV.PER_COM_COVERAGES_TARGET 
)
SELECT
  PUREPOLICYNUMBER,
  LISTAGG(CASE WHEN ITR_TYPE = 'RISK_Building_PM' THEN PAYLOAD END, '\n') AS CM,
  CAST(LOAD_DATE AS DATE) AS LOAD_DATE
FROM CTE1
WHERE ITR_TYPE IN ('RISK_Building_PM')
GROUP BY PUREPOLICYNUMBER,CAST(LOAD_DATE AS DATE);