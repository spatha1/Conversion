create or replace view PA_LINE_LE_PAYLOAD(
	PUREPOLICYNUMBER,
	LINE_LE_UW,
	LINE_LE_CLAUSE,
	VOLUNTARYEXCESS,
	STANDARDEXCESS,
	IMPOSEDEXCESS,
	LEGALEXPENSES_IND,
	LEGALEXPENSESLIMIT,
	LEGALDISPUTEACTIONS,
	LEGALDISPUTEACTIONSDETAILS,
	REDUNDANCIES,
	REDUNDANCIESDETAILS,
	LECLMCNT,
	LECLMINCD,
	LEEXPPREM,
	EXP_PREM_LESTD_SD,
	LOAD_DATE
) as
 with cte_SAMPLE_CBP_LOCATION as
(
select distinct LEGACYPOLICYNUMBER,cmlnumber,EXPIRINGID_P,INSURANCE_FILE_CNT ,ID from AGGNE.PRD.SAMPLE_POLICYATTACH_FINAL_IDENTIFIER --WHERE DATEDIFF(DAY,EXPIRYDATE,GETDATE())<=45 
),cte_COVERAGES as 
(
select distinct PUREPOLICYNUMBER,cmlnumber,EXPIRINGID_P,ID,INSURANCE_FILE_CNT,
CAST(COALESCE(VOLUNTARYEXCESS,0) AS VARCHAR) AS VOLUNTARYEXCESS,
CAST(COALESCE(LEGALEXPENSES_IND,0) AS VARCHAR) AS LEGALEXPENSES_IND,
CAST(COALESCE(LELIMITOFCOVER ,0) AS VARCHAR) AS LEGALEXPENSESLIMIT ,
CAST(COALESCE(LEGALDISPUTEACTIONS ,'No') AS VARCHAR) AS LEGALDISPUTEACTIONS ,
CAST(COALESCE(LEGALDISPUTEACTIONSDETAILS ,'0') AS VARCHAR) AS LEGALDISPUTEACTIONSDETAILS ,
CAST(COALESCE(REDUNDANCIES ,'No') AS VARCHAR) AS REDUNDANCIES ,
CAST(COALESCE(REDUNDANCIESDETAILS ,'0') AS VARCHAR) AS REDUNDANCIESDETAILS ,
CAST(CAST(COALESCE(STANDARDEXCESS,0)AS NUMBER(10,0)) AS VARCHAR) AS STANDARDEXCESS,
CAST(CAST(COALESCE(IMPOSEDEXCESS,0)AS NUMBER(10,0)) AS VARCHAR) AS IMPOSEDEXCESS
from AGGNE.PRD.line_le_coverage_policyattach_IDENTIFIER T1 
) 
, CTE_EXCESS AS(
SELECT DISTINCT
   T1.ID AS PUREPOLICYNUMBER,
t2.PUREPOLICYNUMBER AS LEGACYPOLICYNUMBER,T2.cmlnumber,T2.EXPIRINGID_P,
CAST(COALESCE(VOLUNTARYEXCESS,0) AS VARCHAR) AS VOLUNTARYEXCESS,
CAST(COALESCE(LEGALEXPENSES_IND,0) AS VARCHAR) AS LEGALEXPENSES_IND,
CAST(COALESCE(LEGALEXPENSESLIMIT ,0) AS VARCHAR) AS LEGALEXPENSESLIMIT ,
CAST(COALESCE(LEGALDISPUTEACTIONS ,'No') AS VARCHAR) AS LEGALDISPUTEACTIONS ,
CAST(COALESCE(LEGALDISPUTEACTIONSDETAILS ,'0') AS VARCHAR) AS LEGALDISPUTEACTIONSDETAILS ,
CAST(CAST(COALESCE(STANDARDEXCESS,0)AS NUMBER(10,0)) AS VARCHAR) AS STANDARDEXCESS,
CAST(CAST(COALESCE(IMPOSEDEXCESS,0)AS NUMBER(10,0)) AS VARCHAR) AS IMPOSEDEXCESS,
CAST(COALESCE(REDUNDANCIES ,'No') AS VARCHAR) AS REDUNDANCIES ,
CAST(COALESCE(REDUNDANCIESDETAILS ,'0') AS VARCHAR) AS REDUNDANCIESDETAILS 
FROM 
cte_SAMPLE_CBP_LOCATION T1 
INNER JOIN cte_COVERAGES T2 ON T1.ID=T2.ID
)
,CTE_LISTAGG AS(
SELECT
  ID,
  LISTAGG(CASE WHEN ITR_TYPE = 'BP_LINE_LE_UW' THEN payload END, '\n') AS PA_LINE_LE_UW,
 LISTAGG(CASE WHEN ITR_TYPE = 'BP_LINE_LE_CLAUSE' THEN payload END, '\n') AS  PA_LINE_LE_CLAUSE,
  CAST(LOAD_DATE AS DATE) AS LOAD_DATE 
FROM AGGNE.PRD.PA_LINE_LE_Target
WHERE ITR_TYPE IN ('BP_LINE_LE_UW','BP_LINE_LE_CLAUSE') 
GROUP BY ID,CAST(LOAD_DATE AS DATE)
)
,SUB_COV_PREM AS (
SELECT
  POLICYNUMBER,
LESTD_SD
FROM (
  SELECT POLICYNUMBER, SUB_COVERAGE, EXPPREMIUM
  FROM AGGNE.PRD.Output_SubCover_BSP_Policyattach
) src
PIVOT (
  SUM(EXPPREMIUM) FOR SUB_COVERAGE IN (
    ('LESTD_SD') AS LESTD_SD
  )
) p
)
SELECT distinct 
T1.PUREPOLICYNUMBER,
CASE WHEN PA_LINE_LE_UW IS NOT NULL AND PA_LINE_LE_UW<> '' THEN CAST(PA_LINE_LE_UW AS VARCHAR) ELSE '' END AS LINE_LE_UW,
CASE WHEN PA_LINE_LE_CLAUSE IS NOT NULL AND PA_LINE_LE_CLAUSE<> '' THEN '<Clauses><Type>LegalExpenses</Type>'||CAST(PA_LINE_LE_CLAUSE AS VARCHAR)||'</Clauses>' ELSE '' END AS LINE_LE_CLAUSE,
-- --CAST(LINE_LE_CLAUSE AS VARCHAR) AS LINE_LE_CLAUSE,
CAST(CAST(COALESCE(VOLUNTARYEXCESS,0)AS NUMBER(10,0)) AS VARCHAR) AS VOLUNTARYEXCESS,
CAST(CAST(COALESCE(STANDARDEXCESS,0)AS NUMBER(10,0)) AS VARCHAR) AS STANDARDEXCESS,
CAST(CAST(COALESCE(IMPOSEDEXCESS,0)AS NUMBER(10,0)) AS VARCHAR) AS IMPOSEDEXCESS,
CAST(CAST(COALESCE(LEGALEXPENSES_IND,0)AS NUMBER(10,0)) AS VARCHAR) AS LEGALEXPENSES_IND,
CAST(CAST(COALESCE(LEGALEXPENSESLIMIT ,0)AS NUMBER(10,0)) AS VARCHAR) AS LEGALEXPENSESLIMIT ,
CAST(COALESCE(LEGALDISPUTEACTIONS ,'No') AS VARCHAR) AS LEGALDISPUTEACTIONS ,
CAST(COALESCE(LEGALDISPUTEACTIONSDETAILS ,'') AS VARCHAR) AS LEGALDISPUTEACTIONSDETAILS ,
CAST(COALESCE(REDUNDANCIES ,'No') AS VARCHAR) AS REDUNDANCIES ,
CAST(COALESCE(REDUNDANCIESDETAILS ,'') AS VARCHAR) AS REDUNDANCIESDETAILS ,
CAST(CAST(COALESCE(T4.LECLMCNT,0) AS NUMBER(10,0))AS VARCHAR) AS LECLMCNT,
CAST(CAST(COALESCE(T4.LECLMINCD,0)AS NUMBER(10,0)) AS VARCHAR) AS LECLMINCD,
CAST(COALESCE(T4.LEEXPPREM,0) AS VARCHAR) AS LEEXPPREM,
CAST(COALESCE(CAST(LESTD_SD AS NUMBER(36,3)),0)AS VARCHAR) AS EXP_PREM_LESTD_SD,
CAST(GETDATE() AS DATE) AS LOAD_DATE
FROM CTE_EXCESS T1
--INNER JOIN  AGGNE.PRD.LINE_LE_Target T2 ON T1.PUREPOLICYNUMBER=T2.ID
LEFT JOIN CTE_LISTAGG T3 ON T1.PUREPOLICYNUMBER = T3.ID 
LEFT JOIN AGGNE.PRD.Output_Coverage_BSP_Policyattach T4 
ON T1.LEGACYPOLICYNUMBER=T4.POLICYNUMBER
LEFT JOIN SUB_COV_PREM T5 ON T1.LEGACYPOLICYNUMBER=T5.POLICYNUMBER;