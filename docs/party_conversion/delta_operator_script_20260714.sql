-- STEP-1
UPDATE AGGNE.PRD.DIM_PARTY_SNAPSHOT_ACTIVE_INACTIVE_MEMBERS_SCD2 SET IS_CURRENT = TRUE;

-- STEP-2
TRUNCATE TABLE AGGNE.PRD.DIM_PARTY_SNAPSHOT_ACTIVE_INACTIVE_MEMBERS_SCD2_DELTA;
-- STEP-3
CALL AGGNE.PRD.SP_PURE_SNAPSHOT_TO_WRITE_LOAD_DELTA();

select * from AGGNE.PRD.Party_Conversion_Delta_Changes
/* 1) Build delta-changes (field-level) table */
CREATE OR REPLACE TABLE AGGNE.PRD.Party_Conversion_Delta_Changes AS
WITH BASE AS (
  SELECT
    T1.BK_CMLNUMBER,
    OBJECT_CONSTRUCT(T1.*) AS O1,
    OBJECT_CONSTRUCT(T2.*) AS O2
  FROM AGGNE.PRD.DIM_PARTY_SNAPSHOT_ACTIVE_INACTIVE_MEMBERS_SCD2 T1
  JOIN AGGNE.PRD.DIM_PARTY_SNAPSHOT_ACTIVE_INACTIVE_MEMBERS_SCD2_DELTA T2
    ON T1.BK_CMLNUMBER = T2.BK_CMLNUMBER
  -- WHERE T1.IS_CURRENT = TRUE
    AND COALESCE(T1.HASH_DIFF,'X') <> COALESCE(T2.HASH_DIFF,'X')
),
F1 AS (
  SELECT BK_CMLNUMBER, f.KEY::STRING AS COL, f.VALUE AS V1
  FROM BASE, LATERAL FLATTEN(INPUT => O1) f
),
F2 AS (
  SELECT BK_CMLNUMBER, f.KEY::STRING AS COL, f.VALUE AS V2
  FROM BASE, LATERAL FLATTEN(INPUT => O2) f
)
SELECT
  F1.BK_CMLNUMBER,
  F1.COL AS COLUMN_NAME,
  F1.V1 AS OLD_VALUE,
  F2.V2 AS NEW_VALUE
FROM F1
JOIN F2
  ON F1.BK_CMLNUMBER = F2.BK_CMLNUMBER
 AND F1.COL = F2.COL
WHERE
  COALESCE(TO_VARCHAR(F1.V1),'') <> COALESCE(TO_VARCHAR(F2.V2),'')
  AND F1.COL IN (
    'CMLNUMBER','COUNTRY','CMLLEGALENTITY','CMLTRADINGNAME','MAINCONTACT',
    'CORRESPONDENCELINE1','CORRESPONDENCELINE2','CORRESPONDENCELINE3','CORRESPONDENCELINE4',
    'CORRESPONDENCEPOSTCODE','SITE_STREET','SITE_SUBURB','SITE_STATE','SITE_POSTCODE',
    'PRIMARY_PHONE','PRIMARY_EMAIL','SCONDARYCONTACT',
    'OTHERPHONE','OTHEREMAIL','PAID2DATE','MEM_REF','EFFECTIVE_DATE','AMOUNT',
    'MEMBER_TA_NUMBER','CSL_LEGAL_ENTITY','CML_RISK_ACCOUNT_MANAGER','CSL_AREA_MANAGER',
    'CSL_ZONE','CSL_REGION','CSL_NUMBER','CML_LEGAL_ENTITY','CSL_MEMBER_STATUS',
    'ABN_NZBN','STOP_CREDIT','STOP_CREDIT_REASON',
    'STANDARD_INDUSTRY_CODE','STANDARD_INDUSTRY_CODE_DESCRIPTION',
    'CSL_CREDIT_LIMIT','CSL_CREDIT_RISK',
    'TA_PAYMENT_METHOD','STREET','SUBURB','STATE','POSTCODE',
    'CONTACT_NAME','PHONE','EMAIL','SITE_COUNTRY','MESSAGE'
  );

-- Interim NULL-guard (added 2026-07-14): inspect, then delete value->NULL membership rows
select * from  AGGNE.PRD.Party_Conversion_Delta_Changes where COLUMN_NAME in('PAID2DATE','EFFECTIVE_DATE') and NEW_VALUE is null
--delete from  AGGNE.PRD.Party_Conversion_Delta_Changes where COLUMN_NAME in('PAID2DATE','EFFECTIVE_DATE') and NEW_VALUE is null


/* 2) Persist impacted rows to HISTORY (assumes HISTORY table already exists with LOADDATE column) */
INSERT INTO AGGNE.PRD.DIM_PARTY_SNAPSHOT_ACTIVE_INACTIVE_MEMBERS_SCD2_HISTORY
SELECT T1.*, CURRENT_DATE() AS LOADDATE
FROM AGGNE.PRD.DIM_PARTY_SNAPSHOT_ACTIVE_INACTIVE_MEMBERS_SCD2 T1
WHERE T1.BK_CMLNUMBER IN (SELECT DISTINCT BK_CMLNUMBER FROM AGGNE.PRD.Party_Conversion_Delta_Changes);

/* 3) Replace changed BKs in SCD2 from DELTA */
DELETE FROM AGGNE.PRD.DIM_PARTY_SNAPSHOT_ACTIVE_INACTIVE_MEMBERS_SCD2
WHERE BK_CMLNUMBER IN (SELECT DISTINCT BK_CMLNUMBER FROM AGGNE.PRD.Party_Conversion_Delta_Changes);

UPDATE AGGNE.PRD.DIM_PARTY_SNAPSHOT_ACTIVE_INACTIVE_MEMBERS_SCD2_DELTA
SET IS_CURRENT = FALSE;  -- boolean

INSERT INTO AGGNE.PRD.DIM_PARTY_SNAPSHOT_ACTIVE_INACTIVE_MEMBERS_SCD2
SELECT DISTINCT *
FROM AGGNE.PRD.DIM_PARTY_SNAPSHOT_ACTIVE_INACTIVE_MEMBERS_SCD2_DELTA
WHERE BK_CMLNUMBER IN (SELECT DISTINCT BK_CMLNUMBER FROM AGGNE.PRD.Party_Conversion_Delta_Changes);

/* 4) Insert brand-new BKs (present in DELTA but not in SCD2) */
INSERT INTO AGGNE.PRD.DIM_PARTY_SNAPSHOT_ACTIVE_INACTIVE_MEMBERS_SCD2
SELECT T2.*
FROM AGGNE.PRD.DIM_PARTY_SNAPSHOT_ACTIVE_INACTIVE_MEMBERS_SCD2_DELTA T2
LEFT JOIN AGGNE.PRD.DIM_PARTY_SNAPSHOT_ACTIVE_INACTIVE_MEMBERS_SCD2 T1
  ON T1.BK_CMLNUMBER = T2.BK_CMLNUMBER
WHERE T1.BK_CMLNUMBER IS NULL;


/*5) LOAD DATA INTO AGGNE.PRD_XML.CML_MIGRATION_DCT */
-- CALL AGGNE.PRD.INSERT_PARTY_SNAPSHOT_TO_DCTTABLE_SEC_CONTACT();
select * from AGGNE.PRD_XML.CML_MIGRATION_DCT where RESULTS_JSON is NULL

SELECT PARTY_DIM_ID FROM AGGNE.PRD_XML.CML_MIGRATION_DCT WHERE RESPONSE_XML IS NULL;


/*6) Collect DCT responses back into the queue table */
create or replace temp table AGGNE.PRD_XML.CML_MIGRATION_DCT_PARTYID_RESULTS_TEMP_1 as
select * from AGGNE.PRD_XML.CML_MIGRATION_DCT_PARTYID  where  (PARTYDIM_ID,LOADDATE_DATE) in(
select PARTYDIM_ID,max(LOADDATE_DATE) LOADDATE_DATE from  AGGNE.PRD_XML.CML_MIGRATION_DCT_PARTYID
where LOADDATE_DATE::date=getdate()::date
group by PARTYDIM_ID )

UPDATE AGGNE.PRD_XML.CML_MIGRATION_DCT  t1
SET
    RESULTS_JSON = t2.RESULT_JSON::VARIANT ,
    RESPONSE_XML = t2.RESPONSE_XML,
    UPDATED_AT = CURRENT_TIMESTAMP()
FROM AGGNE.PRD_XML.CML_MIGRATION_DCT_PARTYID_RESULTS_TEMP_1 t2
WHERE TRIM(t1.PARTY_DIM_ID) = TRIM(t2.PARTYDIM_ID)
AND t1.RESULTS_JSON IS NULL;
