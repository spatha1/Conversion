create or replace view PA_BUILDING_UW(
	PUREPOLICYNUMBER,
	LEGACYPOLICYNUMBER,
	EXPIRINGID_P,
	CMLNUMBER,
	RECURRINGINDICATOR,
	UNDERWRITINGDESCRIPTION,
	ADJUSTMENTDOLLARANDPERCENT,
	ADJUSTMENTSELECTION,
	COVERAGE
) as
-- WITH cte_COVERAGES AS (
