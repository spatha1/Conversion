SELECT 
    ID AS PUREPOLICYNUMBER,
    CAST(T1.POLICYNUMBER AS VARCHAR) AS LEGACYPOLICYNUMBER,
    CAST(T1.EXPIRINGID_P AS VARCHAR) AS EXPIRINGID_P,
    CAST(T1.cmlnumber AS VARCHAR) AS CMLNUMBER,
   CAST('1' AS VARCHAR) AS RECURRINGINDICATOR,
        CAST(REPLACE(REPLACE(UWADJUSTNOTE,  '&', '&amp;'),'''', '''''') AS VARCHAR) AS UnderwritingDescription,
            CAST(cast(UWADJUSTAMOUNT AS NUMBER(38,0)) AS VARCHAR) AS AdjustmentDollarAndPercent,
    CAST('1' AS VARCHAR) AS AdjustmentSelection,
    CAST(T1.COVERAGE AS VARCHAR) AS COVERAGE
FROM AGGNE.PRD.OUTPUT_UWADJUST_BSP_POLICYATTACH T1 INNER JOIN AGGNE.PRD.location_bb_coverage_policyattach_IDENTIFIER T2 ON TRIM(T1.POLICYNUMBER)=TRIM(T2.PUREPOLICYNUMBER) AND T1.EXPIRINGID_P=T2.EXPIRINGID_P
    WHERE T1.COVERAGE='BB' AND UWADJUSTAMOUNT IS NOT NULL;