create or replace view POLICY_ATTACH_XML(
	PUREPOLICYNUMBER,
	EXPIRYID,
	REQUEST_XML,
	RESPONSE_XML,
	CREATED_AT,
	EFFECTIVEDATE,
	EXPIRATIONDATE,
	LOADDATE
) as 
SELECT DISTINCT SPLIT_PART(TRIM(ID), '|', 1) AS PUREPOLICYNUMBER,
SPLIT_PART(TRIM(ID), '|', 3) AS EXPIRYID,
REQUEST_XML,
RESPONSE_XML,
CREATED_AT ,
"EFFECTIVEDATE" ::dateTIME AS EFFECTIVEDATE,
"EXPIRATIONDATE" ::dateTIME AS EXPIRATIONDATE,
GETDATE() AS LOADDATE
FROM AGGNE.DEV.POLICYATTACH_MIGRATION_DCT WHERE RESPONSE_XML IS NOT NULL;