create or replace view ACCOUNT_LOC(
	PUREPOLICYNUMBER,
	LOCATIONANZSICCODE,
	LEGACYPOLICYNUMBER,
	RISKNUMBER,
	STATE,
	ADDRESS1,
	SUBURB,
	GNAFPID,
	POSTCODE,
	LOC_COUNTRY,
	LOCATIONADDRESSTAKEN
) as

WITH cte1 as 
(
SELECT  CAST(trim(T1.PUREPOLICYNUMBER) ||'|' || TRIM(T1.cmlnumber) ||'|' || TRIM(T1.EXPIRINGID) AS VARCHAR) AS ID,
T1.* FROM AGGNE.DEV.location_01 T1 inner join AGGNE.DEV.SAMPLE_CBP T2 on TRIM(t1.PUREPOLICYNUMBER)=TRIM(T2.PUREPOLICYNUMBER) AND T1.EXPIRINGID=T2.EXPIRINGID_P
WHERE   T1.EXPIRYDATE >= '2026-01-01'
),
cte2  AS (
SELECT CAST(trim(PUREPOLICYNUMBER) ||'|' || TRIM(cmlnumber) ||'|' || TRIM(EXPIRINGID) AS VARCHAR) AS PUREPOLICYNUMBER,
TRIM(PUREPOLICYNUMBER) as LEGACYPOLICYNUMBER,
STATE,
ADDRESS1,
SUBURB,
CAST(POSTCODE AS VARCHAR) AS POSTCODE,
CAST(COALESCE(GNAFPID ,'0')AS VARCHAR) AS GNAFPID,
COUNTRY,CASE WHEN CAST(LOCATIONANZSICCODE AS VARCHAR) like '%111111%' THEN '111111 - Property Owners Only'
WHEN CAST(LOCATIONANZSICCODE AS VARCHAR) like '%222222%' THEN '222222 - Vehicles Only'
WHEN CAST(LOCATIONANZSICCODE AS VARCHAR) like '%281901%' THEN '281901 - Automotive Component Manufacturing'
WHEN CAST(LOCATIONANZSICCODE AS VARCHAR) like '%462301%' THEN '462301 - Motor Vehicle New Part and Accessories Wholesaling'
WHEN CAST(LOCATIONANZSICCODE AS VARCHAR) like '%524502%' THEN '524502 - Boat Dealers - no Manufacturing - including Servicing'
WHEN CAST(LOCATIONANZSICCODE AS VARCHAR) like '%531103%' THEN '531103 - Agricultural Machinery Dealers - Including Servicing'
WHEN CAST(LOCATIONANZSICCODE AS VARCHAR) like '%531107%' THEN '531107 - Motor Vehicle Dealers - New - excluding Servicing'
WHEN CAST(LOCATIONANZSICCODE AS VARCHAR) like '%531108%' THEN '531108 - Motor Vehicle Dealers - New - including Servicing'
WHEN CAST(LOCATIONANZSICCODE AS VARCHAR) like '%531109%' THEN '531109 - Motor Vehicle Dealers - Used - excluding Servicing'
WHEN CAST(LOCATIONANZSICCODE AS VARCHAR) like '%531110%' THEN '531110 - Motor Vehicle Dealers - Used - including Servicing'
WHEN CAST(LOCATIONANZSICCODE AS VARCHAR) like '%531116%' THEN '531116 - Motor Vehicle Wrecking - Used Parts Reseller'
WHEN CAST(LOCATIONANZSICCODE AS VARCHAR) like '%531301%' THEN '531301 - Motorcycle Dealers - New and Used - including Servicing'
WHEN CAST(LOCATIONANZSICCODE AS VARCHAR) like '%531302%' THEN '531302 - Trailer and Caravan Dealers'
WHEN CAST(LOCATIONANZSICCODE AS VARCHAR) like '%532101%' THEN '532101 - Service Station - excluding Servicing'
WHEN CAST(LOCATIONANZSICCODE AS VARCHAR) like '%532103%' THEN '532103 - Service Station - including Roadhouse - including Servicing'
WHEN CAST(LOCATIONANZSICCODE AS VARCHAR) like '%532201%' THEN '532201 - Automotive Electrical Services'
WHEN CAST(LOCATIONANZSICCODE AS VARCHAR) like '%532301%' THEN '532301 - Body/Smash Repair - Bus, Coach, Trucks and Heavy Machinery'
WHEN CAST(LOCATIONANZSICCODE AS VARCHAR) like '%532302%' THEN '532302 - Body/Smash Repair - Passenger - excluding Bus, Coach, Trucks and Heavy Machinery'
WHEN CAST(LOCATIONANZSICCODE AS VARCHAR) like '%532401%' THEN '532401 - Tyre Retailers and Repairers - excluding Retreading and Remoulding'
WHEN CAST(LOCATIONANZSICCODE AS VARCHAR) like '%532504%' THEN '532504 - Automotive Mechanical Repairs - Mobile Mechanic'
WHEN CAST(LOCATIONANZSICCODE AS VARCHAR) like '%532505%' THEN '532505 - Automotive Mechanical Repairs - Workshop - excluding Smash Repairs'
WHEN CAST(LOCATIONANZSICCODE AS VARCHAR) like '%532901%' THEN '532901 - Automotive Engine Re-Conditioners'
WHEN CAST(LOCATIONANZSICCODE AS VARCHAR) like '%532902%' THEN '532902 - Automotive Exhaust and/or Suspension Specialists'
WHEN CAST(LOCATIONANZSICCODE AS VARCHAR) like '%532903%' THEN '532903 - Automotive Fuel Injection Services'
WHEN CAST(LOCATIONANZSICCODE AS VARCHAR) like '%532904%' THEN '532904 - Automotive LPG Fitters'
WHEN CAST(LOCATIONANZSICCODE AS VARCHAR) like '%532905%' THEN '532905 - Automotive Radiator Repairs'
WHEN CAST(LOCATIONANZSICCODE AS VARCHAR) like '%532908%' THEN '532908 - Automotive Windscreen Installation/Repair'
WHEN CAST(LOCATIONANZSICCODE AS VARCHAR) like '%532909%' THEN '532909 - Automotive Windscreen Tinting'
WHEN CAST(LOCATIONANZSICCODE AS VARCHAR) like '%532912%' THEN '532912 - Motor Vehicle Detailers'
WHEN CAST(LOCATIONANZSICCODE AS VARCHAR) like '%532913%' THEN '532913 - Tow Truck Operator'
WHEN CAST(LOCATIONANZSICCODE AS VARCHAR) like '%540000%' THEN '540000 - Automotive Fabrication and Engineering'
WHEN CAST(LOCATIONANZSICCODE AS VARCHAR) like '%540001%' THEN '540001 - Diesel Mechanic'
WHEN CAST(LOCATIONANZSICCODE AS VARCHAR) like '%540002%' THEN '540002 - Wrecker – Retailer Only'
WHEN CAST(LOCATIONANZSICCODE AS VARCHAR) like '%540003%' THEN '540003 - Service Station – excluding Roadhouse'
WHEN CAST(LOCATIONANZSICCODE AS VARCHAR) like '%600001%' THEN '600001 - Auto Masters'
WHEN CAST(LOCATIONANZSICCODE AS VARCHAR) like '%600002%' THEN '600002 - Ultra-Tune'
WHEN CAST(LOCATIONANZSICCODE AS VARCHAR) like '%600003%' THEN '600003 - Tyre Franchise'
WHEN CAST(LOCATIONANZSICCODE AS VARCHAR) like '%774101%' THEN '774101 - Motor Vehicle Hiring'
ELSE NULL
END AS  LOCATIONANZSICCODE,EXPIRINGID
FROM AGGNE.DEV.location_01
)
,CTE3 as (

select CAST(trim(PUREPOLICYNUMBER) ||'|' || TRIM(cmlnumber) ||'|' || TRIM(EXPIRINGID_P) AS VARCHAR) AS FULLPOLICYNUMBER,* from aggne.dev.line_publicliability_coverage

)
SELECT 
T1.PUREPOLICYNUMBER, T1.LOCATIONANZSICCODE,LEGACYPOLICYNUMBER,
CAST(CAST(ROW_NUMBER() OVER (PARTITION BY T1.LEGACYPOLICYNUMBER ORDER BY t1.EXPIRINGID)AS NUMBER(10,0)) AS VARCHAR) AS RISKNUMBER,
CASE
    WHEN TRIM(T1.COUNTRY) = 'New Zealand' THEN T1.STATE
    WHEN TRIM(T1.COUNTRY) = 'Australia' THEN CONCAT(T1.STATE, 'AU')
    ELSE T1.STATE end as STATE,
T1.ADDRESS1,
T1.SUBURB,
CAST(COALESCE(T1.GNAFPID ,'0')AS VARCHAR) AS GNAFPID,
CAST(T1.POSTCODE AS VARCHAR) AS POSTCODE,
CASE 
    WHEN TRIM(T1.COUNTRY) = 'New Zealand' THEN 'NZ'
    WHEN TRIM(T1.COUNTRY) = 'Australia' THEN 'AU'
    ELSE TRIM(T1.COUNTRY) END AS LOC_COUNTRY ,  
   
   CASE when t3.PROPERTYOWNER='Taken' 
   THEN 'Taken' ELSE 'NotTaken' END LOCATIONADDRESSTAKEN
FROM ctE2 T1
INNER JOIN  CTE1 T2  ON T1.PUREPOLICYNUMBER=T2.ID 
LEFT JOIN CTE3 T3 on T3.FULLPOLICYNUMBER=T1.PUREPOLICYNUMBER
;