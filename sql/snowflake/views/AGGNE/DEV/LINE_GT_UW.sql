create or replace view LINE_GT_UW(
	PUREPOLICYNUMBER,
	LEGACYPOLICYNUMBER,
	EXPIRINGID_P,
	CMLNUMBER,
	RECURRINGINDICATOR,
	UNDERWRITINGDESCRIPTION,
	ADJUSTMENTDOLLARANDPERCENT,
	ADJUSTMENTSELECTION
) as
SELECT DISTINCT
    CAST(trim(POLICYNUMBER) ||'|' || TRIM(cmlnumber) ||'|' || TRIM(EXPIRINGID_P) AS VARCHAR) AS PUREPOLICYNUMBER,
    CAST(trim(POLICYNUMBER) AS VARCHAR) AS LEGACYPOLICYNUMBER,
    CAST(EXPIRINGID_P AS VARCHAR) AS EXPIRINGID_P,
    CAST(cmlnumber AS VARCHAR) AS CMLNUMBER,
    CAST('1' AS VARCHAR) AS RECURRINGINDICATOR,
    CAST(REPLACE(REPLACE(UWADJUSTNOTE,  '&', '&amp;'),'''', '''''') AS VARCHAR) AS UnderwritingDescription,
    CAST(cast(UWADJUSTAMOUNT AS NUMBER(38,0)) AS VARCHAR) AS AdjustmentDollarAndPercent,
    CAST('1' AS VARCHAR) AS AdjustmentSelection   
FROM     aggne.dev.Output_UWAdjust_BSP where COVERAGE='GT' AND UWADJUSTNOTE IS NOT NULL ;