create or replace view CV_MOTOR_UW(
	PUREPOLICYNUMBER,
	POLICYNUMBER,
	EXPIRINGID_P,
	CMLNUMBER,
	VEHICLE_ID,
	RECURRINGIND,
	ADJUSTMENTTYPE,
	COVERAGE,
	UWADJUSTNOTE,
	UWADJUSTAMOUNT
) as
SELECT
    CAST(trim(A.PUREPOLICYNUMBER) ||'|' || TRIM(A.cmlnumber) ||'|' || TRIM(A.EXPIRINGID_P)||'|' || TRIM(VEHICLEID) AS VARCHAR) AS PUREPOLICYNUMBER,
    POLICYNUMBER,
    A.EXPIRINGID_P,
    A.CMLNUMBER,
    B.VEHICLE_ID,
    '1' AS RECURRINGIND,
    '1' AS ADJUSTMENTTYPE,
       COVERAGE,
    UWADJUSTNOTE,
    CAST(UWADJUSTAMOUNT AS VARCHAR) AS UWADJUSTAMOUNT
FROM 
AGGNE.DEV.CM_03 A INNER JOIN
AGGNE.DEV.OUTPUT_UWADJUST_BSP B ON TRIM(A.PUREPOLICYNUMBER) = TRIM(B.POLICYNUMBER)
AND TRIM(A.EXPIRINGID_P) = TRIM(B.EXPIRINGID_P)
AND TRIM(A.CMLNUMBER) = TRIM(B.CMLNUMBER)
AND TRIM(A.VEHICLEID) = TRIM(B.VEHICLE_ID)
WHERE B.COVERAGE = 'CM';