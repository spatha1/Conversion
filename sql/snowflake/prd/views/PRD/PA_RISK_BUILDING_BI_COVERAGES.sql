create or replace view PA_RISK_BUILDING_BI_COVERAGES(
	PUREPOLICYNUMBER,
	LEGACYPOLICYNUMBER,
	CMLNUMBER,
	COVERAGE,
	COVERAGETYPE,
	DESCRIPTION,
	TYPE,
	CODE,
	IVALUE,
	SVALUE,
	EXP_PREM
) as
SELECT distinct 
ID AS PUREPOLICYNUMBER,
T1.PUREPOLICYNUMBER AS LEGACYPOLICYNUMBER, 
    T1.cmlnumber,
    T1.EXPIRINGID_P AS Coverage,
    'Building_BI' AS CoverageType,
    'Claim Preparation' AS Description,
    'CLP_SD' AS Type,
    'BICLP_SD' AS Code,
    cast(CAST("BICLAIMSPREPCOST" AS NUMBER(20,0)) as varchar) AS iValue,
    '' AS sValue,
    CASE WHEN SUB_COVERAGE='BICLP_SD' THEN CAST(CAST(COALESCE(EXPPREMIUM ,0) AS NUMBER(36,3)) AS VARCHAR) ELSE cast(0 as varchar) END AS EXP_PREM
FROM AGGNE.PRD.location_bi_coverage_policyattach_IDENTIFIER T1 LEFT JOIN  AGGNE.PRD.VW_OUTPUT_SUBCOVERAGE_BSP_POLICYATTACH T2 ON CAST(trim(T1.PUREPOLICYNUMBER) ||'|' || TRIM(T1.cmlnumber) ||'|' || TRIM(T1.EXPIRINGID_P) AS VARCHAR)=T2.PUREPOLICYNUMBER 
AND SUB_COVERAGE='BICLP_SD' WHERE COALESCE(BICLAIMSPREPCOST ,0)<>0

UNION ALL
SELECT distinct
ID AS PUREPOLICYNUMBER,
T1.PUREPOLICYNUMBER AS LEGACYPOLICYNUMBER,
    T1.cmlnumber,
    T1.EXPIRINGID_P AS Coverage,
    'Building_BI' AS CoverageType,
    'Accounts Receivable' AS Description,
    'ACR_SD' AS Type,
    'BIACR_SD' AS Code,
    cast(CAST("BIRECEIVABLES" AS NUMBER(20,0)) as varchar) AS iValue,
    '' AS sValue,
    CASE WHEN SUB_COVERAGE='BIACR_SD' THEN CAST(CAST(COALESCE(EXPPREMIUM ,0) AS NUMBER(36,3)) AS VARCHAR) ELSE cast(0 as varchar) END AS EXP_PREM
FROM AGGNE.PRD.location_bi_coverage_policyattach_IDENTIFIER T1 LEFT JOIN  AGGNE.PRD.VW_OUTPUT_SUBCOVERAGE_BSP_POLICYATTACH T2 ON  CAST(trim(T1.PUREPOLICYNUMBER) ||'|' || TRIM(T1.cmlnumber) ||'|' || TRIM(T1.EXPIRINGID_P) AS VARCHAR)=T2.PUREPOLICYNUMBER 
AND SUB_COVERAGE='BIACR_SD' WHERE COALESCE(BIRECEIVABLES ,0)<>0

UNION ALL
SELECT distinct
ID AS PUREPOLICYNUMBER,
T1.PUREPOLICYNUMBER AS LEGACYPOLICYNUMBER,
    T1.cmlnumber,
    T1.EXPIRINGID_P AS Coverage,
    'Building_BI' AS CoverageType,
    'Additional Increased Cost of Working' AS Description,
    'ICW_SD' AS Type,
    'BIICW_SD' AS Code,
    cast(CAST("BICOSTOFWORKING" AS NUMBER(20,0)) as varchar) AS iValue,
    '' AS sValue,
    CASE WHEN SUB_COVERAGE='BIICW_SD' THEN CAST(CAST(COALESCE(EXPPREMIUM ,0) AS NUMBER(36,3)) AS VARCHAR) ELSE cast(0 as varchar) END AS EXP_PREM
FROM AGGNE.PRD.location_bi_coverage_policyattach_IDENTIFIER T1 LEFT JOIN  AGGNE.PRD.VW_OUTPUT_SUBCOVERAGE_BSP_POLICYATTACH T2 ON  CAST(trim(T1.PUREPOLICYNUMBER) ||'|' || TRIM(T1.cmlnumber) ||'|' || TRIM(T1.EXPIRINGID_P) AS VARCHAR)=T2.PUREPOLICYNUMBER
AND SUB_COVERAGE='BIICW_SD' WHERE COALESCE(BICOSTOFWORKING ,0)<>0
;