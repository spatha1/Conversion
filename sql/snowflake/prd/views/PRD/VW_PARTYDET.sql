create or replace view VW_PARTYDET(
	CML_NUMBER,
	PARTY_DIM_ID,
	PARTYID,
	PARTYNUMBER
) as 
SELECT
    d.CML_NUMBER,
    d.PARTY_DIM_ID,
    f.value:"PartyId"::STRING     AS PartyId,
    f.value:"PartyNumber"::STRING AS PartyNumber
FROM AGGNE.PRD_XML.CML_MIGRATION_DCT AS d
CROSS JOIN LATERAL FLATTEN(input => TRY_PARSE_JSON(d.RESULTS_JSON)) AS f
WHERE d.CML_NUMBER IS NOT NULL
  AND NULLIF(TRIM(f.value:"PartyId"::STRING), '') IS NOT NULL
QUALIFY ROW_NUMBER() OVER (
    PARTITION BY d.CML_NUMBER
    ORDER BY f.index
) = 1;