create or replace view RISK_LOCATION_UW_COMBINE(
	PUREPOLICYNUMBER,
	RECURRINGINDICATOR,
	UNDERWRITINGDESCRIPTION,
	ADJUSTMENTDOLLARANDPERCENT,
	ADJUSTMENTSELECTION
) as
with cte as (
SELECT DISTINCT
    PUREPOLICYNUMBER
    FROM  AGGNE.DEV.ACCOUNT_LOC T2 
    )
    select T2.* ,
     CASE WHEN UWADJUSTNOTE IS NULL THEN CAST(NULL AS VARCHAR) ELSE CAST('1' AS VARCHAR) END AS RECURRINGINDICATOR,
    CAST(REPLACE(REPLACE(T1.UWADJUSTNOTE,  '&', '&amp;'),'''', '''''') AS VARCHAR) AS UNDERWRITINGDESCRIPTION,
    CAST(T1.UWADJUSTAMOUNT AS VARCHAR) AS ADJUSTMENTDOLLARANDPERCENT,
    CASE WHEN UWADJUSTNOTE IS NULL THEN CAST(NULL AS VARCHAR) ELSE CAST('1' AS VARCHAR) END AS ADJUSTMENTSELECTION
    from cte T2
    INNER JOIN  AGGNE.DEV.Output_UWAdjust_BSP  T1
    ON CAST(trim(T1.POLICYNUMBER) ||'|' || TRIM(T1.cmlnumber) ||'|' || TRIM(T1.EXPIRINGID_P) AS VARCHAR) = trim(T2.PUREPOLICYNUMBER)
    WHERE T1.COVERAGE='SU' and UWADJUSTNOTE is not null;