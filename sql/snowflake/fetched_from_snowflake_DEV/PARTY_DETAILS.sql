create or replace view PARTY_DETAILS(
	CML_NUMBER,
	REQUEST_XML,
	RESPONSE_XML,
	PARTYID,
	PARTYNUMBER
) as
SELECT DISTINCT CML_NUMBER,REQUEST_XML,RESPONSE_XML,
    f.value:PartyId::STRING AS PartyId,
    f.value:PartyNumber::STRING AS PartyNumber
FROM AGGNE.DEV.CML_MIGRATION_DCT d,
LATERAL FLATTEN(input => d.RESULTS_JSON) f
WHERE CML_NUMBER IS NOT NULL AND f.value:PartyId::STRING IS NOT NULL 
AND RESPONSE_XML NOT LIKE '%error%' 
AND CAST(CREATED_AT AS DATE)= '2025-12-15';