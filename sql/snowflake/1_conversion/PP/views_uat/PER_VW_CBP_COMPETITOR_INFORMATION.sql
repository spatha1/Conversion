create or replace view AGGNE.UAT.PER_VW_CBP_COMPETITOR_INFORMATION(
	PUREPOLICYNUMBER,
	PRIORCARRIER,
	PRICE
) as
-- Fix ATP-10897: was reading from CBP_COMPETITOR_INFORMATION (BSP product only).
-- Correct source is PER_COMPETITOR_INFORMATION (PER/PP product), joined to SAMPLE_PER.
-- Also removed incorrect 'Motor Trade Direct'→'MotorTradeDirect' mapping;
-- PL101 and PC_PER_COMPETITOR_INFORMATION_POLICYATTACH confirm value must keep spaces.
SELECT DISTINCT
    TRIM(T1.PUREPOLICYNUMBER) AS PUREPOLICYNUMBER,
    TO_VARCHAR(T1.PRIORCARRIER) AS PRIORCARRIER,
    CAST(COALESCE(CAST(T1.PRICE AS NUMBER(10,2)), 0) AS VARCHAR) AS PRICE
FROM AGGNE.UAT.PER_COMPETITOR_INFORMATION T1
INNER JOIN AGGNE.UAT.SAMPLE_PER T2
    ON TRIM(T1.PUREPOLICYNUMBER) = TRIM(T2.PUREPOLICYNUMBER)
    AND T1.EXPIRINGID_P = T2.EXPIRINGID_P
WHERE T2.EFFECTIVEDATE >= '2026-01-01';