CREATE OR REPLACE TEMP TABLE AGGNE.DEV.POLICYATTACH_SAS_FINAL_SCENARIO1 AS
SELECT
    TRIM(PUREPOLICYNUMBER) AS PUREPOLICYNUMBER,
    insurance_file_cnt,
    CoverStartDate,
	RISK_FOLDER_CNT,
	Pol_type_adj,
	PUREEXPIRYDATE,RISK_ADDRESS,POLICY_BINDER_ID,
    LAG(CoverStartDate) OVER ( PARTITION BY TRIM(PUREPolicyNumber)   ORDER BY RISK_FOLDER_CNT DESC, insurance_file_cnt DESC) AS CoverEndDate_pre,
    LAG(Pol_type_adj) OVER ( PARTITION BY TRIM(PUREPolicyNumber) ORDER BY RISK_FOLDER_CNT DESC, insurance_file_cnt DESC) AS LagPolType,
    ROW_NUMBER() OVER (PARTITION BY TRIM(PUREPolicyNumber), RISK_FOLDER_CNT ORDER BY  insurance_file_cnt DESC) AS rn3
    
FROM  AGGNE.DEV.POLICYATTACH_TEMP 
QUALIFY  NOT (rn3 > 1  AND CoverStartDate=CoverEndDate_pre )
ORDER BY PUREPOLICYNUMBER, risk_folder_cnt DESC, insurance_file_cnt DESC;


