    END AS EXP_PREM
FROM AGGNE.DEV.PM_03 T1 LEFT JOIN  AGGNE.DEV.Output_SubCover_PER T2 
ON TRIM(T1.PUREPOLICYNUMBER)=TRIM(T2.POLICYNUMBER)
AND T1.EXPIRINGID_P=T2.EXPIRINGID_P AND SUB_COVERAGE='PMCMP_SD'

