create or replace view VW_CLAIM_HISTORY_POLICYATTACH(
	PUREPOLICYNUMBER,
	LEGACYPOLICYNUMBER,
	CMLNUMBER,
	INSURANCE_FILE_CNT,
	DATEOFCLAIM,
	AMOUNTPAID,
	LINE,
	CAUSE
) as 
WITH CTE1 AS(
SELECT DISTINCT
ID AS PUREPOLICYNUMBER,
    TRIM(T1.PUREPOLICYNUMBER) AS LEGACYPOLICYNUMBER,
    TRIM(T1.CMLNUMBER) AS CMLNUMBER,TRIM(INSURANCE_FILE_CNT) AS INSURANCE_FILE_CNT,
    TRY_TO_DATE(REGEXP_REPLACE(TRIM(T1.DATEOFCLAIM), '[A-Za-z]', ''), 'YYYY-MM-DD')AS DATEOFCLAIM,
    TO_VARCHAR(T1.AMOUNTPAID) AS AMOUNTPAID,
    TO_VARCHAR(T1.LINE) AS LINE,
    TO_VARCHAR(T1.CAUSE) AS CAUSE
FROM AGGNE.PRD.CLAIMHISTORY_policyattach_IDENTIFIER AS T1  --7592
) SELECT DISTINCT 
    PUREPOLICYNUMBER,
    TRIM(T1.LEGACYPOLICYNUMBER)AS LEGACYPOLICYNUMBER,
    TRIM(T1.CMLNUMBER)AS CMLNUMBER,
    TRIM(INSURANCE_FILE_CNT) AS INSURANCE_FILE_CNT,
    TO_CHAR(DATEOFCLAIM::DATE, 'YYYY-MM-DD') AS DATEOFCLAIM ,
    TO_VARCHAR(T1.AMOUNTPAID) AS AMOUNTPAID,
    TO_VARCHAR(T1.LINE) AS LINE,
    TO_VARCHAR(T1.CAUSE) AS CAUSE 
    FROM CTE1 T1 ;