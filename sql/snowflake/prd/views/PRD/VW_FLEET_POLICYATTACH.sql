create or replace view VW_FLEET_POLICYATTACH(
	ID,
	FLEET,
	LOAD_DATE
) as 
with CTE1 as(
SELECT  * FROM AGGNE.PRD.RISK_FLEET_VEHICLE_TARGET_POLICY_ATTACH 
),CTE2 AS (
SELECT
  ACTUALID,PAYLOAD,
  -- LISTAGG(CASE WHEN ITR_TYPE = 'BP_Fleet_Vehicle_main' THEN PAYLOAD END, '\n') AS FLEET,
  CAST(LOAD_DATE AS DATE) AS LOAD_DATE
FROM CTE1 T1 INNER JOIN AGGNE.PRD.FLEET_VEHICLE_MAIN_VIEW_POLICYATTACH T2 ON T1.ID=T2.PUREPOLICYNUMBER
WHERE ITR_TYPE IN ('BP_Fleet_Vehicle_main')
GROUP BY ACTUALID,PAYLOAD,CAST(LOAD_DATE AS DATE)
)
SELECT ACTUALID AS ID,LISTAGG( PAYLOAD, '\n') AS FLEET,CAST(LOAD_DATE AS DATE) AS LOAD_DATE FROM CTE2
GROUP BY ACTUALID,CAST(LOAD_DATE AS DATE)
;