ON  TRIM(T1.LEGACYPOLICYNUMBER) = SPLIT_PART(TRIM(T20.ID), '|', 1) AND T20.ITR_TYPE='LINE_TA' AND  T20.load_date in (select max(load_date) as load_date  from AGGNE.DEV.LINE_TA_Target)
LEFT JOIN AGGNE.DEV.VW_PARTYDET T21 
ON T2.CMLNUMBER=T21.CML_NUMBER
LEFT JOIN AGGNE.DEV.AOI_FINAL_AGG T22
 ON TRIM(T1.LEGACYPOLICYNUMBER) =  TRIM(T22.PUREPOLICYNUMBER) AND  T22.load_date in (select max(load_date) as load_date  from AGGNE.DEV.AOI_FINAL_AGG)
