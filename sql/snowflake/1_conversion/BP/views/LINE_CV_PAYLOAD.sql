create or replace view LINE_CV_PAYLOAD(
	PUREPOLICYNUMBER,
	LINE_CV_UW,
	LINE_CV_CLAUSE,
	VOLUNTARYEXCESS,
	CUSTOMERVEHICLES_IND,
	LOSSDAMAGELIMIT,
	CVCLMCNT,
	CVCLMINCD,
	CVEXPPREM,
	EXP_PREM_CVSTD_SD,
	LOAD_DATE
) as
 with cte_SAMPLE_CBP_LOCATION as
(
select distinct PUREPOLICYNUMBER,cmlnumber,EXPIRINGID_P from AGGNE.DEV.SAMPLE_CBP WHERE EXPIRYDATE>='2026-01-01'
),cte_COVERAGES as 
(
select distinct PUREPOLICYNUMBER,cmlnumber,EXPIRINGID_P,
CAST(COALESCE(VOLUNTARYEXCESS ,0) AS VARCHAR) AS VOLUNTARYEXCESS ,
CAST(COALESCE(CUSTOMERVEHICLES_IND ,0) AS VARCHAR) AS CUSTOMERVEHICLES_IND ,
CAST(COALESCE(LOSSDAMAGELIMIT ,0) AS VARCHAR) AS LOSSDAMAGELIMIT 
from AGGNE.DEV.Line_CV_Coverage T1 WHERE EXPIRYDATE>='2026-01-01' --9031
)  
, CTE_EXCESS AS(
SELECT DISTINCT
    CAST(trim(T2.PUREPOLICYNUMBER) ||'|' || TRIM(T2.cmlnumber) ||'|' || TRIM(T2.EXPIRINGID_P) AS VARCHAR) AS PUREPOLICYNUMBER,
t2.PUREPOLICYNUMBER AS LEGACYPOLICYNUMBER,T2.cmlnumber,T2.EXPIRINGID_P,
CAST(COALESCE(VOLUNTARYEXCESS ,0) AS VARCHAR) AS VOLUNTARYEXCESS ,
CAST(COALESCE(CUSTOMERVEHICLES_IND ,0) AS VARCHAR) AS CUSTOMERVEHICLES_IND ,
CAST(COALESCE(LOSSDAMAGELIMIT ,0) AS VARCHAR) AS LOSSDAMAGELIMIT
FROM 
cte_SAMPLE_CBP_LOCATION T1 
INNER JOIN cte_COVERAGES T2 ON --T1.EXPIRINGID_P=T2.EXPIRINGID_P and 
 TRIM(T1.PUREPOLICYNUMBER)=TRIM(T2.PUREPOLICYNUMBER) --WITH - 9031

)
,CTE_LISTAGG AS(
SELECT
  ID,
  LISTAGG(CASE WHEN ITR_TYPE = 'BP_LINE_CV_UW' THEN payload END, '\n') AS LINE_CV_UW,
  LISTAGG(CASE WHEN ITR_TYPE = 'BP_LINE_CV_CLAUSE' THEN payload END, '\n') AS LINE_CV_CLAUSE,
  CAST(LOAD_DATE AS DATE) AS LOAD_DATE
FROM AGGNE.DEV.LINE_CV_Target
WHERE ITR_TYPE IN ('BP_LINE_CV_UW','BP_LINE_CV_CLAUSE') 
GROUP BY ID,CAST(LOAD_DATE AS DATE)
)
,SUB_COV_PREM AS (
SELECT
  PUREPOLICYNUMBER,
CVSTD_SD
FROM (
  SELECT PUREPOLICYNUMBER, SUB_COVERAGE, EXPPREMIUM
  FROM AGGNE.DEV.VW_OUTPUT_SUBCOVERAGE_BSP
) src
PIVOT (
  SUM(EXPPREMIUM) FOR SUB_COVERAGE IN (
    ('CVSTD_SD') AS CVSTD_SD
  )
) p
)
SELECT distinct 
T1.PUREPOLICYNUMBER,
CASE WHEN LINE_CV_UW IS NOT NULL AND LINE_CV_UW<> '' THEN CAST(LINE_CV_UW AS VARCHAR) ELSE '' END AS LINE_CV_UW,
-- CAST(LINE_CV_UW AS VARCHAR) AS LINE_CV_UW,
CASE WHEN LINE_CV_CLAUSE IS NOT NULL AND LINE_CV_CLAUSE<> '' THEN '<Clauses><Type>CustomerVehicles</Type>'||CAST(LINE_CV_CLAUSE AS VARCHAR)||'</Clauses>' ELSE '' END AS LINE_CV_CLAUSE,
-- CAST(LINE_CV_CLAUSE AS VARCHAR) AS LINE_CV_CLAUSE,
CAST(COALESCE(cast(VOLUNTARYEXCESS as number(30,0)) ,0) AS VARCHAR) AS VOLUNTARYEXCESS ,
CAST(COALESCE(cast(CUSTOMERVEHICLES_IND as number(3,0)),0) AS VARCHAR) AS CUSTOMERVEHICLES_IND ,
CAST(COALESCE(cast(LOSSDAMAGELIMIT as number(38,0)) ,0) AS VARCHAR) AS LOSSDAMAGELIMIT ,
CAST(CAST(COALESCE(T4.CVCLMCNT ,0)as number(38,0)) AS VARCHAR) AS CVCLMCNT,
CAST(CAST(COALESCE(T4.CVCLMINCD ,0)as number(38,0)) AS VARCHAR) AS CVCLMINCD,
CAST(COALESCE(T4.CVEXPPREM ,0) AS VARCHAR) AS CVEXPPREM,
CAST(COALESCE(CAST(CVSTD_SD AS NUMBER(36,3)),0)AS VARCHAR) AS EXP_PREM_CVSTD_SD,
CAST(GETDATE() AS DATE) AS LOAD_DATE
FROM CTE_EXCESS T1 
-- INNER JOIN  AGGNE.DEV.LINE_CV_Target T2 ON T1.PUREPOLICYNUMBER=T2.ID
LEFT  JOIN CTE_LISTAGG T3 ON T1.PUREPOLICYNUMBER = T3.ID 
LEFT JOIN AGGNE.DEV.VW_OUTPUT_COVERAGE_BSP T4 ON T1.PUREPOLICYNUMBER=T4.PUREPOLICYNUMBER 
LEFT JOIN SUB_COV_PREM T5 ON T1.PUREPOLICYNUMBER=T5.PUREPOLICYNUMBER;