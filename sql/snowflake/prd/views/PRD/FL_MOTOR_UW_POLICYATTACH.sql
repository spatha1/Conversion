create or replace view FL_MOTOR_UW_POLICYATTACH(
	PUREPOLICYNUMBER,
	PUREPOLICYNUMBER_ACTUAL,
	POLICYNUMBER,
	EXPIRINGID_P,
	CMLNUMBER,
	RECURRINGIND,
	ADJUSTMENTTYPE,
	COVERAGE,
	UWADJUSTNOTE,
	UWADJUSTAMOUNT
) as
    SELECT
    CAST(TRIM(ID) || '|' || NVL(TRIM(registrationnumber),'Unknown') AS VARCHAR ) AS PUREPOLICYNUMBER,
	ID AS PUREPOLICYNUMBER_ACTUAL,
    POLICYNUMBER,
    A.EXPIRINGID_P,
    A.CMLNUMBER,
    '1' AS RECURRINGIND,
    '1' AS ADJUSTMENTTYPE,
       COVERAGE,
    UWADJUSTNOTE,
    CAST(UWADJUSTAMOUNT AS VARCHAR) AS UWADJUSTAMOUNT
FROM 
AGGNE.PRD.VEHICLECOVERAGES_FLEETVEHICLE_POLICYATTACH_IDENTIFIER A INNER JOIN
AGGNE.PRD.OUTPUT_UWADJUST_BSP_POLICYATTACH B ON TRIM(A.PUREPOLICYNUMBER) = TRIM(B.POLICYNUMBER)
AND TRIM(A.EXPIRINGID_P) = TRIM(B.EXPIRINGID_P)
AND TRIM(A.CMLNUMBER) = TRIM(B.CMLNUMBER)
WHERE B.COVERAGE = 'FL';