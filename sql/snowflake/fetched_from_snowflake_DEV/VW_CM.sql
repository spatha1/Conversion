create or replace view VW_CM(
	PUREPOLICYNUMBER,
	CM,
	LOAD_DATE
) as 
with CTE1 as(
SELECT SPLIT_PART(TRIM(ID), '|', 1)  AS PUREPOLICYNUMBER,SPLIT_PART(TRIM(ID), '|', 3)  AS EXPIRYID_P, * FROM AGGNE.DEV.CV_FLEET_VEHICLE_TARGET 
)
SELECT
  PUREPOLICYNUMBER,
  LISTAGG(CASE WHEN ITR_TYPE = 'BP_CV_Vehicle_main' THEN PAYLOAD END, '\n') AS CM,
  CAST(LOAD_DATE AS DATE) AS LOAD_DATE
FROM CTE1
WHERE ITR_TYPE IN ('BP_CV_Vehicle_main')
GROUP BY PUREPOLICYNUMBER,CAST(LOAD_DATE AS DATE);