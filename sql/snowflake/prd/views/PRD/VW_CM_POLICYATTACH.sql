create or replace view VW_CM_POLICYATTACH(
	ID,
	CM,
	LOAD_DATE
) as 
with CTE1 as(
SELECT  * FROM AGGNE.PRD.CV_FLEET_VEHICLE_TARGET_POLICYATTACH  WHERE ITR_TYPE IN ('BP_CV_Vehicle_main') 
),CTE2 AS (
SELECT DISTINCT 
  ACTUALID,PAYLOAD,
  -- LISTAGG(CASE WHEN ITR_TYPE = 'BP_CV_Vehicle_main' THEN PAYLOAD END, '\n') AS CM,
  CAST(LOAD_DATE AS DATE) AS LOAD_DATE
FROM CTE1 T1 INNER JOIN AGGNE.PRD.CV_RISK_COV_FINAL_VIEW_POLICYATTACH T2 ON T1.ID=T2.PUREPOLICYNUMBER
GROUP BY ACTUALID,PAYLOAD,CAST(LOAD_DATE AS DATE)
)
SELECT ACTUALID AS ID,LISTAGG( PAYLOAD, '\n') AS CM,CAST(LOAD_DATE AS DATE) AS LOAD_DATE FROM CTE2
GROUP BY ACTUALID,CAST(LOAD_DATE AS DATE)
;