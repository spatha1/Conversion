create or replace view PA_BC_IDENTIFIER(
	ID,
	PUREPOLICYNUMBER,
	EXPIRINGID_P,
	CMLNUMBER,
	PUREEXPIRYDATE,
	COUNTRY,
	PRODUCT,
	BUSINESSCONTENTS_IND,
	COVERAGE,
	CONTENTSLIMIT,
	STOCKLIMITEXVEHICLESWATERCRAFT,
	PERSONALEFFECTSLIMIT,
	MOTORFUELSLIMIT,
	VEHICLESINSTOCKLIMIT,
	CUSTOMERSVEHICLESLIMIT,
	WATERCRAFTINSTOCKUNDER8MLIMIT,
	CUSTOMERSWATERCRAFTUNDER8MLIMIT,
	EMPLOYEETOOLSOFTRADELIMIT,
	ACCIDENTALLOSSORDAMAGELIMIT,
	BCFLOODPROTECTION,
	FLOODDAMAGE,
	HAILDAMAGE,
	PROPORTIONOFHAILNETTING,
	LANDSLIDELIMIT,
	BCVOLUNTARY,
	VOLUNTARYEXCESS,
	EARTHQUAKEEXCESS,
	FLOODEXCESS,
	HAILDAMAGEEXCESS,
	STANDARDEXCESS,
	IMPOSEDEXCESS,
	RECURRINGINDICATOR,
	UNDERWRITINGDESCRIPTION,
	AJADJUSTMENTVALUE,
	AJADJUSTMENTPERCENT,
	ADJUSTMENTSELECTION,
	ADJUSTMENTDOLLARANDPERCENT
) as
WITH
PB AS (
  SELECT
      ROW_NUMBER() OVER (
        PARTITION BY TRIM(PUREPOLICYNUMBER)
        ORDER BY SD ASC, ED DESC, LENGTH(INSURANCE_FILE_CNT_LIST) DESC
      ) AS RNO,
      CONCAT(
        TRIM(PUREPOLICYNUMBER),'|',TRIM(CMLNUMBER),'|',TRIM(EXPIRINGID_P_LIST),'|',TRIM(INSURANCE_FILE_CNT_LIST)
      ) AS ID,
      *
  FROM POLICYATTACH_BP_V1
),

BD AS ( 
  SELECT *
  FROM AGGNE.DEV.location_bc_coverage_policyattach
),

PB_FLAT AS (
  SELECT
      pb.*,

      /* ✅ token-to-token (zipped) by index */
      TRIM(f_ifc.value::STRING) AS INSURANCE_FILE_CNT_TOKEN,
      TRIM(f_exp.value::STRING) AS EXPIRINGID_P_TOKEN

  FROM PB pb

  /* Flatten IFC list */
  , LATERAL FLATTEN(
        INPUT => SPLIT(pb.INSURANCE_FILE_CNT_LIST, ',')
    ) f_ifc

  /* Flatten Expiring list */
  , LATERAL FLATTEN(
        INPUT => SPLIT(pb.EXPIRINGID_P_LIST, ',')
    ) f_exp

  /* ✅ THIS is the key fix: align by position */
  WHERE f_ifc.index = f_exp.index
)

SELECT DISTINCT PB.ID,BD.* EXCLUDE (INSURANCE_FILE_CNT)
FROM PB_FLAT pb
INNER JOIN BD
  ON TRIM(pb.PUREPolicyNumber)       = TRIM(BD.PUREPolicyNumber)
 AND TRIM(pb.CMLNumber)              = TRIM(BD.CMLNumber)
 AND TRIM(pb.EXPIRINGID_P_TOKEN)     = TRIM(BD.ExpiringID_P)
 AND TRIM(pb.INSURANCE_FILE_CNT_TOKEN) = TRIM(BD.INSURANCE_FILE_CNT)
WHERE pb.PUREPOLICYNUMBER = 'P00001641';