create or replace view VW_FV(
	PUREPOLICYNUMBER,
	FV,
	LOAD_DATE
) as 
with CTE1 as(
SELECT SPLIT_PART(TRIM(ID), '|', 1)  AS PUREPOLICYNUMBER,SPLIT_PART(TRIM(ID), '|', 3)  AS EXPIRYID_P, * FROM AGGNE.DEV.RISK_FLEET_VEHICLE_TARGET 
)
SELECT
  PUREPOLICYNUMBER,
  LISTAGG(CASE WHEN ITR_TYPE = 'BP_Fleet_Vehicle_main' THEN PAYLOAD END, '\n') AS FV,
  CAST(LOAD_DATE AS DATE) AS LOAD_DATE
FROM CTE1
WHERE ITR_TYPE IN ('BP_Fleet_Vehicle_main')
GROUP BY PUREPOLICYNUMBER,CAST(LOAD_DATE AS DATE);