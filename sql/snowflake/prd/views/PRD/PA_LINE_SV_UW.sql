create or replace view PA_LINE_SV_UW(
	PUREPOLICYNUMBER,
	LEGACYPOLICYNUMBER,
	EXPIRINGID_P,
	CMLNUMBER,
	RECURRINGINDICATOR,
	UNDERWRITINGDESCRIPTION,
	ADJUSTMENTDOLLARANDPERCENT,
	ADJUSTMENTSELECTION
) as
SELECT
    ID AS PUREPOLICYNUMBER,
    CAST(T1.POLICYNUMBER AS VARCHAR) AS LEGACYPOLICYNUMBER,
    CAST(T1.EXPIRINGID_P AS VARCHAR) AS EXPIRINGID_P,
    CAST(T1.cmlnumber AS VARCHAR) AS CMLNUMBER,
   CAST('1' AS VARCHAR) AS RECURRINGINDICATOR,
        CAST(REPLACE(REPLACE(UWADJUSTNOTE,  '&', '&amp;'),'''', '''''') AS VARCHAR) AS UnderwritingDescription,
            CAST(cast(UWADJUSTAMOUNT AS NUMBER(38,0)) AS VARCHAR) AS AdjustmentDollarAndPercent,
    CAST('1' AS VARCHAR) AS AdjustmentSelection
    FROM AGGNE.PRD.OUTPUT_UWADJUST_BSP_POLICYATTACH T1 INNER JOIN AGGNE.PRD.LINE_SV_COVERAGE_POLICYATTACH_IDENTIFIER T2 ON TRIM(T1.POLICYNUMBER)=TRIM(T2.PUREPOLICYNUMBER) AND T1.EXPIRINGID_P=T2.EXPIRINGID_P
    WHERE T1.COVERAGE='SV' AND UWADJUSTAMOUNT IS NOT NULL;