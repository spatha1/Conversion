create or replace view LINE_PPL_PAYLOAD(
	PUREPOLICYNUMBER,
	LINE_PPL_UW,
	LINE_PPL_CLAUSE,
	VOLUNTARYEXCESS,
	ASSUMEDLIABILITY,
	CONTRACTANDSUBCON,
	ASSUMEDLIABILITYLIMIT,
	CONTRACTANDSUBCONLIMIT,
	EQUIPMENTGOODSLIMIT,
	EQUIPMENTGOODS,
	PROPERTYOWNER,
	PROTECTIONTYPESTANDARD,
	PROPERTYOWNERSLIABILITYLIMIT,
	PRODUCTSANDPUBLICLIABILITYLIMIT,
	RECTIFYINGFAULTY,
	RECTIFYINGFAULTY_IND,
	COSTOFRECTIFYINGLIMIT,
	PRODUCTANDPUBLIC_IND,
	CONTRACTANDAGREEMENTUNDERWRITER,
	CONTRACTANDAGREEMENTUNDERWRITER_DETAILS,
	EQUIPMENTGOODSDETAILS,
	PPCLMCNT,
	PPCLMINCD,
	PPEXPPREM,
	EXP_PREM_PPLHA_SD,
	EXP_PREM_PPCCA_SD,
	EXP_PREM_PPDFW_SD,
	EXP_PREM_PPGHO_SD,
	EXP_PREM_PPPOO_SD,
	EXP_PREM_PPRFW_SD,
	EXP_PREM_PPRUF_SD,
	EXP_PREM_PPSTB_SD,
	EXP_PREM_PPSTD_SD,
	EXP_PREM_PPCCC_SD,
	PROPERTYOWNERSONLY_XML,
	LOAD_DATE
) as
 with cte_SAMPLE_CBP_LOCATION as
(
select distinct PUREPOLICYNUMBER,cmlnumber,EXPIRINGID_P from AGGNE.DEV.SAMPLE_CBP WHERE EXPIRYDATE>='2026-01-01'
),cte_COVERAGES as 
(
select distinct PUREPOLICYNUMBER,cmlnumber,EXPIRINGID_P,
CAST(CAST(COALESCE(VOLUNTARYEXCESS,0) AS NUMBER(36,0))AS VARCHAR) AS VOLUNTARYEXCESS,
-- CAST(COALESCE(PP1ASSUMELIABCOVER,0) AS VARCHAR) AS ASSUMEDLIABILITY,
case when ASSUMEDLIABILITY='Taken' then '1' else '0' end  AS ASSUMEDLIABILITY,
CAST((
        CASE 
            WHEN CONTRACTORSANDSUBCONTRACTORS = 'Taken' THEN 1 
            ELSE 0 
        END )AS VARCHAR(10)
    ) AS CONTRACTANDSUBCON
, 
CAST(
        (CASE 
            WHEN EQUIPMENTGOODS = 'Taken' THEN 1 
            ELSE 0 
        END )AS VARCHAR(10)
    ) AS EQUIPMENTGOODS
,
CAST(
        (CASE 
            WHEN PROPERTYOWNER = 'Taken' THEN 1 
            ELSE 0 
        END )AS VARCHAR(10)
    )  AS PROPERTYOWNER,
    CAST(
        (CASE 
            WHEN STANDARD = 'Taken' THEN 1 
            ELSE 0 
        END )AS VARCHAR(10)
    )  AS STANDARD,
    
CAST(COALESCE(PROPERTYOWNERSLIABILITYLIMIT,0) AS VARCHAR) AS PROPERTYOWNERSLIABILITYLIMIT,
CAST(COALESCE(PRODUCTSANDPUBLICLIABILITYLIMIT,0) AS VARCHAR) AS PRODUCTSANDPUBLICLIABILITYLIMIT,
CAST(COALESCE(PP1RECTIFYFAULTYWORK,0) AS VARCHAR) AS RECTIFYINGFAULTY,
CAST(COALESCE(COSTOFRECTIFYINGLIMIT,0) AS VARCHAR) AS COSTOFRECTIFYINGLIMIT,
CAST(COALESCE(PRODUCTANDPUBLIC_IND,0) AS VARCHAR) AS PRODUCTANDPUBLIC_IND,
CAST(CONTRACTANDAGREEMENTUNDERWRITER AS VARCHAR) AS CONTRACTANDAGREEMENTUNDERWRITER,
CAST(COALESCE(DETAILS,'') AS VARCHAR) AS CONTRACTANDAGREEMENTUNDERWRITER_DETAILS,
CAST(COALESCE(EQUIPMENTGOODSDETAILS,'') AS VARCHAR) AS EQUIPMENTGOODSDETAILS
from AGGNE.DEV.Line_PublicLiability_Coverage T1 WHERE T1.EXPIRYDATE>='2026-01-01'

) 
, CTE_EXCESS AS(
SELECT DISTINCT
    CAST(trim(T2.PUREPOLICYNUMBER) ||'|' || TRIM(T2.cmlnumber) ||'|' || TRIM(T2.EXPIRINGID_P) AS VARCHAR) AS PUREPOLICYNUMBER,
t2.PUREPOLICYNUMBER AS LEGACYPOLICYNUMBER,T2.cmlnumber,T2.EXPIRINGID_P,
CAST(COALESCE(VOLUNTARYEXCESS,0) AS VARCHAR) AS VOLUNTARYEXCESS,
CAST(COALESCE("ASSUMEDLIABILITY",0) AS VARCHAR) AS ASSUMEDLIABILITY,
CAST(COALESCE(CONTRACTANDSUBCON,0) AS VARCHAR) AS CONTRACTANDSUBCON,
CAST(COALESCE(EQUIPMENTGOODS,0) AS VARCHAR) AS EQUIPMENTGOODS,
CAST(COALESCE(PROPERTYOWNER,0) AS VARCHAR) AS PROPERTYOWNER,
CAST(COALESCE(STANDARD,0) AS VARCHAR) AS STANDARD,
CAST(COALESCE(PROPERTYOWNERSLIABILITYLIMIT,0) AS VARCHAR) AS PROPERTYOWNERSLIABILITYLIMIT,
CAST(COALESCE(PRODUCTSANDPUBLICLIABILITYLIMIT,0) AS VARCHAR) AS PRODUCTSANDPUBLICLIABILITYLIMIT,
CAST(COALESCE("RECTIFYINGFAULTY",0) AS VARCHAR) AS RECTIFYINGFAULTY,
CAST(COALESCE("COSTOFRECTIFYINGLIMIT",0) AS VARCHAR) AS COSTOFRECTIFYINGLIMIT,
CAST(COALESCE(PRODUCTANDPUBLIC_IND,0) AS VARCHAR) AS PRODUCTANDPUBLIC_IND,
CAST(CONTRACTANDAGREEMENTUNDERWRITER AS VARCHAR) AS CONTRACTANDAGREEMENTUNDERWRITER,
CAST(COALESCE(CONTRACTANDAGREEMENTUNDERWRITER_DETAILS,'') AS VARCHAR) AS CONTRACTANDAGREEMENTUNDERWRITER_DETAILS,
CAST(COALESCE(EQUIPMENTGOODSDETAILS,'') AS VARCHAR) AS EQUIPMENTGOODSDETAILS
FROM 
cte_SAMPLE_CBP_LOCATION T1 
INNER JOIN cte_COVERAGES T2 ON
-- T1.EXPIRINGID_P=T2.EXPIRINGID_P AND 
TRIM(T1.PUREPOLICYNUMBER)=TRIM(T2.PUREPOLICYNUMBER)
)
,CTE_LISTAGG AS(
SELECT
  ID,
  LISTAGG(CASE WHEN ITR_TYPE = 'BP_Line_PPL_1_UW' THEN payload END, '\n') AS LINE_PPL_UW,
  LISTAGG(CASE WHEN ITR_TYPE = 'BP_Line_PPL_2_CLAUSE' THEN payload END, '\n') AS LINE_PPL_CLAUSE,
  CAST(LOAD_DATE AS DATE) AS LOAD_DATE
FROM AGGNE.DEV.LINE_PPL_Target
WHERE ITR_TYPE IN ('BP_Line_PPL_1_UW','BP_Line_PPL_2_CLAUSE') 
GROUP BY ID,CAST(LOAD_DATE AS DATE)
),
SUB_COV_PREM AS (
SELECT
  PUREPOLICYNUMBER,
  PPLHA_SD,
  PPCCA_SD,
  PPDFW_SD,
  PPGHO_SD,
  PPPOO_SD,
 PPRFW_SD,
PPRUF_SD,
PPSTB_SD,
PPSTD_SD,
PPCCC_SD
  
FROM (
  SELECT PUREPOLICYNUMBER, SUB_COVERAGE, EXPPREMIUM
  FROM AGGNE.DEV.VW_OUTPUT_SUBCOVERAGE_BSP
) src
PIVOT (
  SUM(EXPPREMIUM) FOR SUB_COVERAGE IN (
    ('PPLHA_SD') AS PPLHA_SD,
    ('PPCCA_SD') AS PPCCA_SD,
    ('PPDFW_SD') AS PPDFW_SD,
    ('PPGHO_SD') AS PPGHO_SD,
    ('PPPOO_SD') AS PPPOO_SD,
    ('PPRFW_SD') AS PPRFW_SD,
    ('PPRUF_SD') AS PPRUF_SD,
    ('PPSTB_SD') AS PPSTB_SD,
    ('PPSTD_SD') AS PPSTD_SD,
    ('PPCCC_SD') AS PPCCC_SD
  )
) p
ORDER BY PUREPOLICYNUMBER
)

SELECT distinct 
T1.PUREPOLICYNUMBER,
CASE WHEN LINE_PPL_UW IS NOT NULL AND LINE_PPL_UW<> '' THEN CAST(LINE_PPL_UW AS VARCHAR) ELSE '' END AS LINE_PPL_UW,
CASE WHEN LINE_PPL_CLAUSE IS NOT NULL AND LINE_PPL_CLAUSE<> '' THEN '<Clauses><Type>PublicProductLiability</Type>'||CAST(LINE_PPL_CLAUSE AS VARCHAR)||'</Clauses>' ELSE '' END AS LINE_PPL_CLAUSE,
--CAST(LINE_PPL_CLAUSE AS VARCHAR) AS LINE_PPL_CLAUSE2,
CAST(CAST(COALESCE(VOLUNTARYEXCESS,0)AS NUMBER(10,0)) AS VARCHAR) AS VOLUNTARYEXCESS,
CAST(CAST(COALESCE("ASSUMEDLIABILITY",0)AS NUMBER(10,0)) AS VARCHAR) AS ASSUMEDLIABILITY,
CAST(CAST(COALESCE(CONTRACTANDSUBCON,0)AS NUMBER(10,0)) AS VARCHAR) AS CONTRACTANDSUBCON,
CASE WHEN ASSUMEDLIABILITY=1 THEN CAST(CAST(COALESCE(PRODUCTSANDPUBLICLIABILITYLIMIT,0)AS NUMBER(10,0)) AS VARCHAR) ELSE '' END AS ASSUMEDLIABILITYLIMIT,
CASE WHEN CONTRACTANDSUBCON =1 THEN CAST(CAST(COALESCE(PRODUCTSANDPUBLICLIABILITYLIMIT,0)AS NUMBER(10,0)) AS VARCHAR)ELSE '' END AS CONTRACTANDSUBCONLIMIT,
CASE WHEN EQUIPMENTGOODS=1 THEN CAST(CAST(COALESCE(PRODUCTSANDPUBLICLIABILITYLIMIT,0)AS NUMBER(10,0)) AS VARCHAR) ELSE '' END AS EQUIPMENTGOODSLIMIT,
CAST(CAST(COALESCE(EQUIPMENTGOODS,0)AS NUMBER(10,0)) AS VARCHAR) AS EQUIPMENTGOODS,
CAST(CAST(COALESCE(PROPERTYOWNER,0)AS NUMBER(10,0)) AS VARCHAR) AS PROPERTYOWNER,
CAST(CAST(COALESCE(STANDARD,0)AS NUMBER(10,0)) AS VARCHAR) AS PROTECTIONTYPESTANDARD,
CAST(CAST(COALESCE(PROPERTYOWNERSLIABILITYLIMIT,0)AS NUMBER(10,0)) AS VARCHAR) AS PROPERTYOWNERSLIABILITYLIMIT,
CAST(CAST(COALESCE(PRODUCTSANDPUBLICLIABILITYLIMIT,0)AS NUMBER(10,0)) AS VARCHAR) AS PRODUCTSANDPUBLICLIABILITYLIMIT,
CAST(CAST(COALESCE("RECTIFYINGFAULTY",0)AS NUMBER(10,0)) AS VARCHAR) AS RECTIFYINGFAULTY,
CASE WHEN RECTIFYINGFAULTY=1 THEN 'Taken' else 'NotTaken' END AS RECTIFYINGFAULTY_IND,
CAST(CAST(COALESCE("COSTOFRECTIFYINGLIMIT",0)AS NUMBER(10,0)) AS VARCHAR) AS COSTOFRECTIFYINGLIMIT,
CAST(CAST(COALESCE(PRODUCTANDPUBLIC_IND,0)AS NUMBER(10,0)) AS VARCHAR) AS PRODUCTANDPUBLIC_IND,
CAST(CONTRACTANDAGREEMENTUNDERWRITER AS VARCHAR) AS CONTRACTANDAGREEMENTUNDERWRITER,
CAST(COALESCE(CONTRACTANDAGREEMENTUNDERWRITER_DETAILS,'') AS VARCHAR) AS CONTRACTANDAGREEMENTUNDERWRITER_DETAILS,
CAST(COALESCE(EQUIPMENTGOODSDETAILS,'') AS VARCHAR) AS EQUIPMENTGOODSDETAILS,
CAST(CAST(COALESCE(T4.PPCLMCNT ,0)AS NUMBER(10,0)) AS VARCHAR) AS PPCLMCNT,
CAST(CAST(COALESCE(T4.PPCLMINCD,0)AS NUMBER(10,0)) AS VARCHAR) AS PPCLMINCD,
CAST(COALESCE(T4.PPEXPPREM,0) AS VARCHAR) AS PPEXPPREM,
CAST(COALESCE(CAST(PPLHA_SD AS NUMBER(36,3)),0)AS VARCHAR) AS EXP_PREM_PPLHA_SD,
CAST(COALESCE(CAST(PPCCA_SD AS NUMBER(36,3)),0)AS VARCHAR) AS EXP_PREM_PPCCA_SD,
CAST(COALESCE(CAST(PPDFW_SD AS NUMBER(36,3)),0)AS VARCHAR) AS EXP_PREM_PPDFW_SD,
CAST(COALESCE(CAST(PPGHO_SD AS NUMBER(36,3)),0)AS VARCHAR) AS EXP_PREM_PPGHO_SD,
CAST(COALESCE(CAST(PPPOO_SD AS NUMBER(36,3)),0)AS VARCHAR) AS EXP_PREM_PPPOO_SD,
CAST(COALESCE(CAST(PPRFW_SD AS NUMBER(36,3)),0)AS VARCHAR) AS EXP_PREM_PPRFW_SD,
CAST(COALESCE(CAST(PPRUF_SD AS NUMBER(36,3)),0)AS VARCHAR) AS EXP_PREM_PPRUF_SD,
CAST(COALESCE(CAST(PPSTB_SD AS NUMBER(36,3)),0)AS VARCHAR) AS EXP_PREM_PPSTB_SD,
CAST(COALESCE(CAST(PPSTD_SD AS NUMBER(36,3)),0)AS VARCHAR) AS EXP_PREM_PPSTD_SD,
CAST(COALESCE(CAST(PPCCC_SD AS NUMBER(36,3)),0)AS VARCHAR) AS EXP_PREM_PPCCC_SD,
coalesce(T6.PROPERTYOWNERSONLY_XML,'<coverage>
	<Indicator>0</Indicator>
	<Type>POO_SD</Type>
	<Code>PPPOO_SD</Code>
	<Description>Property Owners Only</Description>
	<limit>
		<Type>POO_SD</Type>
		<iValue>0</iValue>
	</limit>
	<Premium>0</Premium>
</coverage>') PROPERTYOWNERSONLY_XML,
CAST(GETDATE() AS DATE) AS LOAD_DATE
FROM CTE_EXCESS T1 
-- INNER JOIN  AGGNE.DEV.LINE_PPL_Target T2 ON T1.PUREPOLICYNUMBER=T2.ID
LEFT JOIN CTE_LISTAGG T3 ON T1.PUREPOLICYNUMBER = T3.ID 
LEFT JOIN AGGNE.DEV.VW_OUTPUT_COVERAGE_BSP T4 ON T1.PUREPOLICYNUMBER=T4.PUREPOLICYNUMBER 
LEFT JOIN SUB_COV_PREM T5 ON T1.PUREPOLICYNUMBER=T5.PUREPOLICYNUMBER
LEFT JOIN AGGNE.DEV.LINE_PPL_PropertyOwnersOnly_PAYLOAD t6 ON T1.PUREPOLICYNUMBER=T6.PUREPOLICYNUMBER;