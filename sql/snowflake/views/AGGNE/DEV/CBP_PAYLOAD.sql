ON  TRIM(T1.LEGACYPOLICYNUMBER) = SPLIT_PART(TRIM(T18.ID), '|', 1) AND T18.ITR_TYPE='LINE_SV' AND   T18.load_date in (select max(load_date) as load_date  from AGGNE.DEV.LINE_SV_Target)
