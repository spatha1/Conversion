-- Evidence: DEV quote Q0132851 (P00006837) — both "Specified Items Away from the
-- Premises" and "Unspecified Items Away from the Premises" radios show NO selection.
-- ============================================================
--
-- ROOT CAUSE (manuscript Carrier_PersonalProtectionBase_1_0_0_0.xml, ~line 6634/6651):
--   ContentsAndStocksInput.SpecifiedItemsAwayPremises   path = coverage[Type="SPE_SD"]/sValue
--   ContentsAndStocksInput.UnspecifiedItemsAwayPremises path = coverage[Type="POR_SD"]/sValue
-- i.e. the two radios READ THE sVALUE OF THE SPE_SD / POR_SD SUB-COVERAGE BLOCKS.
--   * Our SPE_SD block sends SVALUE = '' (blank)          -> Specified radio unset
--   * We send NO POR_SD block at all (was commented out)  -> Unspecified radio unset
-- (Proof of mechanism: Accidental Loss Or Damage renders correctly because CAD_SD
--  carries a real <sValue>Taken/NotTaken</sValue>.)
--
-- SOURCE RULE (SAS HomeContents_coversionscriptCapricorn.txt):
--   SpecifiedItemsAway   = 'Taken' iff PER_ITEMSAWAYFROMPREM rows exist   (HC_02.SPECIFIEDITEMSAWAY,   183 Taken)
--   UnspecifiedItemsAway = 'Taken' iff HCUnspecifiedItems in (1,2)        (HC_02.UNSPECIFIEDITEMSAWAY, 1,204 Taken)
-- Premium rows already exist in Output_SubCover_PER: HCSPE_SD (608), HCPOR_SD (1,204).
--
-- CHANGES vs live view (GET_DDL 2026-07-17):
--   1. SPE_SD block: SVALUE '' -> <sValue>Taken/NotTaken</sValue> from SPECIFIEDITEMSAWAY;
--      INDICATOR hardcoded 1 -> derived from the same flag.
--   2. NEW POR_SD block ("Portable Items" / Unspecified Items Away) from UNSPECIFIEDITEMSAWAY,
--      premium joined on SUB_COVERAGE='HCPOR_SD'.
--   All other blocks byte-identical to live.
-- NOTE: supersedes the earlier idea of driving SPE_SD from ANYITEMSEXCEEDVALUE — that flag
-- belongs to the separate "specified contents >= $15k" question, not this radio.
-- ============================================================

CREATE OR REPLACE VIEW PER_HC_SUBCOVERAGES(
	PUREPOLICYNUMBER,
	LEGACYPOLICYNUMBER,
	CMLNUMBER,
	COVERAGE,
	COVERAGETYPE,
	DESCRIPTION,
	TYPE,
	CODE,
	IVALUE,
	SVALUE,
	INDICATOR,
	EXP_PREM
) as
SELECT DISTINCT
CAST(trim(T1.PUREPOLICYNUMBER) ||'|' || TRIM(T1.cmlnumber) ||'|' || TRIM(T1.EXPIRINGID_P) AS VARCHAR) AS PUREPOLICYNUMBER,
T1.PUREPOLICYNUMBER AS LEGACYPOLICYNUMBER,
    T1.cmlnumber,
    T1.EXPIRINGID_P AS Coverage,
    'Building' AS CoverageType,
    'Standard' AS Description,
    'CNT_SD' AS Type,
    'HCCNT_SD' AS CODE,
    CAST(CAST(COALESCE(HOMECONTENTSLIMIT_NEW,0) AS NUMBER(10,0)) AS VARCHAR)   AS IVALUE,
     '' AS SVALUE,
    CAST(CASE WHEN COALESCE(HOMECONTENTSLIMIT_NEW,0) > 0 THEN 1 ELSE 0 END AS VARCHAR) AS INDICATOR,
    CASE WHEN SUB_COVERAGE='HCCNT_SD' THEN CAST(CAST(COALESCE(EXPPREMIUM ,0) AS NUMBER(36,3)) AS VARCHAR) ELSE cast(0 as varchar)
    END AS EXP_PREM
FROM AGGNE.DEV.HC_02 T1 LEFT JOIN  AGGNE.DEV.VW_OUTPUT_SUBCOVERAGE_BSP T2
ON CAST(trim(T1.PUREPOLICYNUMBER) ||'|' || TRIM(T1.cmlnumber) ||'|' || TRIM(T1.EXPIRINGID_P) AS VARCHAR)=T2.PUREPOLICYNUMBER
AND T1.EXPIRINGID_P=T2.EXPIRINGID_P AND SUB_COVERAGE='HCCNT_SD'

UNION ALL

SELECT DISTINCT
CAST(trim(T1.PUREPOLICYNUMBER) ||'|' || TRIM(T1.cmlnumber) ||'|' || TRIM(T1.EXPIRINGID_P) AS VARCHAR) AS PUREPOLICYNUMBER,
T1.PUREPOLICYNUMBER AS LEGACYPOLICYNUMBER,
    T1.cmlnumber,
    T1.EXPIRINGID_P AS Coverage,
    'Building' AS CoverageType,
    'Accidental Damage' AS Description,
    'CAD_SD' AS Type,
    'HCCAD_SD' AS CODE,
    CAST(CAST(COALESCE(ACCIDENTALLOSSORDAMAGELIMIT,0) AS NUMBER(20,0))AS VARCHAR)  AS IVALUE,
     CONCAT('<sValue>',case when COALESCE(ACCIDENTALLOSSORDAMAGE, '')='Taken' then 'Taken' ELSE 'NotTaken' end , '</sValue>') AS SVALUE,
    CAST(CASE WHEN COALESCE(ACCIDENTALLOSSORDAMAGE,'')='Taken' THEN 1 ELSE 0 END AS VARCHAR) AS INDICATOR,
    CASE WHEN SUB_COVERAGE='HCCAD_SD' THEN CAST(CAST(COALESCE(EXPPREMIUM ,0) AS NUMBER(36,3)) AS VARCHAR) ELSE cast(0 as varchar)
    END AS EXP_PREM
FROM AGGNE.DEV.HC_02 T1 LEFT JOIN  AGGNE.DEV.VW_OUTPUT_SUBCOVERAGE_BSP T2
ON CAST(trim(T1.PUREPOLICYNUMBER) ||'|' || TRIM(T1.cmlnumber) ||'|' || TRIM(T1.EXPIRINGID_P) AS VARCHAR)=T2.PUREPOLICYNUMBER
AND T1.EXPIRINGID_P=T2.EXPIRINGID_P AND SUB_COVERAGE='HCCAD_SD'

UNION ALL

SELECT DISTINCT
CAST(trim(T1.PUREPOLICYNUMBER) ||'|' || TRIM(T1.cmlnumber) ||'|' || TRIM(T1.EXPIRINGID_P) AS VARCHAR) AS PUREPOLICYNUMBER,
T1.PUREPOLICYNUMBER AS LEGACYPOLICYNUMBER,
    T1.cmlnumber,
    T1.EXPIRINGID_P AS Coverage,
    'Building' AS CoverageType,
    'Specified Items' AS Description,
    'SPE_SD' AS Type,
    'HCSPE_SD' AS CODE,
    ''  AS IVALUE,
    -- FIX 2026-07-17 (was: '' -> radio unset): manuscript reads this block's sValue as the
    -- "Specified Items Away from the Premises" Taken/NotTaken radio
    CONCAT('<sValue>',case when COALESCE(T1.SPECIFIEDITEMSAWAY, '')='Taken' then 'Taken' ELSE 'NotTaken' end , '</sValue>') AS SVALUE,
    -- FIX 2026-07-17 (was hardcoded 1): follow the same flag
    CAST(CASE WHEN COALESCE(T1.SPECIFIEDITEMSAWAY,'')='Taken' THEN 1 ELSE 0 END AS VARCHAR) AS INDICATOR,
    CASE WHEN SUB_COVERAGE='HCSPE_SD' THEN CAST(CAST(COALESCE(EXPPREMIUM ,0) AS NUMBER(36,3)) AS VARCHAR) ELSE cast(0 as varchar)
    END AS EXP_PREM
FROM AGGNE.DEV.HC_02 T1 LEFT JOIN  AGGNE.DEV.VW_OUTPUT_SUBCOVERAGE_BSP T2
ON CAST(trim(T1.PUREPOLICYNUMBER) ||'|' || TRIM(T1.cmlnumber) ||'|' || TRIM(T1.EXPIRINGID_P) AS VARCHAR)=T2.PUREPOLICYNUMBER
AND T1.EXPIRINGID_P=T2.EXPIRINGID_P AND SUB_COVERAGE='HCSPE_SD'

