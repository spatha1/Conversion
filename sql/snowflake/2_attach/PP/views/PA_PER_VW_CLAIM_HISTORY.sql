create or replace view PA_PER_VW_CLAIM_HISTORY(
	PUREPOLICYNUMBER,
	ACTUALID,
	CMLNUMBER,
	DATEOFCLAIM,
	AMOUNTPAID,
	LINE,
	CAUSE
) as  
WITH CTE1 AS(
SELECT DISTINCT
T1.ID AS PUREPOLICYNUMBER,T1.ACTUALID,
    TRIM(T1.PUREPOLICYNUMBER) AS LEGACYPOLICYNUMBER,
    TRIM(T1.CMLNUMBER) AS CMLNUMBER,
    TRY_TO_DATE(REGEXP_REPLACE(TRIM(T1.DATEOFCLAIM), '[A-Za-z]', ''), 'YYYY-MM-DD')AS DATEOFCLAIM,
    TO_VARCHAR(T1.AMOUNTPAID) AS AMOUNTPAID,
    TO_VARCHAR(T1.LINE) AS LINE,
    TO_VARCHAR(T1.CAUSE) AS CAUSE
FROM AGGNE.PRD.CLAIMHISTORY_policyattach_IDENTIFIER AS T1  --7592
INNER JOIN AGGNE.PRD.POLICYATTACH_PER_IDENTIFIER AS T2 --6869
ON TRIM(T1.PUREPOLICYNUMBER)=TRIM(T2.PUREPOLICYNUMBER) AND T1.EXPIRINGID_P=T2.EXPIRINGID_P 
-- WHERE  T2.EFFECTIVEDATE>='2026-01-01' --5167
) SELECT DISTINCT 
    TRIM(T1.PUREPOLICYNUMBER)AS PUREPOLICYNUMBER,ACTUALID,
    TRIM(T1.CMLNUMBER)AS CMLNUMBER,
    -- Clean and parse DATEOFCLAIM safely
    TO_CHAR(DATEOFCLAIM::DATE, 'YYYY-MM-DD') AS DATEOFCLAIM ,
    TO_VARCHAR(T1.AMOUNTPAID) AS AMOUNTPAID,
    TO_VARCHAR(T1.LINE) AS LINE,
    TO_VARCHAR(T1.CAUSE) AS CAUSE 
    FROM CTE1 T1 ;