create or replace view PER_HB_BUILDING_UW(
	PUREPOLICYNUMBER,
	LEGACYPOLICYNUMBER,
	EXPIRINGID_P,
	INSURANCE_FILE_CNT,
	RECURRINGINDICATOR,
	UNDERWRITINGDESCRIPTION,
	ADJUSTMENTDOLLARANDPERCENT,
	ADJUSTMENTSELECTION,
	COVERAGE
) as
SELECT DISTINCT
    ID AS PUREPOLICYNUMBER,
    CAST(T1.PUREPOLICYNUMBER AS VARCHAR) AS LEGACYPOLICYNUMBER,
    CAST(T1.EXPIRINGID_P AS VARCHAR) AS EXPIRINGID_P,
    CAST(T1.INSURANCE_FILE_CNT AS VARCHAR) AS INSURANCE_FILE_CNT,
    CAST('1'  AS VARCHAR) RECURRINGINDICATOR,
    CAST(REPLACE(REPLACE(T2.UWADJUSTNOTE,  '&', '&amp;'),'''', '''''') AS VARCHAR) AS UnderwritingDescription,
    CAST(T2.UWADJUSTAMOUNT AS VARCHAR) AS AdjustmentDollarAndPercent,
    CAST('1'  AS VARCHAR)  AS AdjustmentSelection,
    CAST(T2.COVERAGE AS VARCHAR) AS COVERAGE
FROM AGGNE.PRD.HB_02_Policyattach_IDENTIFIER T1
INNER JOIN AGGNE.PRD.Output_UWAdjust_PER_Policyattach T2
    ON TRIM(T1.PUREPOLICYNUMBER) = TRIM(T2.POLICYNUMBER)
    AND T1.EXPIRINGID_P = T2.EXPIRINGID_P
    WHERE COVERAGE='HB';