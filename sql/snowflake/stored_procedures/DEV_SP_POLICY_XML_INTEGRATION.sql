CREATE OR REPLACE PROCEDURE "SP_POLICY_XML_INTEGRATION"("POLICYNUM" VARCHAR, "DATEOFLOSS" VARCHAR)
RETURNS TABLE ("PAYLOAD" ARRAY)
LANGUAGE SQL
COMMENT='This Stored Procedure enables Policy Search Integration for Duck Creek'
EXECUTE AS OWNER
AS '
DECLARE
RES RESULTSET DEFAULT (SELECT NULL::STRING AS PAYLOAD);
BEGIN
RES:= (SELECT * FROM TABLE(AGGNE.DEV.UDF_GET_POLICY_XMl(:POLICYNUM,:DATEOFLOSS)));
RETURN TABLE(RES);
END;
';