create or replace view PA_LINE_GP_CLAUSE(
	PUREPOLICYNUMBER,
	PUREPOLICYBINDERID,
	EXPIRINGID_P,
	DCCLAUSETYPE,
	DCINPUT
) as
SELECT 
T1.PUREPOLICYNUMBER,
CAST(T1.PUREPOLICYBINDERID AS VARCHAR) AS PUREPOLICYBINDERID,
CAST(T2.EXPIRINGID_P AS VARCHAR) AS EXPIRINGID_P,
CAST(DCCLAUSETYPE AS VARCHAR) AS DCCLAUSETYPE,
CAST(DCINPUT  AS VARCHAR) AS DCINPUT
FROM AGGNE.PRD.CLAUSES_Policyattach T1
INNER  JOIN AGGNE.PRD.line_gp_coverage_policyattach_IDENTIFIER T2 ON trim(T1.PUREPOLICYNUMBER)=TRIM(T2.PUREPOLICYNUMBER) AND T1.PUREPOLICYBINDERID=T2.EXPIRINGID_P
WHERE T1.COVERAGE='GP' AND _IS_CURRENT='TRUE';