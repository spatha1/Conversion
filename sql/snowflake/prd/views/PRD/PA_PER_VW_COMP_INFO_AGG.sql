create or replace view PA_PER_VW_COMP_INFO_AGG(
	ID,
	ITR_TYPE,
	PAYLOAD,
	LOAD_DATE
) as
SELECT DISTINCT 
    id,
    itr_type,
    LISTAGG(payload, '\n') WITHIN GROUP (ORDER BY load_date) AS payload,
    CAST(LOAD_DATE AS DATE)
FROM AGGNE.PRD.PA_PER_COMPETITOR_INFORMATION_TARGET T1  INNER JOIN AGGNE.PRD.PA_PER_VW_CBP_COMPETITOR_INFORMATION T2 ON T1.ID=T2.PUREPOLICYNUMBER
GROUP BY id, itr_type,CAST(LOAD_DATE AS DATE);