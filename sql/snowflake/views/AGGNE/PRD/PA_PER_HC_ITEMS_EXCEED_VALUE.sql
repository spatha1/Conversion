create or replace view PA_PER_HC_ITEMS_EXCEED_VALUE(
	PUREPOLICYNUMBER,
	LEGACYPOLICYNUMBER,
	VALUE,
	DESCRIPTION
) as
SELECT
  ID AS PUREPOLICYNUMBER,
    PUREPOLICYNUMBER AS LEGACYPOLICYNUMBER,
    CONCAT('<Value>',case when VALUE IS NOT NULL then cast(CAST(COALESCE(VALUE ,0) AS NUMBER(10,0))as varchar) ELSE '' end , '</Value>') AS VALUE,
    CONCAT('<Description>',case when DESCRIPTION IS NOT NULL then  CAST(DESCRIPTION AS VARCHAR) ELSE '' end , '</Description>') AS DESCRIPTION,
    FROM 
    AGGNE.PRD.HC_02_Policyattach_IDENTIFIER
 ;