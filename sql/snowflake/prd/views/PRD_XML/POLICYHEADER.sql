create or replace view POLICYHEADER(
	POLICY_KEY,
	ID,
	POLICY_NUMBER,
	POLICYEFFECTIVEDATE,
	POLICYEXPIRATIONDATE,
	LOAD_TS,
	POLICY_STATUS,
	LINE_OF_BUSINESS,
	CURRENCY,
	POLICY_TERM,
	RATING_STATE,
	PACKAGE_POLICY,
	ANZSIC_CODE,
	POLICY_TYPE,
	SIC_CODE,
	CML_NUMBER,
	CSL_NUMBER,
	RAM_NAME,
	INSURED_ENTITY_TYPE,
	INSURED_NAME,
	INSURED_ABN,
	INSURED_EMAIL,
	INSURED_PHONE,
	INSURED_ADDRESS1,
	INSURED_CITY,
	INSURED_STATE,
	INSURED_POSTCODE,
	INSURED_COUNTRY,
	CONTACT_FIRST_NAME,
	CONTACT_LAST_NAME,
	CONTACT_EMAIL,
	CONTACT_PHONE,
	ASSIGNED_USER,
	ASSIGNED_USER_EMAIL,
	ADDITIONAL_CONTACT_NAME,
	ADDITIONAL_CONTACT_EMAIL,
	ADDITIONAL_CONTACT_PHONE,
	AGENCY_NAME,
	AGENCY_INTERNAL_ID,
	TOTAL_VEHICLES,
	TOTAL_COVERAGES,
	TOTAL_LOCATIONS,
	TOTAL_BUILDINGS
) as
SELECT
    POLICY_KEY,
    ID,
    POLICY_NUMBER,
    POLICYEFFECTIVEDATE,
    POLICYEXPIRATIONDATE,
    LOAD_TS,

    -- Policy fields
    REGEXP_SUBSTR(POLICY_ATTACH_XML, '<PolicyStatus>([^<]+)</PolicyStatus>',
                  1,1,'e',1)                                                    AS policy_status,
    REGEXP_SUBSTR(POLICY_ATTACH_XML, '<LineOfBusiness>([^<]+)</LineOfBusiness>',
                  1,1,'e',1)                                                    AS line_of_business,
    REGEXP_SUBSTR(POLICY_ATTACH_XML, '<PolicyCurrencyCode>([^<]+)</PolicyCurrencyCode>',
                  1,1,'e',1)                                                    AS currency,
    REGEXP_SUBSTR(POLICY_ATTACH_XML, '<PolicyTerm>([^<]+)</PolicyTerm>',
                  1,1,'e',1)                                                    AS policy_term,
    REGEXP_SUBSTR(POLICY_ATTACH_XML, '<PrimaryRatingState>([^<]+)</PrimaryRatingState>',
                  1,1,'e',1)                                                    AS rating_state,
    REGEXP_SUBSTR(POLICY_ATTACH_XML, '<PackagePolicy>([^<]+)</PackagePolicy>',
                  1,1,'e',1)                                                    AS package_policy,
    REGEXP_SUBSTR(POLICY_ATTACH_XML, '<ANZSICCode>([^<]+)</ANZSICCode>',
                  1,1,'e',1)                                                    AS anzsic_code,
    REGEXP_SUBSTR(POLICY_ATTACH_XML, '<PolicyType>([^<]+)</PolicyType>',
                  1,1,'e',1)                                                    AS policy_type,
    REGEXP_SUBSTR(POLICY_ATTACH_XML, '<SICCode>([^<]+)</SICCode>',
                  1,1,'e',1)                                                    AS sic_code,

    -- CML / CSL
    REGEXP_SUBSTR(POLICY_ATTACH_XML, '<CMLNumber>([^<]+)</CMLNumber>',
                  1,1,'e',1)                                                    AS cml_number,
    REGEXP_SUBSTR(POLICY_ATTACH_XML, '<CSLNumber>([^<]+)</CSLNumber>',
                  1,1,'e',1)                                                    AS csl_number,
    REGEXP_SUBSTR(POLICY_ATTACH_XML, '<RAMName>([^<]+)</RAMName>',
                  1,1,'e',1)                                                    AS ram_name,

    -- Insured
    REGEXP_SUBSTR(POLICY_ATTACH_XML, '<Insured[^>]*>.*?<EntityType>([^<]+)</EntityType>',
                  1,1,'es',1)                                                   AS insured_entity_type,
    REGEXP_SUBSTR(POLICY_ATTACH_XML, '<Insured[^>]*>.*?<Name>([^<]+)</Name>',
                  1,1,'es',1)                                                   AS insured_name,
    REGEXP_SUBSTR(POLICY_ATTACH_XML, '<Insured[^>]*>.*?<ABNNumber>([^<]+)</ABNNumber>',
                  1,1,'es',1)                                                   AS insured_abn,
    REGEXP_SUBSTR(POLICY_ATTACH_XML, '<Insured[^>]*>.*?<Email>([^<]+)</Email>',
                  1,1,'es',1)                                                   AS insured_email,
    REGEXP_SUBSTR(POLICY_ATTACH_XML, '<Insured[^>]*>.*?<PrimaryPhone>([^<]+)</PrimaryPhone>',
                  1,1,'es',1)                                                   AS insured_phone,
    REGEXP_SUBSTR(POLICY_ATTACH_XML, '<Insured[^>]*>.*?<Address1>([^<]+)</Address1>',
                  1,1,'es',1)                                                   AS insured_address1,
    REGEXP_SUBSTR(POLICY_ATTACH_XML, '<Insured[^>]*>.*?<City>([^<]+)</City>',
                  1,1,'es',1)                                                   AS insured_city,
    REGEXP_SUBSTR(POLICY_ATTACH_XML, '<Insured[^>]*>.*?<State>([^<]+)</State>',
                  1,1,'es',1)                                                   AS insured_state,
    REGEXP_SUBSTR(POLICY_ATTACH_XML, '<Insured[^>]*>.*?<ZipCode>([^<]+)</ZipCode>',
                  1,1,'es',1)                                                   AS insured_postcode,
    REGEXP_SUBSTR(POLICY_ATTACH_XML, '<Insured[^>]*>.*?<Country>([^<]+)</Country>',
                  1,1,'es',1)                                                   AS insured_country,

    -- Contact
    REGEXP_SUBSTR(POLICY_ATTACH_XML, '<Contact>.*?<FirstName>([^<]+)</FirstName>',
                  1,1,'es',1)                                                   AS contact_first_name,
    REGEXP_SUBSTR(POLICY_ATTACH_XML, '<Contact>.*?<LastName>([^<]+)</LastName>',
                  1,1,'es',1)                                                   AS contact_last_name,
    REGEXP_SUBSTR(POLICY_ATTACH_XML, '<Contact>.*?<Email>([^<]+)</Email>',
                  1,1,'es',1)                                                   AS contact_email,
    REGEXP_SUBSTR(POLICY_ATTACH_XML, '<Contact>.*?<PhoneNumber>([^<]+)</PhoneNumber>',
                  1,1,'es',1)                                                   AS contact_phone,

    -- Assigned User
    REGEXP_SUBSTR(POLICY_ATTACH_XML, '<User[^>]*>.*?<FullName>([^<]+)</FullName>',
                  1,1,'es',1)                                                   AS assigned_user,
    REGEXP_SUBSTR(POLICY_ATTACH_XML, '<User[^>]*>.*?<Email>([^<]+)</Email>',
                  1,1,'es',1)                                                   AS assigned_user_email,

    -- Additional Contact
    REGEXP_SUBSTR(POLICY_ATTACH_XML,
                  '<AdditionalContactInfo[^>]*>.*?<Name>([^<]+)</Name>',
                  1,1,'es',1)                                                   AS additional_contact_name,
    REGEXP_SUBSTR(POLICY_ATTACH_XML,
                  '<AdditionalContactInfo[^>]*>.*?<Email>([^<]+)</Email>',
                  1,1,'es',1)                                                   AS additional_contact_email,
    REGEXP_SUBSTR(POLICY_ATTACH_XML,
                  '<AdditionalContactInfo[^>]*>.*?<Phone>([^<]+)</Phone>',
                  1,1,'es',1)                                                   AS additional_contact_phone,

    -- Agency
    REGEXP_SUBSTR(POLICY_ATTACH_XML, '<Agency[^>]*>.*?<Name>([^<]+)</Name>',
                  1,1,'es',1)                                                   AS agency_name,
    REGEXP_SUBSTR(POLICY_ATTACH_XML, '<Agency[^>]*>.*?<InternalPartyId>([^<]+)</InternalPartyId>',
                  1,1,'es',1)                                                   AS agency_internal_id,

    -- Counts
    REGEXP_COUNT(POLICY_ATTACH_XML, '<Risk id=')                                AS total_vehicles,
    REGEXP_COUNT(POLICY_ATTACH_XML, '<Coverage id=')                            AS total_coverages,
    REGEXP_COUNT(POLICY_ATTACH_XML, '<Location id=')                            AS total_locations,
    REGEXP_COUNT(POLICY_ATTACH_XML, '<Building id=')                            AS total_buildings

FROM AGGNE.PRD.POLICY_ATTACH_TABLE;