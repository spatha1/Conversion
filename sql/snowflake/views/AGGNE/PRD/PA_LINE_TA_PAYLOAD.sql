create or replace view PA_LINE_TA_PAYLOAD(
	PUREPOLICYNUMBER,
	LINE_TA_UW,
	LINE_TA_CLAUSE,
	VOLUNTARYEXCESS,
	STANDARDEXCESS,
	IMPOSEDEXCESS,
	TAXAUDIT_IND,
	TAXAUDITLIMIT,
	AUSTRALIATAXOFFICENOTIFICATION,
	AUSTAXOFFICENOTIFICATIONDETAILS,
	AUSTAXOFFICEHASBEENINVESTIGATED,
	DETAILS,
	TACLMCNT,
	TACLMINCD,
	TAEXPPREM,
	EXP_PREM_TASTD_SD,
	LOAD_DATE
) as
 with cte_SAMPLE_CBP_LOCATION as
(
select distinct LEGACYPOLICYNUMBER,cmlnumber,EXPIRINGID_P,INSURANCE_FILE_CNT,ID from AGGNE.PRD.SAMPLE_POLICYATTACH_FINAL_IDENTIFIER -- WHERE DATEDIFF(DAY,EXPIRYDATE,GETDATE())<=45  
),cte_COVERAGES as 
(
select distinct PUREPOLICYNUMBER,cmlnumber,EXPIRINGID_P,ID,INSURANCE_FILE_CNT,
CAST(COALESCE(VOLUNTARYEXCESS ,0) AS VARCHAR) AS VOLUNTARYEXCESS ,
CAST(COALESCE(TAXAUDIT_IND  ,0) AS VARCHAR) AS TAXAUDIT_IND  ,
CAST(COALESCE(TALIMIT ,0) AS VARCHAR) AS TAXAUDITLIMIT ,
CAST(COALESCE(AUSTRALIATAXOFFICENOTIFICATION,'') AS VARCHAR) AS AUSTRALIATAXOFFICENOTIFICATION ,
CAST(COALESCE(AUSTAXOFFICENOTIFICATIONDETAILS ,'') AS VARCHAR) AS AUSTAXOFFICENOTIFICATIONDETAILS ,
CAST(CAST(COALESCE(STANDARDEXCESS,0)AS NUMBER(10,0)) AS VARCHAR) AS STANDARDEXCESS,
CAST(CAST(COALESCE(IMPOSEDEXCESS,0)AS NUMBER(10,0)) AS VARCHAR) AS IMPOSEDEXCESS,
CAST(COALESCE(AUSTAXOFFICEHASBEENINVESTIGATED ,'') AS VARCHAR) AS AUSTAXOFFICEHASBEENINVESTIGATED ,
CAST(COALESCE(DETAILS ,'No') AS VARCHAR) AS DETAILS 
from AGGNE.PRD.line_ta_coverage_policyattach_IDENTIFIER T1 
) 
, CTE_EXCESS AS(
SELECT DISTINCT
  T2.ID AS PUREPOLICYNUMBER,
TRIM(t2.PUREPOLICYNUMBER) AS LEGACYPOLICYNUMBER,T2.cmlnumber,T2.EXPIRINGID_P,
CAST(COALESCE(VOLUNTARYEXCESS ,0) AS VARCHAR) AS VOLUNTARYEXCESS ,
CAST(COALESCE(TAXAUDIT_IND  ,0) AS VARCHAR) AS TAXAUDIT_IND  ,
CAST(COALESCE(TAXAUDITLIMIT ,0) AS VARCHAR) AS TAXAUDITLIMIT ,
CAST(COALESCE(AUSTRALIATAXOFFICENOTIFICATION ,'') AS VARCHAR) AS AUSTRALIATAXOFFICENOTIFICATION ,
CAST(COALESCE(AUSTAXOFFICENOTIFICATIONDETAILS ,'') AS VARCHAR) AS AUSTAXOFFICENOTIFICATIONDETAILS ,
CAST(COALESCE(AUSTAXOFFICEHASBEENINVESTIGATED ,'') AS VARCHAR) AS AUSTAXOFFICEHASBEENINVESTIGATED ,
CAST(CAST(COALESCE(STANDARDEXCESS,0)AS NUMBER(10,0)) AS VARCHAR) AS STANDARDEXCESS,
CAST(CAST(COALESCE(IMPOSEDEXCESS,0)AS NUMBER(10,0)) AS VARCHAR) AS IMPOSEDEXCESS,
CAST(COALESCE(DETAILS ,'') AS VARCHAR) AS DETAILS 
FROM 
cte_SAMPLE_CBP_LOCATION T1 
INNER JOIN cte_COVERAGES T2 ON T1.ID=T2.ID
)
,CTE_LISTAGG AS(
SELECT
  ID,
  LISTAGG(CASE WHEN ITR_TYPE = 'BP_LINE_TA_UW' THEN payload END, '\n') AS PA_LINE_TA_UW,
  LISTAGG(CASE WHEN ITR_TYPE = 'BP_LINE_TA_CLAUSE' THEN payload END, '\n') AS PA_LINE_TA_CLAUSE,
 CAST(LOAD_DATE AS DATE) AS LOAD_DATE
FROM AGGNE.PRD.PA_LINE_TA_Target
WHERE ITR_TYPE IN ('BP_LINE_TA_UW','BP_LINE_TA_CLAUSE')
GROUP BY ID,CAST(LOAD_DATE AS DATE)
)
,SUB_COV_PREM AS (
SELECT
  PUREPOLICYNUMBER,
TASTD_SD
FROM (
  SELECT PUREPOLICYNUMBER, SUB_COVERAGE, EXPPREMIUM
  FROM AGGNE.PRD.VW_OUTPUT_SUBCOVERAGE_BSP_POLICYATTACH
) src
PIVOT (
  SUM(EXPPREMIUM) FOR SUB_COVERAGE IN (
    ('TASTD_SD') AS TASTD_SD
  )
) p
)
SELECT distinct 
t1.PUREPOLICYNUMBER,
CASE WHEN PA_LINE_TA_UW IS NOT NULL AND PA_LINE_TA_UW<> '' THEN CAST(PA_LINE_TA_UW AS VARCHAR) ELSE '' END AS LINE_TA_UW,
-- CAST(LINE_TA_UW AS VARCHAR) AS LINE_TA_UW,
CASE WHEN PA_LINE_TA_CLAUSE IS NOT NULL AND PA_LINE_TA_CLAUSE<> '' THEN '<Clauses><Type>TaxAudit</Type>'||CAST(PA_LINE_TA_CLAUSE AS VARCHAR)||'</Clauses>' ELSE '' END AS LINE_TA_CLAUSE,
-- CAST(LINE_TA_CLAUSE AS VARCHAR) AS LINE_TA_CLAUSE,
CAST(CAST(COALESCE(VOLUNTARYEXCESS ,0) AS NUMBER(10,0))AS VARCHAR) AS VOLUNTARYEXCESS ,
CAST(CAST(COALESCE(STANDARDEXCESS,0)AS NUMBER(10,0)) AS VARCHAR) AS STANDARDEXCESS,
CAST(CAST(COALESCE(IMPOSEDEXCESS,0)AS NUMBER(10,0)) AS VARCHAR) AS IMPOSEDEXCESS,
CAST(CAST(COALESCE(TAXAUDIT_IND  ,0) AS NUMBER(10,0))AS VARCHAR) AS TAXAUDIT_IND  ,
CAST(CAST(COALESCE(TAXAUDITLIMIT ,0) AS NUMBER(10,0))AS VARCHAR) AS TAXAUDITLIMIT ,
CAST(COALESCE(AUSTRALIATAXOFFICENOTIFICATION ,'') AS VARCHAR) AS AUSTRALIATAXOFFICENOTIFICATION ,
CAST(COALESCE(AUSTAXOFFICENOTIFICATIONDETAILS ,'') AS VARCHAR) AS AUSTAXOFFICENOTIFICATIONDETAILS ,
CAST(COALESCE(AUSTAXOFFICEHASBEENINVESTIGATED ,'') AS VARCHAR) AS AUSTAXOFFICEHASBEENINVESTIGATED ,
CAST(COALESCE(DETAILS ,'No') AS VARCHAR) AS DETAILS ,
CAST(CAST(COALESCE(T4.TACLMCNT,0)AS NUMBER(10,0)) AS VARCHAR) AS TACLMCNT,
CAST(CAST(COALESCE(T4.TACLMINCD,0)AS NUMBER(10,0)) AS VARCHAR) AS TACLMINCD,
CAST(COALESCE(T4.TAEXPPREM,0) AS VARCHAR) AS TAEXPPREM,
CAST(COALESCE(CAST(TASTD_SD AS NUMBER(36,3)),0)AS VARCHAR) AS EXP_PREM_TASTD_SD,
CAST(GETDATE() AS DATE) AS LOAD_DATE
FROM CTE_EXCESS T1 --INNER JOIN  AGGNE.PRD.LINE_TA_Target T2 ON TRIM(T1.PUREPOLICYNUMBER)=TRIM(T2.ID)
LEFT  JOIN CTE_LISTAGG T3 ON TRIM(T1.LEGACYPOLICYNUMBER)= TRIM(T3.ID )
LEFT JOIN AGGNE.PRD.Output_Coverage_BSP_Policyattach  T4 
ON CAST(trim(T1.LEGACYPOLICYNUMBER) ||'|' || TRIM(T1.cmlnumber) ||'|' || TRIM(T1.EXPIRINGID_P) AS VARCHAR)=CAST(trim(T4.POLICYNUMBER) ||'|' || TRIM(T4.cmlnumber) ||'|' || TRIM(T4.EXPIRINGID_P) AS VARCHAR)
LEFT JOIN SUB_COV_PREM T5 ON CAST(trim(T1.LEGACYPOLICYNUMBER) ||'|' || TRIM(T1.cmlnumber) ||'|' || TRIM(T1.EXPIRINGID_P) AS VARCHAR)=T5.PUREPOLICYNUMBER;