create or replace view AGGNE.DEV.RISK_BUILDING_BG_COVERAGES(
	PUREPOLICYNUMBER,
	LEGACYPOLICYNUMBER,
	CMLNUMBER,
	COVERAGE,
	COVERAGETYPE,
	DESCRIPTION,
	TYPE,
	CODE,
	IVALUE,
	SVALUE,
	EXCESSINFO,
	EXTRAINFO,
	EXP_PREM,
	INDICATOR
) as

-- ── ALC_SD : Alcohol ─────────────────────────────────────────
SELECT
    CAST(trim(T1.PUREPOLICYNUMBER) ||'|' || TRIM(T1.cmlnumber) ||'|' || TRIM(T1.EXPIRINGID_P) AS VARCHAR) AS PUREPOLICYNUMBER,
    T1.PUREPOLICYNUMBER AS LEGACYPOLICYNUMBER,
    T1.cmlnumber,
    T1.EXPIRINGID_P AS Coverage,
    'Building_BG' AS CoverageType,
    'Alcohol' AS Description,
    'ALC_SD' AS Type,
    'BGALC_SD' AS Code,
    CAST(CAST(ALCOHOLLIMIT AS NUMBER(10,0)) AS VARCHAR) AS iValue,
    '' AS sValue,
    CONCAT('<Excess>','<CustomerVehicles/>','<Imposed/>','<Standard/>','<Voluntary>',CAST(CAST(COALESCE(VOLUNTARYEXCESS,0)AS NUMBER(10,0))AS VARCHAR),'</Voluntary>','<Amount/>','</Excess>') AS EXCESSINFO,
    '' AS EXTRAINFO,
    CASE WHEN SUB_COVERAGE='BGALC_SD' THEN CAST(CAST(COALESCE(EXPPREMIUM,0) AS NUMBER(36,3)) AS VARCHAR) ELSE CAST(0 AS VARCHAR) END AS EXP_PREM,
    CASE WHEN COALESCE(ALCOHOLLIMIT,0) > 0 THEN CAST(1 AS VARCHAR) ELSE CAST(0 AS VARCHAR) END AS INDICATOR
FROM AGGNE.DEV.Location_BG_Coverage T1
LEFT JOIN AGGNE.DEV.VW_OUTPUT_SUBCOVERAGE_BSP T2
    ON CAST(trim(T1.PUREPOLICYNUMBER)||'|'||TRIM(T1.cmlnumber)||'|'||TRIM(T1.EXPIRINGID_P) AS VARCHAR)=T2.PUREPOLICYNUMBER
    AND T1.EXPIRINGID_P=T2.EXPIRINGID_P AND SUB_COVERAGE='BGALC_SD'

