create or replace view PA_RISK_LOCATION_UW_COMBINE(
	ID,
	ACTUALID,
	PUREPOLICYNUMBER,
	EXPIRINGID_P,
	CMLNUMBER,
	RECURRINGINDICATOR,
	UNDERWRITINGDESCRIPTION,
	ADJUSTMENTDOLLARANDPERCENT,
	ADJUSTMENTSELECTION
) as
with cte as (
SELECT 
T2.ID,T2.ACTUALID,
    CAST(TRIM(T2.PUREPOLICYNUMBER) AS VARCHAR) AS PUREPOLICYNUMBER,
    CAST(T2.EXPIRINGID AS VARCHAR) AS EXPIRINGID_P,
    CAST(T2.cmlnumber AS VARCHAR) AS CMLNUMBER
    FROM  AGGNE.PRD.Location_01_Policyattach_IDENTIFIER T2 
    INNER JOIN AGGNE.PRD.sample_policyattach_final_identifier T3 ON T2.ID=T3.ID
    )
    select DISTINCT T2.* ,
     CAST('1' AS VARCHAR) AS RECURRINGINDICATOR,
    CAST(REPLACE(REPLACE(T1.UWADJUSTNOTE,  '&', '&amp;'),'''', '''''') AS VARCHAR) AS UNDERWRITINGDESCRIPTION,
    CAST(T1.UWADJUSTAMOUNT AS VARCHAR) AS ADJUSTMENTDOLLARANDPERCENT,
   CAST('1' AS VARCHAR) AS AdjustmentSelection
    from cte T2
    LEFT JOIN AGGNE.PRD.OUTPUT_UWADJUST_BSP_POLICYATTACH T1
    ON trim(T1.POLICYNUMBER) = trim(T2.PUREPOLICYNUMBER) AND T2.EXPIRINGID_P=T1.EXPIRINGID_P
    WHERE T1.COVERAGE='SU' AND UWADJUSTNOTE IS NOT NULL;