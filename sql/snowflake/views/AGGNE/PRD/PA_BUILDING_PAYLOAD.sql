create or replace view PA_BUILDING_PAYLOAD(
	PUREPOLICYNUMBER,
	LEGACYPOLICYNUMBER,
	CMLNUMBER,
	EXPIRINGID_P,
	COVERAGE,
	SUBCOV,
	LOC_BB_CLAUSE,
	UW,
	VOLUNTARYEXCESS,
	EARTHQUAKEEXCESS,
	GLASSEXCESS,
	FLOODEXCESS,
	STANDARDEXCESS,
	IMPOSEDEXCESS,
	BBCLMCNT,
	BBCLMINCD,
	BBEXPPREM,
	LOAD_DATE
) as
with cte_SAMPLE_CBP_LOCATION as
(
select distinct T1.PUREPOLICYNUMBER,T1.cmlnumber,T1.EXPIRINGID,T1.INSURANCE_FILE_CNT,T1.ID from AGGNE.PRD.LOCATION_01_POLICYATTACH_IDENTIFIER T1 INNER JOIN AGGNE.PRD.SAMPLE_POLICYATTACH_FINAL_IDENTIFIER T2 ON T1.ID=T2.ID
),cte_COVERAGES as 
(
select distinct PUREPOLICYNUMBER,cmlnumber,EXPIRINGID_P,INSURANCE_FILE_CNT,'BB' AS CLAUSE,'Building' AS  COVERAGE, VOLUNTARYEXCESS AS VOLUNTARYEXCESS,
EARTHQUAKEEXCESS,GLASSEXCESS,
CASE WHEN FLOODDAMAGE='Taken' THEN  FLOODEXCESS ELSE NULL END AS FLOODEXCESS,
STANDARDEXCESS,IMPOSEDEXCESS,ID
from AGGNE.PRD.location_bb_coverage_policyattach_IDENTIFIER T1 
) 
, CTE_EXCESS AS(
SELECT 
    T2.ID AS PUREPOLICYNUMBER,
t2.PUREPOLICYNUMBER AS LEGACYPOLICYNUMBER,T2.cmlnumber,T2.EXPIRINGID_P,COVERAGE,T2.VOLUNTARYEXCESS,
  CASE WHEN EARTHQUAKEEXCESS='$10000' THEN CAST(CAST(10000  AS  NUMBER(10,0) )AS VARCHAR) 
       WHEN EARTHQUAKEEXCESS='$20,000' THEN CAST(CAST(20000  AS  NUMBER(10,0) )AS VARCHAR) ELSE EARTHQUAKEEXCESS END AS EARTHQUAKEEXCESS
,GLASSEXCESS,FLOODEXCESS,STANDARDEXCESS,IMPOSEDEXCESS
FROM 
cte_SAMPLE_CBP_LOCATION T1 
INNER JOIN cte_COVERAGES T2 ON T1.ID=T2.ID
)
,CTE_LISTAGG AS(
SELECT
  ID,
  LISTAGG(CASE WHEN ITR_TYPE = 'BP_Building_SubCov' THEN payload END, '\n') AS SUBCOV,
  LISTAGG(CASE WHEN ITR_TYPE = 'BP_BUILDING_UW'     THEN payload END, '\n') AS UW,
  LISTAGG(CASE WHEN ITR_TYPE = 'BP_LOC_BB_CLAUSE'     THEN payload END, '\n') AS LOC_BB_CLAUSE,
  CAST(load_date AS DATE) AS LOAD_DATE
FROM AGGNE.PRD.PA_RISK_BUILDING_TARGET
WHERE ITR_TYPE IN ('BP_Building_SubCov', 'BP_BUILDING_UW','BP_LOC_BB_CLAUSE') 
GROUP BY ID, CAST(LOAD_DATE AS DATE)
)
SELECT distinct 
T1.PUREPOLICYNUMBER,
T1.LEGACYPOLICYNUMBER,T1.cmlnumber,T1.EXPIRINGID_P,
COVERAGE,
CAST(SUBCOV AS VARCHAR) AS SUBCOV,
CASE WHEN LOC_BB_CLAUSE IS NOT NULL AND LOC_BB_CLAUSE<> '' THEN '<Clauses><Type>Building</Type>'||CAST(LOC_BB_CLAUSE AS VARCHAR)||'</Clauses>' ELSE '' END AS LOC_BB_CLAUSE,
CAST(UW AS VARCHAR) AS UW,
-- CAST(LOC_BB_CLAUSE AS VARCHAR) AS LOC_BB_CLAUSE,
CAST(CAST(COALESCE(VOLUNTARYEXCESS,0)AS NUMBER(20,0)) AS VARCHAR) AS VOLUNTARYEXCESS,
CAST(CAST(REPLACE(REPLACE(EARTHQUAKEEXCESS, '$', ''), ',', '') AS NUMBER)AS VARCHAR) AS EARTHQUAKEEXCESS,
CAST(CAST(COALESCE(GLASSEXCESS,0)AS NUMBER(20,0)) AS VARCHAR) AS GLASSEXCESS,
CAST(CAST(COALESCE(FLOODEXCESS,0)AS NUMBER(20,0)) AS VARCHAR) AS FLOODEXCESS,
CAST(CAST(COALESCE(STANDARDEXCESS,0)AS NUMBER(20,0)) AS VARCHAR) AS STANDARDEXCESS,
CAST(CAST(COALESCE(IMPOSEDEXCESS,0)AS NUMBER(20,0)) AS VARCHAR) as IMPOSEDEXCESS,
CAST(COALESCE(T4.BBCLMCNT,0) AS VARCHAR) AS BBCLMCNT,
CAST(COALESCE(T4.BBCLMINCD,0) AS VARCHAR) AS BBCLMINCD,
CAST(COALESCE(T4.BBEXPPREM,0) AS VARCHAR) AS BBEXPPREM,
CAST(GETDATE() AS DATE) as LOAD_DATE
FROM CTE_EXCESS T1
-- LEFT JOIN  AGGNE.PRD.PA_RISK_BUILDING_TARGET T2 ON T1.PUREPOLICYNUMBER=T2.ID
LEFT JOIN CTE_LISTAGG T3 ON T1.PUREPOLICYNUMBER = T3.ID 
LEFT JOIN AGGNE.PRD.VW_OUTPUT_COVERAGE_BSP_policyattach T4 
ON CAST(trim(T1.LEGACYPOLICYNUMBER) ||'|' || TRIM(T1.cmlnumber) ||'|' || TRIM(T1.EXPIRINGID_P) AS VARCHAR)=CAST(trim(T4.POLICYNUMBER) ||'|' || TRIM(T4.cmlnumber) ||'|' || TRIM(T4.EXPIRINGID_P) AS VARCHAR)
WHERE   COVERAGE='Building'  ;