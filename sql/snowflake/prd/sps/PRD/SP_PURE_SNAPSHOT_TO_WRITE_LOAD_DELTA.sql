    WHEN CMLNUMBER = 'CML00002323' THEN 'P O BOX 3301'
    WHEN CMLNUMBER = 'CML00001232' THEN 'P O BOX 142'
    WHEN CMLNUMBER = 'CML00016574' THEN 'PO BOX 2397'
    WHEN CMLNUMBER = 'CML00027987' THEN '8 Kunara Crescent, Portland Victoria 3305'
    ELSE SITE_STREET
  END AS SITE_STREET,

  SITE_SUBURB,
  SITE_STATE,
  SITE_POSTCODE,
  CSLNUMBER,

  CASE
  /* Step 1: NULL or empty → default by country */
  WHEN PRIMARY_PHONE IS NULL OR TRIM(PRIMARY_PHONE) = '' THEN
    CASE
      WHEN TRIM(COUNTRY) IN ('AU', 'Australia') THEN '0400000000'
      WHEN TRIM(COUNTRY) IN ('NZ', 'New Zealand') THEN '0200000000'
      ELSE NULL
    END

  /* Step 2: Keep only valid digits-only phones with length 9/10/11 */
  WHEN LENGTH(REGEXP_REPLACE(PRIMARY_PHONE, '[^0-9]', '')) IN (9,10,11) THEN
    REGEXP_REPLACE(PRIMARY_PHONE, '[^0-9]', '')

  /* Step 3: Anything else → default by country */
  ELSE
    CASE
      WHEN TRIM(COUNTRY) IN ('AU', 'Australia') THEN '0400000000'
      WHEN TRIM(COUNTRY) IN ('NZ', 'New Zealand') THEN '0200000000'
      ELSE NULL
    END
END AS PRIMARY_PHONE,

  CASE
    WHEN TRIM(SITE_COUNTRY) = 'Australia'
         AND TRIM(PRIMARY_PHONE) LIKE '04%' THEN 'C'

    WHEN TRIM(SITE_COUNTRY) = 'New Zealand'
         AND TRIM(PRIMARY_PHONE) LIKE '02%' THEN 'C'

    ELSE 'T'
END AS PRIMARY_PHONE_TYPE,
  PRIMARY_EMAIL,
  PRIMARY_EMAIL_TYPE,
  PHONE_COUNT,
  EMAIL_COUNT,
  SECONDARYCONTACT_COUNT,
  SCONDARYCONTACT,
  OTHERPHONE, OTHEREMAIL,
  SCONDARYCONTACTKEY,
  PAID2DATE,
  MEM_REF,
  TO_VARCHAR(to_date(effective_date), 'YYYY-MM-DD') AS EFFECTIVE_DATE,
   case when mem_ref is not null and site_country = 'New Zealand' then 11 
when mem_ref is not null and site_country = 'Australia' then 10 else amount end::int as amount ,
  SECONDARYCONTACT_XMLDATA, EMAIL_XMLDATA, PHONE_XMLDATA,
  HASH_DIFF,
  EFFECTIVE_FROM,
  EFFECTIVE_TO,
  IS_CURRENT,
  ACTIVE_FLAG
FROM AGGNE.PRD.SCD2_PREPARED_SRC;



UPDATE AGGNE.PRD.DIM_PARTY_SNAPSHOT_ACTIVE_INACTIVE_MEMBERS_SCD2_DELTA tgt
  SET
    tgt.EFFECTIVE_TO = CURRENT_TIMESTAMP(),
    tgt.IS_CURRENT   = FALSE
  FROM AGGNE.PRD.V_DIM_PARTY_CML_CSL_NEW_FINAL_INACTIVE src
  WHERE tgt.IS_CURRENT = TRUE
    AND src.BK_CMLNUMBER = tgt.BK_CMLNUMBER
    AND src.HASH_DIFF    <> tgt.HASH_DIFF;

  ----------------------------------------------------------------
  -- 2) End-date rows that disappeared from source (soft delete)
  --    Mark ACTIVE_FLAG = FALSE to distinguish soft-deletes from history of changes
  ----------------------------------------------------------------
  UPDATE AGGNE.PRD.DIM_PARTY_SNAPSHOT_ACTIVE_INACTIVE_MEMBERS_SCD2_DELTA tgt
  SET
    tgt.EFFECTIVE_TO = CURRENT_TIMESTAMP(),
    tgt.IS_CURRENT   = FALSE,
    tgt.ACTIVE_FLAG  = FALSE
  WHERE tgt.IS_CURRENT = TRUE
    AND NOT EXISTS (
      SELECT 1
      FROM AGGNE.PRD.V_DIM_PARTY_CML_CSL_NEW_FINAL_INACTIVE src
      WHERE src.BK_CMLNUMBER = tgt.BK_CMLNUMBER
    );

  ----------------------------------------------------------------
  -- 3) Insert new keys and new versions for changed keys
  --    (If no current row with the same HASH exists, insert a fresh current version)
  ----------------------------------------------------------------
  INSERT INTO AGGNE.PRD.DIM_PARTY_SNAPSHOT_ACTIVE_INACTIVE_MEMBERS_SCD2_DELTA (
    BK_CMLNUMBER,
    MEMBER_TA_NUMBER, CSL_LEGAL_ENTITY, CML_RISK_ACCOUNT_MANAGER, CSL_AREA_MANAGER, CSL_ZONE, CSL_REGION,
    CSL_NUMBER, CML_LEGAL_ENTITY, CSL_MEMBER_STATUS, ABN_NZBN, STOP_CREDIT, STOP_CREDIT_REASON,
    CSL_TENURE, CSL_MONTHLY_SPEND, STANDARD_INDUSTRY_CODE, STANDARD_INDUSTRY_CODE_DESCRIPTION,
    CSL_CREDIT_LIMIT, CSL_CREDIT_RISK, CSL_CREDIT_USAGE, PROBABILITY_OF_DEFAULT,
    TA_PAYMENT_METHOD, STREET, SUBURB, STATE, POSTCODE, CONTACT_NAME, PHONE, EMAIL,
    SITE_COUNTRY, MESSAGE,
    CMLNUMBER, COUNTRY, CMLLEGALENTITY, CMLTRADINGNAME, MAINCONTACT,
    CORRESPONDENCELINE1, CORRESPONDENCELINE2, CORRESPONDENCELINE3, CORRESPONDENCELINE4, CORRESPONDENCEPOSTCODE,
    SITE_STREET, SITE_SUBURB, SITE_STATE, SITE_POSTCODE, CSLNUMBER,
    PRIMARY_PHONE, PRIMARY_PHONE_TYPE, PRIMARY_EMAIL, PRIMARY_EMAIL_TYPE,
    PHONE_COUNT, EMAIL_COUNT, SECONDARYCONTACT_COUNT, SCONDARYCONTACT, SCONDARYCONTACTKEY,
    OTHERPHONE, OTHEREMAIL,SECONDARYCONTACT_XMLDATA, EMAIL_XMLDATA, PHONE_XMLDATA,
    PAID2DATE, MEM_REF, EFFECTIVE_DATE, AMOUNT,
    HASH_DIFF, EFFECTIVE_FROM, EFFECTIVE_TO, IS_CURRENT, ACTIVE_FLAG
)
SELECT
    src.BK_CMLNUMBER,
    src.MEMBER_TA_NUMBER, src.CSL_LEGAL_ENTITY, src.CML_RISK_ACCOUNT_MANAGER, src.CSL_AREA_MANAGER, src.CSL_ZONE, src.CSL_REGION,
    src.CSL_NUMBER, src.CML_LEGAL_ENTITY, src.CSL_MEMBER_STATUS, src.ABN_NZBN,

    /* STOP_CREDIT → boolean-safe */
    CASE UPPER(TRIM(src.STOP_CREDIT))
      WHEN 'Y' THEN TRUE
      WHEN 'N' THEN FALSE
      WHEN 'TRUE' THEN TRUE
      WHEN 'FALSE' THEN FALSE
      WHEN '1' THEN TRUE
      WHEN '0' THEN FALSE
      ELSE NULL
    END AS STOP_CREDIT,

    src.STOP_CREDIT_REASON,

    /* Numeric-safe coercions ('' → NULL, bad → NULL) */
    TRY_TO_DECIMAL(NULLIF(TRIM(src.CSL_TENURE), ''),          38, 9) AS CSL_TENURE,
    TRY_TO_DECIMAL(NULLIF(TRIM(src.CSL_MONTHLY_SPEND), ''),   38, 9) AS CSL_MONTHLY_SPEND,
    src.STANDARD_INDUSTRY_CODE, src.STANDARD_INDUSTRY_CODE_DESCRIPTION,
    TRY_TO_DECIMAL(NULLIF(TRIM(src.CSL_CREDIT_LIMIT), ''),    38, 9) AS CSL_CREDIT_LIMIT,
    src.CSL_CREDIT_RISK,
    TRY_TO_DECIMAL(NULLIF(TRIM(src.CSL_CREDIT_USAGE), ''),    38, 9) AS CSL_CREDIT_USAGE,
    /* Already numeric in prepared source */
    src.PROBABILITY_OF_DEFAULT,

    src.TA_PAYMENT_METHOD, src.STREET, src.SUBURB, src.STATE, src.POSTCODE, src.CONTACT_NAME, src.PHONE, src.EMAIL,
    src.SITE_COUNTRY, src.MESSAGE,
    src.CMLNUMBER, src.COUNTRY, src.CMLLEGALENTITY, src.CMLTRADINGNAME, src.MAINCONTACT,
    src.CORRESPONDENCELINE1, src.CORRESPONDENCELINE2, src.CORRESPONDENCELINE3, src.CORRESPONDENCELINE4, src.CORRESPONDENCEPOSTCODE,
    src.SITE_STREET, src.SITE_SUBURB, src.SITE_STATE, src.SITE_POSTCODE, src.CSLNUMBER,
    src.PRIMARY_PHONE, src.PRIMARY_PHONE_TYPE, src.PRIMARY_EMAIL, src.PRIMARY_EMAIL_TYPE,

    /* Count fields → numeric-safe */
    TRY_TO_NUMBER(NULLIF(TRIM(src.PHONE_COUNT), ''))            AS PHONE_COUNT,
    TRY_TO_NUMBER(NULLIF(TRIM(src.EMAIL_COUNT), ''))            AS EMAIL_COUNT,
    TRY_TO_NUMBER(NULLIF(TRIM(src.SECONDARYCONTACT_COUNT), '')) AS SECONDARYCONTACT_COUNT,

    src.SCONDARYCONTACT, src.SCONDARYCONTACTKEY,
    src.OTHERPHONE, src.OTHEREMAIL,src.SECONDARYCONTACT_XMLDATA, src.EMAIL_XMLDATA, src.PHONE_XMLDATA,

    /* Dates/numeric-safe for amount */
    TO_CHAR(src.PAID2DATE::date ,'YYYY-MM-DD') as PAID2DATE , src.MEM_REF, TO_CHAR(src.EFFECTIVE_DATE::date ,'YYYY-MM-DD') as EFFECTIVE_DATE,
    TRY_TO_DECIMAL(NULLIF(TRIM(src.AMOUNT), ''), 38, 9)         AS AMOUNT,

    src.HASH_DIFF, CURRENT_TIMESTAMP(), NULL, TRUE, TRUE
FROM AGGNE.PRD.V_DIM_PARTY_CML_CSL_NEW_FINAL_INACTIVE src
LEFT JOIN AGGNE.PRD.DIM_PARTY_SNAPSHOT_ACTIVE_INACTIVE_MEMBERS_SCD2_DELTA cur
  ON cur.BK_CMLNUMBER = src.BK_CMLNUMBER
 AND cur.IS_CURRENT   = TRUE
WHERE cur.PARTY_DIM_ID IS NULL              -- DIM KEY
   OR cur.HASH_DIFF <> src.HASH_DIFF;


update AGGNE.PRD.DIM_PARTY_SNAPSHOT_ACTIVE_INACTIVE_MEMBERS_SCD2_DELTA   set SUBURB=trim(upper(SUBURB)),SITE_SUBURB=trim(upper(SITE_SUBURB)),CORRESPONDENCELINE3=trim(upper(CORRESPONDENCELINE3));
