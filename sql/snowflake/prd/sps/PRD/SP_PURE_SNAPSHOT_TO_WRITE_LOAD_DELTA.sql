CREATE OR REPLACE TRANSIENT TABLE AGGNE.PRD.T_CMLPAID2DATE_01 AS
WITH base AS (
  SELECT
      t17.CMLNUMBER                AS CMLNUMBER,
       t3.expiry_date::date  AS expiry_dt,
      t3.insurance_ref             AS insurance_ref
  FROM PRD_T5_EXTERNAL_AGGNE.PURE_SNAPSHOT.RISK t1
  JOIN PRD_T5_EXTERNAL_AGGNE.PURE_SNAPSHOT.RISK_FOLDER              t0  ON t1.risk_folder_cnt = t0.risk_folder_cnt
  JOIN PRD_T5_EXTERNAL_AGGNE.PURE_SNAPSHOT.INSURANCE_FILE_RISK_LINK t2  ON t1.risk_cnt = t2.risk_cnt
  JOIN PRD_T5_EXTERNAL_AGGNE.PURE_SNAPSHOT.INSURANCE_FILE           t3  ON t2.insurance_file_cnt = t3.insurance_file_cnt
  JOIN PRD_T5_EXTERNAL_AGGNE.PURE_SNAPSHOT.GIS_POLICY_LINK          t6  ON t3.insured_cnt = t6.party_cnt
  JOIN PRD_T5_EXTERNAL_AGGNE.PURE_SNAPSHOT.CAPPARTY_POLICY_BINDER   t7  ON t6.gis_policy_link_id = t7.gis_policy_link_id
  JOIN PRD_T5_EXTERNAL_AGGNE.PURE_SNAPSHOT.CAPPARTY_MEMBERCSL       t9  ON t7.CAPPARTY_Policy_Binder_id = t9.CAPPARTY_Policy_Binder_id
  JOIN PRD_T5_EXTERNAL_AGGNE.PURE_SNAPSHOT.PARTY                    t14 ON t3.insured_cnt = t14.party_cnt
  LEFT JOIN PRD_T5_EXTERNAL_AGGNE.PURE_SNAPSHOT.RISK_STATUS         t15 ON t1.risk_status_id = t15.risk_status_id
  LEFT JOIN PRD_T5_EXTERNAL_AGGNE.PURE_SNAPSHOT.INSURANCE_FILE_STATUS t16 ON t3.insurance_file_status_id = t16.insurance_file_status_id
  JOIN AGGNE.PRD.T_CML_SAMPLE                               t17 ON TRIM(t14.shortname) = TRIM(t17.CMLNUMBER)
  WHERE CAST(t3.expiry_date AS DATE) > DATEADD(day, -366, CURRENT_DATE())
    AND SUBSTR(t3.insurance_ref, 1, 1) = 'M'
    AND t3.insurance_file_type_id <> 3
    AND COALESCE(t16.description, '') <> 'Cancelled'
    AND t15.description IN ('Referred', 'Quoted')
),
agg AS (
  SELECT
      CMLNUMBER,
      MAX(expiry_dt)     AS max_expiry,
      MAX(insurance_ref) AS mem_ref
  FROM base
  GROUP BY CMLNUMBER
)
SELECT
    CMLNUMBER,
    mem_ref,
    TO_VARCHAR(CASE
      WHEN max_expiry > CURRENT_DATE()
       AND max_expiry < TO_DATE('2026-06-01')
        THEN DATEADD(year, 1, max_expiry)
      ELSE max_expiry
    END ,'YYYY-MM-DD') AS Paid2Date
FROM agg;

CREATE OR REPLACE TRANSIENT TABLE AGGNE.PRD.T_CMLPAID2DATE AS
SELECT
    CMLNUMBER,
    mem_ref,
    TO_VARCHAR(MAX(Paid2Date::date),'YYYY-MM-DD') AS Paid2Date
FROM AGGNE.PRD.T_CMLPAID2DATE_01
GROUP BY CMLNUMBER, mem_ref;



