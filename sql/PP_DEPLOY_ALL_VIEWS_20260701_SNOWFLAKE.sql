-- ══════════════════════════════════════════════════════════════════════════
-- VIEW 1: PER_ACCOUNT_LOC  (PP-CF-15 — NULL STATE guard)
-- ══════════════════════════════════════════════════════════════════════════

create or replace view AGGNE.DEV.PER_ACCOUNT_LOC(
	PUREPOLICYNUMBER,
	LEGACYPOLICYNUMBER,
	RISKNUMBER,
	STATE,
	ADDRESS1,
	SUBURB,
	POSTCODE,
	LOC_COUNTRY,
	ADDRESSOVERRIDE
) as
WITH cte1 as
(
SELECT  CAST(trim(T1.PUREPOLICYNUMBER) ||'|' || TRIM(T1.cmlnumber) ||'|' || TRIM(T1.EXPIRINGID_P) AS VARCHAR) AS ID,
T1.* FROM AGGNE.DEV.Locationdetails_PER T1 inner join AGGNE.DEV.SAMPLE_PER T2 on t1.PUREPOLICYNUMBER=T2.PUREPOLICYNUMBER AND T1.EXPIRINGID_P=T2.EXPIRINGID_P
WHERE   T1.EFFECTIVEDATE >= '2026-01-01'
),
cte2  AS (
SELECT CAST(trim(PUREPOLICYNUMBER) ||'|' || TRIM(cmlnumber) ||'|' || TRIM(EXPIRINGID_P) AS VARCHAR) AS PUREPOLICYNUMBER,
TRIM(PUREPOLICYNUMBER) as LEGACYPOLICYNUMBER,
STATE,
ADDRESS1,
SUBURB,
CAST(POSTCODE AS VARCHAR) AS POSTCODE,
COUNTRY,
EXPIRINGID_P,
CAST(COALESCE(CAST(RISKNUMBER AS NUMBER(10,0)), 0) AS VARCHAR) AS RISKNUMBER,
CAST(COALESCE(OVERRIDE, 0) AS VARCHAR) AS ADDRESSOVERRIDE
FROM AGGNE.DEV.Locationdetails_PER
)
SELECT
T1.PUREPOLICYNUMBER,
LEGACYPOLICYNUMBER,
T1.RISKNUMBER,
CASE
    WHEN TRIM(T1.COUNTRY) = 'New Zealand' THEN T1.STATE
    WHEN TRIM(T1.COUNTRY) = 'Australia' AND T1.STATE IS NOT NULL THEN CONCAT(T1.STATE, 'AU')  -- PP-CF-15: NULL guard prevents invalid 'AU' state code
    ELSE T1.STATE end as STATE,
T1.ADDRESS1,
T1.SUBURB,
CAST(T1.POSTCODE AS VARCHAR) AS POSTCODE,
CASE
    WHEN TRIM(T1.COUNTRY) = 'New Zealand' THEN 'NZ'
    WHEN TRIM(T1.COUNTRY) = 'Australia' THEN 'AU'
    ELSE TRIM(T1.COUNTRY) END AS LOC_COUNTRY,
T1.ADDRESSOVERRIDE
FROM ctE2 T1 INNER JOIN  CTE1 T2  ON T1.PUREPOLICYNUMBER=T2.ID ;


-- ══════════════════════════════════════════════════════════════════════════
-- VIEW 2: PER_HOME_BUILDING_PAYLOAD  (BUG-NEW-02 + BUG-NEW-03)
-- ══════════════════════════════════════════════════════════════════════════

create or replace view AGGNE.DEV.PER_HOME_BUILDING_PAYLOAD(
    PUREPOLICYNUMBER,
    COVERAGE,
    SUBCOV,
    HC_EXCEED_VALUES,
    HC_SPECIFIED_CONTENTS,
    VOLUNTARYEXCESS,
    ACCIDENTALLOSSORDAMAGE,
    SPECIFIEDITEMSAWAY,
    UNSPECIFIEDITEMSAWAY,
    UNSPECIFIEDITEMSAWAYLIMIT,
    ANYITEMSEXCEEDVALUE,
    HCCLMCNT,
    HCCLMINCD,
    HBEXPPREM,
    HOMEBUILDINGSLIMIT,
    LANDLORDPROTECTIONS,
    MINIMUMRENTALPERIOD,
    WEEKLYRENT,
    HBCLMCNT,
    HBCLMINCD,
    EXPPREM,
    HB_CLAUSE,
    HC_CLAUSE,
    UW,
    LOAD_DATE,
    HB_INDICATOR,
    HC_INDICATOR
) as
with cte_SAMPLE_CBP_LOCATION as
(
    select distinct
        trim(T1.PUREPOLICYNUMBER) AS PUREPOLICYNUMBER,
        trim(t1.CMLNUMBER)        AS CMLNUMBER,
        T1.EXPIRINGID_P
    from AGGNE.DEV.Locationdetails_PER T1
    INNER JOIN AGGNE.DEV.SAMPLE_PER T2
        ON TRIM(T1.PUREPOLICYNUMBER) = TRIM(T2.PUREPOLICYNUMBER)
    WHERE t1.EFFECTIVEDATE >= '2026-01-01'
),
cte_COVERAGES as
(
    select distinct
        HC.PUREPOLICYNUMBER, HC.cmlnumber, HC.EXPIRINGID_P,
        'BB'       AS CLAUSE,
        'Building' AS COVERAGE,
        HC.VOLUNTARYEXCESS,
        HC.ACCIDENTALLOSSORDAMAGE,
        HC.SPECIFIEDITEMSAWAY, HC.UNSPECIFIEDITEMSAWAY, HC.UNSPECIFIEDITEMSAWAYLIMIT,
        HC.ANYITEMSEXCEEDVALUE,
        1 AS HC_INDICATOR,
        CASE WHEN EXISTS (
            SELECT 1 FROM AGGNE.DEV.HB_01 H2
            WHERE TRIM(H2.PUREPOLICYNUMBER) = TRIM(HC.PUREPOLICYNUMBER)
              AND H2.EXPIRINGID_P           = HC.EXPIRINGID_P
        ) THEN 1 ELSE 0 END AS HB_INDICATOR
    from AGGNE.DEV.HC_02 HC

    UNION

    select distinct
        H.PUREPOLICYNUMBER, H.cmlnumber, H.EXPIRINGID_P,
        'BB'       AS CLAUSE,
        'Building' AS COVERAGE,
        COALESCE(H.VOLUNTARYEXCESS, 0)   AS VOLUNTARYEXCESS,
        H.ACCIDENTALLOSSORDAMAGE,
        NULL AS SPECIFIEDITEMSAWAY,
        NULL AS UNSPECIFIEDITEMSAWAY,
        NULL AS UNSPECIFIEDITEMSAWAYLIMIT,
        NULL AS ANYITEMSEXCEEDVALUE,
        0 AS HC_INDICATOR,
        1 AS HB_INDICATOR
    from AGGNE.DEV.HB_01 H
    WHERE NOT EXISTS (
        SELECT 1 FROM AGGNE.DEV.HC_02 HC2
        WHERE TRIM(H.PUREPOLICYNUMBER) = TRIM(HC2.PUREPOLICYNUMBER)
          AND H.EXPIRINGID_P           = HC2.EXPIRINGID_P
    )
),
CTE_EXCESS AS (
    SELECT
        CAST(
            TRIM(T2.PUREPOLICYNUMBER) || '|' ||
            TRIM(T2.cmlnumber)        || '|' ||
            TRIM(T2.EXPIRINGID_P)
        AS VARCHAR) AS PUREPOLICYNUMBER,
        t2.PUREPOLICYNUMBER AS LEGACYPOLICYNUMBER,
        T2.cmlnumber,
        T2.EXPIRINGID_P,
        COVERAGE,
        T2.VOLUNTARYEXCESS,
        CASE WHEN T2.ACCIDENTALLOSSORDAMAGE = 'Taken'
             THEN CAST(CAST(1 AS NUMBER(1,0)) AS VARCHAR)
             ELSE CAST(CAST(0 AS NUMBER(1,0)) AS VARCHAR)
        END AS ACCIDENTALLOSSORDAMAGE,
        SPECIFIEDITEMSAWAY, UNSPECIFIEDITEMSAWAY, UNSPECIFIEDITEMSAWAYLIMIT,
        ANYITEMSEXCEEDVALUE,
        T2.HC_INDICATOR,
        T2.HB_INDICATOR
    FROM cte_SAMPLE_CBP_LOCATION T1
    INNER JOIN cte_COVERAGES T2
        ON  T1.EXPIRINGID_P             = T2.EXPIRINGID_P
        AND TRIM(T1.PUREPOLICYNUMBER)   = TRIM(T2.PUREPOLICYNUMBER)
),
CTE_LISTAGG AS (
    SELECT
        ID,
        LISTAGG(CASE WHEN ITR_TYPE = 'Building_SubCov'        THEN payload END, '\n') AS SUBCOV,
        LISTAGG(CASE WHEN ITR_TYPE = 'HC_exceed_values'       THEN payload END, '\n') AS HC_exceed_values,
        LISTAGG(CASE WHEN ITR_TYPE = 'HC_Specified_Contents'  THEN payload END, '\n') AS HC_Specified_Contents,
        LISTAGG(CASE WHEN ITR_TYPE = 'BUILDING_UW'            THEN payload END, '\n') AS UW_ADJUST,  -- BUG-NEW-03
        CAST(LOAD_DATE AS DATE) AS LOAD_DATE
    FROM AGGNE.DEV.PER_HC_TARGET
    WHERE ITR_TYPE IN ('Building_SubCov', 'HC_exceed_values', 'HC_Specified_Contents', 'BUILDING_UW')
      AND CAST(LOAD_DATE AS DATE) = CAST(GETDATE() AS DATE)
    GROUP BY ID, CAST(LOAD_DATE AS DATE)
)
, CTE_BUILDING_CLAUSES AS (
    SELECT
        ID,
        LISTAGG(PAYLOAD, '\n') WITHIN GROUP (ORDER BY PAYLOAD) AS HB_CLAUSE_PAYLOAD
    FROM AGGNE.DEV.PER_BUILDING_TARGET
    WHERE ITR_TYPE = 'HB_CLAUSE'
      AND CAST(LOAD_DATE AS DATE) = CAST(GETDATE() AS DATE)
    GROUP BY ID
)
, CTE_HC_CLAUSES AS (
    SELECT
        ID,
        LISTAGG(PAYLOAD, '\n') WITHIN GROUP (ORDER BY PAYLOAD) AS HC_CLAUSE_PAYLOAD
    FROM AGGNE.DEV.PER_HC_TARGET
    WHERE ITR_TYPE = 'LOC_HC_CLAUSE'  -- BUG-NEW-02: was 'HC_CLAUSE'
      AND CAST(LOAD_DATE AS DATE) = CAST(GETDATE() AS DATE)
    GROUP BY ID
)
SELECT distinct
    T1.PUREPOLICYNUMBER,
    T1.COVERAGE,
    CAST(T3.SUBCOV               AS VARCHAR) AS SUBCOV,
    CAST(T3.HC_exceed_values     AS VARCHAR) AS HC_EXCEED_VALUES,
    CAST(T3.HC_Specified_Contents AS VARCHAR) AS HC_SPECIFIED_CONTENTS,
    CAST(CAST(COALESCE(T1.VOLUNTARYEXCESS, 0) AS NUMBER(20,0)) AS VARCHAR) AS VOLUNTARYEXCESS,
    T1.ACCIDENTALLOSSORDAMAGE AS ACCIDENTALLOSSORDAMAGE,
    CASE WHEN T1.SPECIFIEDITEMSAWAY = 'Taken' THEN 'Taken' ELSE 'Not Taken' END AS SPECIFIEDITEMSAWAY,
    CASE WHEN T1.UNSPECIFIEDITEMSAWAY = 'Taken' THEN 'Taken' ELSE 'Not Taken' END AS UNSPECIFIEDITEMSAWAY,
    CASE WHEN T1.UNSPECIFIEDITEMSAWAYLIMIT = '$2,000 per item up to $10,000 per event'
              THEN '2000peritemupto10000perevent'
         WHEN T1.UNSPECIFIEDITEMSAWAYLIMIT = '$1,250 per item up to $5,000 per event'
              THEN '1250peritemupto5000perevent'
         ELSE ''
    END AS UNSPECIFIEDITEMSAWAYLIMIT,
    CAST(COALESCE(T1.ANYITEMSEXCEEDVALUE, 'No') AS VARCHAR) AS ANYITEMSEXCEEDVALUE,
    CAST(COALESCE(T4.HCCLMCNT,  0) AS VARCHAR) AS HCCLMCNT,
    CAST(COALESCE(T4.HCCLMINCD, 0) AS VARCHAR) AS HCCLMINCD,
    CAST(COALESCE(T4.HMEXPPREM, 0) AS VARCHAR) AS HBEXPPREM,
    CAST(CAST(COALESCE(T5.HOMEBUILDINGSLIMIT, 0) AS NUMBER(10, 0)) AS VARCHAR) AS HOMEBUILDINGSLIMIT,
    CAST(COALESCE(T5.LANDLORDPROTECTIONS, '')                       AS VARCHAR) AS LANDLORDPROTECTIONS,
    CASE TRIM(T5.MINIMUMRENTALPERIOD)
        WHEN 'More than 90 Days' THEN 'Morethan90Days'
        WHEN 'Less than 90 Days' THEN 'Lessthan90Days'
        ELSE CAST(COALESCE(T5.MINIMUMRENTALPERIOD, '') AS VARCHAR)
    END AS MINIMUMRENTALPERIOD,
    CAST(CAST(COALESCE(T5.WEEKLYRENT, 0) AS NUMBER(10, 0))          AS VARCHAR) AS WEEKLYRENT,
    CAST(COALESCE(T4.HBCLMCNT,  0) AS VARCHAR) AS HBCLMCNT,
    CAST(COALESCE(T4.HBCLMINCD, 0) AS VARCHAR) AS HBCLMINCD,
    CAST(COALESCE(T4.HMEXPPREM, 0) AS VARCHAR) AS EXPPREM,
    CAST(COALESCE(T6.HB_CLAUSE_PAYLOAD, '') AS VARCHAR) AS HB_CLAUSE,
    CAST(COALESCE(T7.HC_CLAUSE_PAYLOAD, '') AS VARCHAR) AS HC_CLAUSE,
    CAST(COALESCE(T3.UW_ADJUST, '') AS VARCHAR) AS UW,  -- BUG-NEW-03
    CAST(GETDATE() AS DATE) AS LOAD_DATE,
    CAST(T1.HB_INDICATOR AS VARCHAR) AS HB_INDICATOR,
    CAST(T1.HC_INDICATOR AS VARCHAR) AS HC_INDICATOR
FROM CTE_EXCESS T1
LEFT JOIN AGGNE.DEV.PER_HC_TARGET T2
    ON T1.PUREPOLICYNUMBER = T2.ID
LEFT JOIN CTE_LISTAGG T3
    ON T1.PUREPOLICYNUMBER = T3.ID
LEFT JOIN AGGNE.DEV.Output_Coverage_PER T4
    ON T1.PUREPOLICYNUMBER = T4.POLICYNUMBER
LEFT JOIN AGGNE.DEV.HB_02 T5
    ON  TRIM(T1.LEGACYPOLICYNUMBER) = TRIM(T5.PUREPOLICYNUMBER)
    AND T1.EXPIRINGID_P             = T5.EXPIRINGID_P
LEFT JOIN CTE_BUILDING_CLAUSES T6
    ON T1.PUREPOLICYNUMBER = T6.ID
LEFT JOIN CTE_HC_CLAUSES T7
    ON T1.PUREPOLICYNUMBER = T7.ID
WHERE COVERAGE = 'Building';


-- ══════════════════════════════════════════════════════════════════════════
-- VIEW 3: PER_RISK_BUILDING_FINAL  ('Steel'→'IronSteel' + HOWOCCUPPIED ILIKE)
-- ══════════════════════════════════════════════════════════════════════════

create or replace view AGGNE.DEV.PER_RISK_BUILDING_FINAL(
    PUREPOLICYNUMBER,
    LEGACYPOLICYNUMBER,
    ADDRESSDESCRIPTION,
    RISKNUMBER,
    STOREYS,
    ROOFCONSTRUCTION_FINAL,
    YEARBUILDINGCONSTRUCTED,
    YEARLASTREWIRED,
    YEARLASTREPLUMBED,
    FLOORCONSTRUCTION_FINAL,
    MAINWALLCONSTRUCTION_FINAL,
    ALARMSYSTEMINSTALLED_FINAL,
    DEADLOCKSINSTALLED_FINAL,
    GRILLKEYLOCKINSTALLED_FINAL,
    SECURITYDETAILS,
    HOWOCCUPPIED,
    INTERESTEDPARTY,
    RISK_BUILDING,
    RISK_BC,
    LOAD_DATE
) as
WITH CTE1 AS (
    SELECT
        CAST(TRIM(T2.PUREPOLICYNUMBER) || '|' || TRIM(T2.cmlnumber) || '|' || TRIM(T2.EXPIRINGID_P) AS VARCHAR) AS PUREPOLICYNUMBER,
        T2.PUREPOLICYNUMBER AS LEGACYPOLICYNUMBER,
        ADDRESSDESCRIPTION,
        CAST(T3.RISKNUMBER AS VARCHAR) AS RISKNUMBER,
        CAST(STOREYS AS VARCHAR) AS STOREYS,
        -- pos 6: ROOFCONSTRUCTION
        CASE
            WHEN ROOFCONSTRUCTION = 'Asbestos'                THEN 'Asbestos'
            WHEN ROOFCONSTRUCTION = 'Concrete'                THEN 'Concrete'
            WHEN ROOFCONSTRUCTION = 'Concrete (Flat Roof)'    THEN 'Concrete'
            WHEN ROOFCONSTRUCTION = 'Iron'                    THEN 'IronSteelTin'
            WHEN ROOFCONSTRUCTION = 'Iron/Steel/Tin'          THEN 'IronSteelTin'
            WHEN ROOFCONSTRUCTION = 'Tin'                     THEN 'IronSteelTin'
            WHEN ROOFCONSTRUCTION ILIKE 'Colorbond'           THEN 'Colourbond'
            WHEN ROOFCONSTRUCTION = 'Tile'                    THEN 'Tile'
            WHEN ROOFCONSTRUCTION = 'Wood'                    THEN 'Wood'
            WHEN ROOFCONSTRUCTION = 'Wood (Shingles)'         THEN 'Wood'
            ELSE ROOFCONSTRUCTION
        END AS ROOFCONSTRUCTION_FINAL,
        CAST(YEARBUILDINGCONSTRUCTED AS VARCHAR) AS YEARBUILDINGCONSTRUCTED,
        CAST(YEARLASTREWIRED         AS VARCHAR) AS YEARLASTREWIRED,
        CAST(YEARLASTREPLUMBED       AS VARCHAR) AS YEARLASTREPLUMBED,
        -- pos 10: FLOORCONSTRUCTION
        CASE
            WHEN FLOORCONSTRUCTION = 'Concrete'                            THEN 'Concrete'
            WHEN FLOORCONSTRUCTION = 'Other'                               THEN 'Other'
            WHEN FLOORCONSTRUCTION ILIKE 'Wood - Concrete Footings'        THEN 'WoodConcretefootings'
            WHEN FLOORCONSTRUCTION ILIKE 'Wood - Stilts'                   THEN 'WoodStilts'
            WHEN FLOORCONSTRUCTION ILIKE 'Wood - Stumps'                   THEN 'WoodStumps'
            ELSE FLOORCONSTRUCTION
        END AS FLOORCONSTRUCTION_FINAL,
        -- pos 11: MAINWALLCONSTRUCTION
        -- DCT options: Asbestos | BrickVeneer | Concrete | DoubleBrick | FibroHardiplank | IronSteel | Wood
        -- 'Steel' alone → 'IronSteel' (fixed 2026-07-01)
        CASE
            WHEN MAINWALLCONSTRUCTION = 'Asbestos'                THEN 'Asbestos'
            WHEN MAINWALLCONSTRUCTION = 'Brick Veneer'            THEN 'BrickVeneer'
            WHEN MAINWALLCONSTRUCTION = 'Concrete'                THEN 'Concrete'
            WHEN MAINWALLCONSTRUCTION = 'Double Brick'            THEN 'DoubleBrick'
            WHEN MAINWALLCONSTRUCTION = 'Fibro (Non-Asbestos)'    THEN 'FibroHardiplank'
            WHEN MAINWALLCONSTRUCTION = 'Fibro/Hardiplank'        THEN 'FibroHardiplank'
            WHEN MAINWALLCONSTRUCTION = 'Iron'                    THEN 'IronSteel'
            WHEN MAINWALLCONSTRUCTION = 'Iron/Steel'              THEN 'IronSteel'
            WHEN MAINWALLCONSTRUCTION = 'Steel'                   THEN 'IronSteel'  -- steel-framed = IronSteel in DCT
            WHEN MAINWALLCONSTRUCTION = 'Wood'                    THEN 'Wood'
            ELSE MAINWALLCONSTRUCTION  -- SomeAsbestosAndBrick/Other: client to confirm
        END AS MAINWALLCONSTRUCTION_FINAL,
        -- pos 12: ALARMSYSTEMINSTALLED
        CASE
            WHEN ALARMSYSTEMINSTALLED = 'Local - Audible Only'               THEN 'LocalAudibleOnly'
            WHEN ALARMSYSTEMINSTALLED = 'Monitored - Back to base'           THEN 'MonitoredBacktobase'
            WHEN ALARMSYSTEMINSTALLED = 'Monitored - Security'               THEN 'MonitoredSecurity'
            WHEN ALARMSYSTEMINSTALLED = 'Monitored - To Mobile Phone'        THEN 'MonitoredToMobilePhone'
            WHEN ALARMSYSTEMINSTALLED = 'None'                               THEN 'None'
            ELSE ALARMSYSTEMINSTALLED
        END AS ALARMSYSTEMINSTALLED_FINAL,
        -- pos 13: DEADLOCKSINSTALLED
        CASE
            WHEN DEADLOCKSINSTALLED = 'All doors'  THEN 'AllDoors'
            WHEN DEADLOCKSINSTALLED = 'Some doors' THEN 'SomeDoors'
            WHEN DEADLOCKSINSTALLED = 'None'       THEN 'None'
            ELSE DEADLOCKSINSTALLED
        END AS DEADLOCKSINSTALLED_FINAL,
        -- pos 14: GRILLKEYLOCKINSTALLED
        CASE
            WHEN GRILLKEYLOCKINSTALLED = 'All windows'  THEN 'AllWindows'
            WHEN GRILLKEYLOCKINSTALLED = 'Some windows' THEN 'SomeWindows'
            WHEN GRILLKEYLOCKINSTALLED = 'None'         THEN 'None'
            ELSE GRILLKEYLOCKINSTALLED
        END AS GRILLKEYLOCKINSTALLED_FINAL,
        SECURITYDETAILS,
        -- pos 16: HOWOCCUPPIED — ILIKE for case-insensitive match on 'Tenanted by member' (fixed 2026-07-01)
        CASE
            WHEN HOWOCCUPPIED = 'Owner Occupied'                             THEN 'OwnerOccupied'
            WHEN HOWOCCUPPIED ILIKE 'Tenanted by member'                     THEN 'TenantedbyMember'
            WHEN HOWOCCUPPIED = 'Owned leased to Others - Long Term Lease'   THEN 'OwnedleasedtoOthersLongTermLease'
            WHEN HOWOCCUPPIED = 'Holiday Home'                               THEN 'HolidayHome'
            WHEN HOWOCCUPPIED = 'Owned leased to Others - Short Term Rental' THEN 'OwnedLeasedtoOthersShortTermRental'
            ELSE HOWOCCUPPIED
        END AS HOWOCCUPPIED,
        CAST(INTERESTEDPARTY AS VARCHAR) AS INTERESTEDPARTY
    FROM AGGNE.DEV.Locationdetails_PER T2
    INNER JOIN AGGNE.DEV.PER_ACCOUNT_LOC T3
        ON CAST(TRIM(T2.PUREPOLICYNUMBER) || '|' || TRIM(T2.cmlnumber) || '|' || TRIM(T2.EXPIRINGID_P) AS VARCHAR) = TRIM(T3.PUREPOLICYNUMBER)
)
SELECT DISTINCT T1.*,
    CASE
        WHEN T3.PAYLOAD IS NULL THEN
            '<coverage>
    <Type>Building</Type>
    <Description>Home Buildings</Description>
    <Indicator>0</Indicator>
    </coverage>'
        ELSE T3.PAYLOAD
    END AS RISK_BUILDING,
    CASE
        WHEN T2.PAYLOAD IS NULL THEN
            '<coverage>
    <Type>ContentsAndStocks</Type>
    <Description>Home Contents</Description>
    <Indicator>0</Indicator>
    </coverage>'
        ELSE T2.PAYLOAD
    END AS RISK_BC,
    CAST(GETDATE() AS DATE) AS LOAD_DATE
FROM CTE1 T1
LEFT JOIN AGGNE.DEV.PER_HC_TARGET       T2
    ON T1.PUREPOLICYNUMBER = T2.ID
    AND T2.ITR_TYPE = 'RISK_Building_HC'
    AND CAST(T2.LOAD_DATE AS DATE) = CAST(GETDATE() AS DATE)
LEFT JOIN AGGNE.DEV.PER_BUILDING_TARGET T3
    ON T1.PUREPOLICYNUMBER = T3.ID
    AND T3.ITR_TYPE = 'RISK_Building_HB'
    AND CAST(T3.LOAD_DATE AS DATE) = CAST(GETDATE() AS DATE)
;


