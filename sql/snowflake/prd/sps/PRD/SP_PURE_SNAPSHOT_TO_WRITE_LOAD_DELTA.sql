CREATE OR REPLACE TRANSIENT TABLE AGGNE.PRD.T_CML_PHONE AS
WITH base AS (
  SELECT
    TRIM(CMLNUMBER) AS CMLNUMBER,
    CML_COUNTRY,
    TRIM(AREACODE) AS AREACODE,
    REGEXP_REPLACE(TRIM(NUMBEROREMAILORWEB), '[^0-9]', '') AS digits
  FROM AGGNE.PRD.T_PHONE01
),
step1 AS (
  SELECT
    *,
    CASE
      WHEN AREACODE = '+61' THEN '0' || digits
      WHEN SUBSTR(AREACODE,1,1) = '0'  AND LENGTH(AREACODE) = 2 THEN TRIM(AREACODE) || digits
      WHEN SUBSTR(AREACODE,1,2) = '02' AND LENGTH(AREACODE) = 3 THEN TRIM(AREACODE) || digits
      ELSE NULL
    END AS n1
  FROM base
),
step2 AS (
  SELECT
    *,
    CASE
      WHEN AREACODE = '+61' AND SUBSTR(n1,1,2) = '00' THEN digits
      ELSE n1
    END AS n2
  FROM step1
),
step3 AS (
  SELECT
    *,
    COALESCE(NULLIF(n2, ''), digits) AS n3
  FROM step2
),
step4 AS (
  SELECT
    *,
    CASE
      WHEN LENGTH(n3) = 11 AND SUBSTR(n3,1,2) = '61'  THEN '0' || SUBSTR(n3,3,9)
      WHEN LENGTH(n3) = 11 AND SUBSTR(n3,1,3) = '004' THEN SUBSTR(n3,2,10)
      WHEN LENGTH(n3) > 11 AND SUBSTR(AREACODE,1,1) = '0' AND LENGTH(AREACODE) = 2 THEN digits
      WHEN LENGTH(n3) = 20 THEN SUBSTR(digits,1,10)
      ELSE n3
    END AS NUMBER
  FROM step3
)
SELECT
  CMLNUMBER,
  NUMBER,
  CML_COUNTRY,
  CASE 
      WHEN SUBSTR(NUMBER,2,1) = '4' THEN 'Mobile'
      ELSE 'Telephone Line'
  END AS PHONETYPE
FROM step4
WHERE NUMBER IS NOT NULL
  AND SUBSTR(NUMBER,1,2) <> '00'

  ---------------------------------------------------------
  -- FIXED FILTER BLOCK (Stored Procedure–safe)
  ---------------------------------------------------------
  AND (
        (CML_COUNTRY = 'Australia'    AND LENGTH(NUMBER) >= 10)
     OR (CML_COUNTRY = 'New Zealand'  AND LENGTH(NUMBER) >= 9)
     OR (CML_COUNTRY NOT IN ('Australia','New Zealand') AND LENGTH(NUMBER) >= 9)
      );


