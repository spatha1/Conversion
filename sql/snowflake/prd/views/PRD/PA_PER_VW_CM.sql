create or replace view PA_PER_VW_CM(
	ID,
	CM,
	LOAD_DATE
) as 
with CTE1 as(
SELECT  * FROM AGGNE.PRD.PA_PER_COM_COVERAGES_TARGET  WHERE ITR_TYPE IN ('RISK_Building_PM') 
),CTE2 AS (
SELECT DISTINCT 
  ACTUALID,PAYLOAD,
  -- LISTAGG(CASE WHEN ITR_TYPE = 'BP_CV_Vehicle_main' THEN PAYLOAD END, '\n') AS CM,
  CAST(T1.LOAD_DATE AS DATE) AS LOAD_DATE
FROM CTE1 T1 INNER JOIN AGGNE.PRD.PA_PER_COM_PAYLOAD T2 ON T1.ID=T2.PUREPOLICYNUMBER
GROUP BY ACTUALID,PAYLOAD,CAST(T1.LOAD_DATE AS DATE)
)
SELECT ACTUALID AS ID,LISTAGG( PAYLOAD, '\n') AS CM,CAST(LOAD_DATE AS DATE) AS LOAD_DATE FROM CTE2
GROUP BY ACTUALID,CAST(LOAD_DATE AS DATE)
;