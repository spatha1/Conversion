create or replace view PER_VW_SAMPLE_FINAL(
	ID,
	LEGACYPOLICYNUMBER,
	CMLNUMBER,
	CSLNUMBER,
	EXPIRINGID_P,
	INSURANCE_FILE_CNT,
	COUNTRY,
	PRIMARYRATINGSTATE,
	LINEOFBUSINESS,
	EFFECTIVEDATE,
	EXPIRATIONDATE,
	MEMBERSHIPSYSTEMDATE,
	LINEOFBUSINESS_STD,
	CHOOSEPROTECTION,
	INCEPTIONDATE,
	COMMENCEMENTDATE
) as 
SELECT DISTINCT
CAST(trim(T1.LEGACYPOLICYNUMBER) ||'|' || TRIM(T1.cmlnumber) ||'|' || TRIM(T1.EXPIRINGID_P) AS VARCHAR) AS ID,
T1.* 
FROM AGGNE.DEV.SAMPLE_FINAL  T1  INNER JOIN AGGNE.DEV.SAMPLE_PER T2 ON TRIM(T1.LEGACYPOLICYNUMBER)=TRIM(T2.PUREPOLICYNUMBER) AND T1.EXPIRINGID_P=T2.EXPIRINGID_P AND T1.INSURANCE_FILE_CNT=T2.INSURANCE_FILE_CNT
 WHERE T2.EFFECTIVEDATE >= '2026-01-01';