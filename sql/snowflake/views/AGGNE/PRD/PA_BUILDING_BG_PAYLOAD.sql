create or replace view PA_BUILDING_BG_PAYLOAD(
	PUREPOLICYNUMBER,
	LEGACYPOLICYNUMBER,
	CMLNUMBER,
	EXPIRINGID_P,
	COVERAGE,
	SUBCOV,
	UW,
	LOC_BG_CLAUSE,
	VOLUNTARYEXCESS,
	STANDARDEXCESS,
	IMPOSEDEXCESS,
	BURGLARY_IND,
	BGCLMCNT,
	BBCLMINCD,
	BGEXPPREM,
	LOAD_DATE
) as
 with cte_SAMPLE_CBP_LOCATION as
(
select distinct T1.PUREPOLICYNUMBER,T1.cmlnumber,T1.EXPIRINGID,T1.INSURANCE_FILE_CNT,T1.ID from AGGNE.PRD.LOCATION_01_POLICYATTACH_IDENTIFIER T1 INNER JOIN AGGNE.PRD.SAMPLE_POLICYATTACH_FINAL_IDENTIFIER T2 ON T1.ID=T2.ID

),cte_COVERAGES as 

(

select distinct PUREPOLICYNUMBER,cmlnumber,EXPIRINGID_P,INSURANCE_FILE_CNT,'BG' AS CLAUSE,'Burglary' AS  COVERAGE, CAST(VOLUNTARYEXCESS AS VARCHAR) AS VOLUNTARYEXCESS,BURGLARY_IND ,ID,
STANDARDEXCESS,IMPOSEDEXCESS
FROM AGGNE.PRD.location_bg_coverage_policyattach_identifier T1 

) 
, CTE_EXCESS AS(
SELECT 
   T1.ID AS PUREPOLICYNUMBER,
t2.PUREPOLICYNUMBER AS LEGACYPOLICYNUMBER,T2.cmlnumber,T2.EXPIRINGID_P,COVERAGE,CAST(T2.VOLUNTARYEXCESS AS VARCHAR) AS VOLUNTARYEXCESS,BURGLARY_IND,STANDARDEXCESS,IMPOSEDEXCESS
FROM  
cte_SAMPLE_CBP_LOCATION T1 
INNER JOIN cte_COVERAGES T2 ON TRIM(T1.ID)=TRIM(T2.ID) 
)
,CTE_LISTAGG AS(
SELECT
  ID,
  LISTAGG(CASE WHEN ITR_TYPE = 'BP_Risk_Building_BG_Subcov' THEN payload END, '\n') AS SUBCOV,
  LISTAGG(CASE WHEN ITR_TYPE = 'BP_RISK_BUILDING_BG_UW'     THEN payload END, '\n') AS UW,
   LISTAGG(CASE WHEN ITR_TYPE = 'BP_LOC_BG_CLAUSE'     THEN payload END, '\n') AS LOC_BG_CLAUSE,
 CAST(LOAD_DATE AS DATE) AS LOAD_DATE
FROM AGGNE.PRD.PA_RISK_BUILDING_BG_TARGET
WHERE ITR_TYPE IN ('BP_Risk_Building_BG_Subcov', 'BP_RISK_BUILDING_BG_UW','BP_LOC_BG_CLAUSE')
GROUP BY ID,CAST(LOAD_DATE AS DATE)
)
SELECT distinct 
T1.PUREPOLICYNUMBER,T1.LEGACYPOLICYNUMBER,T1.cmlnumber,T1.EXPIRINGID_P,
COVERAGE,CAST(SUBCOV AS VARCHAR) AS SUBCOV,
CAST(UW AS VARCHAR) AS UW,
CASE WHEN LOC_BG_CLAUSE IS NOT NULL AND LOC_BG_CLAUSE<> '' THEN '<Clauses><Type>Burglary</Type>'||CAST(LOC_BG_CLAUSE AS VARCHAR)||'</Clauses>' ELSE '' END AS LOC_BG_CLAUSE,
-- CAST(LOC_BG_CLAUSE AS VARCHAR) AS LOC_BG_CLAUSE,
 CAST(CAST(COALESCE(T1.VOLUNTARYEXCESS, 0) AS NUMBER(10,0))AS VARCHAR) AS VOLUNTARYEXCESS,
 CAST(CAST(COALESCE(T1.STANDARDEXCESS, 0) AS NUMBER(10,0))AS VARCHAR) AS STANDARDEXCESS,
 CAST(CAST(COALESCE(T1.IMPOSEDEXCESS, 0) AS NUMBER(10,0))AS VARCHAR) AS IMPOSEDEXCESS,
 CAST(BURGLARY_IND AS VARCHAR) AS BURGLARY_IND,
 CAST(CAST(COALESCE(T4.BGCLMCNT, 0) AS NUMBER(10,0))AS VARCHAR) AS BGCLMCNT,
 CAST(CAST(COALESCE(T4.BBCLMINCD, 0)AS NUMBER(10,0)) AS VARCHAR) AS BBCLMINCD,
 CAST(COALESCE(T4.BGEXPPREM, 0) AS VARCHAR) AS BGEXPPREM,
CAST(GETDATE() AS DATE) AS LOAD_DATE
 FROM CTE_EXCESS T1 
 -- INNER JOIN  AGGNE.PRD.RISK_BUILDING_BG_TARGET T2 ON T1.PUREPOLICYNUMBER=T2.ID
LEFT JOIN CTE_LISTAGG T3 ON T1.PUREPOLICYNUMBER = T3.ID 
LEFT JOIN AGGNE.PRD.VW_OUTPUT_COVERAGE_BSP_policyattach T4 
ON CAST(trim(T1.LEGACYPOLICYNUMBER) ||'|' || TRIM(T1.cmlnumber) ||'|' || TRIM(T1.EXPIRINGID_P) AS VARCHAR)=CAST(trim(T4.POLICYNUMBER) ||'|' || TRIM(T4.cmlnumber) ||'|' || TRIM(T4.EXPIRINGID_P) AS VARCHAR)
WHERE   COVERAGE='Burglary';