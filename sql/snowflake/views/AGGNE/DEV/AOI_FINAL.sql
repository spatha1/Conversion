create or replace view AOI_FINAL(
	PUREPOLICYNUMBER,
	EXPIRINGID_P,
	CMLNUMBER,
	EXPIRYDATE,
	ADDITIONALINTDETS,
	LOC_VALUE,
	LINE_VALUE,
	RISKNUMBER,
	LOC_ADDRESS,
	LOC_SUB,
	LOC_POSTCODE,
	LOC_STATE,
	COUNTRY,
	ADDITIONALINTERESTLOC,
	ADDITIONALINTERESTLINE
) as
with cte1 as(
SELECT CAST(trim(PUREPOLICYNUMBER) ||'|' || TRIM(cmlnumber) ||'|' || TRIM(EXPIRINGID_P) AS VARCHAR) AS ID, * FROM AGGNE.DEV.ADDITIONAL_INTEREST where  EXPIRYDATE >= '2026-01-01'
),
cte2 as (
SELECT  CAST(trim(PUREPOLICYNUMBER) ||'|' || TRIM(cmlnumber) ||'|' || TRIM(EXPIRINGID) AS VARCHAR) AS ID,
t1.* ,
CAST(CAST(ROW_NUMBER() OVER (PARTITION BY T1.PUREPOLICYNUMBER ORDER BY t1.EXPIRINGID)AS NUMBER(10,0)) AS VARCHAR) AS RISKNUMBER

FROM AGGNE.DEV.LOCATION_01 T1--WHERE DATEDIFF(DAY,EXPIRYDATE,GETDATE())<=45
)
,cte3 as (
SELECT  CAST(trim(PUREPOLICYNUMBER) ||'|' || TRIM(cmlnumber) ||'|' || TRIM(EXPIRINGID) AS VARCHAR) AS ID,
t1.* 

FROM AGGNE.DEV.BUSINESSDETAILS_FINAL T1--WHERE DATEDIFF(DAY,EXPIRYDATE,GETDATE())<=45
)


 SELECT *,
 CASE WHEN LOC_VALUE is not null THEN  cast('1' as varchar) ELSE cast('0' as varchar) END AS ADDITIONALINTERESTLOC,
 CASE WHEN LINE_VALUE is not null THEN  cast('1' as varchar) ELSE cast('0' as varchar) END AS ADDITIONALINTERESTLINE
 
 FROM (
SELECT 
T1.ID AS PUREPOLICYNUMBER, 
CAST(T1.EXPIRINGID_P AS VARCHAR) AS EXPIRINGID_P,
T1.CMLNUMBER,
CAST(T1.EXPIRYDATE AS VARCHAR) AS EXPIRYDATE,
REPLACE (ADDITIONALINTDETS,'&','&amp;') AS ADDITIONALINTDETS ,
CASE WHEN LOC_VALUE= 'Business Buildings' and t2.BUSINESSBUILDINGS=1 THEN 'BusinessBuilding'
 WHEN LOC_VALUE= 'Business Contents'  and t2.BUSINESSCONTENTS=1 THEN 'BusinessContents' /*----'ContentsAndStocks' @changed by RajuK As per vihari Lookup -- */
 WHEN LOC_VALUE= 'Burglary' and t2.BURGLARY=1  THEN 'Burglary'
 WHEN LOC_VALUE= 'Business Interruption' and t2.BUSINESSINTERRUPTION=1 THEN 'BusinessInterruption'
 WHEN LOC_VALUE= 'Engineering' AND T2.ENGINEERING=1 THEN 'Engineering'
 WHEN LOC_VALUE= 'Money' and T2.MONEY =1 THEN 'Money' ELSE null END AS LOC_VALUE,
-- CASE WHEN ADDITIONALINTERESTLINE='Yes' THEN  cast('1' as varchar) ELSE cast('0' as varchar) END AS ADDITIONALINTERESTLINE,

CASE WHEN LINE_VALUE= 'Products And Public Liability' and t3.PUBLICANDPRODUCTLIABILITY=1  THEN 'PublicProductLiability'
 WHEN LINE_VALUE='General Property'  and t3.GENERALPROPERTY=1  THEN 'GeneralProperty'
 WHEN LINE_VALUE= 'Stock Vehicles'  and t3.STOCKVEHICLES=1  THEN 'StockVehicles'
 WHEN LINE_VALUE='Professional Protection' and t3.PROFESSIONALPROTECTION=1   THEN 'ProfessionalProtection'
 WHEN LINE_VALUE='Customer Vehicles' and t3.CUSTOMERVEHICLE=1   THEN 'CustomerVehicles'
 WHEN LINE_VALUE= 'Tax Audit' and t3.TAXAUDIT=1 THEN 'TaxAudit'
 WHEN LINE_VALUE='Goods In Transit'  and t3.GOODSINTRANSIT=1 THEN 'GoodsInTransit'
 WHEN LINE_VALUE='Legal Expenses'  and t3.LEGALEXPENSES THEN 'LegalExpenses' ELSE NUll END AS LINE_VALUE,
CAST(t2.RISKNUMBER AS VARCHAR) AS RISKNUMBER,
T2.ADDRESS1 AS LOC_ADDRESS,
CAST(T2.SUBURB AS VARCHAR) AS LOC_SUB,
T2.POSTCODE AS LOC_POSTCODE,
CASE
    WHEN TRIM(T2.COUNTRY) = 'New Zealand' THEN T2.STATE
    WHEN TRIM(T2.COUNTRY) = 'Australia' THEN CONCAT(T2.STATE, 'AU')
    ELSE T2.STATE end AS LOC_STATE,
CASE
    WHEN TRIM(T2.COUNTRY) = 'New Zealand' THEN 'NZ'
    WHEN TRIM(T2.COUNTRY) = 'Australia' THEN 'AU'
    ELSE TRIM(T2.COUNTRY) END AS COUNTRY
FROM 
CTE1 T1 LEFT JOIN CTE2 T2 ON T1.ID=T2.ID
LEFT JOIN CTE3 T3 ON T3.ID=T2.ID
)where 
LOC_VALUE is not null or LINE_VALUE is not null;