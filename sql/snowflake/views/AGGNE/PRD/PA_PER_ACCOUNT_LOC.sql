create or replace view PA_PER_ACCOUNT_LOC(
	PUREPOLICYNUMBER,
	ACTUALID,
	LEGACYPOLICYNUMBER,
	RISKNUMBER,
	STATE,
	ADDRESS1,
	SUBURB,
	POSTCODE,
	LOC_COUNTRY
) as
WITH cte1 as 
(
SELECT  T1.* 
FROM AGGNE.PRD.Locationdetails_PER_Policyattach_IDENTIFIER T1 
inner join AGGNE.PRD.POLICYATTACH_PER_IDENTIFIER T2 on t1.ID=T2.ID AND T1.EXPIRINGID_P=T2.EXPIRINGID_P
),
cte2  AS (
SELECT ID AS PUREPOLICYNUMBER,ACTUALID,
TRIM(PUREPOLICYNUMBER) as LEGACYPOLICYNUMBER,
STATE,
ADDRESS1,
SUBURB,
CAST(POSTCODE AS VARCHAR) AS POSTCODE,
-- CAST(COALESCE(GNAFPID ,'0')AS VARCHAR) AS GNAFPID,
COUNTRY,
-- LOCATIONANZSICCODE,
EXPIRINGID_P
FROM AGGNE.PRD.Locationdetails_PER_Policyattach_IDENTIFIER
)
SELECT 
T1.PUREPOLICYNUMBER,
T1.ACTUALID,
-- T1.LOCATIONANZSICCODE,
LEGACYPOLICYNUMBER,
CAST(CAST(ROW_NUMBER() OVER (PARTITION BY T1.ACTUALID ORDER BY t1.EXPIRINGID_P)AS NUMBER(10,0)) AS VARCHAR) AS RISKNUMBER,
CASE
    WHEN TRIM(T1.COUNTRY) = 'New Zealand' THEN T1.STATE
    WHEN TRIM(T1.COUNTRY) = 'Australia' THEN CONCAT(T1.STATE, 'AU')
    ELSE T1.STATE end as STATE,
T1.ADDRESS1,
T1.SUBURB,
-- CAST(COALESCE(T1.GNAFPID ,'0')AS VARCHAR) AS GNAFPID,
CAST(T1.POSTCODE AS VARCHAR) AS POSTCODE,
CASE
    WHEN TRIM(T1.COUNTRY) = 'New Zealand' THEN 'NZ'
    WHEN TRIM(T1.COUNTRY) = 'Australia' THEN 'AU'
    ELSE TRIM(T1.COUNTRY) END AS LOC_COUNTRY 
FROM ctE2 T1 INNER JOIN  CTE1 T2  ON T1.PUREPOLICYNUMBER=T2.ID ;