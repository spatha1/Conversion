create or replace view PA_PER_COM_PAYLOAD(
	PUREPOLICYNUMBER,
	PUREPOLICYNUMBER_ACTUAL,
	ACTUALID,
	COVERAGE,
	SUBCOV,
	CLAUSE,
	UW,
	MVVALUEWITHOUTACCESSORIES,
	VEHHAVEANINTERESTEDPARTY,
	YEAR,
	MAKE,
	MODEL,
	BODYTYPE,
	OVERRIDE,
	REGISTRATIONNUMBER,
	ENGINESIZE,
	MARKETVALUEDESCRIPTIONVALUE,
	GROSSVEHICLEMASS,
	MARKETVALUEDESCRIPTION,
	MVADDACCORMODS,
	AGEOFYOUNGESTREGULARDRIVER,
	RESTRICTIONOFDRIVERAGE,
	VOLUNTARYEXCESS,
	STANDARDEXCESS,
	IMPOSEDEXCESS,
	MVCVAGE19,
	MVCVAGE21,
	MVCVAGE25,
	PROTECTIONTYPE,
	VEHICLETYPE,
	DESCRIPTION,
	NUMBEROFCYLINDERS,
	DRIVEDESCRIPTION,
	INDUCTIONTYPE,
	IMPORTFLAG,
	MARKETVALUEWITHACCESSORIESAMOUNT,
	AGREEDVALUEAMOUNT,
	AGREEDVALUEAMOUNT_CALCULATED,
	ADDDETAILSFORTHEINTERESTEDPARTY,
	HIRECARHIREAFTERINCIDENT,
	CHOICEOFREPAIR,
	EXCESSWAIVERFORGLASS,
	PMCLMINCD,
	PMCLMCNT,
	PMEXPPREM,
	LOAD_DATE
) as 
with cte_SAMPLE_CBP_LOCATION as
(
select distinct trim(T1.PUREPOLICYNUMBER)AS PUREPOLICYNUMBER ,trim(t1.CMLNUMBER) AS CMLNUMBER,T1.EXPIRINGID_P ,t1.INSURANCE_FILE_CNT,T1.ID,T1.ACTUALID,
from AGGNE.PRD.PM_03_Policyattach_IDENTIFIER T1 
INNER JOIN AGGNE.PRD.Policyattach_PER_IDENTIFIER T2
ON T1.ID=T2.ID
),cte_COVERAGES as 
(
select distinct PUREPOLICYNUMBER,cmlnumber,EXPIRINGID_P,'PM' AS CLAUSE,'Motor' AS  COVERAGE, INSURANCE_FILE_CNT,
CAST(
        trim(ID) || '|' || TRIM(VEHICLEID) AS VARCHAR
    ) AS PUREPOLICYNUMBER_VEHICLEID,
ID,ACTUALID,
MVVALUEWITHOUTACCESSORIES,
VEHHAVEANINTERESTEDPARTY,
YEAR,
MAKE,
MODEL,
BODYTYPE,
OVERRIDE,
REGISTRATIONNUMBER,
ENGINESIZE,
MARKETVALUEDESCRIPTIONVALUE,
GROSSVEHICLEMASS,
MARKETVALUEDESCRIPTION,
MVADDACCORMODS,
AGEOFYOUNGESTREGULARDRIVER,
RESTRICTIONOFDRIVERAGE,
VOLUNTARYEXCESS,
PROTECTIONTYPE,
VEHICLETYPE,
DESCRIPTION,
NUMBEROFCYLINDERS,
DRIVEDESCRIPTION,
INDUCTIONTYPE,
IMPORTFLAG,
MARKETVALUEWITHACCESSORIESAMOUNT,
AGREEDVALUEAMOUNT,
NVL(AGREEDVALUEDESCRIPTIONVALUE,0)+NVL(AVVALUEWITHOUTACCESSORIES,0) AS AGREEDVALUEAMOUNT_CALCULATED,
ADDDETAILSFORTHEINTERESTEDPARTY,
HIRECARHIREAFTERINCIDENT,
CHOICEOFREPAIR,
EXCESSWAIVERFORGLASS,
MVCVSTANDARD,
MVCVIMPOSED,
MVCVAGE19,
MVCVAGE21,
MVCVAGE25
from AGGNE.PRD.PM_03_Policyattach_IDENTIFIER T1 
) 
 , CTE_EXCESS AS(
SELECT 
    T1.ID AS PUREPOLICYNUMBER,T1.ACTUALID,PUREPOLICYNUMBER_VEHICLEID,
t2.PUREPOLICYNUMBER AS LEGACYPOLICYNUMBER,T2.cmlnumber,T2.EXPIRINGID_P,COVERAGE,MVVALUEWITHOUTACCESSORIES,t2.INSURANCE_FILE_CNT,
VEHHAVEANINTERESTEDPARTY,-- yes=1,no=0,
YEAR,
MAKE,
MODEL,
BODYTYPE,
OVERRIDE,
REGISTRATIONNUMBER,
ENGINESIZE,
MARKETVALUEDESCRIPTIONVALUE,
GROSSVEHICLEMASS,
MARKETVALUEDESCRIPTION,
MVADDACCORMODS,
AGEOFYOUNGESTREGULARDRIVER,
RESTRICTIONOFDRIVERAGE,
VOLUNTARYEXCESS,
PROTECTIONTYPE,
VEHICLETYPE,
DESCRIPTION,
NUMBEROFCYLINDERS,
DRIVEDESCRIPTION,
INDUCTIONTYPE,
IMPORTFLAG,
MARKETVALUEWITHACCESSORIESAMOUNT,
AGREEDVALUEAMOUNT,
AGREEDVALUEAMOUNT_CALCULATED,
ADDDETAILSFORTHEINTERESTEDPARTY,
HIRECARHIREAFTERINCIDENT,
CHOICEOFREPAIR,
EXCESSWAIVERFORGLASS,
MVCVSTANDARD,
MVCVIMPOSED,
MVCVAGE19,
MVCVAGE21,
MVCVAGE25
FROM 
cte_SAMPLE_CBP_LOCATION T1 
INNER JOIN cte_COVERAGES T2 ON T1.ID=T2.ID
)
,CTE_LISTAGG AS(
SELECT
  ID,
  LISTAGG(CASE WHEN ITR_TYPE = 'Risk_CM' THEN payload END, '\n') AS SUBCOV,
  LISTAGG(CASE WHEN ITR_TYPE = 'PER_PM_BUILDING_UW' THEN payload END, '\n') AS UW,
   LISTAGG(CASE WHEN ITR_TYPE = 'COM_CLAUSE'     THEN payload END, '\n') AS COM_CLAUSE,
  CAST(LOAD_DATE AS DATE) AS LOAD_DATE
FROM AGGNE.PRD.PA_PER_COM_COVERAGES_TARGET
WHERE ITR_TYPE IN ('Risk_CM','COM_CLAUSE','PER_PM_BUILDING_UW')   
GROUP BY ID, CAST(LOAD_DATE AS DATE)
)
SELECT distinct 
PUREPOLICYNUMBER_VEHICLEID AS PUREPOLICYNUMBER,
T1.PUREPOLICYNUMBER AS PUREPOLICYNUMBER_ACTUAL,
T1.ACTUALID,
COVERAGE,
CAST(SUBCOV AS VARCHAR) AS SUBCOV,
 CASE WHEN COM_CLAUSE IS NOT NULL AND COM_CLAUSE<> '' THEN CAST(COM_CLAUSE AS VARCHAR) ELSE '' END AS CLAUSE,
 CAST(UW AS VARCHAR) AS UW,
CAST(COALESCE(MVVALUEWITHOUTACCESSORIES,0) AS VARCHAR) AS MVVALUEWITHOUTACCESSORIES,
case when VEHHAVEANINTERESTEDPARTY ='Yes' THEN CAST('1' AS VARCHAR) ELSE CAST('0' AS VARCHAR) END AS VEHHAVEANINTERESTEDPARTY,-- yes=1,no=0,
CASE WHEN COALESCE(YEAR,0)=0 THEN CAST(CAST('1990' AS NUMBER(4,0)) AS VARCHAR) ELSE  CAST(CAST(YEAR AS NUMBER(4,0)) AS VARCHAR) END AS YEAR,
CASE WHEN COALESCE(MAKE,'Unknown')='' THEN 'Unknown' ELSE  COALESCE(MAKE,'Unknown') END AS MAKE,
CASE WHEN COALESCE(MODEL,'Unknown')='' THEN 'Unknown' ELSE  COALESCE(MODEL,'Unknown') END AS MODEL,
CASE WHEN COALESCE(BODYTYPE,'Unknown')='' THEN 'Unknown' ELSE  COALESCE(BODYTYPE,'Unknown') END AS BODYTYPE,
CAST(OVERRIDE AS VARCHAR) AS OVERRIDE,
CAST(REGISTRATIONNUMBER AS VARCHAR) AS REGISTRATIONNUMBER,
CAST(ENGINESIZE AS VARCHAR) AS ENGINESIZE,
CAST(COALESCE(MARKETVALUEDESCRIPTIONVALUE,0) AS VARCHAR) AS MARKETVALUEDESCRIPTIONVALUE,
CAST(COALESCE(GROSSVEHICLEMASS,0) AS VARCHAR) AS GROSSVEHICLEMASS,
CAST(MARKETVALUEDESCRIPTION AS VARCHAR) AS MARKETVALUEDESCRIPTION,
CAST(MVADDACCORMODS AS VARCHAR) AS MVADDACCORMODS,
CAST(COALESCE(AGEOFYOUNGESTREGULARDRIVER,0) AS VARCHAR) AS AGEOFYOUNGESTREGULARDRIVER,
CASE
            WHEN TRIM(RestrictionOfDriverAge) = 'No Restriction' THEN CAST( 0 AS VARCHAR)
            WHEN TRIM(RestrictionOfDriverAge) = 'Min Age 21' THEN CAST(20 AS VARCHAR)
            WHEN TRIM(RestrictionOfDriverAge) = 'Min Age 25' THEN CAST(24 AS VARCHAR)
            WHEN TRIM(RestrictionOfDriverAge) = 'Min Age 30' THEN CAST(29 AS VARCHAR)
            WHEN TRIM(RestrictionOfDriverAge) = 'Min Age 40' THEN CAST(39 AS VARCHAR)
            ELSE CAST('0' AS VARCHAR) -- or a default code, e.g., -1
        END as RESTRICTIONOFDRIVERAGE,
CAST(CAST(COALESCE(VOLUNTARYEXCESS,0)AS NUMBER(20,0)) AS VARCHAR) AS VOLUNTARYEXCESS,
CAST(CAST(COALESCE(MVCVSTANDARD,0)AS NUMBER(20,0)) AS VARCHAR) AS STANDARDEXCESS,
CAST(CAST(COALESCE(MVCVIMPOSED,0)AS NUMBER(20,0)) AS VARCHAR) AS IMPOSEDEXCESS,
CAST(CAST(COALESCE(MVCVAGE19,0)AS NUMBER(20,0)) AS VARCHAR) AS MVCVAGE19,
CAST(CAST(COALESCE(MVCVAGE21,0)AS NUMBER(20,0)) AS VARCHAR) AS MVCVAGE21,
CAST(CAST(COALESCE(MVCVAGE25,0)AS NUMBER(20,0)) AS VARCHAR) AS MVCVAGE25,
CASE  WHEN PROTECTIONTYPE ='Comprehensive - Market Value' THEN 'ComprehensiveMarket' 
 WHEN PROTECTIONTYPE ='Comprehensive - Agreed Value' THEN 'ComprehensiveAgreedValue' 
 WHEN PROTECTIONTYPE ='Fire and Theft' THEN 'FireandTheft' 
 WHEN PROTECTIONTYPE ='Comprehensive' THEN 'FullComprehensive' 
 WHEN PROTECTIONTYPE ='Third Party Only' THEN 'ThirdPartyOnly' 
 WHEN PROTECTIONTYPE ='Third Party, Fire and Theft' THEN 'ThirdPartyFireandTheft' 
ELSE PROTECTIONTYPE END AS PROTECTIONTYPE ,
VEHICLETYPE,
REPLACE(DESCRIPTION ,'&','&amp;') as DESCRIPTION,
CAST(CAST(COALESCE(NUMBEROFCYLINDERS,0)AS NUMBER(20,0)) AS VARCHAR) AS  NUMBEROFCYLINDERS,
REPLACE(DRIVEDESCRIPTION ,'&','&amp;') as  DRIVEDESCRIPTION,
INDUCTIONTYPE,
IMPORTFLAG,
CASE WHEN   PROTECTIONTYPE ='Comprehensive - Agreed Value' THEN CAST(CAST(COALESCE(AGREEDVALUEAMOUNT_CALCULATED,0)AS NUMBER(20,0)) AS VARCHAR) 
ELSE  CAST(CAST(COALESCE(MARKETVALUEWITHACCESSORIESAMOUNT,0)AS NUMBER(20,0)) AS VARCHAR) END AS MARKETVALUEWITHACCESSORIESAMOUNT,
-- CAST(CAST(COALESCE(MARKETVALUEWITHACCESSORIESAMOUNT,0)AS NUMBER(20,0)) AS VARCHAR) AS MARKETVALUEWITHACCESSORIESAMOUNT,
CAST(CAST(COALESCE(AGREEDVALUEAMOUNT,0)AS NUMBER(20,0)) AS VARCHAR) AS  AGREEDVALUEAMOUNT,
CAST(CAST(AGREEDVALUEAMOUNT_CALCULATED AS NUMBER(20,0)) AS VARCHAR) AS  AGREEDVALUEAMOUNT_CALCULATED,
REPLACE(ADDDETAILSFORTHEINTERESTEDPARTY ,'&','&amp;') as ADDDETAILSFORTHEINTERESTEDPARTY,
case when HIRECARHIREAFTERINCIDENT ='Taken' THEN CAST('1' AS VARCHAR) ELSE CAST('0' AS VARCHAR) END AS  HIRECARHIREAFTERINCIDENT,
case when CHOICEOFREPAIR ='Taken' THEN CAST('1' AS VARCHAR) ELSE CAST('0' AS VARCHAR) END AS  CHOICEOFREPAIR,
case when EXCESSWAIVERFORGLASS ='Yes' THEN CAST('1' AS VARCHAR) ELSE CAST('0' AS VARCHAR) END AS  EXCESSWAIVERFORGLASS,
CAST(COALESCE(T4.PMCLMINCD,0) AS VARCHAR) AS PMCLMINCD,
CAST(COALESCE(T4.PMCLMCNT,0) AS VARCHAR) AS PMCLMCNT,
CAST(COALESCE(T4.PMEXPPREM,0) AS VARCHAR) AS PMEXPPREM,
CAST(GETDATE() AS DATE) as LOAD_DATE
FROM CTE_EXCESS T1
-- LEFT JOIN  AGGNE.PRD.PA_PER_COM_COVERAGES_TARGET T2 ON T1.PUREPOLICYNUMBER=T2.ID
LEFT JOIN CTE_LISTAGG T3 ON T1.PUREPOLICYNUMBER_VEHICLEID = T3.ID 
LEFT JOIN AGGNE.PRD.Output_Coverage_PER_Policyattach T4 ON trim(T1.LEGACYPOLICYNUMBER)=trim(T4.PolicyNumber) AND T1.EXPIRINGID_P=T4.EXPIRINGID_P 
WHERE   COVERAGE='Motor'  ;