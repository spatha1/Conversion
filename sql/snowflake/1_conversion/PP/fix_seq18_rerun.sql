-- ── Step 1: Verify view and target have today's data ─────────────────────
SELECT ITR_TYPE, COUNT(*) AS CNT, CAST(MAX(LOAD_DATE) AS DATE) AS MAX_DATE
FROM   AGGNE.DEV.PER_COM_COVERAGES_TARGET
GROUP  BY ITR_TYPE
ORDER  BY ITR_TYPE;
-- Risk_CM, COM_CLAUSE, PER_PM_BUILDING_UW should all have today's rows.
-- If any are missing, re-run seqs 15/16/17 first.


-- ── Step 2: Confirm PER_COM_PAYLOAD now exposes UW column ────────────────
SELECT COLUMN_NAME
FROM   INFORMATION_SCHEMA.COLUMNS
WHERE  TABLE_SCHEMA = 'DEV'
  AND  TABLE_NAME   = 'PER_COM_PAYLOAD'
ORDER  BY ORDINAL_POSITION;
-- Expected: UW appears after COM_CLAUSE


-- ── Step 3: Preview — check PER_COM_PAYLOAD resolves UW for a policy ─────
SELECT PUREPOLICYNUMBER,
       LEFT(SUBCOV,   100) AS SUBCOV_PREVIEW,
       LEFT(COM_CLAUSE,100) AS COM_CLAUSE_PREVIEW,
       LEFT(UW,        100) AS UW_PREVIEW
FROM   AGGNE.DEV.PER_COM_PAYLOAD
WHERE  PUREPOLICYNUMBER LIKE '%P00012922%'
LIMIT  3;


-- ── Step 4: Delete stale RISK_Building_PM rows ───────────────────────────
-- Removes old rows generated by the old template (had {IMPOSEDEXCESS} etc.)
DELETE FROM AGGNE.DEV.PER_COM_COVERAGES_TARGET
WHERE  ITR_TYPE = 'RISK_Building_PM';


-- ── Step 5: Re-run seq 18 (RISK_Building_PM) ─────────────────────────────
-- IMPORTANT: Copy the ConversionScript from PP_ConversionConfig seq 18
-- AFTER applying fix_seq18_clause_uw.sql (so template has {COM_CLAUSE}).
-- Template is ~6400 chars — paste between $$ delimiters below.
--
-- CALL AGGNE.DEV.DYNAMIC_XML_V1(
