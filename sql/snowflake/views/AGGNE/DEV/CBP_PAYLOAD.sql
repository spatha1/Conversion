 LEFT JOIN AGGNE.DEV.VW_CM T24
 ON TRIM(T1.LEGACYPOLICYNUMBER) =  TRIM(T24.PUREPOLICYNUMBER)  AND  CAST(T24.load_date AS DATE) in (select max(CAST(load_date AS DATE)) as load_date  from AGGNE.DEV.VW_CM)
 LEFT JOIN AGGNE.DEV.VW_LINE_UW_COMBINED T25
 ON TRIM(T1.LEGACYPOLICYNUMBER)=TRIM(T25.LEGACYPOLICYNUMBER) AND   T25.load_date in (select max(load_date) as load_date  from AGGNE.DEV.VW_LINE_UW_COMBINED)
