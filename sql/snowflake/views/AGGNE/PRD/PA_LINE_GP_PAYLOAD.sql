create or replace view PA_LINE_GP_PAYLOAD(
	PUREPOLICYNUMBER,
	LINE_GP_UW,
	LINE_GP_SPECIFIEDTOOLS,
	LINE_GP_CLAUSE,
	VOLUNTARYEXCESS,
	IMPOSEDEXCESS,
	STANDARDEXCESS,
	GENERALPROPERTY_IND,
	GPUNSPECIFIEDTOOLS,
	UNSPECIFIEDTOOLSLIMIT,
	GPUNSPECIFIEDSTOCK,
	UNSPECIFIEDSTOCKLIMIT,
	GPSPECIFIEDTOOLS,
	GPSPECIFIEDSTOCK,
	GPOTHERPROPERTY,
	GPFLOODPROTECTION,
	FLOODDAMAGE,
	SPECIFIEDTOOL,
	SPECIFIEDTOOL_INDICATOR,
	UNSPECIFIEDTOOLSLIMIT_INDICATOR,
	UNSPECIFIEDSTOCKLIMIT_INDICATOR,
	GPCLMCNT,
	GPCLMINCD,
	GPEXPPREM,
	EXP_PREM_GPUNT_SD,
	EXP_PREM_GPFLD_SD,
	EXP_PREM_GPUNS_SD,
	EXP_PREM_GPSPT_SD,
	LOAD_DATE
) as 

 with cte_SAMPLE_CBP as
(
select distinct LEGACYPOLICYNUMBER,cmlnumber,EXPIRINGID_P,INSURANCE_FILE_CNT,ID from AGGNE.PRD.SAMPLE_POLICYATTACH_FINAL_IDENTIFIER --WHERE DATEDIFF(DAY,EXPIRYDATE,GETDATE())<=45
),cte_COVERAGES as 
(
select distinct PUREPOLICYNUMBER,cmlnumber,EXPIRINGID_P,ID,INSURANCE_FILE_CNT,
CAST(CAST(COALESCE(VOLUNTARYEXCESS,0) AS NUMBER(10,0)) AS VARCHAR) AS VOLUNTARYEXCESS,
CAST(CAST(COALESCE(STANDARDEXCESS,0) AS NUMBER(10,0)) AS VARCHAR) AS STANDARDEXCESS,
CAST(CAST(COALESCE(IMPOSEDEXCESS,0) AS NUMBER(10,0)) AS VARCHAR) AS IMPOSEDEXCESS,
CAST(CAST(COALESCE(GENERALPROPERTY_IND,0)AS NUMBER(10,0)) AS VARCHAR) AS GENERALPROPERTY_IND,
CAST(CAST(COALESCE(GPUNSPECIFIEDTOOLS,0)AS NUMBER(10,0)) AS VARCHAR) AS GPUNSPECIFIEDTOOLS,
CAST(CAST(COALESCE(UNSPECIFIEDTOOLSLIMIT,0)AS NUMBER(10,0)) AS VARCHAR) AS UNSPECIFIEDTOOLSLIMIT,
CAST(CAST(COALESCE(GPUNSPECIFIEDSTOCK,0)AS NUMBER(10,0)) AS VARCHAR)AS GPUNSPECIFIEDSTOCK,
CAST(CAST(COALESCE(UNSPECIFIEDSTOCKLIMIT,0)AS NUMBER(10,0)) AS VARCHAR) AS UNSPECIFIEDSTOCKLIMIT,
CAST(CAST(COALESCE("GPSPECIFIEDTOOLS",0)AS NUMBER(10,0)) AS VARCHAR) AS GPSPECIFIEDTOOLS,
CAST(CAST(COALESCE("GPSPECIFIEDSTOCK",0)AS NUMBER(10,0)) AS VARCHAR) AS GPSPECIFIEDSTOCK,
CAST(CAST(COALESCE("GPOTHERPROPERTY",0)AS NUMBER(10,0)) AS VARCHAR) AS GPOTHERPROPERTY,
CAST(CAST(COALESCE( "GPFLOODPROTECTION",0)AS NUMBER(10,0)) AS VARCHAR) AS GPFLOODPROTECTION,
CAST(FLOODDAMAGE AS VARCHAR) AS FLOODDAMAGE,
SPECIFIEDTOOL
from AGGNE.PRD.line_gp_coverage_policyattach_IDENTIFIER 
) 
,CTE_EXCESS AS(
SELECT 
    T1.ID AS PUREPOLICYNUMBER,
t2.PUREPOLICYNUMBER AS LEGACYPOLICYNUMBER,T2.cmlnumber,T2.EXPIRINGID_P,T2.VOLUNTARYEXCESS,GENERALPROPERTY_IND,GPUNSPECIFIEDTOOLS,UNSPECIFIEDTOOLSLIMIT,GPUNSPECIFIEDSTOCK,
UNSPECIFIEDSTOCKLIMIT,GPSPECIFIEDTOOLS,GPSPECIFIEDSTOCK,GPOTHERPROPERTY,GPFLOODPROTECTION,FLOODDAMAGE,SPECIFIEDTOOL,
CAST(CAST(COALESCE(STANDARDEXCESS,0) AS NUMBER(10,0)) AS VARCHAR) AS STANDARDEXCESS,
CAST(CAST(COALESCE(IMPOSEDEXCESS,0) AS NUMBER(10,0)) AS VARCHAR) AS IMPOSEDEXCESS
FROM 
cte_SAMPLE_CBP T1 
INNER JOIN cte_COVERAGES T2 ON T1.ID=T2.ID
)
,CTE_LISTAGG AS(
SELECT
  ID,
  LISTAGG(CASE WHEN ITR_TYPE = 'BP_Line_GP_2_UW' THEN payload END, '\n') AS LINE_GP_UW,
  LISTAGG(CASE WHEN ITR_TYPE = 'BP_Line_GP_1_SpecifiedTools'     THEN payload END, '\n') AS LINE_GP_SpecifiedTools,
  LISTAGG(CASE WHEN ITR_TYPE = 'BP_Line_GP_3_CLAUSE'     THEN payload END, '\n') AS LINE_GP_CLAUSE,  
  CAST(LOAD_DATE AS DATE) AS LOAD_DATE
FROM AGGNE.PRD.PA_LINE_GP_Target
WHERE ITR_TYPE IN ('BP_Line_GP_2_UW', 'BP_Line_GP_1_SpecifiedTools', 'BP_Line_GP_3_CLAUSE')
GROUP BY ID,CAST(LOAD_DATE AS DATE)
)
,SUB_COV_PREM AS (
SELECT DISTINCT 
  POLICYNUMBER,
  EXPIRINGID_P,
  GPUNT_SD,
  GPFLD_SD,
  GPUNS_SD,
  GPSPT_SD
FROM (
  SELECT POLICYNUMBER, SUB_COVERAGE, EXPPREMIUM,EXPIRINGID_P
  FROM AGGNE.PRD.Output_SubCover_BSP_Policyattach
) src
PIVOT (
  SUM(EXPPREMIUM) FOR SUB_COVERAGE IN (
    ('GPUNT_SD') AS GPUNT_SD,
    ('GPFLD_SD') AS GPFLD_SD,
    ('GPUNS_SD') AS GPUNS_SD,
    ('GPSPT_SD') AS GPSPT_SD
  )
) p
ORDER BY POLICYNUMBER
)
SELECT distinct 
T1.PUREPOLICYNUMBER,
CASE WHEN LINE_GP_UW IS NOT NULL AND LINE_GP_UW<> '' THEN CAST(LINE_GP_UW AS VARCHAR) ELSE '' END AS LINE_GP_UW,
--CAST(LINE_GP_UW AS VARCHAR) AS LINE_GP_UW,
CAST(LINE_GP_SpecifiedTools AS VARCHAR) AS LINE_GP_SPECIFIEDTOOLS,
CASE WHEN LINE_GP_CLAUSE IS NOT NULL AND LINE_GP_CLAUSE<> '' THEN '<Clauses><Type>GeneralProperty</Type>'||CAST(LINE_GP_CLAUSE AS VARCHAR)||'</Clauses>' ELSE '' END AS LINE_GP_CLAUSE,
-- CAST(LINE_GP_CLAUSE AS VARCHAR) AS LINE_GP_CLAUSE,
CAST(CAST(COALESCE(VOLUNTARYEXCESS,0)AS NUMBER(10,0)) AS VARCHAR) AS VOLUNTARYEXCESS,
CAST(CAST(COALESCE(IMPOSEDEXCESS,0) AS NUMBER(36,0))AS VARCHAR) AS IMPOSEDEXCESS,
CAST(CAST(COALESCE(STANDARDEXCESS,0) AS NUMBER(36,0))AS VARCHAR) AS STANDARDEXCESS,
CAST(CAST(COALESCE(GENERALPROPERTY_IND,0)AS NUMBER(10,0)) AS VARCHAR) AS GENERALPROPERTY_IND,
CAST(CAST(COALESCE(GPUNSPECIFIEDTOOLS,0)AS NUMBER(10,0)) AS VARCHAR) AS GPUNSPECIFIEDTOOLS,
CAST(CAST(COALESCE(UNSPECIFIEDTOOLSLIMIT,0)AS NUMBER(10,0)) AS VARCHAR) AS UNSPECIFIEDTOOLSLIMIT,
CAST(CAST(COALESCE(GPUNSPECIFIEDSTOCK,0)AS NUMBER(10,0)) AS VARCHAR)AS GPUNSPECIFIEDSTOCK,
CAST(CAST(COALESCE(UNSPECIFIEDSTOCKLIMIT,0)AS NUMBER(10,0)) AS VARCHAR) AS UNSPECIFIEDSTOCKLIMIT,
CAST(CAST(COALESCE(GPSPECIFIEDTOOLS,0)AS NUMBER(10,0)) AS VARCHAR) AS GPSPECIFIEDTOOLS,
CAST(CAST(COALESCE(GPSPECIFIEDSTOCK,0)AS NUMBER(10,0)) AS VARCHAR) AS GPSPECIFIEDSTOCK,
CAST(CAST(COALESCE(GPOTHERPROPERTY,0)AS NUMBER(10,0)) AS VARCHAR) AS GPOTHERPROPERTY,
CAST(CAST(COALESCE(GPFLOODPROTECTION,0)AS NUMBER(10,0)) AS VARCHAR) AS GPFLOODPROTECTION,
-- CAST(FLOODDAMAGE AS VARCHAR) AS FLOODDAMAGE,
CASE WHEN FLOODDAMAGE='Taken' THEN cast('1' as varchar) Else cast('0' as varchar) END AS FLOODDAMAGE,
CASE WHEN SPECIFIEDTOOL='Taken' THEN 'Taken' Else 'NotTaken' END AS SPECIFIEDTOOL,
CASE WHEN SPECIFIEDTOOL='Taken' THEN cast('1' as varchar) Else cast('0' as varchar) END AS SPECIFIEDTOOL_INDICATOR,
CASE WHEN UNSPECIFIEDTOOLSLIMIT<>0 THEN cast('1' as varchar) Else cast('0' as varchar) END AS UNSPECIFIEDTOOLSLIMIT_INDICATOR,
CASE WHEN UNSPECIFIEDSTOCKLIMIT<>0 THEN cast('1' as varchar) Else cast('0' as varchar) END AS UNSPECIFIEDSTOCKLIMIT_INDICATOR,
CAST(CAST(COALESCE(T4.GPCLMCNT,0)AS NUMBER(10,0))AS VARCHAR) AS GPCLMCNT,
CAST(CAST(COALESCE(T4.GPCLMINCD,0)AS NUMBER(10,0))AS VARCHAR) AS GPCLMINCD,
CAST(COALESCE(T4.GPEXPPREM,0)AS VARCHAR) AS GPEXPPREM,
CAST(COALESCE(CAST(T5.GPUNT_SD AS NUMBER(36,3)),0)AS VARCHAR) AS EXP_PREM_GPUNT_SD,
CAST(COALESCE(CAST(T5.GPFLD_SD AS NUMBER(36,3)),0)AS VARCHAR) AS EXP_PREM_GPFLD_SD,
CAST(COALESCE(CAST(T5.GPUNS_SD AS NUMBER(36,3)),0)AS VARCHAR) AS EXP_PREM_GPUNS_SD,
CAST(COALESCE(CAST(T5.GPSPT_SD AS NUMBER(36,3)),0)AS VARCHAR) AS EXP_PREM_GPSPT_SD,
CAST(GETDATE() AS DATE) AS LOAD_DATE
FROM CTE_EXCESS T1 
--INNER JOIN  AGGNE.PRD.PA_LINE_GP_Target T2 ON T1.PUREPOLICYNUMBER=T2.ID
LEFT JOIN CTE_LISTAGG T3 ON T1.PUREPOLICYNUMBER = T3.ID 
LEFT JOIN AGGNE.PRD.Output_Coverage_BSP_Policyattach T4 
ON CAST(trim(T1.LEGACYPOLICYNUMBER) ||'|' || TRIM(T1.cmlnumber) ||'|' || TRIM(T1.EXPIRINGID_P) AS VARCHAR)=CAST(trim(T4.POLICYNUMBER) ||'|' || TRIM(T4.cmlnumber) ||'|' || TRIM(T4.EXPIRINGID_P) AS VARCHAR)
LEFT JOIN SUB_COV_PREM T5 ON T1.LEGACYPOLICYNUMBER=T5.POLICYNUMBER AND T1.EXPIRINGID_P;