create or replace view PER_VW_CBP_COMPETITOR_INFORMATION(
	PUREPOLICYNUMBER,
	PRIORCARRIER,
	PRICE
) as 
SELECT 
DISTINCT TRIM(PUREPOLICYNUMBER) AS PUREPOLICYNUMBER,
case when PRIORCARRIER='Motor Trade Direct' then 'MotorTradeDirect' else PRIORCARRIER END AS PRIORCARRIER,
CAST(COALESCE(CAST (PRICE AS NUMBER(10,2)),0)AS VARCHAR) AS PRICE 
FROM AGGNE.DEV.CBP_COMPETITOR_INFORMATION  WHERE EXPIRYDATE>='2026-01-01';