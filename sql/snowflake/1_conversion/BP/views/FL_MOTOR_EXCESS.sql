create or replace view FL_MOTOR_EXCESS(
	PUREPOLICYNUMBER,
	CMLNUMBER,
	LEGACYPOLICYNUMBER,
	EXPIRINGID_P,
	TYPE,
	FLEETTYPE,
	VOLUNTARYEXCESS
) as 
select CAST(trim(PUREPOLICYNUMBER) ||'|' || TRIM(cmlnumber) ||'|' || TRIM(EXPIRINGID_P) AS VARCHAR) AS PUREPOLICYNUMBER,cmlnumber, purepolicynumber AS legacypolicynumber, expiringid_p,'CommercialVehicle' as Type, 'Default' as FleetType,CAST(CAST(VOLUNTARYEXCESS AS INT) AS VARCHAR) AS VOLUNTARYEXCESS from AGGNE.DEV.VEHICLECOVERAGES_FLEETVEHICLE;