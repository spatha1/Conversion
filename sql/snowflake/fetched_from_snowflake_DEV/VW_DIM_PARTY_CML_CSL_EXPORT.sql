create or replace view VW_DIM_PARTY_CML_CSL_EXPORT(
	PARTY_DIM_ID,
	BK_CMLNUMBER,
	BK_CSLNUMBER,
	MEMBER_TA_NUMBER,
	CSL_LEGAL_ENTITY,
	CML_RISK_ACCOUNT_MANAGER,
	CSL_AREA_MANAGER,
	CSL_ZONE,
	CSL_REGION,
	CSL_NUMBER,
	CML_LEGAL_ENTITY,
	CSL_MEMBER_STATUS,
	ABN_NZBN,
	STOP_CREDIT,
	STOP_CREDIT_REASON,
	CSL_TENURE,
	CSL_MONTHLY_SPEND,
	STANDARD_INDUSTRY_CODE,
	STANDARD_INDUSTRY_CODE_DESCRIPTION,
	CSL_CREDIT_LIMIT,
	CSL_CREDIT_RISK,
	CSL_CREDIT_USAGE,
	PROBABILITY_OF_DEFAULT,
	TA_PAYMENT_METHOD,
	STREET,
	SUBURB,
	STATE,
	POSTCODE,
	CONTACT_NAME,
	PHONE,
	EMAIL,
	SITE_COUNTRY,
	MESSAGE,
	CMLNUMBER,
	COUNTRY,
	CMLLEGALENTITY,
	CMLTRADINGNAME,
	MAINCONTACT,
	CORRESPONDENCELINE1,
	CORRESPONDENCELINE2,
	CORRESPONDENCELINE3,
	CORRESPONDENCELINE4,
	CORRESPONDENCEPOSTCODE,
	SITE_STREET,
	SITE_SUBURB,
	SITE_STATE,
	SITE_POSTCODE,
	CSLNUMBER,
	PRIMARY_PHONE,
	PRIMARY_PHONE_TYPE,
	PRIMARY_EMAIL,
	PRIMARY_EMAIL_TYPE,
	PHONE_COUNT,
	EMAIL_COUNT,
	SECONDARYCONTACT_COUNT,
	SCONDARYCONTACT,
	SCONDARYCONTACTKEY,
	HASH_DIFF,
	EFFECTIVE_FROM,
	EFFECTIVE_TO,
	IS_CURRENT,
	ACTIVE_FLAG,
	INSERTED_AT,
	UPDATED_AT,
	HASH_HEX,
	CURRENTDATE
) as
SELECT
  TOP 10 PARTY_DIM_ID,
  BK_CMLNUMBER,
  NULL::STRING AS BK_CSLNUMBER,
  MEMBER_TA_NUMBER,
  CSL_LEGAL_ENTITY,
  CML_RISK_ACCOUNT_MANAGER,
  CSL_AREA_MANAGER,
  CSL_ZONE,
  CSL_REGION,
  CSL_NUMBER,
  CML_LEGAL_ENTITY,
  CSL_MEMBER_STATUS,
  ABN_NZBN,
  STOP_CREDIT,
  STOP_CREDIT_REASON,
  CSL_TENURE,
  CSL_MONTHLY_SPEND,
  STANDARD_INDUSTRY_CODE,
  STANDARD_INDUSTRY_CODE_DESCRIPTION,
  CSL_CREDIT_LIMIT,
  CSL_CREDIT_RISK,
  CSL_CREDIT_USAGE,
  PROBABILITY_OF_DEFAULT,
  TA_PAYMENT_METHOD,
  STREET,
  SUBURB,
  STATE,
  POSTCODE,
  CONTACT_NAME,
  PHONE,
  EMAIL,
  SITE_COUNTRY,
  MESSAGE,
  CMLNUMBER,
  CASE
    WHEN TRIM(COUNTRY) = 'New Zealand' THEN 'NZ'
    WHEN TRIM(COUNTRY) = 'Australia' THEN 'AU'
    ELSE TRIM(COUNTRY)
  END AS COUNTRY,
  CMLLEGALENTITY,
  CMLTRADINGNAME,
  MAINCONTACT,
  CORRESPONDENCELINE1,
  CORRESPONDENCELINE2,
  CORRESPONDENCELINE3,
  CORRESPONDENCELINE4,
  CORRESPONDENCEPOSTCODE,
  SITE_STREET,
  SITE_SUBURB,
  CASE
    WHEN TRIM(COUNTRY) = 'New Zealand' THEN '100'
    WHEN TRIM(COUNTRY) = 'Australia' THEN CONCAT(SITE_STATE, 'AU')
    ELSE SITE_STATE
  END AS SITE_STATE,
  SITE_POSTCODE,
  CSLNUMBER,
  PRIMARY_PHONE,
  PRIMARY_PHONE_TYPE,
  PRIMARY_EMAIL,
  PRIMARY_EMAIL_TYPE,
  PHONE_COUNT,
  EMAIL_COUNT,
  SECONDARYCONTACT_COUNT,
  SECONDARYCONTACT,
  SECONDARYCONTACTKEY,
  HASH_DIFF,
  EFFECTIVE_FROM,
  EFFECTIVE_TO,
  IS_CURRENT,
  ACTIVE_FLAG,
  '' AS INSERTED_AT,
  '' AS UPDATED_AT,
  '' AS HASH_HEX,
  TO_VARCHAR(CURRENT_TIMESTAMP(), 'YYYY-MM-DD') AS CURRENTDATE
FROM AGGNE.DEV.DIM_PARTY_CML_CSL_NEW
WHERE PARTY_DIM_ID NOT IN (
  SELECT PARTY_DIM_ID FROM AGGNE.DEV.CML_MIGRATION_LOOKUP
);