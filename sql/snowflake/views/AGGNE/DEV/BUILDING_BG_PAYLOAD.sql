create or replace view BUILDING_BG_PAYLOAD(
	PUREPOLICYNUMBER,
	COVERAGE,
	SUBCOV,
	UW,
	LOC_BG_CLAUSE,
	VOLUNTARYEXCESS,
	BURGLARY_IND,
	BGCLMCNT,
	BBCLMINCD,
	BGEXPPREM,
	LOAD_DATE
) as

 with cte_SAMPLE_CBP_LOCATION as
(
select distinct T1.PUREPOLICYNUMBER,T1.cmlnumber,T1.EXPIRINGID from AGGNE.DEV.Location_01 T1 INNER JOIN AGGNE.DEV.
SAMPLE_CBP T2 ON TRIM(T1.PUREPOLICYNUMBER)=TRIM(T2.PUREPOLICYNUMBER)
-- and 
-- T1.EXPIRINGID=T2.EXPIRINGID_P  
WHERE T2.EXPIRYDATE>='2026-01-01'
),cte_COVERAGES as 
(
select distinct PUREPOLICYNUMBER,cmlnumber,EXPIRINGID_P,'BG' AS CLAUSE,'Burglary' AS  COVERAGE, CAST(VOLUNTARYEXCESS AS VARCHAR) AS VOLUNTARYEXCESS,BURGLARY_IND FROM AGGNE.DEV.LOCATION_BG_COVERAGE T1 WHERE EXPIRYDATE>='2026-01-01' --9889
) 
, CTE_EXCESS AS(
SELECT 
    CAST(trim(T2.PUREPOLICYNUMBER) ||'|' || TRIM(T2.cmlnumber) ||'|' || TRIM(T2.EXPIRINGID_P) AS VARCHAR) AS PUREPOLICYNUMBER,
t2.PUREPOLICYNUMBER AS LEGACYPOLICYNUMBER,T2.cmlnumber,T2.EXPIRINGID_P,COVERAGE,CAST(T2.VOLUNTARYEXCESS AS VARCHAR) AS VOLUNTARYEXCESS,BURGLARY_IND
FROM  
cte_SAMPLE_CBP_LOCATION T1 
INNER JOIN cte_COVERAGES T2 ON T1.EXPIRINGID=T2.EXPIRINGID_P
AND TRIM(T1.PUREPOLICYNUMBER)=TRIM(T2.PUREPOLICYNUMBER) --946
)
,CTE_LISTAGG AS(
SELECT
  ID,
  LISTAGG(CASE WHEN ITR_TYPE = 'BP_Risk_Building_BG_Subcov' THEN payload END, '\n') AS SUBCOV,
  LISTAGG(CASE WHEN ITR_TYPE = 'BP_RISK_BUILDING_BG_UW'     THEN payload END, '\n') AS UW,
   LISTAGG(CASE WHEN ITR_TYPE = 'BP_LOC_BG_CLAUSE'     THEN payload END, '\n') AS LOC_BG_CLAUSE,
 CAST(LOAD_DATE AS DATE) AS LOAD_DATE
FROM AGGNE.DEV.RISK_BUILDING_BG_TARGET
WHERE ITR_TYPE IN ('BP_Risk_Building_BG_Subcov', 'BP_RISK_BUILDING_BG_UW','BP_LOC_BG_CLAUSE')
GROUP BY ID,CAST(LOAD_DATE AS DATE)
)
SELECT distinct 
T1.PUREPOLICYNUMBER,
COVERAGE,CAST(SUBCOV AS VARCHAR) AS SUBCOV,
CAST(UW AS VARCHAR) AS UW,
CASE WHEN LOC_BG_CLAUSE IS NOT NULL AND LOC_BG_CLAUSE<> '' THEN '<Clauses><Type>Burglary</Type>'||CAST(LOC_BG_CLAUSE AS VARCHAR)||'</Clauses>' ELSE '' END AS LOC_BG_CLAUSE,
-- CAST(LOC_BG_CLAUSE AS VARCHAR) AS LOC_BG_CLAUSE,
 CAST(CAST(COALESCE(T1.VOLUNTARYEXCESS, 0) AS NUMBER(10,0))AS VARCHAR) AS VOLUNTARYEXCESS,
 CAST(BURGLARY_IND AS VARCHAR) AS BURGLARY_IND,
 CAST(CAST(COALESCE(T4.BGCLMCNT, 0) AS NUMBER(10,0))AS VARCHAR) AS BGCLMCNT,
 CAST(CAST(COALESCE(T4.BBCLMINCD, 0)AS NUMBER(10,0)) AS VARCHAR) AS BBCLMINCD,
 CAST(COALESCE(T4.BGEXPPREM, 0) AS VARCHAR) AS BGEXPPREM,
CAST(GETDATE() AS DATE) AS LOAD_DATE
 FROM CTE_EXCESS T1 
 -- INNER JOIN  AGGNE.DEV.RISK_BUILDING_BG_TARGET T2 ON T1.PUREPOLICYNUMBER=T2.ID
LEFT JOIN CTE_LISTAGG T3 ON T1.PUREPOLICYNUMBER = T3.ID 
LEFT JOIN AGGNE.DEV.VW_OUTPUT_COVERAGE_BSP T4 ON T1.PUREPOLICYNUMBER=T4.PUREPOLICYNUMBER 
WHERE   COVERAGE='Burglary';