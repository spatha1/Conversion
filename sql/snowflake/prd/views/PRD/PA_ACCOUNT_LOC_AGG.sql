create or replace view PA_ACCOUNT_LOC_AGG(
	ID,
	AOI,
	LOAD_DATE
) as 
WITH cte1 AS (
  SELECT * 
  FROM AGGNE.PRD.PA_ACCOUNT_LOC_TARGET 
)
SELECT DISTINCT
  T2.ACTUALID AS ID,
  LISTAGG(
    CASE WHEN ITR_TYPE = 'BP_ACC_LOC' THEN payload END,
    '\n'
  )  AS AOI,  
  CAST(T1.LOAD_DATE AS DATE) AS LOAD_DATE
FROM cte1 T1
INNER JOIN AGGNE.PRD.ACCOUNT_LOC_POLICYATTACH T2
  ON T1.ID = T2.PUREPOLICYNUMBER
WHERE ITR_TYPE IN ('BP_ACC_LOC')
GROUP BY
  T2.ACTUALID,
  CAST(T1.LOAD_DATE AS DATE)
ORDER BY
  T2.ACTUALID, LOAD_DATE;