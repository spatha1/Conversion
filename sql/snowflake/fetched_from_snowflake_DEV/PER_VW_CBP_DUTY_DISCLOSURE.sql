create or replace view PER_VW_CBP_DUTY_DISCLOSURE(
	ID,
	PUREPOLICYNUMBER,
	EXPIRINGID_P,
	CMLNUMBER,
	EXPIRYDATE,
	COUNTRY,
	PRODUCT,
	CRIMINALCONVICTION,
	CRIMINALCONVICTIONDETAILS,
	REFUSEDINSURANCE,
	REFUSEDINSURANCEDETAILS
) as 
SELECT 
CAST(trim(t1.PUREPOLICYNUMBER) ||'|' || TRIM(t1.cmlnumber) ||'|' || TRIM(t1.EXPIRINGID_P) AS VARCHAR) AS ID,
t1.* 
FROM AGGNE.DEV.DUTY_DISCLOSURE t1   INNER JOIN AGGNE.DEV.SAMPLE_PER T2 ON TRIM(T1.PUREPOLICYNUMBER)=TRIM(T2.PUREPOLICYNUMBER) AND T1.EXPIRINGID_P=T2.EXPIRINGID_P;