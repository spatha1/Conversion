CREATE OR REPLACE PROCEDURE "PER_FINAL_TABLE_ARCHIVE_AND_DELETE_XML_V2"()
RETURNS VARCHAR
LANGUAGE SQL
EXECUTE AS CALLER
AS '
BEGIN

    -- 1. Insert matching records into PREVDATA table
    INSERT INTO AGGNE.DEV.PA_PER_POLICYATTACH_MIGRATION_DCT_PREVDATA
    SELECT T1.*
    FROM AGGNE.UAT.PA_PER_POLICYATTACH_MIGRATION_DCT T1
    INNER JOIN AGGNE.DEV.PER_SAMPLE_POLICYATTACH_FINAL_IDENTIFIER T2
        ON T1.ID = T2.ACTUALID;

    -- 2. Delete the same records from source table
    DELETE FROM AGGNE.UAT.PA_PER_POLICYATTACH_MIGRATION_DCT
    WHERE ID IN (
        SELECT ACTUALID
        FROM AGGNE.DEV.PER_SAMPLE_POLICYATTACH_FINAL_IDENTIFIER
    );

    RETURN ''Insert and delete completed successfully'';

END;
';