create or replace view PA_PER_BUILDING_FINAL_AGG(
	ID,
	AOI,
	LOAD_DATE
) as 
WITH cte1 AS (
  SELECT DISTINCT
         *
  FROM AGGNE.PRD.PA_PER_RISK_BUILDING_TARGET
  WHERE   ITR_TYPE = 'RISK_Building'
),
acc AS (
  SELECT DISTINCT
         *
  FROM AGGNE.PRD.PA_PER_RISK_BUILDING_FINAL
)
SELECT
  A.ACTUALID AS ID,
  LISTAGG(t1.payload, '\n') WITHIN GROUP (ORDER BY a.RISKNUMBER) AS AOI,
  t1.LOAD_DATE
FROM cte1 t1
JOIN acc a
  ON TRIM(a.PUREPOLICYNUMBER) = TRIM(t1.ID) 
GROUP BY A.ACTUALID, t1.LOAD_DATE
ORDER BY A.ACTUALID, t1.LOAD_DATE;