-- ============================================================================
-- G-BP-21 fix — SEQ 14 (BP_LINE_PF), Professional Protection: Previous
-- Professional Protection / Previous Event (ATP-10843, "PF 'Is Previous PF
-- in place' is incorrect in UI + Clarity")
-- ============================================================================
-- Root cause (confirmed against SAS + SP + live data, 2026-07-11):
--   The SP (DEV_SP_POLCIY_CONVERSION_PURE_TO_WRITE_LOAD.sql:5327-5338) computes
--   PreviousProfessionalProtection and PreviousEvent with an inverted CASE:
--
--     CASE
--          WHEN (t3.PIPrevProtection IS NOT NULL AND t3.PIPrevProtection <>2) THEN ''
--          WHEN t3.PIPrevProtection = 1 THEN 'Yes'
--          ELSE 'No'
--     END AS PreviousProfessionalProtection
--
--   The first WHEN is a superset of the second: any value that is NOT NULL and
--   NOT 2 (which includes 1) matches WHEN #1 first and returns blank, so
--   "WHEN = 1 THEN 'Yes'" can never be reached. Identical bug shape in the
--   PreviousEvent block (PIPrevClaimEvents, lines 5333-5338) and in
--   RetroactiveProtection (PIRetroactiveCover, lines 5316-5321) — this last one
--   has zero live impact only because LINE_PF_PAYLOAD's ROL_SD indicator is
--   independently re-derived from the raw PIRETROACTIVECOVER column rather than
--   consuming the SP's broken RETROACTIVEPROTECTION column (see view below).
--
--   Client's original SAS (ProfessionalProtection_conversionscriptCapricorn.txt)
--   has the correct, non-inverted logic:
--     CASE WHEN PIPrevProtection IN (.,2) THEN ''
--          WHEN PIPrevProtection = 1 THEN 'Yes'
--          ELSE 'No' END AS PreviousProfessionalProtection
--
--   Live data on AGGNE.DEV.Line_ProfessionalProtection_Coverage (EXPIRYDATE>='2026-01-01',
--   4,655 rows total):
--     Raw PIPREVPROTECTION:    2 -> 3,933   1 -> 498   0 -> 224
--     Staged PREVIOUSPROFESSIONALPROTECTION (post-SP, broken): 'No' -> 3,933   '' -> 722 (=498+224)
--     Final LINE_PF_PAYLOAD.PREVIOUSPROFESSIONALPROTECTION (post-view CASE): 'No' -> ALL 4,655
--   Confirmed: 498 of 4,655 PF policies (10.7%) have Pure's "Yes, there was
--   previous professional protection" (PIPrevProtection=1) but the field is
--   hardcoded blank by the SP bug, then collapsed to 'No' by the view's own
--   PIDATE-gated CASE — the true answer is lost twice over.
--
--   Raw PIPREVCLAIMEVENTS: 2 -> 3,933   0 -> 722   (no rows currently have value 1)
--   -> PreviousEvent has the identical bug shape but ZERO current live impact
--      (no policy in the current dataset actually answered "Yes"). Still worth
--      fixing since the bug is live-data-dependent, not logically inert.
--
--   Manuscript (ProfessionalProtectionInput.PreviousProfessionalProtection /
--   .PreviousEvent) confirms both are plain Yes/No dropdowns with no PIDate
--   dependency — the view's "only populate when PIDATE IS NOT NULL" gate isn't
--   manuscript-required and isn't the actual bug; it's a secondary symptom that
--   further masks the SP's blank output as 'No' instead of surfacing the gap.
--
-- Scope: VIEW-ONLY fix. Re-derives both fields directly from the raw
--   PIPREVPROTECTION / PIPREVCLAIMEVENTS columns (same pattern LINE_PF_PAYLOAD
--   already uses correctly for PIRETROACTIVECOVER -> RETROACTIVE_IND/INDICATOR),
--   bypassing the SP's broken computed columns entirely. No config change
--   needed — SEQ 14 already references {PREVIOUSPROFESSIONALPROTECTION} and
--   {PREVIOUSEVENT} correctly.
--   RECOMMEND SEPARATELY fixing the SP's 3 inverted CASE blocks (lines
--   5316-5321, 5327-5332, 5333-5338) at the source too, since any other
--   consumer reading Line_ProfessionalProtection_Coverage.RETROACTIVEPROTECTION/
--   .PREVIOUSPROFESSIONALPROTECTION/.PREVIOUSEVENT directly (not through this
--   view) would still see the bug. Not scripted here — SP changes go through
--   the SP SAI review-copy process, not a direct view/config fix.
-- Status: DRAFTED, NOT APPLIED. SAFE_MODE — wait for explicit go-ahead before running.
-- ============================================================================

create or replace view LINE_PF_PAYLOAD(
	PUREPOLICYNUMBER,
	LINE_PF_UW,
	LINE_PF_CLAUSE,
	VOLUNTARYEXCESS,
	PROFESSIONALPROTECTIONLIMIT,
	VEHBREAK_IND,
	VEHBREAK_INDICATOR,
	PIBREAKDOWNLIMIT,
	VEHASS_IND,
	VEHASS_INDICATOR,
	PIASSESSMENTLIMIT,
	VEHICLEASSESSMENTSANNUALTURNOVER,
	RETROACTIVE_IND,
	RETROACTIVE_INDICATOR,
	RETROACTIVELIMIT,
	CONTRACTORSANDSUBCONTRACTORS_IND,
	CONTRACTORSANDSUBCONTRACTORS_INDICATOR,
	CONTRACTORSANDSUBCONTRACTORSLIMIT,
	VEHICLEBREAKDOWNANNUALTURNOVER,
	DETAILS,
	PIDATE,
	PREVIOUSPROFESSIONALPROTECTION,
	PREVIOUSEVENT,
	PICLMCNT,
	PICLMINCD,
	PIEXPPREM,
	EXP_PREM_PFVHB_SD,
	EXP_PREM_PFROL_SD,
	EXP_PREM_PFCCA_SD,
	EXP_PREM_PFCSL_SD,
	EXP_PREM_PFSTD_SD,
	LOAD_DATE
) as
 with cte_SAMPLE_CBP_LOCATION as
(
select distinct PUREPOLICYNUMBER,cmlnumber,EXPIRINGID_P from AGGNE.DEV.SAMPLE_CBP WHERE  EXPIRYDATE >= '2026-01-01'
),cte_COVERAGES as
(
select distinct PUREPOLICYNUMBER,cmlnumber,EXPIRINGID_P,
CAST(CAST(COALESCE(VOLUNTARYEXCESS,0) AS NUMBER(30,0)) AS VARCHAR) AS VOLUNTARYEXCESS,
CAST(COALESCE(PROFESSIONALPROTECTIONLIMIT,0) AS VARCHAR) AS PROFESSIONALPROTECTIONLIMIT,
CASE WHEN "PIBREAKDOWNPROTECTION"=1 THEN 'Taken' Else 'NotTaken' END AS VEHBREAK_IND,
CAST(COALESCE("PIBREAKDOWNPROTECTION",0) AS VARCHAR) AS VEHBREAK_INDICATOR,
CAST(COALESCE("PIBREAKDOWNLIMIT",0) AS VARCHAR) AS PIBREAKDOWNLIMIT,
CASE WHEN PIASSESSMENTPROTECTION=1 THEN 'Taken' Else 'NotTaken' END AS VEHASS_IND,
CAST(COALESCE(PIASSESSMENTPROTECTION,0) AS VARCHAR) AS VEHASS_INDICATOR,
CAST(COALESCE("PIASSESSMENTLIMIT",0) AS VARCHAR) AS PIASSESSMENTLIMIT,
CAST(COALESCE(VEHICLEASSESSMENTSANNUALTURNOVER,0) AS VARCHAR) AS VEHICLEASSESSMENTSANNUALTURNOVER,
CASE WHEN PIRETROACTIVECOVER=1 THEN 'Taken' Else 'NotTaken' END AS RETROACTIVE_IND,
CAST(COALESCE(PIRETROACTIVECOVER,0) AS VARCHAR) AS RETROACTIVE_INDICATOR,
CASE WHEN PIACTSOFOTHERS=1 THEN 'Taken' Else 'NotTaken' END AS CONTRACTORSANDSUBCONTRACTORS_IND,
CAST(COALESCE(PIACTSOFOTHERS,0) AS VARCHAR) AS CONTRACTORSANDSUBCONTRACTORS_INDICATOR,
CAST(COALESCE(VEHICLEBREAKDOWNANNUALTURNOVER,0) AS VARCHAR) AS VEHICLEBREAKDOWNANNUALTURNOVER,
CAST(DETAILS AS VARCHAR) AS DETAILS,
TO_CHAR(PIDATE::DATE, 'YYYY-MM-DD') AS PIDATE,
CASE WHEN PIPREVPROTECTION=1 THEN 'Yes' WHEN PIPREVPROTECTION=2 THEN 'No' ELSE '' END AS PREVIOUSPROFESSIONALPROTECTION,   -- FIXED: re-derived from raw PIPREVPROTECTION, matches SAS/manuscript, bypasses broken SP column
CASE WHEN PIPREVCLAIMEVENTS=1 THEN 'Yes' WHEN PIPREVCLAIMEVENTS=2 THEN 'No' ELSE '' END AS PREVIOUSEVENT   -- FIXED: re-derived from raw PIPREVCLAIMEVENTS, matches SAS/manuscript, bypasses broken SP column
from AGGNE.DEV.Line_ProfessionalProtection_Coverage T1  WHERE  EXPIRYDATE >= '2026-01-01' --4693
)
, CTE_EXCESS AS(
SELECT DISTINCT
    CAST(trim(T2.PUREPOLICYNUMBER) ||'|' || TRIM(T2.cmlnumber) ||'|' || TRIM(T2.EXPIRINGID_P) AS VARCHAR) AS PUREPOLICYNUMBER,
t2.PUREPOLICYNUMBER AS LEGACYPOLICYNUMBER,T2.cmlnumber,T2.EXPIRINGID_P,
CAST(CAST(COALESCE(VOLUNTARYEXCESS,0) AS NUMBER(30,0)) AS VARCHAR) AS VOLUNTARYEXCESS,
CAST(COALESCE(PROFESSIONALPROTECTIONLIMIT,0) AS VARCHAR) AS PROFESSIONALPROTECTIONLIMIT,
CAST(VEHBREAK_IND AS VARCHAR) AS VEHBREAK_IND,
CAST(COALESCE(VEHBREAK_INDICATOR,0) AS VARCHAR) AS VEHBREAK_INDICATOR,
CAST(COALESCE(PIBREAKDOWNLIMIT,0) AS VARCHAR) AS PIBREAKDOWNLIMIT,
CAST(VEHASS_IND AS VARCHAR) AS VEHASS_IND,
CAST(COALESCE(VEHASS_INDICATOR,0) AS VARCHAR) AS VEHASS_INDICATOR,
CAST(COALESCE(PIASSESSMENTLIMIT,0) AS VARCHAR) AS PIASSESSMENTLIMIT,
CAST(COALESCE(VEHICLEASSESSMENTSANNUALTURNOVER,0) AS VARCHAR) AS VEHICLEASSESSMENTSANNUALTURNOVER,
CAST(RETROACTIVE_IND AS VARCHAR) AS  RETROACTIVE_IND,
CAST(COALESCE(RETROACTIVE_INDICATOR,0) AS VARCHAR) AS RETROACTIVE_INDICATOR,
CAST(CONTRACTORSANDSUBCONTRACTORS_IND AS VARCHAR) AS  CONTRACTORSANDSUBCONTRACTORS_IND,
CAST(COALESCE(CONTRACTORSANDSUBCONTRACTORS_INDICATOR,0) AS VARCHAR) AS CONTRACTORSANDSUBCONTRACTORS_INDICATOR,
CAST(COALESCE(VEHICLEBREAKDOWNANNUALTURNOVER,0) AS VARCHAR) AS VEHICLEBREAKDOWNANNUALTURNOVER,
CAST(DETAILS AS VARCHAR) AS DETAILS,
TO_CHAR(PIDATE::DATE, 'YYYY-MM-DD') AS PIDATE,
CAST(PREVIOUSPROFESSIONALPROTECTION AS VARCHAR) AS PREVIOUSPROFESSIONALPROTECTION,
CAST(PREVIOUSEVENT AS VARCHAR) AS PREVIOUSEVENT
FROM
cte_SAMPLE_CBP_LOCATION T1
INNER JOIN cte_COVERAGES T2
ON
-- T1.EXPIRINGID_P=T2.EXPIRINGID_P AND
TRIM(T1.PUREPOLICYNUMBER)=TRIM(T2.PUREPOLICYNUMBER)
)
,CTE_LISTAGG AS(
SELECT
  ID,
  LISTAGG(CASE WHEN ITR_TYPE = 'BP_LINE_PF_UW' THEN payload END, '\n') AS LINE_PF_UW,
  LISTAGG(CASE WHEN ITR_TYPE = 'BP_LINE_PF_CLAUSE' THEN payload END, '\n') AS LINE_PF_CLAUSE,
  CAST(LOAD_DATE AS DATE) AS LOAD_DATE
FROM AGGNE.DEV.LINE_PF_Target
WHERE ITR_TYPE IN ('BP_LINE_PF_UW','BP_LINE_PF_CLAUSE')
GROUP BY ID,CAST(LOAD_DATE AS DATE)
)
,SUB_COV_PREM AS (
SELECT
  PUREPOLICYNUMBER,
PFVHB_SD,
PFROL_SD,
PFCCA_SD,
PFCSL_SD,
PFSTD_SD
FROM (
  SELECT PUREPOLICYNUMBER, SUB_COVERAGE, EXPPREMIUM
  FROM AGGNE.DEV.VW_OUTPUT_SUBCOVERAGE_BSP
) src
PIVOT (
  SUM(EXPPREMIUM) FOR SUB_COVERAGE IN (
    ('PFVHB_SD') AS PFVHB_SD,
    ('PFROL_SD') AS PFROL_SD,
    ('PFCCA_SD') AS PFCCA_SD,
    ('PFCSL_SD') AS PFCSL_SD,
    ('PFSTD_SD') AS PFSTD_SD

  )
) p
)
SELECT distinct
T1.PUREPOLICYNUMBER,
CASE WHEN LINE_PF_UW IS NOT NULL AND LINE_PF_UW<> '' THEN CAST(LINE_PF_UW AS VARCHAR) ELSE '' END AS LINE_PF_UW,
-- CAST(LINE_PF_UW AS VARCHAR) AS LINE_PF_UW,
CASE WHEN LINE_PF_CLAUSE IS NOT NULL AND LINE_PF_CLAUSE<> '' THEN '<Clauses><Type>ProfessionalProtection</Type>'||CAST(LINE_PF_CLAUSE AS VARCHAR)||'</Clauses>' ELSE '' END AS LINE_PF_CLAUSE,
-- CAST(LINE_PF_CLAUSE AS VARCHAR) AS LINE_PF_CLAUSE,
CAST(CAST(COALESCE(VOLUNTARYEXCESS,0)AS NUMBER(10,0)) AS VARCHAR) AS VOLUNTARYEXCESS,
CAST(CAST(COALESCE(PROFESSIONALPROTECTIONLIMIT,0)AS NUMBER(10,0)) AS VARCHAR) AS PROFESSIONALPROTECTIONLIMIT,
CAST(VEHBREAK_IND AS VARCHAR) AS VEHBREAK_IND,
CAST(CAST(VEHBREAK_INDICATOR AS NUMBER(10,0)) AS VARCHAR) AS VEHBREAK_INDICATOR,
CAST(CAST(PIBREAKDOWNLIMIT AS NUMBER(10,0)) AS VARCHAR) AS PIBREAKDOWNLIMIT,
CAST(VEHASS_IND AS VARCHAR) AS VEHASS_IND,
CAST(CAST(VEHASS_INDICATOR AS NUMBER(10,0)) AS VARCHAR) AS VEHASS_INDICATOR,
CAST(CAST(PIASSESSMENTLIMIT AS NUMBER(10,0)) AS VARCHAR) AS PIASSESSMENTLIMIT,
CAST(CAST(COALESCE(VEHICLEASSESSMENTSANNUALTURNOVER,0)AS NUMBER(10,0)) AS VARCHAR) AS VEHICLEASSESSMENTSANNUALTURNOVER,
CAST(RETROACTIVE_IND AS VARCHAR) AS RETROACTIVE_IND,
CAST(CAST(RETROACTIVE_INDICATOR AS NUMBER(10,0))AS VARCHAR) AS RETROACTIVE_INDICATOR,
CASE WHEN RETROACTIVE_INDICATOR=1 THEN CAST(CAST(COALESCE(PROFESSIONALPROTECTIONLIMIT,0)AS NUMBER(10,0)) AS VARCHAR) ELSE '' END AS RETROACTIVELIMIT,
CAST(CONTRACTORSANDSUBCONTRACTORS_IND AS VARCHAR) AS CONTRACTORSANDSUBCONTRACTORS_IND,
CAST(CAST(CONTRACTORSANDSUBCONTRACTORS_INDICATOR AS NUMBER(10,0)) AS VARCHAR) AS CONTRACTORSANDSUBCONTRACTORS_INDICATOR,
CASE WHEN CONTRACTORSANDSUBCONTRACTORS_INDICATOR=1 THEN CAST(CAST(COALESCE(PROFESSIONALPROTECTIONLIMIT,0)AS NUMBER(10,0)) AS VARCHAR) ELSE '' END AS CONTRACTORSANDSUBCONTRACTORSLIMIT,
CAST(CAST(COALESCE(VEHICLEBREAKDOWNANNUALTURNOVER,0)AS NUMBER(10,0)) AS VARCHAR) AS VEHICLEBREAKDOWNANNUALTURNOVER,
CAST(DETAILS AS VARCHAR) AS DETAILS,
TO_CHAR(PIDATE::DATE, 'YYYY-MM-DD') AS PIDATE,
CAST(PREVIOUSPROFESSIONALPROTECTION AS VARCHAR) AS PREVIOUSPROFESSIONALPROTECTION,   -- FIXED: direct passthrough of the now-correct CTE value, no PIDATE gate (not manuscript-required)
CAST(PREVIOUSEVENT AS VARCHAR) AS PREVIOUSEVENT,   -- FIXED: direct passthrough of the now-correct CTE value, no PIDATE gate (not manuscript-required)
CAST(CAST(COALESCE(T4.PICLMCNT,0)AS NUMBER(10,0)) AS VARCHAR) AS PICLMCNT,
CAST(CAST(COALESCE(T4.PICLMINCD,0) AS NUMBER(10,0)) AS VARCHAR) AS PICLMINCD,
CAST(COALESCE(T4.PIEXPPREM,0) AS VARCHAR) AS PIEXPPREM,
CAST(COALESCE(CAST(PFVHB_SD AS NUMBER(36,3)),0)AS VARCHAR) AS EXP_PREM_PFVHB_SD,
CAST(COALESCE(CAST(PFROL_SD AS NUMBER(36,3)),0)AS VARCHAR) AS EXP_PREM_PFROL_SD,
CAST(COALESCE(CAST(PFCCA_SD AS NUMBER(36,3)),0)AS VARCHAR) AS EXP_PREM_PFCCA_SD,
CAST(COALESCE(CAST(PFCSL_SD AS NUMBER(36,3)),0)AS VARCHAR) AS EXP_PREM_PFCSL_SD,
CAST(COALESCE(CAST(PFSTD_SD AS NUMBER(36,3)),0)AS VARCHAR) AS EXP_PREM_PFSTD_SD,
CAST(GETDATE() AS DATE) AS LOAD_DATE
FROM CTE_EXCESS T1
--INNER JOIN  AGGNE.DEV.LINE_PF_Target T2 ON T1.PUREPOLICYNUMBER=T2.ID
LEFT JOIN CTE_LISTAGG T3 ON T1.PUREPOLICYNUMBER = T3.ID
LEFT JOIN AGGNE.DEV.VW_OUTPUT_COVERAGE_BSP T4 ON T1.PUREPOLICYNUMBER=T4.PUREPOLICYNUMBER
LEFT JOIN SUB_COV_PREM T5 ON T1.PUREPOLICYNUMBER=T5.PUREPOLICYNUMBER;

