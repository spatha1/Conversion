--         CAST(PUREPOLICYNUMBER AS VARCHAR) AS PUREPOLICYNUMBER,
--         CAST(cmlnumber AS VARCHAR) AS cmlnumber,
--         CAST(EXPIRINGID_P AS VARCHAR) AS EXPIRINGID_P,
