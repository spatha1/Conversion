create or replace view PA_LOC_BC_CLAUSE(
	PUREPOLICYNUMBER,
	PUREPOLICYBINDERID,
	EXPIRINGID_P,
	DCCLAUSETYPE,
	DCINPUT
) as
SELECT 
ID AS PUREPOLICYNUMBER,
CAST(T1.PUREPOLICYBINDERID AS VARCHAR) AS PUREPOLICYBINDERID,
CAST(T2.EXPIRINGID_P AS VARCHAR) AS EXPIRINGID_P,
CAST(DCCLAUSETYPE AS VARCHAR) AS DCCLAUSETYPE,
CAST(DCINPUT  AS VARCHAR) AS DCINPUT
FROM AGGNE.PRD.CLAUSES_Policyattach T1
INNER  JOIN AGGNE.PRD.location_bc_coverage_policyattach_IDENTIFIER T2 ON T1.PUREPOLICYNUMBER=T2.PUREPOLICYNUMBER AND T1.PUREPOLICYBINDERID=T2.EXPIRINGID_P
WHERE T1.COVERAGE='BC' AND _IS_CURRENT='TRUE';