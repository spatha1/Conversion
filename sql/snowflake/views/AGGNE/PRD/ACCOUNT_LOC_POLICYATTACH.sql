create or replace view ACCOUNT_LOC_POLICYATTACH(
	PUREPOLICYNUMBER,
	ACTUALID,
	LEGACYPOLICYNUMBER,
	LOCATIONANZSICCODE,
	RISKNUMBER,
	STATE,
	ADDRESS1,
	SUBURB,
	GNAFPID,
	POSTCODE,
	LOC_COUNTRY
) as
WITH
 cte2 AS (
  SELECT DISTINCT
         ID AS PUREPOLICYNUMBER,ACTUALID,
         TRIM(PUREPOLICYNUMBER)                                     AS LEGACYPOLICYNUMBER,
         STATE,
         ADDRESS1,
         SUBURB,
         CAST(POSTCODE AS VARCHAR)                                   AS POSTCODE,
         CAST(COALESCE(GNAFPID, '0') AS VARCHAR)                     AS GNAFPID,
         COUNTRY,
         LOCATIONANZSICCODE
  FROM AGGNE.PRD.Location_01_Policyattach_IDENTIFIER 
)
  SELECT DISTINCT
  PUREPOLICYNUMBER AS PUREPOLICYNUMBER,ACTUALID,
    LEGACYPOLICYNUMBER,
    t2.LOCATIONANZSICCODE,
    CAST(CAST(ROW_NUMBER() OVER (PARTITION BY T2.ACTUALID ORDER BY t2.PUREPOLICYNUMBER ASC )AS NUMBER(10,0)) AS VARCHAR) AS RISKNUMBER,
    /* Apply your STATE rule */
    CASE
      WHEN TRIM(t2.COUNTRY) = 'New Zealand' THEN t2.STATE
      WHEN TRIM(t2.COUNTRY) = 'Australia'   THEN CONCAT(t2.STATE, 'AU')
      ELSE t2.STATE
    END AS STATE,
    t2.ADDRESS1,
    t2.SUBURB,
    CAST(COALESCE(t2.GNAFPID, '0') AS VARCHAR) AS GNAFPID,
    CAST(t2.POSTCODE AS VARCHAR)               AS POSTCODE,
    /* LOC_COUNTRY rule */
    CASE
      WHEN TRIM(t2.COUNTRY) = 'New Zealand' THEN 'NZ'
      WHEN TRIM(t2.COUNTRY) = 'Australia'   THEN 'AU'
      ELSE TRIM(t2.COUNTRY)
    END AS LOC_COUNTRY
  FROM cte2 t2;