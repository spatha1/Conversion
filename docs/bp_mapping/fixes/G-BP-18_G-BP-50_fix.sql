-- ============================================================================
-- G-BP-18 / G-BP-50 fix — SEQ 11 (BP_LINE_PPL), PublicProductLiability coverage
-- ============================================================================
-- Root cause (confirmed against manuscript + live data, 2026-07-11):
--   STB_SD, STD_SD, CCC_SD /Indicator and DFW_SD /Indicator + /sValue are all
--   hardcoded to Taken (1 / "Taken") in ConversionConfig SEQ 11 regardless of
--   Pure's actual data. Manuscript (Carrier_CoverageLibrary_Data_1_0_0_0.xml)
--   confirms all four are meant to mirror a single flag:
--     PublicProductLiabilityInput.PublicLiabilityStandardIndicator  (STB_SD)  = ProtectionTypeStandard
--     PublicProductLiabilityInput.ProductsLiabilityStandardIndicator (STD_SD) = ProtectionTypeStandard
--     PublicProductLiabilityInput.PropertyCareCustodyOrControlIndicator (CCC_SD) = (ProductsandPublicLiabilityLimit > 0)
--     PublicProductLiabilityInput.DamageResultingfromFaultyWorksmanshipIndicator (DFW_SD) = (sValue == "Taken")
--     DFW_SD/sValue default/value = "Taken" only when Indicator AND ProtectionTypeStandard are both true
--   Live check on AGGNE.DEV.Line_PublicLiability_Coverage (EXPIRYDATE>='2026-01-01'):
--     STANDARD='Taken'      -> 10,920 rows  (PRODUCTSANDPUBLICLIABILITYLIMIT > 0 in all of them)
--     STANDARD='Not Taken'  ->  1,343 rows  (PRODUCTSANDPUBLICLIABILITYLIMIT = 0  in all of them)
--   So ProtectionTypeStandard ({PROTECTIONTYPESTANDARD}, already a token in this
--   same SEQ 11 template) is a 100% reliable proxy for all four conditions above.
--   Currently 1,343 of 12,263 PPL records (11%) will incorrectly show DFW_SD,
--   STB_SD, STD_SD and CCC_SD as "Taken" in DCT when Pure recorded "Not Taken".
--
--   G-BP-49 (RUF_SD hardcoded Indicator=0) is NOT part of this fix — separately
--   confirmed correct-by-design: the SP and the client's original SAS both
--   exclude any policy with PP1RunOffLiab>0 AND PublicAndProductLiability=1
--   from the whole conversion extraction, so a converted PPL record can never
--   have Runoff Liability Taken. See seq09-11_publicproductliability.md.
--
-- Scope: view (add PROTECTIONTYPESTANDARD_IND, string twin of PROTECTIONTYPESTANDARD,
--        same pattern already used for RECTIFYINGFAULTY_IND) + config (SEQ 11 token wiring).
-- Status: DRAFTED, NOT APPLIED. SAFE_MODE — wait for explicit go-ahead before running.
-- View DDL below re-pulled live 2026-07-11 immediately before drafting this script —
-- confirmed identical to the copy used to write the seq09-11 card, no drift.
-- ============================================================================

