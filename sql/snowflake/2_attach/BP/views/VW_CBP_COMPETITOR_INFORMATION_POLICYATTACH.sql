create or replace view VW_CBP_COMPETITOR_INFORMATION_POLICYATTACH(
	PUREPOLICYNUMBER,
	LEGACYPOLICYNUMBER,
	PRIORCARRIER,
	PRICE
) as 
SELECT DISTINCT 
ID AS PUREPOLICYNUMBER,
 TRIM(PUREPOLICYNUMBER) AS LEGACYPOLICYNUMBER,
PRIORCARRIER,
CAST(COALESCE(CAST (PRICE AS NUMBER(10,0)),0)AS VARCHAR) AS PRICE 
FROM AGGNE.PRD.Competitor_Information_Policyattach_IDENTIFIER  ;