create or replace view LINE_LE_PAYLOAD(
	PUREPOLICYNUMBER,
	LINE_LE_UW,
	LINE_LE_CLAUSE,
	VOLUNTARYEXCESS,
	LEGALEXPENSES_IND,
	LEGALEXPENSESLIMIT,
	LEGALDISPUTEACTIONS,
	LEGALDISPUTEACTIONSDETAILS,
	REDUNDANCIES,
	REDUNDANCIESDETAILS,
	LECLMCNT,
	LECLMINCD,
	LEEXPPREM,
	EXP_PREM_LESTD_SD,
	LOAD_DATE
) as
 with cte_SAMPLE_CBP_LOCATION as
(
select distinct PUREPOLICYNUMBER,cmlnumber,EXPIRINGID_P from AGGNE.DEV.SAMPLE_CBP WHERE EXPIRYDATE>='2026-01-01'
),cte_COVERAGES as 
(
select distinct PUREPOLICYNUMBER,cmlnumber,EXPIRINGID_P,
CAST(COALESCE(VOLUNTARYEXCESS,0) AS VARCHAR) AS VOLUNTARYEXCESS,
CAST(COALESCE(LEGALEXPENSES_IND,0) AS VARCHAR) AS LEGALEXPENSES_IND,
CAST(COALESCE(LEGALEXPENSESLIMIT ,0) AS VARCHAR) AS LEGALEXPENSESLIMIT ,
CAST(COALESCE(LEGALDISPUTEACTIONS ,'No') AS VARCHAR) AS LEGALDISPUTEACTIONS ,
CAST(COALESCE(LEGALDISPUTEACTIONSDETAILS ,'0') AS VARCHAR) AS LEGALDISPUTEACTIONSDETAILS ,
CAST(COALESCE(REDUNDANCIES ,'No') AS VARCHAR) AS REDUNDANCIES ,
CAST(COALESCE(REDUNDANCIESDETAILS ,'0') AS VARCHAR) AS REDUNDANCIESDETAILS 
from AGGNE.DEV.Line_LE_Coverage T1 WHERE EXPIRYDATE>='2026-01-01'
) 
, CTE_EXCESS AS(
SELECT DISTINCT
    CAST(trim(T2.PUREPOLICYNUMBER) ||'|' || TRIM(T2.cmlnumber) ||'|' || TRIM(T2.EXPIRINGID_P) AS VARCHAR) AS PUREPOLICYNUMBER,
t2.PUREPOLICYNUMBER AS LEGACYPOLICYNUMBER,T2.cmlnumber,T2.EXPIRINGID_P,
CAST(COALESCE(VOLUNTARYEXCESS,0) AS VARCHAR) AS VOLUNTARYEXCESS,
CAST(COALESCE(LEGALEXPENSES_IND,0) AS VARCHAR) AS LEGALEXPENSES_IND,
CAST(COALESCE(LEGALEXPENSESLIMIT ,0) AS VARCHAR) AS LEGALEXPENSESLIMIT ,
CAST(COALESCE(LEGALDISPUTEACTIONS ,'No') AS VARCHAR) AS LEGALDISPUTEACTIONS ,
CAST(COALESCE(LEGALDISPUTEACTIONSDETAILS ,'0') AS VARCHAR) AS LEGALDISPUTEACTIONSDETAILS ,
CAST(COALESCE(REDUNDANCIES ,'No') AS VARCHAR) AS REDUNDANCIES ,
CAST(COALESCE(REDUNDANCIESDETAILS ,'0') AS VARCHAR) AS REDUNDANCIESDETAILS 
FROM 
cte_SAMPLE_CBP_LOCATION T1 
INNER JOIN cte_COVERAGES T2 ON-- T1.EXPIRINGID_P=T2.EXPIRINGID_P AND 
 TRIM(T1.PUREPOLICYNUMBER)=TRIM(T2.PUREPOLICYNUMBER)
)
,CTE_LISTAGG AS(
SELECT DISTINCT
  ID,
  LISTAGG(CASE WHEN ITR_TYPE = 'BP_LINE_LE_UW' THEN payload END, '\n') AS LINE_LE_UW,
 LISTAGG(CASE WHEN ITR_TYPE = 'BP_LINE_LE_CLAUSE' THEN payload END, '\n') AS  LINE_LE_CLAUSE,
  CAST(LOAD_DATE AS DATE) AS LOAD_DATE
FROM AGGNE.DEV.LINE_LE_Target
WHERE ITR_TYPE IN ('BP_LINE_LE_UW','BP_LINE_LE_CLAUSE') 
GROUP BY ID,CAST(LOAD_DATE AS DATE)
)
,SUB_COV_PREM AS (
SELECT
  PUREPOLICYNUMBER,
LESTD_SD
FROM (
  SELECT PUREPOLICYNUMBER, SUB_COVERAGE, EXPPREMIUM
  FROM AGGNE.DEV.VW_OUTPUT_SUBCOVERAGE_BSP
) src
PIVOT (
  SUM(EXPPREMIUM) FOR SUB_COVERAGE IN (
    ('LESTD_SD') AS LESTD_SD
  )
) p
)
SELECT distinct 
T1.PUREPOLICYNUMBER,
CASE WHEN LINE_LE_UW IS NOT NULL AND LINE_LE_UW<> '' THEN CAST(LINE_LE_UW AS VARCHAR) ELSE '' END AS LINE_LE_UW,
CASE WHEN LINE_LE_CLAUSE IS NOT NULL AND LINE_LE_CLAUSE<> '' THEN '<Clauses><Type>LegalExpenses</Type>'||CAST(LINE_LE_CLAUSE AS VARCHAR)||'</Clauses>' ELSE '' END AS LINE_LE_CLAUSE,
-- --CAST(LINE_LE_CLAUSE AS VARCHAR) AS LINE_LE_CLAUSE,
CAST(CAST(COALESCE(VOLUNTARYEXCESS,0)AS NUMBER(10,0)) AS VARCHAR) AS VOLUNTARYEXCESS,
CAST(CAST(COALESCE(LEGALEXPENSES_IND,0)AS NUMBER(10,0)) AS VARCHAR) AS LEGALEXPENSES_IND,
CAST(CAST(COALESCE(LEGALEXPENSESLIMIT ,0)AS NUMBER(10,0)) AS VARCHAR) AS LEGALEXPENSESLIMIT ,
CAST(COALESCE(LEGALDISPUTEACTIONS ,'No') AS VARCHAR) AS LEGALDISPUTEACTIONS ,
CAST(COALESCE(LEGALDISPUTEACTIONSDETAILS ,'') AS VARCHAR) AS LEGALDISPUTEACTIONSDETAILS ,
CAST(COALESCE(REDUNDANCIES ,'No') AS VARCHAR) AS REDUNDANCIES ,
CAST(COALESCE(REDUNDANCIESDETAILS ,'') AS VARCHAR) AS REDUNDANCIESDETAILS ,
CAST(CAST(COALESCE(T4.LECLMCNT,0) AS NUMBER(10,0))AS VARCHAR) AS LECLMCNT,
CAST(CAST(COALESCE(T4.LECLMINCD,0)AS NUMBER(10,0)) AS VARCHAR) AS LECLMINCD,
CAST(COALESCE(T4.LEEXPPREM,0) AS VARCHAR) AS LEEXPPREM,
CAST(COALESCE(CAST(LESTD_SD AS NUMBER(36,3)),0)AS VARCHAR) AS EXP_PREM_LESTD_SD,
CAST(GETDATE() AS DATE) AS LOAD_DATE
FROM CTE_EXCESS T1
--INNER JOIN  AGGNE.DEV.LINE_LE_Target T2 ON T1.PUREPOLICYNUMBER=T2.ID
LEFT JOIN CTE_LISTAGG T3 ON T1.PUREPOLICYNUMBER = T3.ID 
LEFT JOIN AGGNE.DEV.VW_OUTPUT_COVERAGE_BSP T4 ON T1.PUREPOLICYNUMBER=T4.PUREPOLICYNUMBER 
LEFT JOIN SUB_COV_PREM T5 ON T1.PUREPOLICYNUMBER=T5.PUREPOLICYNUMBER;