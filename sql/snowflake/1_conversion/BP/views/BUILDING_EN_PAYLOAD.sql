create or replace view BUILDING_EN_PAYLOAD(
	PUREPOLICYNUMBER,
	COVERAGE,
	SUBCOV,
	UW,
	LOC_EN_CLAUSE,
	EQUIPMENTREGULAR,
	ENGINEERING_IND,
	AVERAGEAGEOFEQUIPMENT,
	AGEOFTHEOLDEST,
	ENCLMCNT,
	ENCLMINCD,
	ENEXPPREM,
	LOAD_DATE
) as
with cte_SAMPLE_CBP_LOCATION as
(
select distinct T1.PUREPOLICYNUMBER,T1.cmlnumber,EXPIRINGID from AGGNE.DEV.Location_01 T1 INNER JOIN AGGNE.DEV.SAMPLE_CBP T2 ON TRIM(T1.PUREPOLICYNUMBER)=TRIM(T2.PUREPOLICYNUMBER) 
-- and T1.EXPIRINGID=T2.EXPIRINGID_P 
WHERE t1.EXPIRYDATE>='2026-01-01'
),cte_COVERAGES as 
(
select distinct PUREPOLICYNUMBER,cmlnumber,EXPIRINGID_P,'EN' AS CLAUSE,'Engineering' AS  COVERAGE, 
CAST(CASE WHEN "EQUIPMENTREGULARLYMAINTAINED"='Yes' Then 'Yes' Else 'No' End AS VARCHAR) AS EQUIPMENTREGULAR,
CAST(ENGINEERING_IND AS VARCHAR) AS ENGINEERING_IND ,
CAST(AVERAGEAGEOFEQUIPMENT AS VARCHAR) AS AVERAGEAGEOFEQUIPMENT,
CAST(AGEOFTHEOLDEST AS VARCHAR) AS AGEOFTHEOLDEST
FROM AGGNE.DEV.Location_EN_Coverage T1 WHERE EXPIRYDATE>='2026-01-01'  --4525
) 
 , CTE_EXCESS AS(
SELECT 
CAST(trim(T2.PUREPOLICYNUMBER) ||'|' || TRIM(T2.cmlnumber) ||'|' || TRIM(T2.EXPIRINGID_P) AS VARCHAR) AS PUREPOLICYNUMBER,
t2.PUREPOLICYNUMBER AS LEGACYPOLICYNUMBER,T2.cmlnumber,T2.EXPIRINGID_P,COVERAGE,CAST(EQUIPMENTREGULAR AS VARCHAR) AS EQUIPMENTREGULAR,
CAST(ENGINEERING_IND AS VARCHAR) AS ENGINEERING_IND ,
CAST(AVERAGEAGEOFEQUIPMENT AS VARCHAR) AS AVERAGEAGEOFEQUIPMENT,
CAST(AGEOFTHEOLDEST AS VARCHAR) AS AGEOFTHEOLDEST
FROM  
cte_SAMPLE_CBP_LOCATION T1 
INNER JOIN cte_COVERAGES T2 ON TRIM(T1.EXPIRINGID)=TRIM(T2.EXPIRINGID_P)
AND TRIM(T1.PUREPOLICYNUMBER)=TRIM(T2.PUREPOLICYNUMBER)  --376
)
,CTE_LISTAGG AS(
SELECT
  ID,
  LISTAGG(CASE WHEN ITR_TYPE = 'BP_Risk_Building_EN_Subcov' THEN payload END, '\n') AS SUBCOV,
  LISTAGG(CASE WHEN ITR_TYPE = 'BP_RISK_BUILDING_EN_UW'     THEN payload END, '\n') AS UW,
  LISTAGG(CASE WHEN ITR_TYPE = 'BP_LOC_EN_CLAUSE'     THEN payload END, '\n') AS LOC_EN_CLAUSE,
  CAST(LOAD_DATE AS DATE) AS LOAD_DATE
FROM AGGNE.DEV.RISK_BUILDING_EN_TARGET
WHERE ITR_TYPE IN ('BP_Risk_Building_EN_Subcov', 'BP_RISK_BUILDING_EN_UW','BP_LOC_EN_CLAUSE')
GROUP BY ID,CAST(LOAD_DATE AS DATE)
)
SELECT distinct 
T1.PUREPOLICYNUMBER,
COVERAGE,CAST(SUBCOV AS VARCHAR) AS SUBCOV,
CAST(UW AS VARCHAR) AS UW,
CASE WHEN LOC_EN_CLAUSE IS NOT NULL AND LOC_EN_CLAUSE<> '' THEN '<Clauses><Type>Engineering</Type>'||CAST(LOC_EN_CLAUSE AS VARCHAR)||'</Clauses>' ELSE '' END AS LOC_EN_CLAUSE,
-- CAST(LOC_EN_CLAUSE AS VARCHAR) AS LOC_EN_CLAUSE,
 CAST(EQUIPMENTREGULAR AS VARCHAR) AS EQUIPMENTREGULAR,
CAST(cast(COALESCE(ENGINEERING_IND,0)as NUMBER(10,0) )AS VARCHAR) AS ENGINEERING_IND ,
CAST(AVERAGEAGEOFEQUIPMENT AS VARCHAR) AS AVERAGEAGEOFEQUIPMENT,
CAST(AGEOFTHEOLDEST AS VARCHAR) AS AGEOFTHEOLDEST,
CAST(COALESCE(T4.ENCLMCNT,0 )AS VARCHAR) AS ENCLMCNT,
CAST(COALESCE(T4.ENCLMINCD,0) AS VARCHAR) AS ENCLMINCD,
CAST(COALESCE(T4.ENEXPPREM,0) AS VARCHAR) AS ENEXPPREM,
CAST(GETDATE() AS DATE) AS LOAD_DATE
 FROM CTE_EXCESS T1
 -- INNER JOIN  AGGNE.DEV.RISK_BUILDING_EN_TARGET T2 ON T1.PUREPOLICYNUMBER=T2.ID
LEFT JOIN CTE_LISTAGG T3 ON T1.PUREPOLICYNUMBER = T3.ID 
LEFT JOIN AGGNE.DEV.VW_OUTPUT_COVERAGE_BSP T4 ON T1.PUREPOLICYNUMBER=T4.PUREPOLICYNUMBER 
WHERE   COVERAGE='Engineering';