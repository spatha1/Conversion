create or replace view FL_MOTOR_EXCESS_POLICYATTACH(
	PUREPOLICYNUMBER,
	PUREPOLICYNUMBER_ACTUAL,
	CMLNUMBER,
	LEGACYPOLICYNUMBER,
	EXPIRINGID_P,
	TYPE,
	FLEETTYPE,
	VOLUNTARYEXCESS,
	STANDARDEXCESS,
	IMPOSEDEXCESS,
	ONHOOKTOWINGPROTECTION,
	FVLESSTHAN17,
	FVLESSTHAN19,
	FVLESSTHAN21,
	FVLESSTHAN25
) as
select
    CAST(TRIM(ID) || '|' || NVL(TRIM(REGISTRATIONNUMBER),'Unknown') AS VARCHAR ) AS PUREPOLICYNUMBER,
    ID AS PUREPOLICYNUMBER_actual,
    cmlnumber,
    purepolicynumber AS legacypolicynumber,
    expiringid_p,
    'CommercialVehicle' as Type,
    'Default' as FleetType,
    CAST(CAST(VOLUNTARYEXCESS AS INT) AS VARCHAR) AS VOLUNTARYEXCESS,
    CAST(CAST(standardexcess AS INT) AS VARCHAR) AS standardexcess,
    CAST(CAST(imposedexcess AS INT) AS VARCHAR) AS imposedexcess,
    CAST(CAST(FVHOOKLIABEXCESS AS INT) AS VARCHAR) AS onhooktowingprotection,
    CAST(CAST(FVLESSTHAN17 AS INT) AS VARCHAR) AS FVLESSTHAN17,
    CAST(CAST(FVLESSTHAN19 AS INT) AS VARCHAR) AS FVLESSTHAN19,
    CAST(CAST(FVLESSTHAN21 AS INT) AS VARCHAR) AS FVLESSTHAN21,
    CAST(CAST(FVLESSTHAN25 AS INT) AS VARCHAR) AS FVLESSTHAN25
from
    AGGNE.PRD.VEHICLECOVERAGES_FLEETVEHICLE_POLICYATTACH_IDENTIFIER ;